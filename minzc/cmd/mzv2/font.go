// ocrCell tries to match 8 bytes of pixel data against the ZX Spectrum ROM font.
// Returns the matched ASCII character (0x20–0x7F), or 0 if no match.
// Supports both normal (ink-on-paper) and inverse (paper-on-ink) text.
func ocrCell(pixels [8]byte) (ch byte, inverse bool) {
	// Try normal match
	for i := 0; i < 96; i++ {
		off := i * 8
		match := true
		for r := 0; r < 8; r++ {
			if pixels[r] != zxFont[off+r] {
				match = false
				break
			}
		}
		if match {
			return byte(0x20 + i), false
		}
	}
	// Try inverse match (all bits flipped)
	for i := 0; i < 96; i++ {
		off := i * 8
		match := true
		for r := 0; r < 8; r++ {
			if pixels[r] != ^zxFont[off+r] {
				match = false
				break
			}
		}
		if match {
			return byte(0x20 + i), true
		}
	}
	return 0, false
}

// readCellPixels reads the 8 pixel bytes for character cell (cx, cy) from ZX screen RAM.
// ZX Spectrum screen layout: address = 010TTLLL RRRCCCCC
//
//	T = third (0-2), L = line within char (0-7), R = row within third (0-7), C = column (0-31)
func readCellPixels(zxMem *[65536]byte, cx, cy int) [8]byte {
	var pixels [8]byte
	for line := 0; line < 8; line++ {
		y := cy*8 + line
		third := y >> 6        // 0-2
		row := (y >> 3) & 7    // row within third
		scanline := y & 7      // line within char row
		addr := 0x4000 | (third << 11) | (scanline << 8) | (row << 5) | cx
		pixels[line] = zxMem[addr]
	}
	return pixels
}
