// pipeline.go — VIR module-level codegen entry point.
//
// This is the --vir entry point: MIR2 → VIR → Z3 solver → PIR → ASM.
// Replaces the 5-layer LIR pipeline with a single unified solver pass.
package vir

import (
	"encoding/json"
	"fmt"
	"os"
	"sort"
	"strings"

	"github.com/minz/minzc/pkg/mir2"
)

// FuncResult tracks per-function codegen outcome.
type FuncResult struct {
	Name  string
	OK    bool
	Error string
	ASM   string
}

// CodegenModule runs the VIR unified solver on all functions in a MIR2 module.
// Returns assembly text and per-function results.
func CodegenModule(m *mir2.Module, opts SolverOptions) (string, []FuncResult) {
	// VIR_STRICT env var controls strict mode (default: ON).
	// Treats warnings as errors, logs implicit decisions.
	// Set VIR_STRICT=0 to disable, or remove env var for default ON.
	if os.Getenv("VIR_STRICT") != "0" {
		opts.Strict = true
	}

	var sb strings.Builder
	var results []FuncResult

	// Phase 0: Z3-PFCCO — find optimal calling conventions for all functions.
	// This is interprocedural: Z3 considers all call sites simultaneously.
	pfccoResults, pfccoErr := OptimizePFCCO(m, Z80, PFCCOOptions{
		Z3Path:  opts.Z3Path,
		Timeout: opts.Timeout,
	})
	if pfccoErr == nil && len(pfccoResults) > 0 {
		sb.WriteString("; generated by VIR unified solver (Z3-PFCCO + Z3 joint isel+regalloc)\n")
		sb.WriteString("; calling conventions optimized by Z3 SMT solver\n\n")

		// Wire PFCCO results into FuncParamLocs for use by CodegenFunc.
		// Maps PFCCO's per-param physical register → vreg-based constraint.
		pfccoLocs := make(map[string]map[int]int)
		pfccoIdx := make(map[string]int) // funcName → index in pfccoResults
		for ri, pr := range pfccoResults {
			pfccoIdx[pr.FuncName] = ri
			if len(pr.ParamNames) > 0 {
				sb.WriteString(fmt.Sprintf("; %s: params=[%s] ret=%s (Z3-PFCCO)\n",
					pr.FuncName, strings.Join(pr.ParamNames, ","), pr.ReturnName))
			}
			// Map param index → vreg → phys register
			f := m.FuncByName(pr.FuncName)
			if f == nil || len(pr.ParamLocs) == 0 {
				continue
			}
			pl := make(map[int]int)
			for pi, phys := range pr.ParamLocs {
				if pi < len(f.Contract.Params) {
					pl[int(f.Contract.Params[pi].Reg)] = phys
				}
			}
			pfccoLocs[pr.FuncName] = pl
		}
		_ = pfccoIdx // available for dual-mode strategy

		// PFCCO results are informational for now. Wiring them as hard
		// constraints causes unsat for complex functions. The dual-mode
		// strategy in CodegenFunc handles the constrained/standalone choice
		// using caller-provided FuncParamLocs (from PBQP).
		_ = pfccoLocs // available for future adapter-based wiring
		sb.WriteString("\n")
	} else {
		sb.WriteString("; generated by VIR unified solver (Z3 joint isel+regalloc)\n\n")
	}

	// Dump call graph JSON if requested (for z80-optimizer partopt)
	if os.Getenv("VIR_DUMP_CALLGRAPH") != "" {
		dumpCallGraph(m, opts)
	}

	// Dump merged GPU problems if requested (for z80-optimizer partopt)
	// VIR_DUMP_MERGED=path.json — reads merge pairs from stdin or generates from call graph
	if mergedPath := os.Getenv("VIR_DUMP_MERGED"); mergedPath != "" {
		dumpMergedProblems(m, opts, mergedPath)
	}

	// Dump per-program-point liveness for island decomposition
	// VIR_DUMP_LIVENESS=path.json — functions with >15 vregs (or all if VIR_LIVENESS_ALL=1)
	if livePath := os.Getenv("VIR_DUMP_LIVENESS"); livePath != "" {
		dumpLiveness(m, opts, livePath)
	}

	// Dump island sub-problems: split large functions at VIR level, BuildGPUDesc per island
	// VIR_DUMP_ISLANDS=path.json — reads split config from VIR_ISLAND_CONFIG or auto-splits
	if islandPath := os.Getenv("VIR_DUMP_ISLANDS"); islandPath != "" {
		dumpIslands(m, opts, islandPath)
	}

	// Emit main first
	funcs := m.Funcs
	if main := m.FuncByName("main"); main != nil && len(funcs) > 0 && funcs[0].Name != "main" {
		ordered := make([]*mir2.Func, 0, len(funcs))
		ordered = append(ordered, main)
		for _, f := range funcs {
			if f.Name != "main" {
				ordered = append(ordered, f)
			}
		}
		funcs = ordered
	}

	for _, f := range funcs {
		asm, err := CodegenFunc(f, m, opts)
		// Post-emit validation: heuristic check for clobbered 16-bit loads.
		// Z3 pair aliasing constraints are the authoritative interference check.
		// In strict mode: ERROR (catches real bugs, may have false positives).
		// In non-strict mode: WARNING (for prod after false positives are fixed).
		if err == nil {
			if clobErr := validateNoClobber(asm); clobErr != "" {
				if opts.Strict {
					err = fmt.Errorf("[STRICT] post-emit validation: %s", clobErr)
				} else {
					fmt.Fprintf(os.Stderr, "[vir] %s: post-emit warning: %s\n", f.Name, clobErr)
				}
			}
		}
		r := FuncResult{Name: f.Name}
		if err != nil {
			r.Error = err.Error()
			if opts.Verbose {
				fmt.Fprintf(os.Stderr, "[vir] %s: %v\n", f.Name, err)
			}
		} else {
			r.OK = true
			r.ASM = asm
			sb.WriteString(asm)
			sb.WriteByte('\n')
		}
		results = append(results, r)
	}

	// Emit runtime routines referenced by generated code
	asmText := sb.String()
	if strings.Contains(asmText, "__mul8") || strings.Contains(asmText, "__mul16") ||
		strings.Contains(asmText, "__div8") || strings.Contains(asmText, "__div16") ||
		strings.Contains(asmText, "__mod8") || strings.Contains(asmText, "__mod16") {
		sb.WriteString(emitRuntimeRoutines(asmText))
	}

	// Emit VIR memory spill slots (DW 0 storage for _vir_memN labels)
	asmText = sb.String()
	for i := 0; i < 4; i++ {
		label := fmt.Sprintf("_vir_mem%d", i)
		if strings.Contains(asmText, label) {
			sb.WriteString(fmt.Sprintf("%s: DW 0\n", label))
		}
	}

	// Emit _spill_* storage for any spill labels referenced but not defined.
	// These come from PBQP spill slots that VIR inherits via MIR2 lowering.
	asmText = sb.String()
	emittedSpills := make(map[string]bool)
	for _, line := range strings.Split(asmText, "\n") {
		trimmed := strings.TrimSpace(line)
		// Look for references to _spill_* labels (in operands, not as definitions)
		if strings.Contains(trimmed, "_spill_") && !strings.HasSuffix(trimmed, ":") {
			// Extract _spill_xxx label from the line
			for _, part := range strings.Fields(trimmed) {
				// Strip parens and commas: (_spill_main_r74) → _spill_main_r74
				part = strings.Trim(part, "(),")
				if strings.HasPrefix(part, "_spill_") && !emittedSpills[part] {
					// Check it's not already defined as a label
					if !strings.Contains(asmText, part+":") {
						sb.WriteString(fmt.Sprintf("%s: DW 0\n", part))
						emittedSpills[part] = true
					}
				}
			}
		}
	}

	// Grace reroll: -Osize — replace repeated CALL patterns with DJNZ loops
	if opts.OptSize {
		finalAsm := sb.String()
		// Apply reroll per function (extract function name from labels)
		lines := strings.Split(finalAsm, "\n")
		currentFunc := ""
		funcStart := 0
		var rerolled []string
		for i, line := range lines {
			trimmed := strings.TrimSpace(line)
			// Detect function label (not local label, not comment)
			if strings.HasSuffix(trimmed, ":") && !strings.HasPrefix(trimmed, ".") &&
				!strings.HasPrefix(trimmed, ";") && !strings.HasPrefix(trimmed, "_vir_") &&
				!strings.HasPrefix(trimmed, "_mir2_") && !strings.HasPrefix(trimmed, "_spill_") {
				if currentFunc != "" {
					// Reroll previous function
					funcLines := lines[funcStart:i]
					funcLines = graceReroll(funcLines, currentFunc)
					rerolled = append(rerolled, funcLines...)
				}
				currentFunc = strings.TrimSuffix(trimmed, ":")
				funcStart = i
			}
		}
		// Last function + remaining
		if currentFunc != "" && funcStart < len(lines) {
			funcLines := lines[funcStart:]
			funcLines = graceReroll(funcLines, currentFunc)
			rerolled = append(rerolled, funcLines...)
		} else {
			rerolled = append(rerolled, lines[funcStart:]...)
		}
		sb.Reset()
		sb.WriteString(strings.Join(rerolled, "\n"))
	}

	return sb.String(), results
}

// emitRuntimeRoutines appends Z80 runtime helper routines referenced by VIR code.
func emitRuntimeRoutines(asm string) string {
	var sb strings.Builder

	if strings.Contains(asm, "__mul8") {
		sb.WriteString(`; __mul8: A = A * B (8-bit multiply, ~80T)
__mul8:
    LD C, A
    XOR A
    LD D, 8
.__mul8_lp:
    SRL C
    JR NC, .__mul8_sk
    ADD A, B
.__mul8_sk:
    SLA B
    DEC D
    JR NZ, .__mul8_lp
    RET
`)
	}

	if strings.Contains(asm, "__mul16") {
		sb.WriteString(`; __mul16: HL = HL * DE (~200T)
__mul16:
    LD B, H
    LD C, L
    LD HL, 0
    LD A, 16
.__mul16_lp:
    SRL B
    RR C
    JR NC, .__mul16_sk
    ADD HL, DE
.__mul16_sk:
    SLA E
    RL D
    DEC A
    JR NZ, .__mul16_lp
    RET
`)
	}

	if strings.Contains(asm, "__div8") {
		// DIVU111 algorithm (Dark / X-Trade, 1997)
		// Input: A=dividend, B=divisor. Output: A=quotient, C=remainder.
		sb.WriteString(`; __div8: A = A / B (quotient), C = remainder
__div8:
    LD C, B
    LD B, A
    XOR A
    LD D, 8
.__div8_lp:
    SLA B
    RLA
    CP C
    JR C, .__div8_sk
    SUB C
    INC B
.__div8_sk:
    DEC D
    JR NZ, .__div8_lp
    LD A, B
    RET
`)
	}

	if strings.Contains(asm, "__mod8") {
		// Uses __div8 internally, returns remainder (A after div loop, before LD A,B)
		sb.WriteString(`; __mod8: A = A mod B
__mod8:
    LD C, B
    LD B, A
    XOR A
    LD D, 8
.__mod8_lp:
    SLA B
    RLA
    CP C
    JR C, .__mod8_sk
    SUB C
    INC B
.__mod8_sk:
    DEC D
    JR NZ, .__mod8_lp
    RET
`)
	}

	if strings.Contains(asm, "__div16") {
		// 16-bit unsigned division: HL / DE → HL=quotient, DE=remainder
		// Shift-and-subtract long division, 16 iterations.
		sb.WriteString(`; __div16: HL = HL / DE (quotient), DE = remainder
__div16:
    LD B, H
    LD C, L
    LD HL, 0
    LD A, 16
.__div16_lp:
    SLA C
    RL B
    ADC HL, HL
    SBC HL, DE
    JR NC, .__div16_sk
    ADD HL, DE
    JR .__div16_noinc
.__div16_sk:
    INC C
.__div16_noinc:
    DEC A
    JR NZ, .__div16_lp
    EX DE, HL
    LD H, B
    LD L, C
    RET
`)
	}

	if strings.Contains(asm, "__mod16") {
		// 16-bit unsigned modulo: HL % DE → HL=remainder
		sb.WriteString(`; __mod16: HL = HL mod DE (remainder)
__mod16:
    LD B, H
    LD C, L
    LD HL, 0
    LD A, 16
.__mod16_lp:
    SLA C
    RL B
    ADC HL, HL
    SBC HL, DE
    JR NC, .__mod16_sk
    ADD HL, DE
.__mod16_sk:
    DEC A
    JR NZ, .__mod16_lp
    RET
`)
	}

	return sb.String()
}

// CodegenFunc runs the VIR solver on a single MIR2 function.
// Dual-mode strategy: solves with ABI constraints AND standalone (unconstrained).
// Currently prefers constrained; falls back to standalone when constrained fails.
// Logs potential savings from standalone+adapter for future optimization.
func CodegenFunc(f *mir2.Func, m *mir2.Module, opts SolverOptions) (string, error) {
	desc := Z80

	// Pre-lower MIR2 optimizations
	mir2.FuseAbsDiff(f) // SUB+CMP → SUB with carry reuse (4 insts vs 11)

	// Lower MIR2 → VIR
	vf, err := LowerFunc(f, desc, m)
	if err != nil {
		return "", fmt.Errorf("vir lower %s: %w", f.Name, err)
	}

	// Collect all ops for table lookup and GPU batch dump
	var allOps []VIROp
	for _, b := range vf.Blocks {
		allOps = append(allOps, b.Ops...)
	}

	// Dump GPU batch JSON if requested (for offline CUDA solve)
	if os.Getenv("VIR_DUMP_GPU_BATCH") != "" {
		if gf, nv, err := BuildGPUDesc(allOps, desc, opts); err == nil {
			sig := computeGPUSignature(allOps, desc)
			type batchEntry struct {
				Name string       `json:"name"`
				Sig  string       `json:"sig"`
				NV   int          `json:"nVregs"`
				Desc *GPUFuncDesc `json:"desc"`
			}
			jsonData, _ := json.Marshal(batchEntry{f.Name, sig, nv, gf})
			fmt.Fprintf(os.Stdout, "%s\n", jsonData)
		}
	}

	// Try precomputed regalloc table first (O(1) lookup, provably optimal).
	// Direct PIR emit — no Z3 needed. GPU assignment is the final answer.
	// Only use for functions where ABI constraints are satisfied by the table assignment.
	if table := GetRegAllocTable(); table.Size() > 0 {
		if assignment, cost, ok := table.Lookup(allOps, desc); ok {
			// Verify ABI compatibility: table assignment must match param/return constraints
			abiOK := verifyABICompat(allOps, assignment, opts)
			if abiOK {
				result, err := emitFromTable(f, vf, allOps, assignment, desc, opts)
				if err == nil {
					fmt.Fprintf(os.Stderr, "[vir] %s: table emit OK (cost=%d)\n", f.Name, cost)
					return result, nil
				}
				fmt.Fprintf(os.Stderr, "[vir] %s: table hit (cost=%d) but emit failed: %v\n", f.Name, cost, err)
			}
		}
	}

	// Skip dual-mode for trivial functions (extern stubs, empty bodies)
	trivial := len(vf.Blocks) == 0 || (len(vf.Blocks) == 1 && len(vf.Blocks[0].Ops) <= 1)
	if trivial {
		vfCopy := deepCopyFunc(vf)
		return codegenFuncCFG(f, vfCopy, desc, opts)
	}

	// Check if we have caller-imposed param constraints
	hasConstraints := false
	var callerParamLocs map[int]int
	if opts.FuncParamLocs != nil {
		if pl, ok := opts.FuncParamLocs[f.Name]; ok && len(pl) > 0 {
			hasConstraints = true
			callerParamLocs = pl
		}
	}

	// --- Mode 1: Constrained solve (ABI-compatible) ---
	var constASM string
	constRan := false
	var constErr error
	if hasConstraints {
		constRan = true
		vfConst := deepCopyFunc(vf)
		constASM, constErr = codegenFuncCFG(f, vfConst, desc, opts)
	}

	// --- Mode 2: Standalone solve (no param constraints) ---
	optsStand := opts
	optsStand.FuncParamLocs = nil
	optsStand.ParamLocs = nil
	vfStand := deepCopyFunc(vf)
	standParamLocs, standASM, standErr := codegenFuncCFGFull(f, vfStand, desc, optsStand)

	// --- Pick winner ---
	if constRan && constErr == nil && standErr == nil {
		constInsts := countASMInstructions(constASM)
		standInsts := countASMInstructions(standASM)

		// Compute real adapter cost: only count params where registers differ
		adapterCost := 0
		for vreg, callerPhys := range callerParamLocs {
			if standPhys, ok := standParamLocs[vreg]; ok && standPhys != callerPhys {
				adapterCost++
			}
		}

		if standInsts+adapterCost < constInsts {
			// Standalone wins — emit adapter moves at function entry
			adapted := emitAdapterEntry(standASM, f, callerParamLocs, standParamLocs, desc)
			fmt.Fprintf(os.Stderr, "[vir] %s: standalone+adapter wins (%d+%d=%d vs %d constrained, saved %d)\n",
				f.Name, standInsts, adapterCost, standInsts+adapterCost, constInsts,
				constInsts-(standInsts+adapterCost))
			return adapted, nil
		}
		return constASM, nil
	}

	// One mode succeeded
	if constRan && constErr == nil {
		return constASM, nil
	}
	if standErr == nil {
		if constRan && hasConstraints {
			// Check for adapter conflicts: if a move's destination is another param's
			// caller register, the adapter will clobber that param. In this case,
			// skip standalone+adapter and fall to per-block.
			adapterConflict := false
			callerRegsUsed := make(map[int]bool)
			for _, phys := range callerParamLocs {
				callerRegsUsed[phys] = true
			}
			for vreg, callerPhys := range callerParamLocs {
				standPhys, ok := standParamLocs[vreg]
				if ok && standPhys != callerPhys {
					// This move writes to standPhys. Is standPhys another param's caller reg?
					if callerRegsUsed[standPhys] {
						adapterConflict = true
						break
					}
				}
			}

			if adapterConflict {
				fmt.Fprintf(os.Stderr, "[vir] %s: adapter conflict, trying whole-function\n", f.Name)
			} else {
				adapterCost := 0
				for vreg, callerPhys := range callerParamLocs {
					if standPhys, ok := standParamLocs[vreg]; ok && standPhys != callerPhys {
						adapterCost++
					}
				}
				adapted := emitAdapterEntry(standASM, f, callerParamLocs, standParamLocs, desc)
				fmt.Fprintf(os.Stderr, "[vir] %s: constrained unsat, using standalone+adapter (%d adapters)\n",
					f.Name, adapterCost)
				return adapted, nil
			}
		} else {
			return standASM, nil
		}
	}

	// Both CFG solves failed — try whole-function solve (flattens all blocks)
	// First try with caller constraints (params in expected registers)
	vfWhole := deepCopyFunc(vf)
	wholeASM, wholeErr := codegenFuncWhole(f, vfWhole, desc, opts)
	if wholeErr == nil {
		fmt.Fprintf(os.Stderr, "[vir] %s: CFG unsat, whole-function solve OK (constrained)\n", f.Name)
		if os.Getenv("VIR_DEBUG_ASM") != "" {
			fmt.Fprintf(os.Stderr, "[DEBUG-ASM] %s:\n%s\n", f.Name, wholeASM)
		}
		return wholeASM, nil
	}
	// Then try standalone + adapter
	vfWhole2 := deepCopyFunc(vf)
	wholeASM, wholeErr = codegenFuncWhole(f, vfWhole2, desc, optsStand)
	if wholeErr == nil && !hasConstraints {
		adapted := emitAdapterEntry(wholeASM, f, callerParamLocs, standParamLocs, desc)
		fmt.Fprintf(os.Stderr, "[vir] %s: CFG unsat, whole-function standalone+adapter OK\n", f.Name)
		return adapted, nil
	} else if wholeErr == nil {
		fmt.Fprintf(os.Stderr, "[vir] %s: CFG unsat, whole-function standalone OK (no constraints)\n", f.Name)
		return wholeASM, nil
	}

	// Last resort: per-block fallback
	errMsg := standErr
	if constRan && constErr != nil {
		errMsg = constErr
	}
	fmt.Fprintf(os.Stderr, "[vir] %s: all solvers failed (%v), falling back to per-block\n", f.Name, errMsg)
	vfFallback := deepCopyFunc(vf)
	return codegenFuncPerBlock(f, vfFallback, desc, opts)
}

// resolveParallelMoves orders adapter moves to avoid clobbering.
// Uses topological sort; breaks cycles with EX DE,HL or temp via PUSH/POP.
type adapterMove struct {
	fromPhys, toPhys int
}

func resolveParallelMoves(moves []adapterMove, desc *MachineDesc) []string {

	if len(moves) <= 1 {
		var result []string
		for _, mv := range moves {
			result = append(result, emitRegMove(desc.Locs[mv.fromPhys], desc.Locs[mv.toPhys])...)
		}
		return result
	}

	// Build dependency graph: which destination registers are also sources?
	destIsSource := make(map[int]bool)
	for _, mv := range moves {
		destIsSource[mv.toPhys] = false
	}
	for _, mv := range moves {
		if _, ok := destIsSource[mv.fromPhys]; ok {
			destIsSource[mv.fromPhys] = true
		}
	}

	// Emit moves where the destination is NOT someone else's source first
	var result []string
	emitted := make(map[int]bool) // source index → done
	changed := true
	for changed {
		changed = false
		for i, mv := range moves {
			if emitted[i] {
				continue
			}
			// Check: is mv.toPhys used as source by any un-emitted move?
			blocked := false
			for j, other := range moves {
				if j != i && !emitted[j] && other.fromPhys == mv.toPhys {
					blocked = true
					break
				}
			}
			if !blocked {
				result = append(result, emitRegMove(desc.Locs[mv.fromPhys], desc.Locs[mv.toPhys])...)
				emitted[i] = true
				changed = true
			}
		}
	}

	// Any remaining moves form cycles — break with EX DE,HL or PUSH/POP
	for i, mv := range moves {
		if emitted[i] {
			continue
		}
		from := desc.Locs[mv.fromPhys]
		to := desc.Locs[mv.toPhys]
		// Try EX DE,HL for DE↔HL swap
		if (from.Name == "D" || from.Name == "E" || from.Name == "H" || from.Name == "L") &&
			(to.Name == "D" || to.Name == "E" || to.Name == "H" || to.Name == "L") {
			result = append(result, "EX DE, HL")
			// Mark all DE↔HL moves as done
			for j, other := range moves {
				if !emitted[j] {
					of := desc.Locs[other.fromPhys].Name
					ot := desc.Locs[other.toPhys].Name
					if (of == "D" || of == "E" || of == "H" || of == "L") &&
						(ot == "D" || ot == "E" || ot == "H" || ot == "L") {
						emitted[j] = true
					}
				}
			}
		} else {
			// Generic cycle break for 2-element cycle (swap):
			// Find the OTHER move in the cycle, emit as 3-move swap via temp.
			// For A↔C: LD B,A / LD A,C / LD C,B (using B as temp)
			var partner int = -1
			for j, other := range moves {
				if !emitted[j] && j != i && other.toPhys == mv.fromPhys {
					partner = j
					break
				}
			}
			if partner >= 0 {
				// 2-element swap via temp: A↔C → LD B,A / LD A,C / LD C,B
				tempLoc := -1
				for t := 0; t < 7; t++ {
					if t != mv.fromPhys && t != mv.toPhys {
						tempLoc = t
						break
					}
				}
				if tempLoc >= 0 {
					temp := desc.Locs[tempLoc].Name
					result = append(result,
						fmt.Sprintf("LD %s, %s", temp, from.Name),  // save first
						fmt.Sprintf("LD %s, %s", from.Name, to.Name), // move second → first
						fmt.Sprintf("LD %s, %s", to.Name, temp),   // restore first to second's old loc
					)
					emitted[i] = true
					emitted[partner] = true
				}
			}
			if !emitted[i] {
				// Fallback: PUSH/POP
				result = append(result, fmt.Sprintf("PUSH AF ; save %s", from.Name))
				result = append(result, emitRegMove(from, to)...)
				result = append(result, "POP AF")
				emitted[i] = true
			}
		}
	}

	return result
}

// emitAdapterEntry inserts LD moves after the function label to shuffle params
// from caller's convention (callerLocs) to standalone solver's convention (standLocs).
func emitAdapterEntry(asm string, f *mir2.Func, callerLocs, standLocs map[int]int, desc *MachineDesc) string {
	// Collect adapter moves needed (skip SP/F — not valid param locations)
	var moves []adapterMove
	for _, cp := range f.Contract.Params {
		vreg := int(cp.Reg)
		callerPhys, cOK := callerLocs[vreg]
		standPhys, sOK := standLocs[vreg]
		if cOK && sOK && callerPhys != standPhys {
			// Skip SP (index 10) and F (index 13) — not valid param registers
			if callerPhys < len(desc.Locs) && (desc.Locs[callerPhys].Name == "SP" || desc.Locs[callerPhys].Name == "F") {
				continue
			}
			if standPhys < len(desc.Locs) && (desc.Locs[standPhys].Name == "SP" || desc.Locs[standPhys].Name == "F") {
				continue
			}
			moves = append(moves, adapterMove{callerPhys, standPhys})
		}
	}
	if len(moves) == 0 {
		return asm
	}

	// Resolve parallel moves: topological sort to avoid clobbering.
	// If move B writes to a register that move A reads from, do A first.
	// For cycles (A→B, B→A): use a temp register or PUSH/POP.
	resolved := resolveParallelMoves(moves, desc)

	var adapter strings.Builder
	adapter.WriteString("    ; adapter: caller→standalone convention\n")
	for _, inst := range resolved {
		adapter.WriteString("    " + inst + "\n")
	}

	// Insert after function label line (funcname:)
	lines := strings.SplitN(asm, "\n", -1)
	var result strings.Builder
	inserted := false
	for _, line := range lines {
		result.WriteString(line)
		result.WriteByte('\n')
		if !inserted && strings.HasSuffix(strings.TrimSpace(line), ":") &&
			!strings.HasPrefix(strings.TrimSpace(line), ";") &&
			!strings.HasPrefix(strings.TrimSpace(line), ".") {
			// This is the function label — insert adapters after it
			result.WriteString(adapter.String())
			inserted = true
		}
	}
	return result.String()
}

// emitRegMove generates Z80 instructions to move a value between physical locations.
// Handles 8→8, 16→16, 8→IXH/IXL, and cross-width cases.
func emitRegMove(from, to Loc) []string {
	// Same register — no move needed
	if from.Name == to.Name {
		return nil
	}

	// 8-bit → 8-bit GPR: LD dst, src
	if from.Width == 8 && to.Width == 8 {
		// Z80 DD-prefix limitation: LD IXH/IXL, H/L is not encodable
		// (DD prefix replaces H→IXH, L→IXL in the opcode).
		// Route through A as intermediate.
		isIXY := to.Name == "IXH" || to.Name == "IXL" || to.Name == "IYH" || to.Name == "IYL"
		isHL := from.Name == "H" || from.Name == "L"
		if isIXY && isHL {
			return []string{
				fmt.Sprintf("LD A, %s", from.Name),
				fmt.Sprintf("LD %s, A", to.Name),
			}
		}
		return []string{fmt.Sprintf("LD %s, %s", to.Name, from.Name)}
	}

	// 16-bit pair → 16-bit pair
	if from.Width == 16 && to.Width == 16 {
		// Special case: HL↔DE can use EX DE, HL
		if (from.Name == "HL" && to.Name == "DE") || (from.Name == "DE" && to.Name == "HL") {
			return []string{"EX DE, HL"}
		}
		// Special case: LD SP, HL (opcode F9) — POP SP doesn't exist
		if to.Name == "SP" && from.Name == "HL" {
			return []string{"LD SP, HL"}
		}
		// SP as source or dest with non-HL: route through HL
		if to.Name == "SP" {
			return []string{
				fmt.Sprintf("PUSH %s", from.Name),
				"POP HL",
				"LD SP, HL",
			}
		}
		if from.Name == "SP" {
			// No direct LD rr, SP on Z80. Use ADD HL,SP trick or memory.
			// Simplest: LD HL, 0 / ADD HL, SP / PUSH HL / POP dst
			return []string{
				"LD HL, 0",
				"ADD HL, SP",
				fmt.Sprintf("PUSH HL"),
				fmt.Sprintf("POP %s", to.Name),
			}
		}
		// General: PUSH src / POP dst (works for AF, BC, DE, HL, IX, IY)
		return []string{
			fmt.Sprintf("PUSH %s", from.Name),
			fmt.Sprintf("POP %s", to.Name),
		}
	}

	// 8-bit → 16-bit: zero-extend (LD toL, src / LD toH, 0)
	if from.Width == 8 && to.Width == 16 {
		lo, hi := pairHalves(to.Name)
		return []string{
			fmt.Sprintf("LD %s, %s", lo, from.Name),
			fmt.Sprintf("LD %s, 0", hi),
		}
	}

	// 16-bit → 8-bit: truncate (LD dst, srcL)
	if from.Width == 16 && to.Width == 8 {
		lo, _ := pairHalves(from.Name)
		// DD-prefix limitation: LD IXH/IXL, H/L not encodable
		isIXYDst := to.Name == "IXH" || to.Name == "IXL" || to.Name == "IYH" || to.Name == "IYL"
		isHLSrc := lo == "H" || lo == "L"
		if isIXYDst && isHLSrc {
			return []string{
				fmt.Sprintf("LD A, %s", lo),
				fmt.Sprintf("LD %s, A", to.Name),
			}
		}
		return []string{fmt.Sprintf("LD %s, %s", to.Name, lo)}
	}

	// Fallback: try direct LD (may work for IXH/IXL etc)
	return []string{fmt.Sprintf("LD %s, %s", to.Name, from.Name)}
}

// pairHalves returns (low, high) register names for a 16-bit pair.
// pairHalvesASM returns (high, low) for PUSH/POP pairs. Returns ("","") for AF/SP.
func pairHalvesASM(pair string) (string, string) {
	switch pair {
	case "BC":
		return "B", "C"
	case "DE":
		return "D", "E"
	case "HL":
		return "H", "L"
	case "IX":
		return "IXH", "IXL"
	case "IY":
		return "IYH", "IYL"
	default:
		return "", "" // AF, SP — can't decompose
	}
}

func pairHalves(pair string) (string, string) {
	switch pair {
	case "BC":
		return "C", "B"
	case "DE":
		return "E", "D"
	case "HL":
		return "L", "H"
	case "IX":
		return "IXL", "IXH"
	case "IY":
		return "IYL", "IYH"
	default:
		return pair, pair
	}
}

// countASMInstructions counts Z80 instructions in assembly text (excluding
// comments, labels, and directives).
func countASMInstructions(asm string) int {
	count := 0
	for _, line := range strings.Split(asm, "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, ";") || strings.HasSuffix(line, ":") {
			continue
		}
		if strings.HasPrefix(line, ".") && strings.Contains(line, ":") {
			continue // local label like .func_block1:
		}
		count++
	}
	return count
}

// emitFuncHeader writes the ABI annotation comment for a function.
// Format: ; fun name(p1: type = REG, ...) -> type = REG ; clobbers: REG, ...
func emitFuncHeader(sb *strings.Builder, f *mir2.Func, opts SolverOptions) {
	sb.WriteString("; fun " + f.Name + "(")
	for i, p := range f.Contract.Params {
		if i > 0 {
			sb.WriteString(", ")
		}
		tyName := "u8"
		if p.Ty != nil {
			if p.Ty.Width() > 8 {
				tyName = "u16"
			}
		}
		regName := p.Class.String()
		// Use PBQP allocation if available
		if opts.FuncParamLocs != nil {
			if pl, ok := opts.FuncParamLocs[f.Name]; ok {
				if phys, ok2 := pl[int(p.Reg)]; ok2 && phys < len(Z80.Locs) {
					regName = Z80.Locs[phys].Name
				}
			}
		}
		sb.WriteString(fmt.Sprintf("%s: %s = %s", p.Name, tyName, regName))
	}
	sb.WriteString(")")
	if len(f.Contract.Returns) > 0 {
		r := f.Contract.Returns[0]
		retReg := "A"
		if r.Ty != nil && r.Ty.Width() > 8 {
			retReg = "HL"
		}
		tyName := "u8"
		if r.Ty != nil && r.Ty.Width() > 8 {
			tyName = "u16"
		}
		sb.WriteString(fmt.Sprintf(" -> %s = %s", tyName, retReg))
	}
	sb.WriteString(" ; clobbers: F\n")
}

// deepCopyFunc creates a deep copy of a VIR Func to avoid stale mutations.
func deepCopyFunc(vf *Func) *Func {
	cp := &Func{Name: vf.Name}
	for _, b := range vf.Blocks {
		ops := make([]VIROp, len(b.Ops))
		for i, op := range b.Ops {
			ops[i] = op
			// Reset hints to prevent stale mutations from previous runs
			ops[i].SrcHint = [2]LocSet{}
		}
		params := make([]int, len(b.Params))
		copy(params, b.Params)
		cp.Blocks = append(cp.Blocks, Block{Label: b.Label, Ops: ops, Params: params})
	}
	return cp
}

// codegenFuncCFG uses the CFG-aware solver: per-block variables with edge constraints.
func codegenFuncCFG(f *mir2.Func, vf *Func, desc *MachineDesc, opts SolverOptions) (string, error) {
	_, asm, err := codegenFuncCFGFull(f, vf, desc, opts)
	return asm, err
}

// codegenFuncCFGFull returns param register assignments + assembly.
func codegenFuncCFGFull(f *mir2.Func, vf *Func, desc *MachineDesc, opts SolverOptions) (map[int]int, string, error) {
	sol, err := SolveCFGFull(vf, f, desc, opts)
	if err != nil {
		return nil, "", err
	}

	// Emit assembly
	var sb strings.Builder
	emitFuncHeader(&sb, f, opts)
	sb.WriteString(f.Name + ":\n")

	for bi, block := range vf.Blocks {
		label := block.Label
		if bi > 0 && label != "" {
			sb.WriteString("." + f.Name + "_" + label + ":\n")
		}

		pirOps := sol.BlockPIR[label]
		for _, p := range pirOps {
			line := p.Emit(desc)
			if !isSelfMove(line) {
				emitLine(&sb, line)
			}
		}

		if bi < len(f.Blocks) {
			emitTerminator(&sb, f.Blocks[bi], f.Name)
		}
	}

	return sol.ParamLocs, peepholeCleanup(sb.String()), nil
}

// codegenFuncWhole solves ALL blocks of a function in one Z3 query.
// Cross-block register state is handled automatically via per-instruction variables.
func codegenFuncWhole(f *mir2.Func, vf *Func, desc *MachineDesc, opts SolverOptions) (string, error) {
	// Flatten all blocks into one VIROp sequence, tracking block boundaries
	var allOps []VIROp
	type blockRange struct {
		label string
		start int
		end   int
	}
	var ranges []blockRange

	// Seed param locations from PBQP (if available)
	paramHints := make(map[int]int) // vreg → phys
	if opts.FuncParamLocs != nil {
		if pl, ok := opts.FuncParamLocs[f.Name]; ok {
			for v, p := range pl {
				paramHints[v] = p
			}
		}
	}
	for v, p := range opts.ParamLocs {
		if _, ok := paramHints[v]; !ok {
			paramHints[v] = p
		}
	}

	// Apply param SrcHints to first block's ops
	for bi, block := range vf.Blocks {
		start := len(allOps)

		if bi == 0 && len(paramHints) > 0 {
			for i := range block.Ops {
				for j, s := range block.Ops[i].Src {
					if s > 0 {
						if phys, ok := paramHints[s]; ok {
							block.Ops[i].SrcHint[j] = Singleton(phys)
						}
					}
				}
			}
		}

		allOps = append(allOps, block.Ops...)
		ranges = append(ranges, blockRange{block.Label, start, len(allOps)})
	}

	if len(allOps) == 0 {
		// Empty function
		var sb strings.Builder
		sb.WriteString(fmt.Sprintf("; %s — VIR codegen\n", f.Name))
		sb.WriteString(f.Name + ":\n    RET\n")
		return sb.String(), nil
	}

	// Solve entire function as one block
	pirOps, err := Solve(allOps, desc, opts)
	if err != nil {
		return "", err
	}

	// Simplest approach: emit ALL PIROps as one flat sequence,
	// with block labels and terminators injected based on block boundaries.
	var sb strings.Builder
	sb.WriteString(fmt.Sprintf("; %s — VIR codegen\n", f.Name))
	sb.WriteString(f.Name + ":\n")

	// Emit all PIROps (the solver handled cross-block register state)
	for _, p := range pirOps {
		line := p.Emit(desc)
		if !isSelfMove(line) {
			emitLine(&sb, line)
		}
	}

	// Now emit terminators for ALL blocks
	// The terminators provide control flow (JR/JP/RET) between blocks.
	// They reference block labels which we emit as well.
	for bi, br := range ranges {
		if bi > 0 && br.label != "" {
			// Insert label — but where? The flat PIR already has the instructions.
			// We need labels BEFORE the block's instructions.
			// This flat approach can't easily insert labels mid-stream.
			// Use a different strategy: just emit terminators at the end.
			_ = br
		}
		if bi < len(f.Blocks) {
			_ = f.Blocks[bi] // terminator
		}
	}

	// Actually: the flat approach without labels won't work for branching.
	// Fall back to per-block emission with the whole-function PIROps.
	// We know the original VIROp count per block, and PIROps include
	// inserted moves. Let's emit block-by-block using a PIROp cursor.
	sb.Reset()
	sb.WriteString(fmt.Sprintf("; %s — VIR codegen\n", f.Name))
	sb.WriteString(f.Name + ":\n")

	// Simple heuristic: the number of PIROps per block equals
	// original ops + (PIROps total - original ops total) distributed.
	// Since most moves are for the block that needs them, we can
	// just emit ALL PIROps first, then all labels+terminators.
	// But this doesn't work for branching.

	// Best approach: reconstruct block structure from the flat PIR.
	// Use the original op count as guide, emit extra PIROps with the
	// block they belong to.

	pirCursor := 0
	for bi, br := range ranges {
		if bi > 0 && br.label != "" {
			sb.WriteString("." + f.Name + "_" + br.label + ":\n")
		}

		blockOrigOps := br.end - br.start
		// Emit PIROps: each original op may have 0-2 move PIROps before it
		for k := 0; k < blockOrigOps && pirCursor < len(pirOps); {
			p := pirOps[pirCursor]
			line := p.Emit(desc)
			if !isSelfMove(line) {
				emitLine(&sb, line)
			}
			pirCursor++

			// Count: if this PIROp matches a non-move original op, advance k
			if p.Pat != nil && p.Pat.Op != OpMove {
				k++
			} else if p.Pat != nil && p.Pat.Op == OpMove {
				// Check if the original op at this position was also a move
				origOpIdx := br.start + k
				if origOpIdx < len(allOps) && allOps[origOpIdx].Op == OpMove {
					k++ // original move, advance
				}
				// else: inserted move, don't advance k
			}
		}

		if bi < len(f.Blocks) {
			emitTerminator(&sb, f.Blocks[bi], f.Name)
		}
	}

	// Emit any remaining PIROps (shouldn't happen normally)
	for pirCursor < len(pirOps) {
		line := pirOps[pirCursor].Emit(desc)
		if !isSelfMove(line) {
			emitLine(&sb, line)
		}
		pirCursor++
	}

	return peepholeCleanup(sb.String()), nil
}

// codegenFuncPerBlock is the original per-block solver (fallback).
func codegenFuncPerBlock(f *mir2.Func, vf *Func, desc *MachineDesc, opts SolverOptions) (string, error) {

	var sb strings.Builder

	// Function header with ABI annotation
	emitFuncHeader(&sb, f, opts)
	sb.WriteString(f.Name + ":\n")

	// Track vreg → physical register across blocks.
	// Seed with ParamLocs from PBQP allocation (if available).
	vregPhys := make(map[int]int)
	// Per-function param locs (priority)
	if opts.FuncParamLocs != nil {
		if pl, ok := opts.FuncParamLocs[f.Name]; ok {
			for vreg, phys := range pl {
				vregPhys[vreg] = phys
			}
		}
	}
	// Global param locs (fallback)
	for vreg, phys := range opts.ParamLocs {
		if _, ok := vregPhys[vreg]; !ok {
			vregPhys[vreg] = phys
		}
	}

	// Process each block — emit PIROps + terminator
	for bi, block := range vf.Blocks {
		// Block label (prefix with function name for uniqueness)
		label := block.Label
		if bi == 0 {
			// First block = function entry, label already emitted
		} else if label != "" {
			sb.WriteString("." + f.Name + "_" + label + ":\n")
		}

		// For non-entry blocks: apply known vreg locations as SrcHint
		// so the solver knows where cross-block vregs live.
		// Cross-block register awareness:
		if len(vregPhys) > 0 {
			if bi == 0 {
				// Entry block: hard SrcHint on ALL ops (params MUST match ABI)
				for i := range block.Ops {
					for j, s := range block.Ops[i].Src {
						if s > 0 {
							if phys, ok := vregPhys[s]; ok {
								block.Ops[i].SrcHint[j] = Singleton(phys)
							}
						}
					}
				}
			} else {
				// Non-entry blocks: inject pin moves at block start.
				// Each pin defines where a cross-block vreg lives.
				// The per-instruction solver can then insert moves as needed.
				var pins []VIROp
				pinMap := make(map[int]int) // original vreg → pin vreg
				nextPin := 8500

				// Collect cross-block vregs used in this block
				used := make(map[int]bool)
				for _, op := range block.Ops {
					for _, s := range op.Src {
						if s > 0 { used[s] = true }
					}
				}

				for vreg := range used {
					phys, ok := vregPhys[vreg]
					if !ok { continue }
					// Skip if vreg is defined in this block
					definedHere := false
					for _, op := range block.Ops {
						if op.Dst == vreg { definedHere = true; break }
					}
					if definedHere { continue }

					pinReg := nextPin
					nextPin++
					pinMap[vreg] = pinReg

					// Pin: "pinReg lives in phys register, loaded from vreg"
					w := 8
					for _, op := range block.Ops {
						for _, s := range op.Src {
							if s == vreg && op.Width > 0 { w = op.Width }
						}
					}
					// Pin: source vreg is in phys (hard SrcHint).
				// Destination is UNCONSTRAINED — solver picks optimal register.
				// Per-inst solver can then move from phys to wherever needed.
				pins = append(pins, VIROp{
						Op: OpMove, Dst: pinReg,
						Src: [2]int{vreg, -1}, Width: w,
						SrcHint: [2]LocSet{Singleton(phys)},
						// No DstHint — let solver freely place the pin
					})
				}

				// Rewrite block ops: replace cross-block vregs with pin vregs
				if len(pins) > 0 {
					for i := range block.Ops {
						for j, s := range block.Ops[i].Src {
							if pin, ok := pinMap[s]; ok {
								block.Ops[i].Src[j] = pin
							}
						}
					}
					block.Ops = append(pins, block.Ops...)
				}
			}
		}

		// Solve block ops
		if len(block.Ops) > 0 {
			pirOps, err := Solve(block.Ops, desc, opts)
			if err != nil {
				return "", fmt.Errorf("vir solve %s/%s: %w", f.Name, block.Label, err)
			}

			// Record vreg → physical register from solution.
			// DON'T overwrite PBQP param locations — those are the ABI truth.
			paramVRegs := make(map[int]bool)
			if opts.FuncParamLocs != nil {
				if pl, ok := opts.FuncParamLocs[f.Name]; ok {
					for v := range pl { paramVRegs[v] = true }
				}
			}
			for v := range opts.ParamLocs { paramVRegs[v] = true }

			for k, p := range pirOps {
				if k < len(block.Ops) {
					op := block.Ops[k]
					if op.Dst > 0 && p.DstPhys >= 0 && !paramVRegs[op.Dst] {
						vregPhys[op.Dst] = p.DstPhys
					}
					for j, s := range op.Src {
						if s > 0 && p.SrcPhys[j] >= 0 && !paramVRegs[s] {
							vregPhys[s] = p.SrcPhys[j]
						}
					}
				}
			}

			for _, p := range pirOps {
				line := p.Emit(desc)
				if isSelfMove(line) {
					continue
				}
				emitLine(&sb, line)
			}
		}

		// Emit terminator (control flow between blocks)
		if bi < len(f.Blocks) {
			mir2Block := f.Blocks[bi]
			emitTerminator(&sb, mir2Block, f.Name)
		}
	}

	// Apply peephole cleanup (PUSH/POP, fallthrough, LD A,0→XOR A, etc.)
	return peepholeCleanup(sb.String()), nil
}

// emitLine writes one or more assembly lines (handles multi-line templates).
func emitLine(sb *strings.Builder, line string) {
	if line == "" {
		return
	}
	for _, subline := range strings.Split(line, "\n") {
		subline = strings.TrimSpace(subline)
		if subline != "" {
			sb.WriteString("    " + subline + "\n")
		}
	}
}

// validateNoClobber detects Z3 interference bugs where a 16-bit load is
// overwritten before being used (e.g., LD HL,(db) then LD H,D / LD L,E).
// Tracks 16-bit pair loads and flags if the pair is overwritten by half-reg
// writes before a CALL/JP/JR that would consume the value.
// Returns error description or "" if clean.
func validateNoClobber(asm string) string {
	lines := strings.Split(asm, "\n")
	hlFromMem := false
	hRead := false // H value was consumed (LD r, H)
	lRead := false // L value was consumed (LD r, L)

	for i := 0; i < len(lines); i++ {
		line := strings.TrimSpace(lines[i])

		// Reset tracking on labels, branches, returns, comments, blanks
		if strings.HasSuffix(line, ":") || strings.HasPrefix(line, "JR ") ||
			strings.HasPrefix(line, "JP ") || line == "RET" ||
			strings.HasPrefix(line, ";") || line == "" {
			hlFromMem = false
			hRead = false
			lRead = false
			continue
		}

		// LD HL, (addr) — 16-bit load from memory
		if strings.HasPrefix(line, "LD HL, (") && !strings.HasPrefix(line, "LD HL, (HL)") {
			hlFromMem = true
			hRead = false
			lRead = false
			continue
		}

		if hlFromMem {
			// HL consumed as whole: CALL, PUSH HL, ADD HL, LD (addr), EX DE, etc.
			if strings.HasPrefix(line, "CALL ") || strings.HasPrefix(line, "JP ") ||
				strings.HasPrefix(line, "ADD HL") || strings.HasPrefix(line, "PUSH HL") ||
				strings.HasPrefix(line, "LD (") || line == "RET" ||
				strings.HasPrefix(line, "EX DE") || strings.HasPrefix(line, "SBC HL") {
				hlFromMem = false
				continue
			}

			// Track reads of H and L individually
			if strings.HasPrefix(line, "LD ") && !strings.HasPrefix(line, "LD H,") && !strings.HasPrefix(line, "LD L,") {
				if strings.HasSuffix(line, ", H") {
					hRead = true
				}
				if strings.HasSuffix(line, ", L") {
					lRead = true
				}
			}

			// Both halves consumed → HL fully used, stop tracking
			if hRead && lRead {
				hlFromMem = false
				continue
			}

			// Write to H or L: clobber only if NEITHER half was consumed yet.
			// Once either half is read (LD r, H or LD r, L), the code is
			// decomposing HL into separate bytes — writing the other half
			// is building a new value, not clobbering the 16-bit load.
			if strings.HasPrefix(line, "LD H, ") || strings.HasPrefix(line, "LD L, ") {
				if !hRead && !lRead {
					return fmt.Sprintf("16-bit HL load clobbered before use at: %s", line)
				}
			}
		}
	}
	return ""
}

// emitFromTable generates assembly directly from a GPU table assignment.
// No Z3 solver needed — just pattern selection + PIR emit.
func emitFromTable(f *mir2.Func, vf *Func, allOps []VIROp, assignment map[int]int, desc *MachineDesc, opts SolverOptions) (string, error) {
	var sb strings.Builder
	emitFuncHeader(&sb, f, opts)
	sb.WriteString(f.Name + ":\n")

	opIdx := 0
	for bi, block := range vf.Blocks {
		label := block.Label
		if bi > 0 && label != "" {
			sb.WriteString("." + f.Name + "_" + label + ":\n")
		}

		for _, op := range block.Ops {
			if opIdx >= len(allOps) {
				break
			}

			// Inline asm: emit verbatim
			if op.Op == OpAsmBlock {
				pir := PIROp{AsmText: op.AsmTemplate}
				emitLine(&sb, pir.Emit(desc))
				opIdx++
				continue
			}

			// Find the cheapest pattern that matches this op AND the GPU assignment
			dstPhys := -1
			if op.Dst > 0 {
				if loc, ok := assignment[op.Dst]; ok {
					dstPhys = loc
				}
			}
			var srcPhys [2]int
			srcPhys[0] = -1
			srcPhys[1] = -1
			for j, s := range op.Src {
				if s > 0 {
					if loc, ok := assignment[s]; ok {
						srcPhys[j] = loc
					}
				}
			}

			pat := findBestPattern(op, dstPhys, srcPhys, desc)
			if pat == nil {
				return "", fmt.Errorf("no pattern for op %d (%v) dst=%d src=%v", opIdx, op.Op, dstPhys, srcPhys)
			}

			pir := PIROp{
				Pat:     pat,
				DstPhys: dstPhys,
				SrcPhys: srcPhys,
				Imm:     op.Imm,
				Sym:     op.Sym,
			}

			line := pir.Emit(desc)
			if !isSelfMove(line) {
				emitLine(&sb, line)
			}
			opIdx++
		}

		if bi < len(f.Blocks) {
			emitTerminator(&sb, f.Blocks[bi], f.Name)
		}
	}

	return peepholeCleanup(sb.String()), nil
}

// verifyABICompat checks if a GPU table assignment is compatible with ABI constraints.
// ParamLocs from PFCCO must match the table assignment for constrained vregs.
func verifyABICompat(ops []VIROp, assignment map[int]int, opts SolverOptions) bool {
	// Check param constraints
	paramLocs := opts.ParamLocs
	if paramLocs == nil && opts.FuncParamLocs != nil {
		// FuncParamLocs checked later — for now just allow
	}
	for vreg, requiredLoc := range paramLocs {
		if tableLoc, ok := assignment[vreg]; ok {
			if tableLoc != requiredLoc {
				return false // table puts vreg at wrong loc for ABI
			}
		}
	}
	// Check DstHint/SrcHint constraints from ops
	for _, op := range ops {
		if op.Dst > 0 && !op.DstHint.IsEmpty() {
			if loc, ok := assignment[op.Dst]; ok {
				if !op.DstHint.Has(loc) {
					return false
				}
			}
		}
	}
	return true
}

// findBestPattern finds the cheapest pattern matching an op with given physical locs.
func findBestPattern(op VIROp, dstPhys int, srcPhys [2]int, desc *MachineDesc) *Pattern {
	var best *Pattern
	bestCost := 1<<30

	for i := range desc.Patterns {
		pat := &desc.Patterns[i]
		if !pat.Matches(op) {
			continue
		}
		// Check dst loc is in pattern's allowed set
		if dstPhys >= 0 && !pat.DstLocs.IsEmpty() && !pat.DstLocs.Has(dstPhys) {
			continue
		}
		// Check src0 loc
		if srcPhys[0] >= 0 && !pat.SrcLocs[0].IsEmpty() && !pat.SrcLocs[0].Has(srcPhys[0]) {
			continue
		}
		// Check src1 loc
		if srcPhys[1] >= 0 && !pat.SrcLocs[1].IsEmpty() && !pat.SrcLocs[1].Has(srcPhys[1]) {
			continue
		}
		// Tied constraint: dst must equal src0
		if pat.TiedDstSrc && dstPhys >= 0 && srcPhys[0] >= 0 && dstPhys != srcPhys[0] {
			continue
		}
		if pat.Cost < bestCost {
			best = pat
			bestCost = pat.Cost
		}
	}
	return best
}

// emitTerminator generates Z80 control flow instructions for a MIR2 block terminator.
func emitTerminator(sb *strings.Builder, b *mir2.Block, funcName string) {
	if b.Term == nil {
		return
	}
	prefix := "." + funcName + "_"

	switch t := b.Term.(type) {
	case *mir2.TermRet:
		sb.WriteString("    RET\n")

	case *mir2.TermJmp:
		sb.WriteString(fmt.Sprintf("    JP %s%s\n", prefix, t.Target))

	case *mir2.TermBrIf:
		// Find the CMP that defined the condition vreg to determine flag semantics
		cmpCond := findCmpCond(b, t.Cond)
		elseLabel := prefix + t.Else

		// Emit branch based on comparison kind:
		// CP sets Z (equal) and C (a < b unsigned)
		switch cmpCond {
		case mir2.CmpUgt: // a > b: skip to else if Z or C
			sb.WriteString(fmt.Sprintf("    JR Z, %s\n", elseLabel))
			sb.WriteString(fmt.Sprintf("    JR C, %s\n", elseLabel))
			// fall through = then (a > b)
		case mir2.CmpUlt: // a < b: skip to else if NC (a >= b)
			sb.WriteString(fmt.Sprintf("    JR NC, %s\n", elseLabel))
			// fall through = then (a < b, C set)
		case mir2.CmpUge: // a >= b: skip to else if C (a < b)
			sb.WriteString(fmt.Sprintf("    JR C, %s\n", elseLabel))
		case mir2.CmpUle: // a <= b: skip to else if not Z and NC
			sb.WriteString(fmt.Sprintf("    JR Z, %s%s\n", prefix, t.Then))
			sb.WriteString(fmt.Sprintf("    JR NC, %s\n", elseLabel))
		case mir2.CmpEq: // a == b
			sb.WriteString(fmt.Sprintf("    JR NZ, %s\n", elseLabel))
		case mir2.CmpNe: // a != b
			sb.WriteString(fmt.Sprintf("    JR Z, %s\n", elseLabel))
		case mir2.CmpSubCarry: // carry set by preceding SUB means a < b
			sb.WriteString(fmt.Sprintf("    JR NC, %s\n", elseLabel))
			// fall through = then (a < b, carry set)
		case mir2.CmpSubCarryNot: // no carry means a >= b
			sb.WriteString(fmt.Sprintf("    JR C, %s\n", elseLabel))
		default:
			// Generic: treat as NZ (bool condition)
			sb.WriteString(fmt.Sprintf("    JR NZ, %s%s\n", prefix, t.Then))
			if t.Else != "" {
				sb.WriteString(fmt.Sprintf("    JP %s\n", elseLabel))
			}
			return
		}
		// Fall-through to Then block (or explicit jump if blocks aren't adjacent)
		sb.WriteString(fmt.Sprintf("    JP %s%s\n", prefix, t.Then))

	case *mir2.TermBrIf2:
		// Two-way branch based on comparison result
		// Lhs vs Rhs already compared, flags set
		if t.Eq != "" && t.Lt == "" && t.Gt == "" {
			// Simple equality check
			sb.WriteString(fmt.Sprintf("    JR Z, %s%s\n", prefix, t.Eq))
		} else {
			// Full three-way
			if t.Eq != "" {
				sb.WriteString(fmt.Sprintf("    JR Z, %s%s\n", prefix, t.Eq))
			}
			if t.Lt != "" {
				sb.WriteString(fmt.Sprintf("    JR C, %s%s\n", prefix, t.Lt))
			}
			if t.Gt != "" {
				sb.WriteString(fmt.Sprintf("    JP %s%s\n", prefix, t.Gt))
			}
		}

	case *mir2.TermDJNZ:
		sb.WriteString(fmt.Sprintf("    DJNZ %s%s\n", prefix, t.Body))
		if t.Exit != "" {
			sb.WriteString(fmt.Sprintf("    JP %s%s\n", prefix, t.Exit))
		}

	case *mir2.TermCondRet:
		// If cond==0, return vals. Else jump to Then.
		cmpCond := findCmpCond(b, t.Cond)
		if t.Then != "" {
			switch cmpCond {
			case mir2.CmpSubCarry:
				// Carry set by preceding SUB means a < b → RET NC (return if a >= b)
				sb.WriteString(fmt.Sprintf("    JR C, %s%s\n", prefix, t.Then))
			case mir2.CmpSubCarryNot:
				sb.WriteString(fmt.Sprintf("    JR NC, %s%s\n", prefix, t.Then))
			default:
				// Generic: Z flag = equal/zero → jump when NZ
				sb.WriteString(fmt.Sprintf("    JR NZ, %s%s\n", prefix, t.Then))
			}
		}
		sb.WriteString("    RET\n")

	case *mir2.TermUnreachable:
		sb.WriteString("    ; unreachable\n")
	}
}

// findCmpCond looks up the CmpCond of the OpCmp instruction that defines
// the given condition vreg. Returns -1 if not found.
func findCmpCond(b *mir2.Block, condReg mir2.Reg) mir2.CmpCond {
	for i := len(b.Insts) - 1; i >= 0; i-- {
		inst := b.Insts[i]
		if inst.Op == mir2.OpCmp && inst.Dst == condReg {
			return inst.Cond
		}
	}
	return mir2.CmpCond(255) // not found
}

