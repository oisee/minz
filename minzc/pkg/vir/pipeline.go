// isSelfMove detects Z80 no-op moves that can be eliminated:
//   LD A, A    — register self-copy
//   PUSH HL / POP HL  — stack self-move (from coalescing artifacts)
//   ; trunc ... (alias) — zero-cost aliases (already no instruction)
func isSelfMove(line string) bool {
	line = strings.TrimSpace(line)
	if line == "" {
		return false
	}

	// LD r, r (self-copy): LD A, A / LD B, B / etc.
	if strings.HasPrefix(line, "LD ") {
		parts := strings.SplitN(line[3:], ", ", 2)
		if len(parts) == 2 && strings.TrimSpace(parts[0]) == strings.TrimSpace(parts[1]) {
			return true
		}
	}

	// PUSH r / POP r on consecutive lines (handled as multi-line template)
	if strings.HasPrefix(line, "PUSH ") {
		// Check if next part is POP with same register
		// Multi-line templates are split before reaching here, so check single lines
	}

	return false
}

// resolveBValue scans backwards through emitted ASM lines to determine the
// constant value in register B at the current point. Returns -1 if unknown.
// Handles: LD B, N (direct), LD B, r where r was set by LD r, N (one level of indirection).
func resolveBValue(lines []string) int {
	return resolveRegValue(lines, "B", 2) // max 2 levels of indirection
}

func resolveRegValue(lines []string, target string, depth int) int {
	if depth <= 0 {
		return -1
	}
	for i := len(lines) - 1; i >= 0; i-- {
		line := strings.TrimSpace(lines[i])
		if line == "" || strings.HasPrefix(line, ";") || strings.HasSuffix(line, ":") {
			continue
		}
		prefix := "LD " + target + ", "
		if strings.HasPrefix(line, prefix) {
			val := strings.TrimPrefix(line, prefix)
			if n, ok := parseSmallInt(val); ok {
				return n
			}
			// LD target, <reg> — recurse to resolve that register's value
			if len(val) == 1 && val[0] >= 'A' && val[0] <= 'L' {
				return resolveRegValue(lines[:i], val, depth-1)
			}
			return -1
		}
		// Any other instruction that writes target → stop (unknown)
		if writesReg(line, target) {
			return -1
		}
	}
	return -1
}

func parseSmallInt(s string) (int, bool) {
	n := 0
	for _, c := range s {
		if c < '0' || c > '9' { return 0, false }
		n = n*10 + int(c-'0')
	}
	if len(s) == 0 { return 0, false }
	return n, true
}

func writesReg(line, reg string) bool {
	// Instructions that write to a register: LD, INC, DEC, ADD, SUB, AND, OR, XOR, SRL, SLA, RR, RL, POP, etc.
	line = strings.TrimSpace(line)
	// LD reg, ...
	if strings.HasPrefix(line, "LD "+reg+", ") { return true }
	// INC/DEC reg
	if line == "INC "+reg || line == "DEC "+reg { return true }
	// POP BC writes B and C
	if reg == "B" && (line == "POP BC" || strings.HasPrefix(line, "POP BC")) { return true }
	// Any ALU op that targets A (if checking B, not relevant unless it's B)
	// For simplicity, conservatively return true for ops that could affect B
	if reg == "B" {
		if strings.HasPrefix(line, "SRL B") || strings.HasPrefix(line, "SLA B") ||
			strings.HasPrefix(line, "RR B") || strings.HasPrefix(line, "RL B") ||
			strings.HasPrefix(line, "RLC B") || strings.HasPrefix(line, "RRC B") {
			return true
		}
	}
	return false
}

// peepholeCleanup applies additional Z80 peephole optimizations.
// Inspired by SDCC's peephole rules (https://sdcc.sourceforge.net/).
func peepholeCleanup(asm string) string {
	lines := strings.Split(asm, "\n")
	var result []string
	inlineCounter := 0

	for i := 0; i < len(lines); i++ {
		line := strings.TrimSpace(lines[i])

		// PUSH rr / POP rr → remove both (self-move via stack)
		if i+1 < len(lines) && strings.HasPrefix(line, "PUSH ") {
			next := strings.TrimSpace(lines[i+1])
			reg := strings.TrimPrefix(line, "PUSH ")
			if next == "POP "+reg {
				i++ // skip both lines
				continue
			}
		}

		// JP label where label is the very next line → remove (fallthrough)
		if strings.HasPrefix(line, "JP ") {
			target := strings.TrimPrefix(line, "JP ")
			target = strings.TrimSpace(target)
			if i+1 < len(lines) {
				nextLine := strings.TrimSpace(lines[i+1])
				// Next line is "target:" label
				if nextLine == target+":" || nextLine == "."+target+":" {
					continue // skip redundant jump
				}
			}
		}

		// LD A, 0 → XOR A (1 byte shorter, faster)
		if line == "LD A, 0" {
			result = append(result, "    XOR A")
			continue
		}

		// CP 0 → OR A (sets Z flag same way, 1 byte shorter)
		if line == "CP 0" {
			result = append(result, "    OR A")
			continue
		}

		// ── Superoptimizer-derived rules (z80-optimizer/CUDA) ────────

		// CALL label / RET → JP label (tail call optimization, saves 1 byte + 17T)
		// Only for local labels (starting with .) — external function tail calls
		// are unsafe because the callee may expect params in _vir_mem locations
		// that the caller hasn't stored.
		if i+1 < len(lines) && strings.HasPrefix(line, "CALL ") {
			next := strings.TrimSpace(lines[i+1])
			if next == "RET" {
				target := strings.TrimPrefix(line, "CALL ")
				target = strings.TrimSpace(target)
				// Only tail-call to local labels (.funcname_block) or runtime (__mul8 etc)
				if strings.HasPrefix(target, ".") || strings.HasPrefix(target, "__") {
					result = append(result, "    JP "+target)
					i++ // skip RET
					continue
				}
			}
		}

		// Inline runtime calls — replace CALL __div8/mod8/mul8 with inline body.
		// Each instance gets a unique label suffix. Dedup'd in post-pass.

		// Specialization: divmod10 — GPU-discovered optimal sequence (124T, 27 insts).
		// Clobbers only B,C,F — HL/DE untouched! Verified for all 256 inputs.
		// Detect: B holds constant 10 before the CALL (direct LD B,10 or via LD B,r chain).
		if (strings.HasPrefix(line, "CALL __div8") || strings.HasPrefix(line, "JP __div8")) &&
			resolveBValue(result) == 10 {
			idx := inlineCounter
			inlineCounter++
			// divmod10 doesn't use B as input (divisor is baked in).
			// The LD B,10 before this is dead code — strip it if it's the last emitted line.
			if len(result) > 0 && strings.TrimSpace(result[len(result)-1]) == "LD B, 10" {
				result = result[:len(result)-1]
			}
			result = append(result,
				"    ; divmod10 (GPU-optimal, 124T)",
				"    LD C, A",       // save n
				"    SRL A",         // n >> 1
				"    LD B, A",       // B = n >> 1
				"    SRL A",         // n >> 2
				"    ADD A, B",      // (n>>1) + (n>>2) = q0
				"    LD B, A",
				"    RRA",           // ┐
				"    RRA",           // │ q0 >> 4 via RRA + mask
				"    RRA",           // │
				"    RRA",           // ┘
				"    AND 0x0F",       // mask to 4 bits
				"    ADD A, B",      // q0 + (q0 >> 4)
				"    RRA",           // ┐
				"    RRA",           // │ >> 3 via RRA + mask
				"    RRA",           // ┘
				"    AND 0x1F",       // quotient approximation
				"    LD B, A",       // B = quotient
				"    ADD A, A",      // ┐
				"    ADD A, A",      // │ ×10 = (q×4 + q) × 2
				"    ADD A, B",      // │
				"    ADD A, A",      // ┘
				"    SUB C",         // remainder = -(n - 10q)
				"    NEG",           // fix sign
				"    CP 10",         // correction needed?
				fmt.Sprintf("    JR C, .vir_div10_ok_%d", idx), // no → done
				"    SUB 10",        // yes → adjust remainder
				"    INC B",         // and quotient
				fmt.Sprintf(".vir_div10_ok_%d:", idx),
				"    LD A, B",       // A = quotient (matches __div8 ABI)
			)
			if i+1 < len(lines) {
				next := strings.TrimSpace(lines[i+1])
				if strings.HasPrefix(next, "LD A, ") && next != "LD A, B" {
					i++
				}
			}
			continue
		}
		if (strings.HasPrefix(line, "CALL __mod8") || strings.HasPrefix(line, "JP __mod8")) &&
			resolveBValue(result) == 10 {
			idx := inlineCounter
			inlineCounter++
			if len(result) > 0 && strings.TrimSpace(result[len(result)-1]) == "LD B, 10" {
				result = result[:len(result)-1]
			}
			result = append(result,
				"    ; modulo10 (GPU-optimal, 124T)",
				"    LD C, A",
				"    SRL A",
				"    LD B, A",
				"    SRL A",
				"    ADD A, B",
				"    LD B, A",
				"    RRA",
				"    RRA",
				"    RRA",
				"    RRA",
				"    AND 0x0F",
				"    ADD A, B",
				"    RRA",
				"    RRA",
				"    RRA",
				"    AND 0x1F",
				"    LD B, A",       // B = quotient (discarded for mod)
				"    ADD A, A",
				"    ADD A, A",
				"    ADD A, B",
				"    ADD A, A",
				"    SUB C",
				"    NEG",           // A = raw remainder
				"    CP 10",
				fmt.Sprintf("    JR C, .vir_mod10_ok_%d", idx),
				"    SUB 10",
				fmt.Sprintf(".vir_mod10_ok_%d:", idx),
				// A = n % 10 (mod result — no quotient fixup needed)
			)
			if i+1 < len(lines) {
				next := strings.TrimSpace(lines[i+1])
				if strings.HasPrefix(next, "LD A, ") { i++ }
			}
			continue
		}

		if strings.HasPrefix(line, "CALL __div8") || strings.HasPrefix(line, "JP __div8") {
			idx := inlineCounter
			inlineCounter++
			result = append(result,
				"    LD C, B",
				"    LD B, A",
				"    XOR A",
				"    LD D, 8",
				fmt.Sprintf(".vir_div8_%d:", idx),
				"    SLA B",
				"    RLA",
				"    CP C",
				fmt.Sprintf("    JR C, .vir_div8_sk_%d", idx),
				"    SUB C",
				"    INC B",
				fmt.Sprintf(".vir_div8_sk_%d:", idx),
				"    DEC D",
				fmt.Sprintf("    JR NZ, .vir_div8_%d", idx),
				"    LD A, B",  // A = quotient
			)
			// Skip subsequent LD A, r (return-move — result already in A)
			if i+1 < len(lines) {
				next := strings.TrimSpace(lines[i+1])
				if strings.HasPrefix(next, "LD A, ") && next != "LD A, B" {
					i++ // skip redundant return move
				}
			}
			continue
		}
		if strings.HasPrefix(line, "CALL __mod8") || strings.HasPrefix(line, "JP __mod8") {
			idx := inlineCounter
			inlineCounter++
			result = append(result,
				"    LD C, B",
				"    LD B, A",
				"    XOR A",
				"    LD D, 8",
				fmt.Sprintf(".vir_mod8_%d:", idx),
				"    SLA B",
				"    RLA",
				"    CP C",
				fmt.Sprintf("    JR C, .vir_mod8_sk_%d", idx),
				"    SUB C",
				"    INC B",
				fmt.Sprintf(".vir_mod8_sk_%d:", idx),
				"    DEC D",
				fmt.Sprintf("    JR NZ, .vir_mod8_%d", idx),
			)
			if i+1 < len(lines) {
				next := strings.TrimSpace(lines[i+1])
				if strings.HasPrefix(next, "LD A, ") { i++ }
			}
			continue
		}
		// Constant multiply optimization: if B holds a known constant K and
		// we have a GPU-optimal sequence for A×K→A, inline it directly.
		// Saves ~60T vs the general __mul8 loop (80T).
		if (strings.HasPrefix(line, "CALL __mul8") || strings.HasPrefix(line, "JP __mul8")) &&
			resolveBValue(result) > 0 {
			k := resolveBValue(result)
			mulTable := GetMulOptTable()
			if entry := mulTable.Lookup(k, false); entry != nil {
				// Strip the LD B, K (dead — constant is baked into the sequence)
				if len(result) > 0 && strings.TrimSpace(result[len(result)-1]) == fmt.Sprintf("LD B, %d", k) {
					result = result[:len(result)-1]
				}
				result = append(result, fmt.Sprintf("    ; mul×%d (GPU-optimal, %dT)", k, entry.TStates))
				for _, op := range entry.Ops {
					result = append(result, "    "+op)
				}
				if i+1 < len(lines) {
					next := strings.TrimSpace(lines[i+1])
					if strings.HasPrefix(next, "LD A, ") { i++ }
				}
				continue
			}
		}
		if strings.HasPrefix(line, "CALL __mul8") || strings.HasPrefix(line, "JP __mul8") {
			idx := inlineCounter
			inlineCounter++
			result = append(result,
				"    LD C, A",
				"    XOR A",
				"    LD D, 8",
				fmt.Sprintf(".vir_mul8_%d:", idx),
				"    SRL C",
				fmt.Sprintf("    JR NC, .vir_mul8_sk_%d", idx),
				"    ADD A, B",
				fmt.Sprintf(".vir_mul8_sk_%d:", idx),
				"    SLA B",
				"    DEC D",
				fmt.Sprintf("    JR NZ, .vir_mul8_%d", idx),
			)
			if i+1 < len(lines) {
				next := strings.TrimSpace(lines[i+1])
				if strings.HasPrefix(next, "LD A, ") { i++ }
			}
			continue
		}

		// Inline 16-bit runtime calls
		if strings.HasPrefix(line, "CALL __div16") || strings.HasPrefix(line, "JP __div16") {
			idx := inlineCounter
			inlineCounter++
			result = append(result,
				"    LD B, H",
				"    LD C, L",
				"    LD HL, 0",
				"    LD A, 16",
				fmt.Sprintf(".vir_div16_%d:", idx),
				"    SLA C",
				"    RL B",
				"    ADC HL, HL",
				"    SBC HL, DE",
				fmt.Sprintf("    JR NC, .vir_div16_sk_%d", idx),
				"    ADD HL, DE",
				fmt.Sprintf("    JR .vir_div16_ni_%d", idx),
				fmt.Sprintf(".vir_div16_sk_%d:", idx),
				"    INC C",
				fmt.Sprintf(".vir_div16_ni_%d:", idx),
				"    DEC A",
				fmt.Sprintf("    JR NZ, .vir_div16_%d", idx),
				"    EX DE, HL",   // DE = remainder
				"    LD H, B",     // HL = quotient
				"    LD L, C",
			)
			continue
		}
		if strings.HasPrefix(line, "CALL __mod16") || strings.HasPrefix(line, "JP __mod16") {
			idx := inlineCounter
			inlineCounter++
			result = append(result,
				"    LD B, H",
				"    LD C, L",
				"    LD HL, 0",
				"    LD A, 16",
				fmt.Sprintf(".vir_mod16_%d:", idx),
				"    SLA C",
				"    RL B",
				"    ADC HL, HL",
				"    SBC HL, DE",
				fmt.Sprintf("    JR NC, .vir_mod16_sk_%d", idx),
				"    ADD HL, DE",
				fmt.Sprintf(".vir_mod16_sk_%d:", idx),
				"    DEC A",
				fmt.Sprintf("    JR NZ, .vir_mod16_%d", idx),
			)
			continue
		}
		if strings.HasPrefix(line, "CALL __mul16") || strings.HasPrefix(line, "JP __mul16") {
			idx := inlineCounter
			inlineCounter++
			result = append(result,
				"    LD B, H",
				"    LD C, L",
				"    LD HL, 0",
				"    LD A, 16",
				fmt.Sprintf(".vir_mul16_%d:", idx),
				"    SRL B",
				"    RR C",
				fmt.Sprintf("    JR NC, .vir_mul16_sk_%d", idx),
				"    ADD HL, DE",
				fmt.Sprintf(".vir_mul16_sk_%d:", idx),
				"    SLA E",
				"    RL D",
				"    DEC A",
				fmt.Sprintf("    JR NZ, .vir_mul16_%d", idx),
			)
			continue
		}

		// LD r, r (self-move) — also catch at peephole level
		if strings.HasPrefix(line, "LD ") {
			parts := strings.SplitN(line[3:], ", ", 2)
			if len(parts) == 2 && strings.TrimSpace(parts[0]) == strings.TrimSpace(parts[1]) {
				continue // remove self-move
			}
		}

		// ADD A, 0 → remove (no effect, just sets flags)
		if line == "ADD A, 0" {
			continue
		}

		// SUB 0 → remove
		if line == "SUB 0" {
			continue
		}

		// LD A, r / LD r, A → remove second (redundant store-back)
		if i+1 < len(lines) && strings.HasPrefix(line, "LD A, ") {
			src := strings.TrimPrefix(line, "LD A, ")
			next := strings.TrimSpace(lines[i+1])
			if next == "LD "+src+", A" {
				result = append(result, lines[i]) // keep first LD
				i++                                // skip second
				continue
			}
		}

		// LD r, A / LD A, r → remove second (redundant reload)
		if i+1 < len(lines) && strings.HasPrefix(line, "LD ") && strings.HasSuffix(line, ", A") {
			reg := strings.TrimSuffix(strings.TrimPrefix(line, "LD "), ", A")
			reg = strings.TrimSpace(reg)
			next := strings.TrimSpace(lines[i+1])
			if next == "LD A, "+reg {
				result = append(result, lines[i]) // keep first LD
				i++                                // skip second
				continue
			}
		}

		// OR A / OR A → remove duplicate (idempotent)
		if i+1 < len(lines) && line == "OR A" {
			next := strings.TrimSpace(lines[i+1])
			if next == "OR A" {
				result = append(result, lines[i]) // keep one
				i++                                // skip duplicate
				continue
			}
		}

		// XOR A / LD A, 0 → keep only XOR A (both set A=0)
		if i+1 < len(lines) && line == "XOR A" {
			next := strings.TrimSpace(lines[i+1])
			if next == "LD A, 0" || next == "XOR A" {
				result = append(result, lines[i])
				i++
				continue
			}
		}

		// ── Codegen suboptimality fixes ──────────────────────────────

		// LD r, N / INC A / RET → INC A / RET (dead const, only when RET follows)
		if i+2 < len(lines) && strings.HasPrefix(line, "LD ") && !strings.HasPrefix(line, "LD A,") {
			next := strings.TrimSpace(lines[i+1])
			next2 := strings.TrimSpace(lines[i+2])
			if (next == "INC A" || next == "DEC A") && next2 == "RET" {
				parts := strings.SplitN(line[3:], ", ", 2)
				if len(parts) == 2 && strings.TrimSpace(parts[0]) != "A" {
					continue // skip dead const load
				}
			}
		}

		// LD r, N / LD A, r → LD A, N (const through intermediate, only for immediates)
		if i+1 < len(lines) && strings.HasPrefix(line, "LD ") && !strings.HasPrefix(line, "LD A,") {
			parts := strings.SplitN(line[3:], ", ", 2)
			if len(parts) == 2 {
				reg := strings.TrimSpace(parts[0])
				imm := strings.TrimSpace(parts[1])
				next := strings.TrimSpace(lines[i+1])
				// Only merge when imm is a numeric constant (not a register name)
				isImm := len(imm) > 0 && (imm[0] >= '0' && imm[0] <= '9')
				if next == "LD A, "+reg && isImm {
					result = append(result, "    LD A, "+imm)
					i++
					continue
				}
			}
		}

		// XOR A / SUB r → NEG (when input was in A, 0-x = negate)
		// Actually: XOR A sets A=0, then SUB r = 0-r = -r = NEG if r had the value
		// This is tricky — only valid if the SUB source had the original A value.
		// Skip for now — needs more context.

		// ── INC r / DEC r → remove both (cancel) ────────────────────
		if i+1 < len(lines) {
			next := strings.TrimSpace(lines[i+1])
			if strings.HasPrefix(line, "INC ") && strings.HasPrefix(next, "DEC ") {
				reg := strings.TrimSpace(line[4:])
				nreg := strings.TrimSpace(next[4:])
				if reg == nreg && len(reg) <= 2 {
					i++ // skip both
					continue
				}
			}
			if strings.HasPrefix(line, "DEC ") && strings.HasPrefix(next, "INC ") {
				reg := strings.TrimSpace(line[4:])
				nreg := strings.TrimSpace(next[4:])
				if reg == nreg && len(reg) <= 2 {
					i++
					continue
				}
			}
		}

		// ── JP/JR cc, next_label → remove (dead conditional branch) ─
		if i+1 < len(lines) {
			next := strings.TrimSpace(lines[i+1])
			if strings.HasSuffix(next, ":") {
				label := strings.TrimSuffix(next, ":")
				deadBranch := false
				for _, prefix := range []string{"JP Z, ", "JP NZ, ", "JP C, ", "JP NC, ",
					"JR Z, ", "JR NZ, ", "JR C, ", "JR NC, "} {
					if strings.HasPrefix(line, prefix) {
						target := strings.TrimSpace(line[len(prefix):])
						if target == label {
							deadBranch = true
							break
						}
					}
				}
				if deadBranch {
					continue // skip dead branch to next instruction
				}
			}
		}

		// ── PUSH rr / POP different_rr → LD pair halves (saves 3T) ──
		if i+1 < len(lines) && strings.HasPrefix(line, "PUSH ") {
			next := strings.TrimSpace(lines[i+1])
			if strings.HasPrefix(next, "POP ") {
				srcPair := strings.TrimSpace(line[5:])
				dstPair := strings.TrimSpace(next[4:])
				if srcPair != dstPair { // same pair already handled above
					srcH, srcL := pairHalvesASM(srcPair)
					dstH, dstL := pairHalvesASM(dstPair)
					if srcH != "" && dstH != "" {
						result = append(result,
							fmt.Sprintf("    LD %s, %s", dstH, srcH),
							fmt.Sprintf("    LD %s, %s", dstL, srcL),
						)
						i++ // skip POP
						continue
					}
				}
			}
		}

		// ── AND 0FFh → AND A (1 byte shorter, same flags) ──────────
		if line == "AND 0FFh" || line == "AND 255" {
			result = append(result, "    AND A")
			continue
		}

		// ── OR 00h → OR A (1 byte shorter, same flags) ─────────────
		if line == "OR 00h" || line == "OR 0" {
			result = append(result, "    OR A")
			continue
		}

		// ── Grace-like CFG rules (on assembly level) ─────────────────

		// Conditional RET: JR/JP cc, .target / [labels...] / RET / .target: → RET cc_inverted
		// Also handles: JR/JP cc, .target / [labels...] / RET / [labels...] / .target:
		// This is a massive win — saves 2 instructions per conditional return.
		if (strings.HasPrefix(line, "JR ") || strings.HasPrefix(line, "JP ")) &&
			!strings.HasPrefix(line, "JR .") && !strings.HasPrefix(line, "JP .") &&
			!strings.HasPrefix(line, "JP (") {
			prefix := "JR "
			if strings.HasPrefix(line, "JP ") {
				prefix = "JP "
			}
			rest := strings.TrimPrefix(line, prefix)
			if commaIdx := strings.Index(rest, ", "); commaIdx > 0 {
				cc := strings.TrimSpace(rest[:commaIdx])
				target := strings.TrimSpace(rest[commaIdx+2:])
				// Scan forward: skip labels, find RET, then find target label
				retIdx := -1
				for j := i + 1; j < len(lines) && j <= i+4; j++ {
					t := strings.TrimSpace(lines[j])
					if t == "" || strings.HasSuffix(t, ":") || strings.HasPrefix(t, ";") {
						continue // skip labels, comments, empty
					}
					if t == "RET" {
						retIdx = j
						break
					}
					break // non-label, non-RET instruction → stop
				}
				if retIdx > 0 {
					// Now find target label after RET
					targetIdx := -1
					for j := retIdx + 1; j < len(lines) && j <= retIdx+3; j++ {
						t := strings.TrimSpace(lines[j])
						if t == "" || strings.HasPrefix(t, ";") {
							continue
						}
						if t == target+":" {
							targetIdx = j
							break
						}
						if strings.HasSuffix(t, ":") {
							continue // other labels, keep scanning
						}
						break // instruction → stop
					}
					if targetIdx > 0 {
						invCC := invertCC(cc)
						if invCC != "" {
							result = append(result, "    RET "+invCC)
							i = targetIdx - 1 // skip up to target label; label preserved on next iteration
							continue
						}
					}
				}
			}
		}

		// Duplicate CP elimination: CP r / JR cc, label / [labels...] / CP r → skip second CP
		// JR and labels don't modify flags, so the second CP is redundant on fall-through.
		if strings.HasPrefix(line, "CP ") {
			operand := strings.TrimPrefix(line, "CP ")
			// Look back: was the previous non-label, non-comment instruction a JR cc?
			// And before that, was there a CP with the same operand?
			prevCPIdx := -1
			allFlagsSafe := true
			for j := len(result) - 1; j >= 0 && j >= len(result)-4; j-- {
				prev := strings.TrimSpace(result[j])
				if prev == "" || strings.HasSuffix(prev, ":") || strings.HasPrefix(prev, ";") {
					continue // labels/comments don't touch flags
				}
				if strings.HasPrefix(prev, "JR ") {
					continue // JR reads but doesn't modify flags
				}
				if prev == "CP "+operand {
					prevCPIdx = j
					break
				}
				allFlagsSafe = false // some other instruction modifies flags
				break
			}
			if prevCPIdx >= 0 && allFlagsSafe {
				continue // skip redundant CP
			}
		}

		// Dead LD elimination: LD r, X / LD r, Y → remove first (same dest, first is dead)
		// Only for single registers, not memory or pairs
		if i+1 < len(lines) && strings.HasPrefix(line, "LD ") {
			parts := strings.SplitN(line[3:], ", ", 2)
			if len(parts) == 2 {
				dst := strings.TrimSpace(parts[0])
				nextLine := strings.TrimSpace(lines[i+1])
				if strings.HasPrefix(nextLine, "LD ") && !strings.HasPrefix(dst, "(") {
					nextParts := strings.SplitN(nextLine[3:], ", ", 2)
					if len(nextParts) == 2 {
						nextDst := strings.TrimSpace(nextParts[0])
						if dst == nextDst && len(dst) <= 3 && !strings.HasPrefix(dst, "(") {
							continue // skip first LD — dead store
						}
					}
				}
			}
		}

		// Reverse-copy elimination: LD X, Y / LD Y, X → keep only first
		if i+1 < len(lines) && strings.HasPrefix(line, "LD ") {
			parts := strings.SplitN(line[3:], ", ", 2)
			if len(parts) == 2 {
				a := strings.TrimSpace(parts[0])
				b := strings.TrimSpace(parts[1])
				nextLine := strings.TrimSpace(lines[i+1])
				if nextLine == "LD "+b+", "+a {
					result = append(result, lines[i]) // keep first
					i++                                // skip second
					continue
				}
			}
		}

		result = append(result, lines[i])
	}

	// Second pass: remove consecutive duplicate labels
	var pass2 []string
	for i, line := range result {
		// Skip empty lines between labels
		trimmed := strings.TrimSpace(line)
		if trimmed == "" && i+1 < len(result) && strings.HasSuffix(strings.TrimSpace(result[i+1]), ":") {
			continue
		}
		pass2 = append(pass2, line)
	}

	// Grace pass: multi-instruction CFG-aware optimizations
	pass3 := gracePass(pass2)

	return strings.Join(pass3, "\n")
}

// gracePass applies Grace-like CFG pattern rules on Z80 assembly.
// These are multi-instruction patterns that the simple peephole can't catch.
// invertCC returns the inverted Z80 condition code, or "" if unknown.
func invertCC(cc string) string {
	switch strings.ToUpper(cc) {
	case "Z":
		return "NZ"
	case "NZ":
		return "Z"
	case "C":
		return "NC"
	case "NC":
		return "C"
	case "PE":
		return "PO"
	case "PO":
		return "PE"
	case "M":
		return "P"
	case "P":
		return "M"
	default:
		return ""
	}
}

// fuseAbsDiffASM detects the abs_diff pattern in assembly and rewrites to SUB/RET NC/NEG/RET.
// Pattern: CP r / JR Z+JR C → block1(a-b, RET) / block2(b-a, RET)
// Replacement: SUB r / RET NC / NEG / RET (4 instructions)
func fuseAbsDiffASM(lines []string) []string {
	for i := 0; i < len(lines)-5; i++ {
		l := strings.TrimSpace(lines[i])
		// Look for: CP r (where r is a single register)
		if !strings.HasPrefix(l, "CP ") {
			continue
		}
		reg := strings.TrimPrefix(l, "CP ")
		reg = strings.TrimSpace(reg)
		if len(reg) == 0 || len(reg) > 3 || strings.Contains(reg, "(") {
			continue
		}

		// Next two lines must be: JR Z, .label / JR C, .label (same label)
		l1 := strings.TrimSpace(lines[i+1])
		l2 := strings.TrimSpace(lines[i+2])
		if !strings.HasPrefix(l1, "JR Z, ") || !strings.HasPrefix(l2, "JR C, ") {
			continue
		}
		joinLabel := strings.TrimPrefix(l1, "JR Z, ")
		joinLabel2 := strings.TrimPrefix(l2, "JR C, ")
		if joinLabel != joinLabel2 {
			continue
		}

		// Scan forward to find: block1 ending with SUB + RET, then joinLabel, block2 ending with SUB + RET
		// block1: [labels] [LD...] SUB r / RET
		// block2: joinLabel: [LD...] SUB r / RET
		block1End := -1
		for j := i + 3; j < len(lines) && j < i+12; j++ {
			t := strings.TrimSpace(lines[j])
			if t == "RET" {
				block1End = j
				break
			}
		}
		if block1End < 0 {
			continue
		}

		// Check block1 has SUB before RET
		block1Sub := strings.TrimSpace(lines[block1End-1])
		if !strings.HasPrefix(block1Sub, "SUB ") {
			continue
		}

		// Find join label after block1
		joinIdx := -1
		for j := block1End + 1; j < len(lines) && j <= block1End+3; j++ {
			t := strings.TrimSpace(lines[j])
			if t == joinLabel+":" {
				joinIdx = j
				break
			}
			if t == "" || strings.HasSuffix(t, ":") {
				continue
			}
			break
		}
		if joinIdx < 0 {
			continue
		}

		// Find block2's SUB + RET
		block2End := -1
		for j := joinIdx + 1; j < len(lines) && j < joinIdx+8; j++ {
			t := strings.TrimSpace(lines[j])
			if t == "RET" {
				block2End = j
				break
			}
		}
		if block2End < 0 {
			continue
		}

		block2Sub := strings.TrimSpace(lines[block2End-1])
		if !strings.HasPrefix(block2Sub, "SUB ") {
			continue
		}

		// Pattern matched! Replace everything from CP to block2 RET with:
		// SUB reg / RET NC / NEG / RET
		var newLines []string
		newLines = append(newLines, lines[:i]...)
		indent := "    "
		newLines = append(newLines, indent+"SUB "+reg)
		newLines = append(newLines, indent+"RET NC")
		newLines = append(newLines, indent+"NEG")
		newLines = append(newLines, indent+"RET")
		newLines = append(newLines, lines[block2End+1:]...)
		return fuseAbsDiffASM(newLines) // recurse for multiple patterns
	}
	return lines
}

func gracePass(lines []string) []string {
	// First: fuse abs_diff patterns
	lines = fuseAbsDiffASM(lines)

	// JP threading: JP .label where .label only contains JP .target → JP .target
	// Build label→first-instruction map
	labelTarget := make(map[string]string) // label → JP target (if label block is just JP)
	for i := 0; i < len(lines)-1; i++ {
		t := strings.TrimSpace(lines[i])
		if strings.HasSuffix(t, ":") && strings.HasPrefix(t, ".") {
			label := strings.TrimSuffix(t, ":")
			// Find next non-label, non-empty line
			for j := i + 1; j < len(lines) && j <= i+3; j++ {
				next := strings.TrimSpace(lines[j])
				if next == "" || strings.HasSuffix(next, ":") || strings.HasPrefix(next, ";") {
					continue
				}
				if strings.HasPrefix(next, "JP ") && !strings.HasPrefix(next, "JP (") {
					target := strings.TrimPrefix(next, "JP ")
					target = strings.TrimSpace(target)
					labelTarget[label] = target
				}
				break
			}
		}
	}
	// Rewrite JP/JR targets through chains
	if len(labelTarget) > 0 {
		for i, line := range lines {
			t := strings.TrimSpace(line)
			for _, prefix := range []string{"JP ", "JR Z, ", "JR NZ, ", "JR C, ", "JR NC, ", "JR "} {
				if strings.HasPrefix(t, prefix) {
					target := strings.TrimSpace(strings.TrimPrefix(t, prefix))
					if newTarget, ok := labelTarget[target]; ok {
						lines[i] = "    " + prefix + newTarget
					}
					break
				}
			}
		}
	}

	var result []string

	for i := 0; i < len(lines); i++ {
		line := strings.TrimSpace(lines[i])

		// ── Dead instruction before RET ─────────────────────────────
		// Any instruction that writes to a register right before RET is dead
		// if it doesn't write to A (return value) or affect flags for conditional return.
		// Example: DEC HL / RET → RET (HL not used after return)
		if i+1 < len(lines) {
			next := strings.TrimSpace(lines[i+1])
			if next == "RET" {
				// DEC/INC rr / RET → RET (dead before unconditional return)
				// BUT: keep INC/DEC on return registers (A for u8, HL for u16/ptr)
				if strings.HasPrefix(line, "DEC ") || strings.HasPrefix(line, "INC ") {
					reg := strings.TrimSpace(line[4:])
					if reg != "A" && reg != "HL" && reg != "DE" && reg != "BC" {
						continue
					}
				}
				// EX DE, HL / RET → RET (register swap is dead before return)
				if line == "EX DE, HL" {
					continue
				}
				// LD r, N / RET where r != A → skip (dead const load before return)
				if strings.HasPrefix(line, "LD ") && !strings.HasPrefix(line, "LD A") &&
					!strings.HasPrefix(line, "LD (") {
					parts := strings.SplitN(line[3:], ", ", 2)
					if len(parts) == 2 {
						reg := strings.TrimSpace(parts[0])
						if reg != "A" && !strings.HasPrefix(reg, "(") {
							continue // dead load before RET
						}
					}
				}
				// Note: OR/AND/XOR before RET are NOT dead — they set flags
				// for callers that check CY/Z after return.
			}
		}

		// ── EX DE,HL / LD A,(HL) → LD A,(DE) ────────────────────────
		// When EX is only used to access memory through HL, use direct (DE) access
		if i+1 < len(lines) && line == "EX DE, HL" {
			next := strings.TrimSpace(lines[i+1])
			if next == "LD A, (HL)" {
				result = append(result, "    LD A, (DE)")
				i++ // skip LD A, (HL)
				// Check if next is EX DE, HL (restore) — skip it too
				if i+1 < len(lines) && strings.TrimSpace(lines[i+1]) == "EX DE, HL" {
					i++
				}
				continue
			}
		}

		// ── LD BC, 0 / ADD HL, BC → nothing (add 0 = nop) ──────────
		if i+1 < len(lines) && (line == "LD BC, 0" || line == "LD DE, 0") {
			next := strings.TrimSpace(lines[i+1])
			pair := "BC"
			if strings.HasPrefix(line, "LD DE") { pair = "DE" }
			if next == "ADD HL, "+pair {
				i++ // skip both
				continue
			}
		}

		// ── Redundant EX DE, HL pairs ────────────────────────────────
		// EX DE, HL / EX DE, HL → remove both (self-canceling)
		if i+1 < len(lines) && line == "EX DE, HL" {
			next := strings.TrimSpace(lines[i+1])
			if next == "EX DE, HL" {
				i++ // skip both
				continue
			}
		}

		// ── EX DE,HL sandwich elimination ────────────────────────────
		// EX DE,HL / instr / EX DE,HL → rewrite instr to swap DE↔HL refs
		// Only when the middle instruction doesn't branch or use both DE and HL.
		if i+2 < len(lines) && line == "EX DE, HL" {
			mid := strings.TrimSpace(lines[i+1])
			after := strings.TrimSpace(lines[i+2])
			if after == "EX DE, HL" && !strings.HasPrefix(mid, "J") &&
				!strings.HasPrefix(mid, "CALL") && !strings.HasPrefix(mid, "RET") &&
				// Z80 ADD/ADC/SBC only work with HL as implicit dest.
				// Swapping HL↔DE would produce invalid ADD DE,rr / SBC DE,rr.
				!strings.HasPrefix(mid, "ADD HL") &&
				!strings.HasPrefix(mid, "ADC HL") &&
				!strings.HasPrefix(mid, "SBC HL") {
				// Swap DE↔HL references in the middle instruction
				swapped := mid
				swapped = strings.ReplaceAll(swapped, "HL", "##HL##")
				swapped = strings.ReplaceAll(swapped, "DE", "HL")
				swapped = strings.ReplaceAll(swapped, "##HL##", "DE")
				swapped = strings.ReplaceAll(swapped, " H,", " ##H##,")
				swapped = strings.ReplaceAll(swapped, " L,", " ##L##,")
				swapped = strings.ReplaceAll(swapped, " D,", " H,")
				swapped = strings.ReplaceAll(swapped, " E,", " L,")
				swapped = strings.ReplaceAll(swapped, " ##H##,", " D,")
				swapped = strings.ReplaceAll(swapped, " ##L##,", " E,")
				swapped = strings.ReplaceAll(swapped, ",H", ",##H##")
				swapped = strings.ReplaceAll(swapped, ",L", ",##L##")
				swapped = strings.ReplaceAll(swapped, ",D", ",H")
				swapped = strings.ReplaceAll(swapped, ",E", ",L")
				swapped = strings.ReplaceAll(swapped, ",##H##", ",D")
				swapped = strings.ReplaceAll(swapped, ",##L##", ",E")
				if swapped != mid { // only if something actually changed
					result = append(result, "    "+swapped)
					i += 2 // skip both EX
					continue
				}
			}
		}

		// ── Dead LD before CALL ──────────────────────────────────────
		// LD r, X / CALL func → remove LD if CALL clobbers r.
		// CALL clobbers A and F always (return value + flags).
		if i+1 < len(lines) && strings.HasPrefix(line, "LD ") {
			next := strings.TrimSpace(lines[i+1])
			if strings.HasPrefix(next, "CALL ") {
				parts := strings.SplitN(line[3:], ", ", 2)
				if len(parts) == 2 {
					reg := strings.TrimSpace(parts[0])
					// CALL always clobbers A. If we're loading into A
					// and the next instruction is CALL (which overwrites A
					// with its return value), the LD is dead.
					if reg == "A" {
						continue // dead store — CALL will overwrite A
					}
				}
			}
		}

		// ── Empty label blocks ───────────────────────────────────────
		// .label: / .next_label: → merge (empty block)
		if strings.HasSuffix(line, ":") && i+1 < len(lines) {
			next := strings.TrimSpace(lines[i+1])
			if strings.HasSuffix(next, ":") && !strings.HasPrefix(line, ";") {
				// Keep both labels — they may be branch targets
			}
		}

		result = append(result, lines[i])
	}

	return result
}

// graceReroll detects repeated CALL patterns with varying immediate args
// and replaces them with a data table + DJNZ loop.
//
// Pattern: N repetitions of { LD reg1, imm1 / [LD reg2, imm2] / CALL func }
// Result:  data table + IX-indexed loop with DJNZ
//
// This is a SIZE optimization — the loop is slightly slower per iteration
// but saves (N-1) * pattern_size bytes for N repetitions.
// Only fires when N >= 4 (at least 4 repetitions).
func graceReroll(lines []string, funcName string) []string {
	const minRepeats = 4

	// Scan for repeated CALL patterns
	type callBlock struct {
		startIdx int
		endIdx   int      // exclusive
		callFunc string
		ldArgs   []string // LD instruction lines (with immediate values)
	}

	var blocks []callBlock
	i := 0
	for i < len(lines) {
		line := strings.TrimSpace(lines[i])

		// Look for sequence: LD reg, imm [...] CALL func
		if strings.HasPrefix(line, "LD ") && strings.Contains(line, ", ") {
			start := i
			var lds []string

			// Collect LD instructions
			j := i
			for j < len(lines) {
				l := strings.TrimSpace(lines[j])
				if strings.HasPrefix(l, "LD ") {
					lds = append(lds, l)
					j++
				} else if strings.HasPrefix(l, "; ") || l == "" {
					j++ // skip comments/empty
				} else {
					break
				}
			}

			// Next non-LD should be CALL
			if j < len(lines) && len(lds) > 0 {
				callLine := strings.TrimSpace(lines[j])
				if strings.HasPrefix(callLine, "CALL ") {
					blocks = append(blocks, callBlock{
						startIdx: start,
						endIdx:   j + 1,
						callFunc: callLine,
						ldArgs:   lds,
					})
					i = j + 1
					continue
				}
			}
		}
		i++
	}

	// Find runs of identical CALL targets with same LD pattern structure
	if len(blocks) < minRepeats {
		return lines // not enough blocks
	}

	type rerollCandidate struct {
		blocks []callBlock
	}
	var candidates []rerollCandidate

	ri := 0
	for ri < len(blocks) {
		run := []callBlock{blocks[ri]}
		rj := ri + 1

		// Extend run: same CALL target, same number of LD args, consecutive in source
		for rj < len(blocks) &&
			blocks[rj].callFunc == blocks[ri].callFunc &&
			len(blocks[rj].ldArgs) == len(blocks[ri].ldArgs) &&
			blocks[rj].startIdx == run[len(run)-1].endIdx {

			// Check same LD register targets (only immediates differ)
			sameStructure := true
			for k := range blocks[ri].ldArgs {
				regA := strings.SplitN(blocks[ri].ldArgs[k][3:], ", ", 2)[0]
				regB := strings.SplitN(blocks[rj].ldArgs[k][3:], ", ", 2)[0]
				if regA != regB {
					sameStructure = false
					break
				}
			}
			if !sameStructure {
				break
			}

			run = append(run, blocks[rj])
			rj++
		}

		if len(run) >= minRepeats {
			candidates = append(candidates, rerollCandidate{blocks: run})
		}
		ri = rj
	}

	if len(candidates) == 0 {
		return lines
	}

	// Apply reroll: replace the first (largest) candidate
	// For now, just annotate — full rewrite needs data table emission
	cand := candidates[0]
	n := len(cand.blocks)
	nArgs := len(cand.blocks[0].ldArgs)

	// Extract register names and values
	var regs []string
	for _, ld := range cand.blocks[0].ldArgs {
		parts := strings.SplitN(ld[3:], ", ", 2)
		regs = append(regs, strings.TrimSpace(parts[0]))
	}

	// Build replacement: annotate with comment for now
	// Full implementation would emit IX-indexed loop + data table
	var result []string

	// Copy lines before the candidate
	for i := 0; i < cand.blocks[0].startIdx; i++ {
		result = append(result, lines[i])
	}

	// Emit reroll comment
	result = append(result, fmt.Sprintf("    ; [REROLL] %d × %s (%d args: %s) → data table + DJNZ loop",
		n, strings.TrimPrefix(cand.blocks[0].callFunc, "CALL "),
		nArgs, strings.Join(regs, ", ")))

	// Classify each arg as 8-bit (DB) or 16-bit (DW) based on register name
	type argInfo struct {
		reg    string
		is16   bool
		offset int // byte offset within data entry
	}
	var args []argInfo
	offset := 0
	for _, reg := range regs {
		is16 := reg == "HL" || reg == "DE" || reg == "BC" || reg == "IX" || reg == "IY"
		args = append(args, argInfo{reg: reg, is16: is16, offset: offset})
		if is16 {
			offset += 2
		} else {
			offset += 1
		}
	}
	entrySize := offset

	// Emit the loop
	tableLabel := fmt.Sprintf(".%s_reroll_data", funcName)
	result = append(result,
		fmt.Sprintf("    LD IX, %s", tableLabel),
		fmt.Sprintf("    LD B, %d", n),
		fmt.Sprintf(".%s_reroll_loop:", funcName),
	)
	for _, arg := range args {
		if arg.is16 {
			// 16-bit: load pair from (IX+offset) and (IX+offset+1)
			lo, hi := pairHalvesASM(arg.reg)
			result = append(result,
				fmt.Sprintf("    LD %s, (IX+%d)", lo, arg.offset),
				fmt.Sprintf("    LD %s, (IX+%d)", hi, arg.offset+1),
			)
		} else {
			result = append(result, fmt.Sprintf("    LD %s, (IX+%d)", arg.reg, arg.offset))
		}
	}
	if entrySize <= 4 {
		// Small entry: INC IX × entrySize (no DE clobber)
		for k := 0; k < entrySize; k++ {
			result = append(result, "    INC IX")
		}
	} else {
		result = append(result,
			fmt.Sprintf("    LD DE, %d", entrySize),
			"    ADD IX, DE",
		)
	}
	result = append(result,
		"    "+cand.blocks[0].callFunc,
		fmt.Sprintf("    DJNZ .%s_reroll_loop", funcName),
	)

	// Emit data table
	result = append(result, tableLabel+":")
	for _, blk := range cand.blocks {
		var vals []string
		for k, ld := range blk.ldArgs {
			parts := strings.SplitN(ld[3:], ", ", 2)
			val := strings.TrimSpace(parts[1])
			if args[k].is16 {
				vals = append(vals, "DW "+val)
			} else {
				vals = append(vals, "DB "+val)
			}
		}
		result = append(result, "    "+strings.Join(vals, " : "))
	}

	// Copy remaining lines after the candidate
	lastEnd := cand.blocks[len(cand.blocks)-1].endIdx
	for i := lastEnd; i < len(lines); i++ {
		result = append(result, lines[i])
	}

	return result
}

// ── Call Graph Dump ─────────────────────────────────────────────────────────
// Outputs {name, sig, nVregs, callees[]} per function as JSONL to stdout.
// Used by z80-optimizer's partopt prototype for cross-function DP partitioning.

type callGraphEntry struct {
	Name    string   `json:"name"`
	Sig     string   `json:"sig"`
	NVregs  int      `json:"nVregs"`
	Callees []string `json:"callees"`
}

func dumpCallGraph(m *mir2.Module, opts SolverOptions) {
	desc := Z80
	var entries []callGraphEntry

	for _, f := range m.Funcs {
		vf, err := LowerFunc(f, desc, m)
		if err != nil {
			fmt.Fprintf(os.Stderr, "[callgraph] skip %s: %v\n", f.Name, err)
			continue
		}

		var allOps []VIROp
		for _, b := range vf.Blocks {
			allOps = append(allOps, b.Ops...)
		}

		sig := computeGPUSignature(allOps, desc)

		_, nVregs, _ := BuildGPUDesc(allOps, desc, SolverOptions{})

		// Extract unique callees from OpCall instructions
		seen := make(map[string]bool)
		callees := make([]string, 0)
		for _, op := range allOps {
			if op.Op == OpCall && op.Sym != "" {
				if !seen[op.Sym] {
					seen[op.Sym] = true
					callees = append(callees, op.Sym)
				}
			}
		}

		entries = append(entries, callGraphEntry{
			Name:    f.Name,
			Sig:     sig,
			NVregs:  nVregs,
			Callees: callees,
		})
	}

	// Output as JSON array to file (env var = file path, or "1"/"-" for stdout)
	jsonData, err := json.MarshalIndent(entries, "", "  ")
	if err != nil {
		fmt.Fprintf(os.Stderr, "[callgraph] marshal error: %v\n", err)
		return
	}

	outPath := os.Getenv("VIR_DUMP_CALLGRAPH")
	if outPath == "1" || outPath == "-" {
		fmt.Fprintf(os.Stderr, "%s\n", jsonData)
	} else {
		if writeErr := os.WriteFile(outPath, append(jsonData, '\n'), 0644); writeErr != nil {
			fmt.Fprintf(os.Stderr, "[callgraph] write error: %v\n", writeErr)
			return
		}
	}
	fmt.Fprintf(os.Stderr, "[callgraph] dumped %d functions to %s\n", len(entries), outPath)
}

// ── Merged Function GPU Problem Dump ────────────────────────────────────────
// For z80-optimizer's partopt: merge caller+callee VIR ops into a single
// GPU allocation problem. Remap vregs, add boundary interference.

type mergedProblem struct {
	Name    string      `json:"name"`
	Funcs   []string    `json:"funcs"`
	NVregs  int         `json:"nVregs"`
	Desc    *GPUFuncDesc `json:"desc"`
}

type mergePair struct {
	Funcs []string `json:"funcs"` // function names to merge
}

type mergedFuncData struct {
	ops  []VIROp
	gpu  *GPUFuncDesc
	nv   int
}

func dumpMergedProblems(m *mir2.Module, opts SolverOptions, outPath string) {
	desc := Z80

	// Read merge pairs from VIR_MERGE_PAIRS env var (JSON array of {funcs: [...]})
	// or auto-detect from call graph (all caller→callee pairs where merged nVregs ≤ 14)
	var pairs []mergePair
	if pairsJSON := os.Getenv("VIR_MERGE_PAIRS"); pairsJSON != "" {
		if err := json.Unmarshal([]byte(pairsJSON), &pairs); err != nil {
			fmt.Fprintf(os.Stderr, "[merged] parse VIR_MERGE_PAIRS: %v\n", err)
			return
		}
	} else {
		// Auto-detect: for each function, merge with each callee if combined ≤ 14 vregs
		pairs = autoDetectMergePairs(m, desc)
	}

	// Lower all functions once
	cache := make(map[string]*mergedFuncData)
	for _, f := range m.Funcs {
		vf, err := LowerFunc(f, desc, m)
		if err != nil {
			continue
		}
		var allOps []VIROp
		for _, b := range vf.Blocks {
			allOps = append(allOps, b.Ops...)
		}
		gf, nv, err := BuildGPUDesc(allOps, desc, SolverOptions{})
		if err != nil || nv == 0 {
			continue
		}
		cache[f.Name] = &mergedFuncData{allOps, gf, nv}
	}

	var results []mergedProblem
	for _, pair := range pairs {
		if len(pair.Funcs) < 2 {
			continue
		}
		merged := mergeFuncDescs(pair.Funcs, cache)
		if merged != nil {
			results = append(results, *merged)
		}
	}

	jsonData, err := json.MarshalIndent(results, "", "  ")
	if err != nil {
		fmt.Fprintf(os.Stderr, "[merged] marshal error: %v\n", err)
		return
	}
	if err := os.WriteFile(outPath, append(jsonData, '\n'), 0644); err != nil {
		fmt.Fprintf(os.Stderr, "[merged] write error: %v\n", err)
		return
	}
	fmt.Fprintf(os.Stderr, "[merged] dumped %d merged problems to %s\n", len(results), outPath)
}

func autoDetectMergePairs(m *mir2.Module, desc *MachineDesc) []mergePair {
	// Lower all and count vregs
	nv := make(map[string]int)
	callees := make(map[string][]string)
	for _, f := range m.Funcs {
		vf, err := LowerFunc(f, desc, m)
		if err != nil {
			continue
		}
		var allOps []VIROp
		for _, b := range vf.Blocks {
			allOps = append(allOps, b.Ops...)
		}
		_, n, _ := BuildGPUDesc(allOps, desc, SolverOptions{})
		nv[f.Name] = n
		seen := make(map[string]bool)
		for _, op := range allOps {
			if op.Op == OpCall && op.Sym != "" && !seen[op.Sym] {
				seen[op.Sym] = true
				callees[f.Name] = append(callees[f.Name], op.Sym)
			}
		}
	}

	var pairs []mergePair
	for caller, cees := range callees {
		for _, callee := range cees {
			if nv[caller]+nv[callee] <= 14 && nv[callee] > 0 {
				pairs = append(pairs, mergePair{Funcs: []string{caller, callee}})
			}
		}
	}
	return pairs
}

func mergeFuncDescs(names []string, cache map[string]*mergedFuncData) *mergedProblem {
	// Collect all func data
	var descs []*mergedFuncData
	for _, name := range names {
		fd, ok := cache[name]
		if !ok {
			fmt.Fprintf(os.Stderr, "[merged] skip %s: not found\n", name)
			return nil
		}
		descs = append(descs, fd)
	}

	// Compute vreg offset per function
	offsets := make([]int, len(descs))
	totalVregs := 0
	for i, fd := range descs {
		offsets[i] = totalVregs
		totalVregs += fd.nv
	}

	merged := &GPUFuncDesc{NVregs: totalVregs}

	// Merge widths
	hasWidths := false
	allWidths := make([]int, totalVregs)
	for i := range allWidths {
		allWidths[i] = 8 // default
	}
	for fi, fd := range descs {
		if fd.gpu.Widths != nil {
			hasWidths = true
			for vi, w := range fd.gpu.Widths {
				allWidths[offsets[fi]+vi] = w
			}
		}
	}
	if hasWidths {
		merged.Widths = allWidths
	}

	// Merge ops (remap vreg indices)
	for fi, fd := range descs {
		off := offsets[fi]
		for _, op := range fd.gpu.Ops {
			remapped := GPUOpDesc{
				Dst:      remapIdx(op.Dst, off),
				Src0:     remapIdx(op.Src0, off),
				Src1:     remapIdx(op.Src1, off),
				Patterns: op.Patterns, // patterns are location-based, no remap needed
			}
			merged.Ops = append(merged.Ops, remapped)
		}
	}

	// Merge interference (remap indices)
	seen := make(map[[2]int]bool)
	for fi, fd := range descs {
		off := offsets[fi]
		for _, pair := range fd.gpu.Interference {
			a, b := pair[0]+off, pair[1]+off
			if a > b { a, b = b, a }
			key := [2]int{a, b}
			if !seen[key] {
				seen[key] = true
				merged.Interference = append(merged.Interference, key)
			}
		}
	}

	// Add boundary interference: caller's live-at-call vregs interfere
	// with callee's vregs. Conservative: all caller vregs that appear in
	// ops AFTER a call to the callee interfere with ALL callee vregs.
	// This is an over-approximation but safe.
	for fi := 0; fi < len(descs)-1; fi++ {
		callerNV := descs[fi].nv
		calleeOff := offsets[fi+1]
		calleeNV := descs[fi+1].nv
		// All caller vregs that could be live across the call boundary
		// interfere with all callee vregs.
		// Conservative: caller param vregs that are used after the call
		// In practice, the call's return value is the only thing that
		// crosses the boundary. Use all callee vregs for safety.
		for cv := 0; cv < callerNV; cv++ {
			for ev := 0; ev < calleeNV; ev++ {
				a, b := offsets[fi]+cv, calleeOff+ev
				if a > b { a, b = b, a }
				key := [2]int{a, b}
				if !seen[key] {
					seen[key] = true
					merged.Interference = append(merged.Interference, key)
				}
			}
		}
	}

	// Merge param constraints (only from first function — the entry point)
	for _, pc := range descs[0].gpu.ParamConstraints {
		merged.ParamConstraints = append(merged.ParamConstraints, pc)
	}

	return &mergedProblem{
		Name:   strings.Join(names, "+"),
		Funcs:  names,
		NVregs: totalVregs,
		Desc:   merged,
	}
}

func remapIdx(idx, offset int) int {
	if idx < 0 {
		return idx
	}
	return idx + offset
}

// ── Per-Point Liveness Dump ─────────────────────────────────────────────────
// For z80-optimizer island decomposition: find liveness bottlenecks to split
// large functions into GPU-solvable islands.

type livenessEntry struct {
	Name   string          `json:"name"`
	NVregs int             `json:"nVregs"`
	Points []livenessPoint `json:"points"`
}

type livenessPoint struct {
	PC       int    `json:"pc"`
	Op       string `json:"op"`
	Dst      int    `json:"dst"`
	NLive    int    `json:"nLive"`
	LiveRegs []int  `json:"liveRegs"`
	IsCall   bool   `json:"isCall,omitempty"`
	CallSym  string `json:"callSym,omitempty"`
}

func dumpLiveness(m *mir2.Module, opts SolverOptions, outPath string) {
	desc := Z80
	minVregs := 15 // only dump functions needing decomposition
	if os.Getenv("VIR_LIVENESS_ALL") == "1" {
		minVregs = 0
	}

	var entries []livenessEntry

	for _, f := range m.Funcs {
		vf, err := LowerFunc(f, desc, m)
		if err != nil {
			continue
		}

		// Flatten all blocks into one op sequence (like codegenFuncWhole)
		var allOps []VIROp
		for _, b := range vf.Blocks {
			allOps = append(allOps, b.Ops...)
		}

		prob := buildProblem(allOps, desc)
		nv := len(prob.vregs)
		if nv < minVregs {
			continue
		}

		// Build vreg index map (sorted for deterministic output)
		vregList := make([]int, 0, len(prob.vregs))
		for v := range prob.vregs {
			vregList = append(vregList, v)
		}
		sort.Ints(vregList)
		vregIdx := make(map[int]int)
		for i, v := range vregList {
			vregIdx[v] = i
		}

		var points []livenessPoint
		for i, op := range allOps {
			// Remap live vregs to dense indices
			var liveRegs []int
			if i < len(prob.liveness) {
				for v := range prob.liveness[i].live {
					if idx, ok := vregIdx[v]; ok {
						liveRegs = append(liveRegs, idx)
					}
				}
				sort.Ints(liveRegs)
			}

			dst := -1
			if op.Dst > 0 {
				if idx, ok := vregIdx[op.Dst]; ok {
					dst = idx
				}
			}

			pt := livenessPoint{
				PC:       i,
				Op:       opName(op.Op),
				Dst:      dst,
				NLive:    len(liveRegs),
				LiveRegs: liveRegs,
				IsCall:   op.Op == OpCall || op.Op == OpAsmBlock,
			}
			if op.Op == OpCall {
				pt.CallSym = op.Sym
			}
			points = append(points, pt)
		}

		entries = append(entries, livenessEntry{
			Name:   f.Name,
			NVregs: nv,
			Points: points,
		})
	}

	jsonData, err := json.MarshalIndent(entries, "", "  ")
	if err != nil {
		fmt.Fprintf(os.Stderr, "[liveness] marshal error: %v\n", err)
		return
	}
	if err := os.WriteFile(outPath, append(jsonData, '\n'), 0644); err != nil {
		fmt.Fprintf(os.Stderr, "[liveness] write error: %v\n", err)
		return
	}
	fmt.Fprintf(os.Stderr, "[liveness] dumped %d functions to %s\n", len(entries), outPath)
}

// ── Island Sub-Problem Dump (VIR-level splitting) ───────────────────────────
// Correct approach: split VIR ops at liveness bottlenecks, then BuildGPUDesc
// per island. Each island gets fresh pattern matching against its own vregs.

type islandConfig struct {
	Func   string `json:"func"`
	Splits []int  `json:"splits"` // PC indices where to split (exclusive end of each island)
}

type islandResult struct {
	Name         string       `json:"name"`
	Func         string       `json:"func"`
	IslandIdx    int          `json:"islandIdx"`
	PCRange      [2]int       `json:"pcRange"`
	NVregs       int          `json:"nVregs"`
	Desc         *GPUFuncDesc `json:"desc"`
	BoundaryIn   []int        `json:"boundaryIn,omitempty"`  // vregs live at island entry (from previous island)
	BoundaryOut  []int        `json:"boundaryOut,omitempty"` // vregs live at island exit (to next island)
}

func dumpIslands(m *mir2.Module, opts SolverOptions, outPath string) {
	desc := Z80

	// Read island config or auto-detect
	var configs []islandConfig
	if cfgJSON := os.Getenv("VIR_ISLAND_CONFIG"); cfgJSON != "" {
		if err := json.Unmarshal([]byte(cfgJSON), &configs); err != nil {
			// Try reading from file
			data, ferr := os.ReadFile(cfgJSON)
			if ferr != nil {
				fmt.Fprintf(os.Stderr, "[islands] parse config: %v\n", err)
				return
			}
			if err2 := json.Unmarshal(data, &configs); err2 != nil {
				fmt.Fprintf(os.Stderr, "[islands] parse config file: %v\n", err2)
				return
			}
		}
	} else {
		// Auto-detect: split functions with >15 vregs at call sites where live ≤ threshold
		liveThresh := 4
		if lt := os.Getenv("VIR_ISLAND_THRESHOLD"); lt != "" {
			fmt.Sscanf(lt, "%d", &liveThresh)
		}
		configs = autoDetectIslands(m, desc, 15, liveThresh)
	}

	var results []islandResult

	for _, cfg := range configs {
		f := m.FuncByName(cfg.Func)
		if f == nil {
			fmt.Fprintf(os.Stderr, "[islands] function %s not found\n", cfg.Func)
			continue
		}

		vf, err := LowerFunc(f, desc, m)
		if err != nil {
			fmt.Fprintf(os.Stderr, "[islands] lower %s: %v\n", cfg.Func, err)
			continue
		}

		// Flatten all blocks into one op sequence
		var allOps []VIROp
		for _, b := range vf.Blocks {
			allOps = append(allOps, b.Ops...)
		}

		// Compute liveness for boundary detection
		prob := buildProblem(allOps, desc)

		// Build split points: [0, split0, split1, ..., len(allOps)]
		splits := []int{0}
		splits = append(splits, cfg.Splits...)
		splits = append(splits, len(allOps))

		for i := 0; i < len(splits)-1; i++ {
			start, end := splits[i], splits[i+1]
			if start >= end || start >= len(allOps) {
				continue
			}
			if end > len(allOps) {
				end = len(allOps)
			}

			// Extract VIR ops for this island
			islandOps := allOps[start:end]

			// Compute boundary vregs: live at entry and exit of island
			var boundaryIn, boundaryOut []int
			if start > 0 && start < len(prob.liveness) {
				for v := range prob.liveness[start].live {
					boundaryIn = append(boundaryIn, v)
				}
				sort.Ints(boundaryIn)
			}
			if end < len(prob.liveness) {
				for v := range prob.liveness[end-1].live {
					boundaryOut = append(boundaryOut, v)
				}
				sort.Ints(boundaryOut)
			}

			// Build GPU desc from the island's VIR ops (fresh pattern matching!)
			maxVregs := 15
			if mv := os.Getenv("VIR_GPU_MAX_VREGS"); mv != "" {
				fmt.Sscanf(mv, "%d", &maxVregs)
			}
			origMax := os.Getenv("VIR_GPU_MAX_VREGS")
			os.Setenv("VIR_GPU_MAX_VREGS", fmt.Sprintf("%d", maxVregs))
			gf, nv, err := BuildGPUDesc(islandOps, desc, SolverOptions{})
			if origMax != "" {
				os.Setenv("VIR_GPU_MAX_VREGS", origMax)
			} else {
				os.Unsetenv("VIR_GPU_MAX_VREGS")
			}

			if err != nil {
				fmt.Fprintf(os.Stderr, "[islands] %s island %d: BuildGPUDesc: %v\n", cfg.Func, i, err)
				continue
			}

			name := fmt.Sprintf("%s_island%d", cfg.Func, i)
			results = append(results, islandResult{
				Name:        name,
				Func:        cfg.Func,
				IslandIdx:   i,
				PCRange:     [2]int{start, end},
				NVregs:      nv,
				Desc:        gf,
				BoundaryIn:  boundaryIn,
				BoundaryOut: boundaryOut,
			})
			fmt.Fprintf(os.Stderr, "[islands] %s: %dv, %d ops, %d intf, boundary in=%d out=%d\n",
				name, nv, len(gf.Ops), len(gf.Interference), len(boundaryIn), len(boundaryOut))
		}
	}

	jsonData, err := json.MarshalIndent(results, "", "  ")
	if err != nil {
		fmt.Fprintf(os.Stderr, "[islands] marshal error: %v\n", err)
		return
	}
	if err := os.WriteFile(outPath, append(jsonData, '\n'), 0644); err != nil {
		fmt.Fprintf(os.Stderr, "[islands] write error: %v\n", err)
		return
	}
	fmt.Fprintf(os.Stderr, "[islands] dumped %d islands to %s\n", len(results), outPath)
}

// autoDetectIslands finds split points for functions with >maxVregs vregs.
// Splits at call sites where liveness ≤ liveThreshold.
func autoDetectIslands(m *mir2.Module, desc *MachineDesc, maxVregs, liveThreshold int) []islandConfig {
	var configs []islandConfig

	for _, f := range m.Funcs {
		vf, err := LowerFunc(f, desc, m)
		if err != nil {
			continue
		}

		var allOps []VIROp
		for _, b := range vf.Blocks {
			allOps = append(allOps, b.Ops...)
		}

		prob := buildProblem(allOps, desc)
		if len(prob.vregs) <= maxVregs {
			continue
		}

		// Find split points: call sites with low liveness
		var splits []int
		for i, op := range allOps {
			if (op.Op == OpCall || op.Op == OpAsmBlock) && i > 0 && i < len(allOps)-1 {
				if i < len(prob.liveness) && len(prob.liveness[i].live) <= liveThreshold {
					splits = append(splits, i)
				}
			}
		}

		if len(splits) > 0 {
			// Greedily merge adjacent islands that would have ≤ maxVregs
			filtered := greedyMergeIslands(allOps, prob, splits, maxVregs)
			if len(filtered) > 0 {
				configs = append(configs, islandConfig{Func: f.Name, Splits: filtered})
			}
		}
	}

	return configs
}

// greedyMergeIslands merges adjacent tiny islands while staying ≤ maxVregs.
// Returns split points (exclusive ends of islands, except last which is implicit).
func greedyMergeIslands(ops []VIROp, prob *problem, splits []int, maxVregs int) []int {
	countVregs := func(start, end int) int {
		seen := make(map[int]bool)
		for i := start; i < end && i < len(ops); i++ {
			op := ops[i]
			if op.Dst > 0 { seen[op.Dst] = true }
			for _, s := range op.Src {
				if s > 0 { seen[s] = true }
			}
		}
		return len(seen)
	}

	// All boundaries: [0, split0, split1, ..., len(ops)]
	bounds := []int{0}
	bounds = append(bounds, splits...)
	bounds = append(bounds, len(ops))

	// Greedy: walk through boundaries, accumulate segments while ≤ maxVregs
	var result []int
	islandStart := 0
	lastGoodSplit := 0
	for i := 1; i < len(bounds); i++ {
		nv := countVregs(islandStart, bounds[i])
		if nv > maxVregs && lastGoodSplit > islandStart {
			// Split at the last boundary that fit
			result = append(result, lastGoodSplit)
			islandStart = lastGoodSplit
		}
		if countVregs(islandStart, bounds[i]) <= maxVregs {
			lastGoodSplit = bounds[i]
		}
	}

	return result
}

func opName(op Op) string {
	names := map[Op]string{
		OpConst: "const", OpMove: "move", OpAdd: "add", OpSub: "sub",
		OpMul: "mul", OpAnd: "and", OpOr: "or", OpXor: "xor",
		OpCmp: "cmp", OpLoad: "load", OpStore: "store", OpCall: "call",
		OpRet: "ret", OpShl: "shl", OpShr: "shr", OpNeg: "neg",
		OpAddImm: "addimm", OpSubImm: "subimm", OpAndImm: "andimm",
		OpOrImm: "orimm", OpXorImm: "xorimm", OpCmpImm: "cmpimm",
		OpStoreGlobal: "storeglobal", OpLoadGlobal: "loadglobal",
		OpCondRet: "condret", OpLoad16LE: "load16le", OpAsmBlock: "asmblock",
	}
	if n, ok := names[op]; ok {
		return n
	}
	return fmt.Sprintf("op%d", int(op))
}
