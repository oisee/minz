// Z80Codegen lowers allocated MIR2 to Z80 assembly text (.a80 format).
//
// Prerequisites:
//   - AllocResult covering every virtual register in the module
//   - Verified MIR2 module (Verify passed)
//
// Output: a string of Z80 assembly ready for MZA.
// Label format: @funcname_blockname (underscore-joined, no special chars).
//
// Supported opcodes (first pass):
//
//	OpConst        → LD r, n  /  LD rr, nn
//	OpMove         → LD r, r  /  EX DE,HL  /  PUSH+POP
//	OpAdd          → ADD A,r  /  ADD HL,rr
//	OpSub          → SUB r    /  SBC HL,rr
//	OpAnd/Or/Xor   → AND/OR/XOR r
//	OpNeg          → NEG
//	OpNot          → CPL
//	OpExt          → LD H,0 / LD L,r  (zero-extend u8→u16 via HL)
//	OpCmp          → CP r  (result stays in F; ClassFlag)
//	OpLoad         → LD A,(HL)  /  LD r,(HL)
//	OpStore        → LD (HL),A  /  LD (HL),r
//	OpCall         → CALL label
//	OpPatchSlot    → LD r, 0   (initial value; literal byte patchable)
//	OpLoadPatched  → LD r, r   (SMC: already patched in stream)
//	OpPatch        → (comment: SMC patch — no emission in pure assembler)
//	TermJmp        → JP label
//	TermBrIf       → JP Z/NZ/C/NC label  (flag-class cond)
//	TermRet        → RET

// ── Public entry point ────────────────────────────────────────────────────────

// Z80Codegen generates Z80 assembly for the entire module.
func Z80Codegen(m *Module, ar *AllocResult) string {
	var sb strings.Builder
	cg := &z80cg{ar: ar, sb: &sb, mod: m}

	sb.WriteString("; generated by MIR2 Z80 codegen\n\n")

	for _, f := range m.Funcs {
		cg.genFunc(f)
		sb.WriteByte('\n')
	}

	// Emit global variable data sections.
	if len(m.Globals) > 0 {
		sb.WriteString("; globals\n")
		for _, g := range m.Globals {
			w := ByteWidth(g.Ty)
			if w == 0 {
				continue
			}
			// Page-aligned globals (e.g. LUT tables): emit ALIGN directive first.
			if at, ok := g.Ty.(*ArrayTy); ok && at.Align > 0 {
				fmt.Fprintf(&sb, "    ALIGN %d\n", at.Align)
			}
			sanitized := sanitizeIdent(g.Name)
			sb.WriteString(sanitized + ":\n")
			// Emit as DB sequence for all types — always readable,
			// correct for struct fields, and unambiguous byte order.
			sb.WriteString("    DB ")
			for i := 0; i < w; i++ {
				if i > 0 {
					sb.WriteString(", ")
				}
				b := byte(0)
				if i < len(g.Init) {
					b = g.Init[i]
				}
				fmt.Fprintf(&sb, "%d", b)
			}
			sb.WriteByte('\n')
			// For struct globals, emit EQU labels for each field so that direct
			// addressing (LD A,(sym__field)) works without pointer arithmetic.
			// Format: sanitizeIdent(sym)__fieldName  EQU  sym + byteOffset
			if st, ok := g.Ty.(*StructTy); ok {
				off := 0
				for _, f := range st.Fields {
					var equLbl string
					if f.Name != "" {
						equLbl = sanitized + "__" + f.Name
					} else {
						equLbl = fmt.Sprintf("%s__off%d", sanitized, off)
					}
					if off == 0 {
						fmt.Fprintf(&sb, "%s    EQU  %s\n", equLbl, sanitized)
					} else {
						fmt.Fprintf(&sb, "%s    EQU  %s + %d\n", equLbl, sanitized, off)
					}
					off += ByteWidth(f.Ty)
				}
			}
		}
	}

	// Emit string pool — NUL-terminated byte sequences.
	// Symbol names: @mir2.str.N → mir2_str_N (sanitized for assembler).
	if m.Strings.Len() > 0 {
		sb.WriteString("; strings\n")
		for i := 0; i < m.Strings.Len(); i++ {
			sym := sanitizeIdent(m.Strings.Symbol(i))
			s := m.Strings.At(i)
			sb.WriteString(sym + ":\n")
			sb.WriteString("    DB ")
			for j, c := range []byte(s) {
				if j > 0 {
					sb.WriteString(", ")
				}
				fmt.Fprintf(&sb, "%d", c)
			}
			sb.WriteString(", 0\n") // NUL terminator
		}
	}

	return sb.String()
}

// ── Internal codegen state ────────────────────────────────────────────────────

type z80cg struct {
	ar         *AllocResult
	sb         *strings.Builder
	mod        *Module // parent module (for callee contract lookup at call sites)
	fn         *Func   // current function
	blockIdx   int     // index of current block in fn.Blocks (for fall-through)
	cmpSwapped  map[Reg]bool    // dst reg → operands were swapped in genCmp
	cmpAndZero  map[Reg]bool    // dst reg → comparison used AND A (rhs=0), use NZ/Z not NC/C
	cmpNeedsTwo map[Reg]bool    // dst reg → CmpGt/CmpLe with lhs in A, needs two-JP in BrIf
	callFlags   map[Reg]CmpCond // dst reg of OpCall → FlagCond when callee returns ClassFlag
	constVals  map[Reg]int64 // virtual reg → compile-time constant value (for peepholes)
	deadConsts map[Reg]bool  // OpConst dsts whose LD is suppressed by DSE

	// holdsPhys is a bidirectional alias map for local copy-propagation within a
	// basic block.  holdsPhys[r] = s means physical register r currently holds the
	// same value as s (and holdsPhys[s] = r by symmetry).  Used to eliminate
	// redundant LD instructions: if A ≡ D, we skip "LD A, D" before an ALU op.
	// The map is cleared at every block boundary and at any CALL.
	holdsPhys map[string]string

	// physOverride tracks dynamic relocation of virtual registers that happened
	// as a side-effect of call-argument setup (emitCallArgs parallel copies).
	// physOverride[r] = "B" means virtual register r is now in physical "B",
	// overriding the static allocator assignment g.ar.Loc(r).Name.
	// Cleared at every CALL (the call clobbers volatile state).
	physOverride map[Reg]string

	// trampolines: small glue blocks emitted after main function body that
	// perform block-argument parallel copies then jump to the real target.
	// Needed for BrIf edges where the non-fall-through path requires copies.
	trampolines []trampolineBlock
	trampIdx    int

	// Page-aligned LUT optimisation (21T vs 39T).
	// Pre-scanned per block; cleared at each new block.
	//
	// lutLoadPat: Load dst → pattern descriptor for page-aligned table accesses.
	//   When set, emit LD HL,sym + LD L,src8 + LD A,(HL) instead of the
	//   general Ext+PtrAdd+Load sequence.
	// lutSkip: virtual regs whose emit is merged into the Load instruction above.
	//   Affected: Ext(idx16), AddrOf(base), PtrAdd(ptr).
	lutLoadPat map[Reg]lutLoadPat
	lutSkip    map[Reg]bool

	// Global struct field direct-addressing optimisation.
	// Pre-scanned per block; cleared at each new block.
	//
	// globalFieldLoad[loadDst]  → info for emitting LD A,(sym__field) / LD (sym__field),A
	// globalFieldStore[addrReg] → info for emitting LD (sym__field),val
	// globalFieldSkip[r]        → these intermediate regs are no-ops in genInst
	//   Affected: AddrOf(base), Field(fptr), and (for stores) the store's addrReg.
	globalFieldLoad  map[Reg]globalFieldInfo
	globalFieldStore map[Reg]globalFieldInfo
	globalFieldSkip  map[Reg]bool

	// lastFlagsLhs / lastFlagsRhs track the effective operands of the most recent
	// flags-setting instruction (SUB / CP / AND A) within the current block.
	// Empty strings mean "unknown / not tracked".
	// Used by genCmp to suppress a redundant CP when SUB already set the same flags.
	lastFlagsLhs string // physical location of the lhs (always A at time of emission)
	lastFlagsRhs string // physical location or immediate string of the rhs
}

// lutLoadPat describes a page-aligned LUT access merged at codegen time.
type lutLoadPat struct {
	sym     string // page-aligned global symbol
	src8Reg Reg    // virtual reg holding the 8-bit index (after lo-subtract if any)
}

// globalFieldInfo describes a global struct field access that can be lowered
// to direct Z80 addressing: LD A,(sym__field) or LD (sym__field),A.
//
// The EQU label is: {sanitizeIdent(sym)}__{fieldName}  (or just sanitizeIdent(sym) for offset 0).
// Emission: LD A,(sym__field)  for loads; LD A,val + LD (sym__field),A  for stores.
type globalFieldInfo struct {
	sym       string // global symbol name (raw, before sanitize)
	offset    int64  // byte offset within the global
	fieldName string // field name for the EQU label (may be empty → use offset)
	// HL-chain: when true, emit LD HL,sym chain instead of LD (sym__field),A.
	hlChain bool // part of a consecutive-field HL-chain group
	hlHead  bool // first in group → emit LD HL,sym before
	hlLast  bool // last in group  → no INC HL after
}

// trampolineBlock is emitted after all regular blocks of a function.
// It resolves block-argument copies for one outgoing BrIf edge.
type trampolineBlock struct {
	label  string        // local label for this trampoline
	copies []parallelCopy
	target string        // real destination label (already formatted)
}

// parallelCopy is a single register-to-register move in a parallel copy sequence.
type parallelCopy struct {
	srcName string
	dstName string
	ty      Ty
}

func (g *z80cg) emit(s string) { g.sb.WriteString(s); g.sb.WriteByte('\n') }
func (g *z80cg) emitf(f string, args ...any) { g.emit(fmt.Sprintf(f, args...)) }
func (g *z80cg) comment(s string)            { g.emitf("    ; %s", s) }

// isIXY reports whether reg is an index register (IX or IY).
// Z80 indexed loads/stores require explicit displacement: (IX+d), never bare (IX).
func isIXY(reg string) bool { return reg == "IX" || reg == "IY" }

// ptrIndirect returns the memory-operand string for a pointer register.
// For IX/IY the Z80 requires an explicit displacement byte — even zero:
//
//	HL → "(HL)"
//	IX → "(IX+0)"   DE → "(DE)"
//
// An optional byte offset d shifts the displacement for 16-bit multi-byte accesses.
func ptrIndirect(ptr string, d int) string {
	if isIXY(ptr) {
		if d == 0 {
			return fmt.Sprintf("(%s+0)", ptr)
		}
		return fmt.Sprintf("(%s+%d)", ptr, d)
	}
	return fmt.Sprintf("(%s)", ptr)
}

// isSimpleReg reports whether s names a plain physical register (no parens,
// no digits) — safe to use as an alias key in holdsPhys.
func isSimpleReg(s string) bool {
	if len(s) == 0 {
		return false
	}
	for _, c := range s {
		if !((c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z')) {
			return false
		}
	}
	return true
}

// ── Register topology ─────────────────────────────────────────────────────────
//
// Writing to a 16-bit pair register (e.g. HL) implicitly changes its bytes
// (H, L), and vice versa: writing to H invalidates HL.  These tables encode
// that topology so invalidate() can clear all affected aliases at once.

// regBytes maps a 16-bit register to its 8-bit byte components.
var regBytes = map[string][]string{
	"BC": {"B", "C"},
	"DE": {"D", "E"},
	"HL": {"H", "L"},
	"IX": {"IXH", "IXL"},
	"IY": {"IYH", "IYL"},
}

// regParent maps an 8-bit component to its 16-bit parent register.
var regParent = map[string]string{
	"B": "BC", "C": "BC",
	"D": "DE", "E": "DE",
	"H": "HL", "L": "HL",
	"IXH": "IX", "IXL": "IX",
	"IYH": "IY", "IYL": "IY",
}

// killOne removes a single register and its bidirectional partner from holdsPhys.
func (g *z80cg) killOne(r string) {
	if partner, ok := g.holdsPhys[r]; ok {
		delete(g.holdsPhys, partner)
		delete(g.holdsPhys, r)
	}
}

// invalidate removes all tracking for r: kills r itself, its byte components
// (if r is a 16-bit pair), and its parent pair (if r is an 8-bit component).
func (g *z80cg) invalidate(r string) {
	g.killOne(r)
	if bytes, ok := regBytes[r]; ok {
		for _, b := range bytes {
			g.killOne(b)
		}
	}
	if parent, ok := regParent[r]; ok {
		g.killOne(parent)
	}
}

// setCopy records that dst was loaded from src (they now hold the same value).
// Invalidates dst's old aliases and clears src's previous bidirectional link
// before establishing the new one, preventing stale reverse entries.
func (g *z80cg) setCopy(dst, src string) {
	g.invalidate(dst)
	g.killOne(src) // break src's old reverse-link (could be left by a prior setCopy)
	if isSimpleReg(dst) && isSimpleReg(src) {
		g.holdsPhys[dst] = src
		g.holdsPhys[src] = dst
	}
}

// holdsValue reports whether physical register a currently holds the same
// value as b (either they are the same register, or a copy alias exists).
func (g *z80cg) holdsValue(a, b string) bool {
	return a == b || g.holdsPhys[a] == b
}

// emitLDA emits "LD A, src" and records the copy alias A ≡ src.
func (g *z80cg) emitLDA(src string) {
	g.emitf("    LD A, %s", src)
	g.setCopy("A", src)
}

// loc returns the physical location name for virtual register r.
func (g *z80cg) loc(r Reg) string {
	if r == NoReg {
		return "?"
	}
	if phys, ok := g.physOverride[r]; ok {
		return phys
	}
	return g.ar.Loc(r).Name
}

// ── Function ──────────────────────────────────────────────────────────────────

// computeDeadConsts returns the set of OpConst dsts whose LD can be suppressed
// because every use of the constant is already handled by a codegen peephole:
//
//   - OpCmp with Src[1] being the const → CP imm8 fires (no register needed).
//   - OpAdd/OpSub with Src[1]==const, value==1, and lhs/dst at the same physical
//     location → INC/DEC fires (no register needed).
//
// Constants with zero uses are also suppressed.
func computeDeadConsts(f *Func, ar *AllocResult) map[Reg]bool {
	// Collect all OpConst dsts and their immediate values.
	constVal := make(map[Reg]int64)
	for _, b := range f.Blocks {
		for _, inst := range b.Insts {
			if inst.Op == OpConst {
				constVal[inst.Dst] = inst.Imm
			}
		}
	}
	if len(constVal) == 0 {
		return nil
	}

	physName := func(r Reg) string {
		if loc, ok := ar.Locs[r]; ok {
			return loc.Name
		}
		return ""
	}

	totalUses  := make(map[Reg]int)
	foldedUses := make(map[Reg]int)

	for _, b := range f.Blocks {
		for _, inst := range b.Insts {
			// Call/CallIndirect args live in inst.Args, not inst.Src — count them
			// as non-peephole uses so their LD is not suppressed.
			for _, src := range inst.Args {
				if _, isConst := constVal[src]; isConst {
					totalUses[src]++
					// call args are never peephole-foldable
				}
			}
			for _, src := range inst.Src {
				cv, isConst := constVal[src]
				if !isConst {
					continue
				}
				totalUses[src]++
				switch inst.Op {
				case OpCmp:
					// CP imm8: fires when rhs (Src[1]) has a known constant.
					if src == inst.Src[1] {
						foldedUses[src]++
					}
				case OpAdd, OpSub:
					// INC/DEC: fires when rhs==1 and the op is in-place (lhs phys == dst phys).
					if src == inst.Src[1] && cv == 1 &&
						physName(inst.Src[0]) == physName(inst.Dst) {
						foldedUses[src]++
					}
				case OpAnd, OpOr, OpXor:
					// AND/OR/XOR immediate peephole: always emits "AND n" etc., no register needed.
					if src == inst.Src[1] {
						foldedUses[src]++
					}
				case OpMul:
					// genMul folds constant Src[1] into shift sequences.
					if src == inst.Src[1] {
						foldedUses[src]++
					}
					case OpShl, OpShr, OpSar:
					// genShift always shifts by 1 and completely ignores Src[1].
					// Any constant passed as the shift count is effectively dead.
					if src == inst.Src[1] {
						foldedUses[src]++
					}
				}
			}
		}
		// Block args in terminators (TermJmp.Args, TermBrIf.*Args, TermRet.Vals)
		// are general uses — they cannot be peephole-folded.
		if b.Term != nil {
			for _, src := range b.Term.termUses() {
				if _, isConst := constVal[src]; isConst {
					totalUses[src]++
					// no foldedUses increment — terminators are never peephole-dead
				}
			}
		}
	}

	dead := make(map[Reg]bool)
	for r := range constVal {
		total := totalUses[r]
		if total == 0 || total == foldedUses[r] {
			dead[r] = true
		}
	}
	return dead
}

func (g *z80cg) genFunc(f *Func) {
	g.fn = f
	g.cmpSwapped = make(map[Reg]bool)
	g.cmpAndZero = make(map[Reg]bool)
	g.cmpNeedsTwo = make(map[Reg]bool)
	g.callFlags = make(map[Reg]CmpCond)
	g.constVals = make(map[Reg]int64)
	g.deadConsts = computeDeadConsts(f, g.ar)
	g.holdsPhys = make(map[string]string)
	g.physOverride = make(map[Reg]string)
	g.trampolines = g.trampolines[:0]
	g.trampIdx = 0
	g.lutLoadPat = make(map[Reg]lutLoadPat)
	g.lutSkip = make(map[Reg]bool)
	g.globalFieldLoad = make(map[Reg]globalFieldInfo)
	g.globalFieldStore = make(map[Reg]globalFieldInfo)
	g.globalFieldSkip = make(map[Reg]bool)

	label := sanitizeIdent(f.Name)
	g.emitf("%s:", label)

	for i, b := range f.Blocks {
		g.blockIdx = i
		g.genBlock(f, b)
	}

	// Emit trampoline blocks: small copy+JR stubs for BrIf edges with block args.
	// MZA auto-promotes JR→JP if the target is beyond ±127 bytes.
	for _, tramp := range g.trampolines {
		g.emitf("%s:", tramp.label)
		g.emitParallelCopy(tramp.copies)
		g.emitf("    JRS %s", tramp.target)
	}
}

// ── Page-aligned LUT pre-scan ──────────────────────────────────────────────────

// scanLUTPatterns detects the pattern emitted by LUTGen for page-aligned tables:
//
//	idx16 = Ext(src8, u8→u16, ClassIndex)
//	base  = AddrOf("sym")                      ← sym has Align==256
//	ptr   = PtrAdd(base, idx16)
//	dst   = Load(ptr, u8, ClassAcc)
//
// When found:
//   - g.lutLoadPat[dst] = {sym, src8Reg}
//   - g.lutSkip[idx16, base, ptr] = true
//
// The pattern is cleared (g.lutLoadPat, g.lutSkip rebuilt) at each new block.
// This is safe because LUTGen only ever creates single-use intermediate regs.
func (g *z80cg) scanLUTPatterns(b *Block) {
	// Reset per-block maps (keep same map objects; just clear them).
	clear(g.lutLoadPat)
	clear(g.lutSkip)

	// Build: reg → defining instruction (within this block only).
	defInst := make(map[Reg]*Inst, len(b.Insts))
	for _, inst := range b.Insts {
		if inst.Dst != NoReg {
			defInst[inst.Dst] = inst
		}
	}

	for _, inst := range b.Insts {
		// Looking for: dst = Load(ptr, u8)
		if inst.Op != OpLoad || inst.Ty.Width() != 8 || inst.Dst == NoReg {
			continue
		}
		ptrReg := inst.Src[0]

		// ptr = PtrAdd(base, idx16)
		ptrInst, ok := defInst[ptrReg]
		if !ok || ptrInst.Op != OpPtrAdd {
			continue
		}
		baseReg := ptrInst.Src[0]
		idx16Reg := ptrInst.Src[1]

		// base = AddrOf(sym) where sym is page-aligned
		baseInst, ok := defInst[baseReg]
		if !ok || baseInst.Op != OpAddrOf {
			continue
		}
		sym := baseInst.Sym
		if !g.isGlobalPageAligned(sym) {
			continue
		}

		// idx16 = Ext(src8, u8→u16)
		extInst, ok := defInst[idx16Reg]
		if !ok || extInst.Op != OpExt {
			continue
		}
		if extInst.SrcTy == nil || extInst.SrcTy.Width() != 8 || extInst.Ty.Width() != 16 {
			continue
		}
		src8Reg := extInst.Src[0]

		// Pattern matched: record and mark intermediates for skipping.
		g.lutLoadPat[inst.Dst] = lutLoadPat{sym: sym, src8Reg: src8Reg}
		g.lutSkip[idx16Reg] = true
		g.lutSkip[baseReg] = true
		g.lutSkip[ptrReg] = true
	}
}

// isGlobalPageAligned reports whether the named global in the current module
// has Align == 256 (i.e. is a page-aligned LUT candidate).
func (g *z80cg) isGlobalPageAligned(sym string) bool {
	for _, gl := range g.mod.Globals {
		if gl.Name == sym {
			if at, ok := gl.Ty.(*ArrayTy); ok {
				return at.Align == 256
			}
		}
	}
	return false
}

// globalFieldLabel returns the EQU label for a global struct field access.
// Format: sanitizeIdent(sym)__fieldName  (or just sanitizeIdent(sym) for offset 0 / no name).
func globalFieldLabel(sym string, offset int64, fieldName string) string {
	base := sanitizeIdent(sym)
	if fieldName != "" {
		return base + "__" + fieldName
	}
	if offset == 0 {
		return base
	}
	return fmt.Sprintf("%s__off%d", base, offset)
}

// globalStructField looks up a global in the module by symbol name and returns its
// StructTy if it has one, plus the field name for a given byte offset.
// Returns ("", -1, false) when not found or not a struct global.
func (g *z80cg) globalStructField(sym string, offset int64) (fieldName string, found bool) {
	for _, gl := range g.mod.Globals {
		if gl.Name != sym {
			continue
		}
		st, ok := gl.Ty.(*StructTy)
		if !ok {
			return "", false
		}
		// Find field by byte offset.
		off := int64(0)
		for _, f := range st.Fields {
			if off == offset {
				return f.Name, true
			}
			off += int64(ByteWidth(f.Ty))
		}
		// Offset is valid but doesn't align with a named field boundary — still use it.
		return "", false
	}
	return "", false
}

// scanGlobalFieldPatterns detects patterns where a global struct field is loaded
// or stored via AddrOf + optional Field + Load/Store.  When found, the load/store
// is rewritten to use Z80 direct addressing (LD A,(sym__field) or LD (sym__field),A).
//
// Patterns detected (u8 only — all addressable via single LD A,(nn)):
//
//	Load pattern (with field):
//	  base  = AddrOf(sym)            [OpAddrOf]
//	  fptr  = Field(base, imm)       [OpField]
//	  dst   = Load(fptr, u8)         [OpLoad]
//
//	Load pattern (field 0, no OpField):
//	  base  = AddrOf(sym)            [OpAddrOf]
//	  dst   = Load(base, u8)         [OpLoad]
//
//	Store pattern (with field):
//	  base  = AddrOf(sym)
//	  fptr  = Field(base, imm)
//	          Store(fptr, val, u8)   [OpStore, Dst==NoReg]
//
//	Store pattern (field 0):
//	  base  = AddrOf(sym)
//	          Store(base, val, u8)
//
// Only fires when the AddrOf refers to a global in m.Globals (not a func symbol).
// Only u8 loads and stores are handled (single-byte LD A,(nn) / LD (nn),A).
func (g *z80cg) scanGlobalFieldPatterns(b *Block) {
	// Reset per-block maps.
	clear(g.globalFieldLoad)
	clear(g.globalFieldStore)
	clear(g.globalFieldSkip)

	// Build: reg → defining instruction within this block.
	defInst := make(map[Reg]*Inst, len(b.Insts))
	for _, inst := range b.Insts {
		if inst.Dst != NoReg {
			defInst[inst.Dst] = inst
		}
	}

	// Helper: check if sym names a module-level global (not a string or function symbol).
	isGlobal := func(sym string) bool {
		for _, gl := range g.mod.Globals {
			if gl.Name == sym {
				return true
			}
		}
		return false
	}

	// Count uses of each virtual reg in this block (instructions + block terminators).
	// Used to guard against skipping intermediates that are shared with other users.
	useCount := make(map[Reg]int)
	for _, inst := range b.Insts {
		for _, s := range inst.Src {
			if s != NoReg {
				useCount[s]++
			}
		}
		for _, s := range inst.Args {
			if s != NoReg {
				useCount[s]++
			}
		}
	}
	if b.Term != nil {
		for _, s := range b.Term.termUses() {
			if s != NoReg {
				useCount[s]++
			}
		}
	}

	// Scan Load instructions.
	// Only mark intermediates as skip when:
	//   1. The load's allocated destination IS A (LD A,(nn) is the only direct read on Z80).
	//   2. Each intermediate register (AddrOf/Field results) is used exactly once —
	//      by this Load (and the Field uses the AddrOf, counted once).
	//      If an intermediate is shared (e.g., base ptr reused for multiple fields),
	//      we must not skip it or the other consumer will see a dead register.
	for _, inst := range b.Insts {
		if inst.Op == OpLoad && inst.Ty.Width() == 8 && inst.Dst != NoReg {
			// Only apply when the allocated destination is the A register.
			if g.ar.Loc(inst.Dst).Name != "A" {
				continue
			}
			ptrReg := inst.Src[0]
			ptrInst, hasDef := defInst[ptrReg]
			if !hasDef {
				continue
			}

			switch ptrInst.Op {
			case OpAddrOf:
				// Pattern: Load(AddrOf(sym), u8)  — offset 0
				if !isGlobal(ptrInst.Sym) {
					continue
				}
				// Only skip AddrOf if its result is used only by this Load.
				if useCount[ptrReg] != 1 {
					continue
				}
				fieldName, _ := g.globalStructField(ptrInst.Sym, 0)
				g.globalFieldLoad[inst.Dst] = globalFieldInfo{
					sym:       ptrInst.Sym,
					offset:    0,
					fieldName: fieldName,
				}
				g.globalFieldSkip[ptrReg] = true

			case OpField:
				// Pattern: Load(Field(AddrOf(sym), imm), u8)
				// Guard: Field result used only by this Load, AddrOf result used only by Field.
				if useCount[ptrReg] != 1 {
					continue
				}
				baseReg := ptrInst.Src[0]
				baseDef, ok := defInst[baseReg]
				if !ok || baseDef.Op != OpAddrOf {
					continue
				}
				if !isGlobal(baseDef.Sym) {
					continue
				}
				if useCount[baseReg] != 1 {
					continue
				}
				offset := ptrInst.Imm
				fieldName, _ := g.globalStructField(baseDef.Sym, offset)
				g.globalFieldLoad[inst.Dst] = globalFieldInfo{
					sym:       baseDef.Sym,
					offset:    offset,
					fieldName: fieldName,
				}
				g.globalFieldSkip[ptrReg] = true    // Field result
				g.globalFieldSkip[baseReg] = true   // AddrOf result
			}
		}
	}

	// Scan Store instructions (Dst==NoReg, Src[0]=addr, Src[1]=val).
	for _, inst := range b.Insts {
		if inst.Op != OpStore || inst.Ty.Width() != 8 {
			continue
		}
		addrReg := inst.Src[0]
		addrInst, hasDef := defInst[addrReg]
		if !hasDef {
			continue
		}

		switch addrInst.Op {
		case OpAddrOf:
			if !isGlobal(addrInst.Sym) {
				continue
			}
			// Only skip if the AddrOf result is used solely by this Store.
			if useCount[addrReg] != 1 {
				continue
			}
			fieldName, _ := g.globalStructField(addrInst.Sym, 0)
			g.globalFieldStore[addrReg] = globalFieldInfo{
				sym:       addrInst.Sym,
				offset:    0,
				fieldName: fieldName,
			}
			g.globalFieldSkip[addrReg] = true

		case OpField:
			if useCount[addrReg] != 1 {
				continue
			}
			baseReg2 := addrInst.Src[0]
			baseDef, ok := defInst[baseReg2]
			if !ok || baseDef.Op != OpAddrOf {
				continue
			}
			if !isGlobal(baseDef.Sym) {
				continue
			}
			if useCount[baseReg2] != 1 {
				continue
			}
			offset := addrInst.Imm
			fieldName, _ := g.globalStructField(baseDef.Sym, offset)
			g.globalFieldStore[addrReg] = globalFieldInfo{
				sym:       baseDef.Sym,
				offset:    offset,
				fieldName: fieldName,
			}
			g.globalFieldSkip[addrReg] = true     // Field result
			g.globalFieldSkip[baseReg2] = true    // AddrOf result
		}
	}

	// ── HL-chain detection ──────────────────────────────────────────────────────
	// When 2+ stores to the same global struct cover consecutive byte offsets and
	// all value registers are safe (not H or L, which alias with the HL pointer),
	// replace independent LD (sym__field),A sequences with:
	//   LD HL,sym  ;  LD (HL),r  ;  INC HL  ;  LD (HL),r  ;  ...
	// Saves 8T and 4 bytes for a 3-field struct (61T→53T, 12B→8B).
	type hlEntry struct {
		addrReg Reg
		valReg  Reg
		offset  int64
	}
	symStores := make(map[string][]hlEntry)
	for addrReg, info := range g.globalFieldStore {
		for _, inst := range b.Insts {
			if inst.Op == OpStore && inst.Src[0] == addrReg {
				symStores[info.sym] = append(symStores[info.sym], hlEntry{
					addrReg: addrReg,
					valReg:  inst.Src[1],
					offset:  info.offset,
				})
				break
			}
		}
	}
	for _, entries := range symStores {
		if len(entries) < 2 {
			continue
		}
		sort.Slice(entries, func(i, j int) bool { return entries[i].offset < entries[j].offset })
		// Check consecutive offsets.
		consecutive := true
		for i := 1; i < len(entries); i++ {
			if entries[i].offset != entries[i-1].offset+1 {
				consecutive = false
				break
			}
		}
		if !consecutive {
			continue
		}
		// Check all value regs safe (not H/L which aliases with HL pointer).
		safe := true
		for _, e := range entries {
			if e.valReg != NoReg {
				loc := g.ar.Loc(e.valReg).Name
				if loc == "H" || loc == "L" {
					safe = false
					break
				}
			}
		}
		if !safe {
			continue
		}
		// Mark as HL-chain.
		for i, e := range entries {
			entry := g.globalFieldStore[e.addrReg]
			entry.hlChain = true
			entry.hlHead = (i == 0)
			entry.hlLast = (i == len(entries)-1)
			g.globalFieldStore[e.addrReg] = entry
		}
	}
}

// ── Block ─────────────────────────────────────────────────────────────────────

func (g *z80cg) genBlock(f *Func, b *Block) {
	if b.Label != "entry" {
		g.emitf(".%s_%s:", sanitizeIdent(f.Name), sanitizeIdent(b.Label))
	}
	clear(g.holdsPhys)       // all register aliases unknown at block entry
	g.lastFlagsLhs = ""      // flags state unknown at block entry
	g.lastFlagsRhs = ""

	// Pre-scan: identify page-aligned LUT access patterns so we can merge
	// Ext + AddrOf + PtrAdd + Load into: LD HL,sym; LD L,src8; LD A,(HL).
	g.scanLUTPatterns(b)

	// Pre-scan: identify global struct field accesses so we can emit
	// LD A,(sym__field) / LD (sym__field),A instead of LD HL,sym + INC HL… + LD A,(HL).
	g.scanGlobalFieldPatterns(b)

	// Detect DJNZ peephole: DEC B + JP loop_head → DJNZ loop_body.
	peep := g.detectDJNZPeephole(f, b)

	limit := len(b.Insts)
	if peep.skipLast {
		limit-- // skip final DEC B; DJNZ handles it
	}
	for _, inst := range b.Insts[:limit] {
		g.genInst(inst)
	}

	if peep.bodyLbl != "" {
		g.emitf("    DJNZ %s", peep.bodyLbl)
		// Exit path after DJNZ falls through (B=0).
		// Use the check block's Else edge copies.
		exitCopies := g.buildBlockCopies(f, peep.checkBrif.Else, peep.checkBrif.ElseArgs)
		g.emitParallelCopy(exitCopies)
		if !g.isFallThrough(f, peep.checkBrif.Else) || len(exitCopies) != 0 {
			g.emitf("    JRS %s", blockLabel(f.Name, peep.checkBrif.Else))
		}
	} else {
		g.genTerm(f, b.Term)
	}
}

// ── Instructions ──────────────────────────────────────────────────────────────

func (g *z80cg) genInst(inst *Inst) {
	// Instructions merged into a page-aligned LUT load are skipped here;
	// their code is emitted by the Load case below.
	if g.lutSkip[inst.Dst] {
		return
	}

	// Instructions merged into a global-field direct-addressing sequence are
	// skipped here; their code is emitted by the Load/Store case below.
	// (Stores have Dst==NoReg; check the addr-reg via the instruction's Src[0].)
	if inst.Op != OpStore && g.globalFieldSkip[inst.Dst] {
		return
	}

	// Flag-clobbering ops clear lastFlagsLhs/Rhs explicitly in their cases.
	// Flag-preserving ops (LD, PUSH, POP, …) leave the tracker intact so that
	// the Sub+CmpLt flag-fusion peephole can fire across an intervening LD.

	dst := g.loc(inst.Dst)

	switch inst.Op {
	case OpConst:
		g.constVals[inst.Dst] = inst.Imm
		if dst == "F" {
			// Bool constant into flag register: SCF (true) or AND A (false, clears C+sets Z).
			g.lastFlagsLhs = ""
			g.lastFlagsRhs = ""
			if inst.Imm != 0 {
				g.emit("    SCF")
			} else {
				g.emit("    AND A") // A=A (no change), clears C, sets Z based on A
			}
			return
		}
		if !g.deadConsts[inst.Dst] {
			g.emitf("    LD %s, %d", dst, inst.Imm)
		}

	case OpMove:
		src := g.loc(inst.Src[0])
		if dst == src {
			return // no-op
		}
		g.emitMov(dst, src, inst.Ty.Width())

	case OpAdd:
		g.lastFlagsLhs = ""
		g.lastFlagsRhs = ""
		g.genBinOp("ADD", inst)

	case OpSub:
		g.lastFlagsLhs = "" // clear stale tracking before this sub
		g.lastFlagsRhs = ""
		g.genBinOp("SUB", inst)
		// Record that flags were set by SUB(lhs, rhs) for the Sub+CmpLt fusion.
		// Only track 8-bit subs; 16-bit uses SBC which sets different flags.
		if inst.Ty.Width() <= 8 {
			rhsP := g.loc(inst.Src[1])
			if cv, ok := g.constVals[inst.Src[1]]; ok {
				rhsP = fmt.Sprintf("%d", cv)
			}
			if rhsP != "A" { // skip NEG-trick case (rhs was in A)
				g.lastFlagsLhs = g.loc(inst.Src[0]) // logical lhs
				g.lastFlagsRhs = rhsP
			}
		}

	case OpMul:
		g.lastFlagsLhs = ""
		g.lastFlagsRhs = ""
		g.genMul(inst)

	case OpAnd:
		g.lastFlagsLhs = ""
		g.lastFlagsRhs = ""
		g.genBinOp("AND", inst)

	case OpOr:
		g.lastFlagsLhs = ""
		g.lastFlagsRhs = ""
		g.genBinOp("OR", inst)

	case OpXor:
		g.lastFlagsLhs = ""
		g.lastFlagsRhs = ""
		g.genBinOp("XOR", inst)

	case OpNeg:
		g.lastFlagsLhs = ""
		g.lastFlagsRhs = ""
		if inst.Ty.Width() == 16 {
			// 16-bit NEG HL using the classic demo-scene SBC A,A trick:
			//   XOR A      ; A=0, CF=0
			//   SUB L      ; A = 0-L, CF=1 if L≠0 (borrow)
			//   LD L, A    ; save negated low byte
			//   SBC A, A   ; A = 0-CF → 0x00 or 0xFF (propagate borrow)
			//   SUB H      ; A = -CF - H  (correct high byte with borrow)
			//   LD H, A    ; save negated high byte
			// 6 bytes, 24T — saves 2 bytes and 7T vs NEG-based sequence.
			g.emit("    XOR A")
			g.emit("    SUB L")
			g.emit("    LD L, A")
			g.emit("    SBC A, A")
			g.emit("    SUB H")
			g.emit("    LD H, A")
			g.invalidate("A")
			g.invalidate("HL")
		} else {
			g.emit("    NEG")
			g.invalidate("A")
		}

	case OpNot:
		g.lastFlagsLhs = ""
		g.lastFlagsRhs = ""
		g.emit("    CPL")
		g.invalidate("A")

	case OpShl:
		g.lastFlagsLhs = ""
		g.lastFlagsRhs = ""
		g.genShift("SLA", inst)

	case OpShr:
		g.lastFlagsLhs = ""
		g.lastFlagsRhs = ""
		g.genShift("SRL", inst)

	case OpSar:
		g.lastFlagsLhs = ""
		g.lastFlagsRhs = ""
		g.genShift("SRA", inst)

	case OpExt:
		// Zero-extend srcTy → Ty.  Primary case: u8 → u16 into HL.
		// genExt may emit XOR (flag-clobbering) — clear to be safe.
		g.lastFlagsLhs = ""
		g.lastFlagsRhs = ""
		g.genExt(inst)

	case OpSext:
		g.lastFlagsLhs = ""
		g.lastFlagsRhs = ""
		g.genSext(inst)

	case OpTrunc:
		src := g.loc(inst.Src[0])
		// Truncate 16-bit → 8-bit: take low byte.
		// If dst is L and src is HL, or dst is E and src is DE — no-op.
		if dst != src {
			g.emitf("    LD %s, %s", dst, lowByte(src))
		}

	case OpCmp:
		g.genCmp(inst)

	case OpLoad:
		// Page-aligned LUT fast path:
		//   LD H, sym^H  ;  7T, 2 bytes — only need the page (high byte)
		//   LD L, idx8   ;  4T           — L is overwritten anyway
		//   LD A, (HL)   ;  7T  → 18T total vs 21T (LD HL) vs 39T general
		// MZA supports the ^H suffix: sym^H extracts (addr >> 8) & 0xFF.
		// LD HL, sym would also load L=low(sym), which is immediately
		// discarded by the following LD L — wasted 3T and 1 byte.
		if pat, ok := g.lutLoadPat[inst.Dst]; ok {
			src8 := g.loc(pat.src8Reg)
			g.emitf("    LD H, %s^H", sanitizeIdent(pat.sym))
			g.invalidate("H")
			g.emitf("    LD L, %s", src8)
			g.invalidate("L")
			if dst != "A" {
				g.emitf("    LD A, (HL)")
				g.invalidate("A")
				g.emitMov(dst, "A", 8)
			} else {
				g.emitf("    LD A, (HL)")
				g.invalidate("A")
			}
			break
		}
		// Global struct field direct-addressing fast path:
		//   LD A, (sym__field)   ; 13T, 3 bytes — direct memory addressing
		// Replaces: LD HL,sym + INC HL×N + LD r,(HL) + (LD A,r)  = 33–43T, 4–8 bytes.
		// Only u8 loads where dst == A are eligible without clobbering risk.
		// When dst != A the intermediates (AddrOf/Field) are NOT skipped in this path,
		// so the original HL-indirect code is emitted instead.
		if info, ok := g.globalFieldLoad[inst.Dst]; ok && dst == "A" {
			lbl := globalFieldLabel(info.sym, info.offset, info.fieldName)
			g.emitf("    LD A, (%s)", lbl)
			g.invalidate("A")
			break
		}
		ptr := g.loc(inst.Src[0])
		w := inst.Ty.Width()
		if w <= 8 {
			// Z80 restriction: only LD A,(BC) and LD A,(DE) exist for BC/DE indirect.
			// Any other destination register must load through A first.
			if (ptr == "BC" || ptr == "DE") && dst != "A" {
				g.emitf("    LD A, %s", ptrIndirect(ptr, 0))
				g.invalidate("A")
				g.emitMov(dst, "A", 8)
			} else {
				g.emitf("    LD %s, %s", dst, ptrIndirect(ptr, 0))
			}
		} else if isIXY(ptr) {
			// 16-bit load via IX/IY: use displacement addressing — avoids INC/DEC IX.
			// LD lo, (IX+0) ; LD hi, (IX+1)  — 2×19T = 38T
			g.emitf("    LD %s, %s     ; lo", lowByte(dst), ptrIndirect(ptr, 0))
			g.emitf("    LD %s, %s     ; hi", highByte(dst), ptrIndirect(ptr, 1))
		} else {
			// 16-bit load via HL/DE/BC: INC/DEC trick — little-endian
			g.emitf("    LD %s, (%s)     ; lo", lowByte(dst), ptr)
			g.emitf("    INC %s", ptr)
			g.emitf("    LD %s, (%s)     ; hi", highByte(dst), ptr)
			g.emitf("    DEC %s", ptr)
		}

	case OpStore:
		addrReg := inst.Src[0]
		if info, ok := g.globalFieldStore[addrReg]; ok && inst.Ty.Width() == 8 {
			if info.hlChain {
				// HL-chain: consecutive field stores share one LD HL,sym base load.
				//   head:  LD HL, sym   ; 10T
				//   each:  LD (HL), r   ; 7T  (r already in correct reg)
				//          INC HL       ; 6T  (omitted for last)
				if info.hlHead {
					g.emitf("    LD HL, %s", sanitizeIdent(info.sym))
				}
				val := g.loc(inst.Src[1])
				g.emitf("    LD (HL), %s", val)
				if !info.hlLast {
					g.emitf("    INC HL")
				}
			} else {
				// Global struct field direct-addressing fast path:
				//   LD A, val           ; 4T (omitted when val is already A)
				//   LD (sym__field), A  ; 13T
				val := g.loc(inst.Src[1])
				lbl := globalFieldLabel(info.sym, info.offset, info.fieldName)
				if val != "A" {
					g.emitLDA(val)
				}
				g.emitf("    LD (%s), A", lbl)
			}
			break
		}
		ptr := g.loc(inst.Src[0])
		val := g.loc(inst.Src[1])
		w := inst.Ty.Width()
		if w <= 8 {
			g.emitf("    LD %s, %s", ptrIndirect(ptr, 0), val)
		} else if isIXY(ptr) {
			// 16-bit store via IX/IY: use displacement addressing — avoids INC/DEC IX.
			// LD (IX+0), lo ; LD (IX+1), hi  — 2×19T = 38T
			g.emitf("    LD %s, %s     ; lo", ptrIndirect(ptr, 0), lowByte(val))
			g.emitf("    LD %s, %s     ; hi", ptrIndirect(ptr, 1), highByte(val))
		} else {
			g.emitf("    LD (%s), %s     ; lo", ptr, lowByte(val))
			g.emitf("    INC %s", ptr)
			g.emitf("    LD (%s), %s     ; hi", ptr, highByte(val))
			g.emitf("    DEC %s", ptr)
		}

	case OpCall, OpCallIndirect:
		g.lastFlagsLhs = ""
		g.lastFlagsRhs = ""
		g.genCall(inst)

	case OpAddrOf:
		g.emitf("    LD %s, %s", dst, inst.Sym)

	case OpPtrAdd:
		// Runtime pointer advance: dst = base_ptr + offset_u16.
		// ADD HL, DE (16-bit) clobbers H and C flags.
		// Z80: needs both operands in 16-bit register pairs.
		// Optimal: base in HL (dst), offset in DE → ADD HL, DE (11T, no A clobber).
		g.lastFlagsLhs = ""
		g.lastFlagsRhs = ""
		base := g.loc(inst.Src[0])
		off := g.loc(inst.Src[1])
		if dst != base {
			g.emitMov(dst, base, 16)
		}
		// Ensure offset is in a 16-bit pair different from dst.
		offPair := off
		if len(off) == 1 { // 8-bit reg (A, B, C, D, E, H, L) — zero-extend to pair
			offPair = "DE"
			if dst == "DE" {
				offPair = "BC"
			}
			g.emitf("    LD %s, 0", offPair)
			g.emitf("    LD %s, %s", lowByte(offPair), off)
		} else if off == dst {
			// Same pair: ADD HL, HL doubles the pointer — that's wrong.
			// Move offset to temp pair first.
			offPair = "DE"
			if dst == "DE" {
				offPair = "BC"
			}
			g.emitMov(offPair, off, 16)
		}
		g.emitf("    ADD %s, %s", dst, offPair)
		g.invalidate(dst)

	case OpField, OpPtrBump:
		// Advance pointer by compile-time byte offset.
		// OpField: struct field access; OpPtrBump: iterator advance.
		// SoA256 special strides: -1 → INC L (element advance), 256 → INC H (field switch).
		// INC and ADD clobber flags.
		g.lastFlagsLhs = ""
		g.lastFlagsRhs = ""
		src := g.loc(inst.Src[0])
		offset := inst.Imm
		if dst != src {
			g.emitMov(dst, src, 16) // copy base ptr
		}
		switch {
		case offset == 0:
			// nothing — dst already at target
		case offset == -1:
			// SoA256: INC L — advance element index (H=column, L=index)
			g.emitf("    INC %s", lowByte(dst))
		case offset == 256:
			// SoA256: INC H — switch to next field column (H=column, L=index)
			g.emitf("    INC %s", highByte(dst))
		case offset <= 3:
			for range offset {
				g.emitf("    INC %s", dst)
			}
		default:
			// LD BC, offset; ADD HL, BC  (or equivalent pair for dst)
			tmp := "BC"
			if dst == "BC" {
				tmp = "DE"
			}
			g.emitf("    LD %s, %d", tmp, offset)
			g.emitf("    ADD %s, %s", dst, tmp)
		}
		g.invalidate(dst)

	case OpAlloca:
		// Reserve bytes on stack; dst = current SP.
		n := inst.Imm
		for range n {
			g.emit("    DEC SP")
		}
		g.emitf("    LD %s, SP", dst)

	case OpPatchSlot:
		// Mutable immediate: emit initial value; the byte after LD is patchable.
		w := inst.Ty.Width()
		if w <= 8 {
			g.emitf("    LD %s, %d          ; [patch_slot init=%d]", dst, inst.Imm, inst.Imm)
		} else {
			g.emitf("    LD %s, %d          ; [patch_slot init=%d]", dst, inst.Imm, inst.Imm)
		}

	case OpLoadPatched:
		// After patching, the slot register already holds the new value.
		// Emit a move; the codegen may elide this if dst == slot.
		slot := g.loc(inst.Src[0])
		if dst != slot {
			g.emitMov(dst, slot, inst.Ty.Width())
		}

	case OpPatch:
		// SMC patch: at runtime the code rewrites the immediate in OpPatchSlot.
		// In the pure-assembler path we emit a self-modifying write sequence.
		// slot = inst.Src[0], newVal = inst.Src[1]
		slotReg := g.loc(inst.Src[0])
		newVal := g.loc(inst.Src[1])
		g.comment(fmt.Sprintf("patch %s ← %s  (SMC: rewrite immediate in stream)", slotReg, newVal))
		// The patch_slot instruction is always LD r, n (2 bytes).
		// At runtime: caller computes address of the immediate byte and writes newVal.
		// We emit a placeholder comment; actual SMC requires knowing the patch address.
		// The Z80 backend will resolve this in a second pass.
		g.emitf("    ; TODO: LD (patch_addr_%s), %s", slotReg, newVal)

	case OpPush:
		src := g.loc(inst.Src[0])
		// PUSH requires a 16-bit pair; pad single registers to their pair.
		pair := toPair(src)
		g.emitf("    PUSH %s", pair)
		g.invalidate(src)

	case OpPop:
		pair := toPair(dst)
		g.emitf("    POP %s", pair)
		g.invalidate(pair)

	case OpAsm:
		// Inline asm may emit any instruction — conservatively clobber flags.
		g.lastFlagsLhs = ""
		g.lastFlagsRhs = ""
		if inst.Asm != nil {
			g.emitf("    %s", inst.Asm.Template)
		}

	default:
		g.comment(fmt.Sprintf("TODO: %s", inst.Op))
	}
}

// ── Binary operations ─────────────────────────────────────────────────────────

func (g *z80cg) genBinOp(mnem string, inst *Inst) {
	dst := g.loc(inst.Dst)
	lhs := g.loc(inst.Src[0])
	rhs := g.loc(inst.Src[1])
	w := inst.Ty.Width()

	if w <= 8 {
		// Peephole: ADD/SUB dst, N where dst == lhs and N ≤ 3 → INC/DEC dst × N.
		// N=1: 1B/4T vs 4B/15T; N=2: 2B/8T vs 4B/15T; N=3: 3B/12T vs 4B/15T.
		// N=4 would be 16T vs 15T — worse in T-states, skip and fall through to ALU.
		if mnem == "ADD" && lhs == dst {
			if cv, ok := g.constVals[inst.Src[1]]; ok && cv >= 1 && cv <= 3 {
				for range cv {
					g.emitf("    INC %s", dst)
				}
				g.invalidate(dst)
				return
			}
		}
		if mnem == "SUB" && lhs == dst {
			if cv, ok := g.constVals[inst.Src[1]]; ok && cv >= 1 && cv <= 3 {
				for range cv {
					g.emitf("    DEC %s", dst)
				}
				g.invalidate(dst)
				return
			}
		}
		// 8-bit: accumulator must hold lhs.  Emit LD A,lhs if needed.
		//
		// Special case: rhs is already A and lhs is elsewhere.
		// Loading lhs into A would destroy the rhs value.
		//   ADD: commutative → just ADD A, lhs.
		//   SUB: A = lhs - A → NEG first (A = -A), then ADD A, lhs.
		if rhs == "A" && lhs != "A" {
			g.invalidate("A") // A about to hold a new result
			switch mnem {
			case "ADD":
				g.emitf("    ADD A, %s", lhs)
			case "SUB":
				g.emit("    NEG")
				g.emitf("    ADD A, %s", lhs)
			default:
				g.comment(fmt.Sprintf("TODO: 8-bit %s %s, A → %s with A as rhs", mnem, lhs, dst))
				g.emitf("    LD A, %s", lhs)
				g.emit8ALU(mnem, rhs)
			}
			if dst != "A" {
				g.emitf("    LD %s, A", dst)
				g.setCopy(dst, "A")
			}
			return
		}
		// Coalescing: if A already holds lhs or (commutative) rhs, skip LD A, reg.
		isCommutative := mnem == "ADD" || mnem == "AND" || mnem == "OR" || mnem == "XOR"
		if g.holdsValue("A", lhs) {
			// A == lhs already — skip LD A, lhs.
			g.invalidate("A")
			g.emit8ALU(mnem, rhs)
			if dst != "A" {
				g.emitf("    LD %s, A", dst)
				g.setCopy(dst, "A")
			}
			return
		}
		if isCommutative && g.holdsValue("A", rhs) {
			// A == rhs, commutative swap: emit OP A, lhs instead.
			g.invalidate("A")
			g.emit8ALU(mnem, lhs)
			if dst != "A" {
				g.emitf("    LD %s, A", dst)
				g.setCopy(dst, "A")
			}
			return
		}

		// Immediate peephole: AND/OR/XOR/ADD/SUB n — no register needed for rhs.
		if cv, ok := g.constVals[inst.Src[1]]; ok {
			if lhs != "A" {
				g.emitLDA(lhs)
			}
			switch mnem {
			case "AND", "OR", "XOR", "SUB":
				g.emitf("    %s %d", mnem, cv)
			case "ADD":
				g.emitf("    ADD A, %d", cv)
			default:
				g.emit8ALU(mnem, rhs)
			}
			g.invalidate("A") // ALU result is a new value — break old lhs alias
			if dst != "A" {
				g.emitf("    LD %s, A", dst)
				g.setCopy(dst, "A")
			}
			return
		}
		if lhs != "A" {
			g.emitLDA(lhs)
		}
		g.emit8ALU(mnem, rhs)
		g.invalidate("A") // ALU result is a new value — break old lhs alias
		if dst != "A" {
			g.emitf("    LD %s, A", dst)
			g.setCopy(dst, "A")
		}
	} else {
		// 16-bit peephole: INC/DEC rr when adding/subtracting 1 in-place.
		if lhs == dst {
			if cv, ok := g.constVals[inst.Src[1]]; ok {
				if mnem == "ADD" && cv == 1 {
					g.emitf("    INC %s", dst)
					g.invalidate(dst) // pair + its bytes all change
					return
				}
				if mnem == "SUB" && cv == 1 {
					g.emitf("    DEC %s", dst)
					g.invalidate(dst)
					return
				}
			}
		}
		// 16-bit ADD: ADD HL,rr  (Z80 only has ADD HL,rr natively)
		// SUB/AND/OR/XOR on 16-bit require workarounds; emit comment for now.
		switch mnem {
		case "ADD":
			// Ensure lhs is in dst (HL usually).
			if lhs != dst {
				g.emitMov(dst, lhs, w)
			}
			g.emitf("    ADD %s, %s", dst, rhs)
			g.invalidate(dst)
		case "SUB":
			// SBC HL,rr (but clobbers carry; assume carry=0 before).
			if lhs != dst {
				// emitMov for HL↔DE emits EX DE,HL which is a SWAP, not a copy.
				// Update rhs to reflect the new physical location of the original value.
				if (dst == "HL" && lhs == "DE") || (dst == "DE" && lhs == "HL") {
					switch rhs {
					case "HL":
						rhs = "DE"
					case "DE":
						rhs = "HL"
					}
				}
				g.emitMov(dst, lhs, w)
			}
			g.emit("    SCF")
			g.emit("    CCF") // clear carry
			g.emitf("    SBC %s, %s", dst, rhs)
			g.invalidate(dst)
		default:
			g.comment(fmt.Sprintf("TODO: 16-bit %s %s, %s → %s", mnem, lhs, rhs, dst))
		}
	}
}

// emit8ALU emits an 8-bit ALU instruction with A as the implicit destination.
// MZA requires "ADD A, src" (two operands) but "SUB/AND/OR/XOR src" (one operand).
func (g *z80cg) emit8ALU(mnem, src string) {
	switch mnem {
	case "ADD", "ADC":
		g.emitf("    %s A, %s", mnem, src)
	default:
		g.emitf("    %s %s", mnem, src)
	}
}

// ── Shifts ────────────────────────────────────────────────────────────────────

func (g *z80cg) genShift(mnem string, inst *Inst) {
	dst := g.loc(inst.Dst)
	src := g.loc(inst.Src[0])
	if dst != src {
		g.emitf("    LD %s, %s", dst, src)
		g.setCopy(dst, src)
	}
	// Shift count in Src[1] — Z80 shifts are always by 1 per instruction.
	// For constant counts, emit N copies.  Variable shifts → TODO.
	count := int64(1)
	if cv, ok := g.constVals[inst.Src[1]]; ok && cv > 0 {
		count = cv
	}
	for i := int64(0); i < count; i++ {
		g.emitf("    %s %s", mnem, dst)
	}
	g.invalidate(dst) // shift modifies dst
}

// ── Multiply ──────────────────────────────────────────────────────────────────

// genMul emits 8-bit unsigned multiply via shift-and-add.
// Power-of-2 constants use N×(ADD A,A); small constants use LD tmp,A + adds.
// Variable or large constants fall back to a software-loop comment (TODO).
func (g *z80cg) genMul(inst *Inst) {
	dst := g.loc(inst.Dst)
	lhs := g.loc(inst.Src[0])

	if inst.Ty.Width() > 8 {
		g.comment(fmt.Sprintf("TODO: 16-bit mul → %s", dst))
		return
	}

	cv, isConst := g.constVals[inst.Src[1]]

	if isConst {
		switch cv {
		case 0:
			g.emit("    XOR A")
			g.invalidate("A")
			if dst != "A" {
				g.emitf("    LD %s, A", dst)
				g.setCopy(dst, "A")
			}
			return
		case 1:
			if dst != lhs {
				g.emitMov(dst, lhs, 8)
			}
			return
		}
		// Power-of-2: log2(cv) × (ADD A,A).
		if cv > 0 && cv&(cv-1) == 0 {
			shifts := 0
			for n := cv; n > 1; n >>= 1 {
				shifts++
			}
			if !g.holdsValue("A", lhs) {
				g.emitLDA(lhs)
			}
			for i := 0; i < shifts; i++ {
				g.emit("    ADD A, A")
			}
			g.invalidate("A")
			if dst != "A" {
				g.emitf("    LD %s, A", dst)
				g.setCopy(dst, "A")
			}
			return
		}
		// x*3 = x + x*2: LD tmp,A; ADD A,A; ADD A,tmp
		// x*5 = x + x*4: LD tmp,A; ADD A,A; ADD A,A; ADD A,tmp
		// x*6 = x*2 + x*4: LD tmp,A; ADD A,A (tmp=x*2 in tmp); ADD A,A (A=x*4); ADD A,tmp
		// x*9 = x + x*8:   LD tmp,A; 3×ADD A,A; ADD A,tmp
		if cv == 3 || cv == 5 || cv == 6 || cv == 9 {
			if !g.holdsValue("A", lhs) {
				g.emitLDA(lhs)
			}
			// Pick a temp register that isn't A or dst.
			tmp := "C"
			if dst == "C" {
				tmp = "D"
			}
			switch cv {
			case 3: // x + x*2
				g.emitf("    LD %s, A", tmp) // tmp = x
				g.emit("    ADD A, A")        // A  = x*2
				g.emitf("    ADD A, %s", tmp) // A  = x*3
			case 5: // x + x*4
				g.emitf("    LD %s, A", tmp)
				g.emit("    ADD A, A")
				g.emit("    ADD A, A")         // A  = x*4
				g.emitf("    ADD A, %s", tmp) // A  = x*5
			case 6: // x*2 + x*4
				g.emit("    ADD A, A")         // A  = x*2
				g.emitf("    LD %s, A", tmp)  // tmp= x*2
				g.emit("    ADD A, A")         // A  = x*4
				g.emitf("    ADD A, %s", tmp) // A  = x*6
			case 9: // x + x*8
				g.emitf("    LD %s, A", tmp)
				g.emit("    ADD A, A")
				g.emit("    ADD A, A")
				g.emit("    ADD A, A")         // A  = x*8
				g.emitf("    ADD A, %s", tmp) // A  = x*9
			}
			g.invalidate("A")
			if dst != "A" {
				g.emitf("    LD %s, A", dst)
				g.setCopy(dst, "A")
			}
			return
		}
	}

	// Variable or unsupported constant: emit software-loop comment.
	rhs := g.loc(inst.Src[1])
	g.comment(fmt.Sprintf("TODO: general mul %s * %s → %s", lhs, rhs, dst))
}

// ── Type conversions ──────────────────────────────────────────────────────────

func (g *z80cg) genExt(inst *Inst) {
	dst := g.loc(inst.Dst)
	src := g.loc(inst.Src[0])
	srcW := inst.SrcTy.Width()
	dstW := inst.Ty.Width()

	if srcW == 8 && dstW == 16 {
		// Zero-extend u8 → u16.
		// dst should be a 16-bit reg (HL/DE/BC/IX/IY).
		// Most natural: put source in low byte, zero high byte.
		lo := lowByte(dst)
		hi := highByte(dst)
		if src != lo {
			g.emitf("    LD %s, %s", lo, src)
		}
		g.emitf("    LD %s, 0", hi)
		return
	}
	// Fallback.
	g.comment(fmt.Sprintf("TODO: ext %s→%s %s→%s", inst.SrcTy, inst.Ty, src, dst))
}

func (g *z80cg) genSext(inst *Inst) {
	dst := g.loc(inst.Dst)
	src := g.loc(inst.Src[0])
	srcW := inst.SrcTy.Width()
	dstW := inst.Ty.Width()

	if srcW == 8 && dstW == 16 {
		// Sign-extend u8 → u16 via A.
		lo := lowByte(dst)
		hi := highByte(dst)
		if src != "A" {
			g.emitf("    LD A, %s", src)
		}
		if lo != "A" {
			g.emitf("    LD %s, A", lo)
		}
		// Propagate sign bit into high byte: RLCA; SBC A,A gives 0x00 or 0xFF.
		g.emit("    RLCA")
		g.emit("    SBC A, A")
		if hi != "A" {
			g.emitf("    LD %s, A", hi)
		}
		return
	}
	g.comment(fmt.Sprintf("TODO: sext %s→%s %s→%s", inst.SrcTy, inst.Ty, src, dst))
}

// ── Compare ───────────────────────────────────────────────────────────────────

func (g *z80cg) genCmp(inst *Inst) {
	// CmpSubCarry: carry flag already set by the immediately preceding SUB.
	// Src[0] = sub result (r), Src[1] = original rhs (b).
	// carry ≡ (r + b) >= 2^width ≡ original_a < b unsigned — emit nothing.
	if inst.Cond == CmpSubCarry {
		return
	}

	lhs := g.loc(inst.Src[0])
	rhs := g.loc(inst.Src[1])

	// 16-bit comparison: one or both operands are register pairs (HL/DE/BC/…).
	// Z80 only supports SBC HL, rr for 16-bit flag-setting subtraction.
	if isPairReg(lhs) || isPairReg(rhs) {
		g.genCmp16(inst)
		return
	}

	// CmpGt / CmpUgt and CmpLe / CmpUle are not directly expressible as a
	// single Z80 flag after a normal CP (which would need NC+NZ or C+Z).
	// Fix: force-swap the operands.
	//   CmpGt(a,b): a>b ↔ b<a → put b in A, CP a → C flag single-condition ✓
	//   CmpLe(a,b): a≤b ↔ b≥a → put b in A, CP a → NC flag single-condition ✓
	// Exception: rhs==0 is handled by the AND A path below (cmpAndZero mechanism
	// already returns NZ for Gt and Z for Le in condCode, so no swap needed).
	isGtOrLe := inst.Cond == CmpGt || inst.Cond == CmpUgt ||
		inst.Cond == CmpLe || inst.Cond == CmpUle
	if isGtOrLe {
		rhsIsZero := false
		if cv, ok := g.constVals[inst.Src[1]]; ok && cv == 0 {
			rhsIsZero = true
		}
		if !rhsIsZero {
			if lhs != "A" {
				// Force-swap: put rhs in A, emit CP lhs → single condition.
				//   CmpGt(a,b) → b<a → C flag ✓
				//   CmpLe(a,b) → b≥a → NC flag ✓
				if cv, ok := g.constVals[inst.Src[1]]; ok {
					g.emitf("    LD A, %d", cv)
					g.invalidate("A")
				} else if !g.holdsValue("A", rhs) {
					g.emitLDA(rhs)
				}
				g.emitf("    CP %s", lhs)
				g.cmpSwapped[inst.Dst] = true
				return
			}
			// lhs IS "A": force-swap would clobber the live value in A.
			// Emit normally (A=lhs already, CP rhs); TermBrIf will use two JPs.
			g.cmpNeedsTwo[inst.Dst] = true
			// Fall through to normal CP code (which will find A=lhs and emit CP rhs).
		}
		// rhsIsZero: fall through to AND A path (cmpAndZero handles NZ/Z).
	}

	// Z80 CP instruction: computes A − operand and sets flags.
	// We need A = lhs, then CP rhs.
	//
	// Peephole: if rhs is a known constant, use CP imm8 directly.
	// This avoids an extra register load (e.g. LD C,0 / LD A,B / CP C
	// → LD A,B / CP 0), and the constant no longer needs to be
	// materialised into a register (eliminating a dead store).
	if cv, ok := g.constVals[inst.Src[1]]; ok {
		if !g.holdsValue("A", lhs) {
			g.emitLDA(lhs)
		}
		g.lastFlagsLhs = ""
		g.lastFlagsRhs = ""
		if cv == 0 {
			g.emit("    AND A") // AND A ≡ CP 0 for all flags; 1B/4T vs 2B/7T
			g.cmpAndZero[inst.Dst] = true
		} else {
			g.emitf("    CP %d", cv)
		}
		// CP/AND A does not modify A; aliases remain valid.
		return
	}

	// Two-address conflict: if rhs is already in A and lhs is elsewhere,
	// loading lhs into A would destroy rhs.
	// Fix: swap operands (emit CP lhs with A=rhs) and mark as swapped.
	// condCode() will invert the CmpCond to compensate.
	if rhs == "A" && lhs != "A" {
		// A already holds rhs. CP lhs computes A−lhs = rhs−lhs.
		// This is the swapped comparison; condCode will invert it.
		g.lastFlagsLhs = ""
		g.lastFlagsRhs = ""
		g.emitf("    CP %s", lhs)
		g.cmpSwapped[inst.Dst] = true
		// CP does not modify A; aliases remain valid.
		return
	}

	// Coalescing: A already holds lhs — skip LD A, lhs.
	if !g.holdsValue("A", lhs) {
		g.emitLDA(lhs)
	}
	// Sub+CmpLt flag fusion: if the immediately preceding instruction was
	// SUB with the same operands (A=lhs, rhs unchanged), the carry flag is
	// already set identically to what CP would produce → skip the CP.
	if (inst.Cond == CmpLt || inst.Cond == CmpUlt) &&
		g.lastFlagsLhs == lhs && g.lastFlagsRhs == rhs {
		// Flags valid from preceding SUB — no CP needed.
		return
	}
	g.lastFlagsLhs = ""
	g.lastFlagsRhs = ""
	g.emitf("    CP %s", rhs)
	// CP does not modify A; aliases remain valid.
}

// ── Calls ─────────────────────────────────────────────────────────────────────

func (g *z80cg) genCall(inst *Inst) {
	clear(g.holdsPhys) // calls clobber all volatile registers
	if inst.Op == OpCallIndirect {
		ptr := g.loc(inst.Src[0])
		g.emitf("    CALL (%s)          ; indirect", ptr)
		return
	}

	// ── Built-in intrinsics (inlined, no CALL emitted) ────────────────────────
	switch inst.Sym {
	case "@mir.io.print.str":
		// Emit inline NUL-terminated string output loop via OUT (0x01), A.
		// The string pointer must be in HL (ClassPointer).
		// HL is advanced in-place; A and F are clobbered.
		idx := g.trampIdx
		g.trampIdx++
		g.emitf(".print_str_%d:", idx)
		g.emit("    LD A, (HL)")
		g.emit("    AND A")
		g.emitf("    JR Z, .print_str_done_%d", idx)
		g.emit("    OUT (0x01), A")
		g.emit("    INC HL")
		g.emitf("    JR .print_str_%d", idx)
		g.emitf(".print_str_done_%d:", idx)
		// A, F, HL clobbered — invalidate holdsPhys entries for these.
		g.invalidate("A")
		g.invalidate("HL")
		return

	case "@mir.io.print.u8":
		// Emit single OUT (0x01), A.  The value must already be in A.
		g.emit("    OUT (0x01), A")
		g.invalidate("A")
		return

	case "@mir.io.print.nl":
		// Emit newline (\n = 0x0A) via OUT (0x01), A.
		g.emit("    LD A, 0x0A")
		g.emit("    OUT (0x01), A")
		g.invalidate("A")
		return
	}

	sym := sanitizeIdent(inst.Sym)

	// Emit argument setup (parallel copy) when we have explicit Args and the
	// callee's contract is known.  This covers cases where the current physical
	// locations of the argument registers differ from the callee's expected
	// parameter locations (e.g. phi in C must move to A for the second CALL).
	var callee *Func
	if g.mod != nil {
		callee = g.mod.FuncByName(inst.Sym)
	}
	if len(inst.Args) > 0 && callee != nil && len(callee.Contract.Params) > 0 {
		g.emitCallArgs(inst.Args, callee.Contract.Params)
	}

	g.emitf("    CALL %s", sym)

	// The CALL clobbers A and F (volatile registers on Z80).  Remove physOverride
	// entries for any virtual register that was relocated into A or F by
	// emitCallArgs — those locations are no longer valid after the call.
	// Non-volatile relocations (B/C/D/E/H/L) remain valid.
	for r, phys := range g.physOverride {
		if phys == "A" || phys == "F" {
			delete(g.physOverride, r)
		}
	}

	// Flag-return ABI: if the callee returns ClassFlag, the result is in the CPU
	// flag register (not A).  Record which condition means "true" so that a
	// subsequent TermBrIf on inst.Dst can emit JP <cond> directly without
	// AND A / CP 0.
	if inst.Dst != NoReg && callee != nil {
		if len(callee.Contract.Returns) > 0 {
			ret := callee.Contract.Returns[0]
			if ret.Class == ClassFlag {
				g.callFlags[inst.Dst] = ret.FlagCond
			}
		}
	}
}

// emitCallArgs emits the parallel-copy argument setup for a CALL instruction.
// It maps the current physical locations of the call arguments to the physical
// locations expected by the callee's parameter contract and uses emitParallelCopy
// to resolve any cycles (e.g. A→B, C→A).
//
// As a side effect it updates physOverride so that loc(r) returns the new
// physical location for any virtual register that was moved by the copy.
// physOverride is cleared after the CALL by genCall.
func (g *z80cg) emitCallArgs(args []Reg, params []Param) {
	var copies []parallelCopy
	for i, arg := range args {
		if i >= len(params) {
			break
		}
		srcPhys := g.loc(arg)
		dstPhys := canonicalReturnLoc(params[i].Class, params[i].Ty)
		if srcPhys != dstPhys {
			copies = append(copies, parallelCopy{srcName: srcPhys, dstName: dstPhys, ty: params[i].Ty})
		}
	}
	if len(copies) == 0 {
		return
	}
	g.emitParallelCopy(copies)

	// Update physOverride for each argument that was relocated.
	// After any parallel copy sequence, each source arg ends up at its declared
	// destination physical location — regardless of chain/cycle resolution order.
	for i, arg := range args {
		if i >= len(params) {
			break
		}
		srcPhys := g.ar.Loc(arg).Name
		if p, ok := g.physOverride[arg]; ok {
			srcPhys = p
		}
		dstPhys := canonicalReturnLoc(params[i].Class, params[i].Ty)
		if srcPhys != dstPhys {
			g.physOverride[arg] = dstPhys
		}
	}
}

// ── Move helper ───────────────────────────────────────────────────────────────

func (g *z80cg) emitMov(dst, src string, widthBits int) {
	if dst == src {
		return
	}

	// ── Flag-register special cases ───────────────────────────────────────────

	if dst == "F" {
		// Materialise a register value into the flag register.
		// Convention: Z=1 (zero) means false, NZ means true — i.e. AND A / OR A.
		// Callers using CmpNe (NZ) as the flag condition get this for free.
		if src == "A" {
			g.emit("    AND A") // sets Z/NZ and clears C based on A's value
		} else {
			// Load into A first, then set flags.
			g.emitf("    LD A, %s", src)
			g.emit("    AND A")
		}
		g.invalidate("A")
		return
	}

	if src == "F" {
		// Materialise a flag result into a register.
		// Uses the SBC A,A trick for C-flag convention: A = 0xFF (carry set = true)
		// or 0x00 (carry clear = false).  Works for CmpLt/CmpUlt/CmpGe/CmpUge.
		//
		// For Z-flag convention (CmpEq/CmpNe), the sequence is:
		//   JR NZ, $+3 / SCF / then SBC A,A — converts Z to C, then materialise.
		// We use the simpler carry path by default; HIR lowers bool-returning
		// functions to carry-based comparisons where possible.
		if dst == "A" {
			g.emit("    SBC A, A") // A=0xFF if C=1 (true), A=0x00 if C=0 (false)
		} else {
			g.emit("    SBC A, A")
			g.emitf("    LD %s, A", dst)
		}
		g.invalidate("A")
		return
	}

	// ── Normal register moves ─────────────────────────────────────────────────

	if widthBits <= 8 {
		g.emitf("    LD %s, %s", dst, src)
		if isSimpleReg(dst) && isSimpleReg(src) {
			g.setCopy(dst, src)
		}
		return
	}
	// 16-bit register move.
	switch {
	case dst == "HL" && src == "DE":
		g.emit("    EX DE, HL")
	case dst == "DE" && src == "HL":
		g.emit("    EX DE, HL")
	case (dst == "IX" || dst == "IY") && (src == "DE" || src == "BC"):
		// DE/BC → IX/IY: undocumented byte-copy (DD/FD prefix), 2×8T = 16T.
		// Safe because D, E, B, C are NOT substituted by the DD/FD prefix.
		// e.g. DE→IX: LD IXH, D (DD 62) / LD IXL, E (DD 6B)
		//      BC→IX: LD IXH, B (DD 60) / LD IXL, C (DD 69)
		g.emitf("    LD %s, %s", highByte(dst), highByte(src))
		g.emitf("    LD %s, %s", lowByte(dst), lowByte(src))
	case (dst == "IX" || dst == "IY") && src == "HL":
		// HL→IX: byte-copy is INVALID — DD prefix substitutes H→IXH, L→IXL,
		// so LD IXH,H encodes as LD IXH,IXH (NOP). Must use PUSH/POP.
		g.emitf("    PUSH HL")
		g.emitf("    POP %s", dst)
	case (src == "IX" || src == "IY") && (dst == "DE" || dst == "BC"):
		// IX/IY → DE/BC: safe byte-copy, D/E/B/C not substituted by DD prefix.
		// e.g. IX→DE: LD D, IXH (DD 57? no — DD 7A? no) actually DD prefix on LD D,H:
		// opcode 0x54 = LD D,H → DD 54 = LD D,IXH ✓ (D is destination, IXH is source)
		g.emitf("    LD %s, %s", highByte(dst), highByte(src))
		g.emitf("    LD %s, %s", lowByte(dst), lowByte(src))
	case (src == "IX" || src == "IY") && dst == "HL":
		// IX→HL: byte-copy INVALID (H,L substituted). Must use PUSH/POP.
		g.emitf("    PUSH %s", src)
		g.emit("    POP HL")
	default:
		// General 16-bit move via PUSH/POP.
		g.emitf("    PUSH %s", src)
		g.emitf("    POP %s", dst)
	}
	// Track the copy alias so downstream redundant moves can be suppressed.
	g.setCopy(dst, src)
}

// ── Terminators ───────────────────────────────────────────────────────────────

func (g *z80cg) genTerm(f *Func, t Term) {
	switch t := t.(type) {
	case *TermRet:
		// Move each return value to its calling-convention physical register.
		// Skip the move if the destination already holds the same value (copy alias).
		for i, rv := range t.Vals {
			if i >= len(g.fn.Contract.Returns) {
				break
			}
			ret := g.fn.Contract.Returns[i]
			retLoc := canonicalReturnLoc(ret.Class, ret.Ty)
			src := g.loc(rv)
			if src != retLoc && !g.holdsValue(retLoc, src) {
				g.emitMov(retLoc, src, ret.Ty.Width())
			}
		}
		g.emit("    RET")

	case *TermJmp:
		// Resolve block-argument parallel copies before the jump.
		copies := g.buildBlockCopies(f, t.Target, t.Args)
		g.emitParallelCopy(copies)
		// Fall-through elimination: if the target is the very next physical block,
		// the JR is redundant — execution falls through naturally.
		if !g.isFallThrough(f, t.Target) {
			g.emitf("    JRS %s", blockLabel(f.Name, t.Target))
		}

	case *TermBrIf:
		cc := g.condCode(f, t.Cond)

		// Build block-arg copies for each edge.
		thenCopies := g.buildBlockCopies(f, t.Then, t.ThenArgs)
		elseCopies := g.buildBlockCopies(f, t.Else, t.ElseArgs)

		// If a branch has non-trivial copies, it cannot be a fall-through:
		// redirect it through a trampoline that performs the copies then JR.
		thenLbl := g.branchLabel(f, t.Then, thenCopies)
		elseLbl := g.branchLabel(f, t.Else, elseCopies)

		// Fall-through is only possible when there are no copies for that edge.
		thenFT := g.isFallThrough(f, t.Then) && len(thenCopies) == 0
		elseFT := g.isFallThrough(f, t.Else) && len(elseCopies) == 0

		// Two-condition sentinels: CmpGt/CmpLe with lhs in A (no operand swap).
		// CGT = NC && NZ (a > b); CLE = C || Z (a ≤ b).
		// Note: CLE/CGT need two jumps — first uses JR, second uses JR too.
		// MZA auto-promotes any JR to JP when out of range.
		if cc == "CLE" {
			// a ≤ b: branch to then if C (a<b) or Z (a==b).
			g.emitf("    JRS C, %s", thenLbl)
			g.emitf("    JRS Z, %s", thenLbl)
			if !elseFT {
				g.emitf("    JRS %s", elseLbl)
			}
		} else if cc == "CGT" {
			// a > b: branch to else if Z (a==b) or C (a<b), else fall/JR to then.
			g.emitf("    JRS Z, %s", elseLbl)
			g.emitf("    JRS C, %s", elseLbl)
			if !thenFT {
				g.emitf("    JRS %s", thenLbl)
			}
		} else if elseFT {
			g.emitf("    JRS %s, %s", cc, thenLbl)
			// else falls through naturally
		} else if thenFT {
			g.emitf("    JRS %s, %s", invertCC(cc), elseLbl)
			// then falls through naturally
		} else {
			g.emitf("    JRS %s, %s", cc, thenLbl)
			g.emitf("    JRS %s", elseLbl)
		}

	case *TermBrIf2:
		// Three-way unsigned comparison: one CP, three outcomes (==, <, >).
		// Emit: CP rhs (with A=lhs), then JR Z eq, JR C lt, fall-through/JR gt.
		lhs := g.loc(t.Lhs)
		rhs := g.loc(t.Rhs)

		// Emit the CP (same logic as genCmp).
		if cv, ok := g.constVals[t.Rhs]; ok {
			if !g.holdsValue("A", lhs) {
				g.emitLDA(lhs)
			}
			g.emitf("    CP %d", cv)
		} else if rhs == "A" && lhs != "A" {
			// A already holds rhs; swap: CP lhs computes rhs-lhs.
			// Eq is still Z (rhs-lhs==0 ↔ rhs==lhs), but C now means rhs<lhs.
			// So we swap Lt↔Gt below.
			g.emitf("    CP %s", lhs)
			// Build copies for eq, swapped lt/gt.
			eqCopies := g.buildBlockCopies(f, t.Eq, t.EqArgs)
			ltCopies := g.buildBlockCopies(f, t.Gt, t.GtArgs) // swapped: C→gt
			gtCopies := g.buildBlockCopies(f, t.Lt, t.LtArgs) // swapped: NC,NZ→lt
			eqLbl := g.branchLabel(f, t.Eq, eqCopies)
			ltLbl := g.branchLabel(f, t.Gt, ltCopies)
			gtLbl := g.branchLabel(f, t.Lt, gtCopies)
			g.emitf("    JRS Z, %s", eqLbl)
			g.emitf("    JRS C, %s", ltLbl)
			if !g.isFallThrough(f, t.Lt) || len(gtCopies) != 0 {
				g.emitf("    JRS %s", gtLbl)
			}
			return
		} else {
			if !g.holdsValue("A", lhs) {
				g.emitLDA(lhs)
			}
			g.emitf("    CP %s", rhs)
		}

		// Build copies for each of the three edges.
		eqCopies := g.buildBlockCopies(f, t.Eq, t.EqArgs)
		ltCopies := g.buildBlockCopies(f, t.Lt, t.LtArgs)
		gtCopies := g.buildBlockCopies(f, t.Gt, t.GtArgs)
		eqLbl := g.branchLabel(f, t.Eq, eqCopies)
		ltLbl := g.branchLabel(f, t.Lt, ltCopies)
		gtLbl := g.branchLabel(f, t.Gt, gtCopies)

		g.emitf("    JRS Z, %s", eqLbl)
		g.emitf("    JRS C, %s", ltLbl)
		if !g.isFallThrough(f, t.Gt) || len(gtCopies) != 0 {
			g.emitf("    JRS %s", gtLbl)
		}

	case *TermDJNZ:
		// Emit body-edge copies for non-counter args.
		// The counter (B) is handled implicitly by DJNZ.
		// body.Params[0] = counter (gets decremented B); BodyArgs = params[1:].
		bodyBlock := f.BlockByLabel(t.Body)
		var bodyCopies []parallelCopy
		if bodyBlock != nil {
			for i, arg := range t.BodyArgs {
				if i+1 >= len(bodyBlock.Params) {
					break
				}
				param := bodyBlock.Params[i+1] // skip counter param[0]
				src := g.loc(arg)
				dst := g.ar.Loc(param.Dst).Name
				if src != dst {
					bodyCopies = append(bodyCopies, parallelCopy{srcName: src, dstName: dst, ty: param.Ty})
				}
			}
		}
		g.emitParallelCopy(bodyCopies)
		g.emitf("    DJNZ %s", blockLabel(f.Name, t.Body))
		// Exit path.
		exitCopies := g.buildBlockCopies(f, t.Exit, t.ExitArgs)
		g.emitParallelCopy(exitCopies)
		if !g.isFallThrough(f, t.Exit) || len(exitCopies) != 0 {
			g.emitf("    JP %s", blockLabel(f.Name, t.Exit))
		}

	case *TermCondRet:
		// Move each return value to its calling-convention register (same as TermRet).
		for i, rv := range t.Vals {
			if i >= len(g.fn.Contract.Returns) {
				break
			}
			ret := g.fn.Contract.Returns[i]
			retLoc := canonicalReturnLoc(ret.Class, ret.Ty)
			src := g.loc(rv)
			if src != retLoc && !g.holdsValue(retLoc, src) {
				g.emitMov(retLoc, src, ret.Ty.Width())
			}
		}
		// Emit conditional return: RET when Cond == 0 (inverted condition).
		cc := g.condCode(f, t.Cond)
		g.emitf("    RET %s", invertCC(cc))
		// Emit jump to Then (with fall-through elimination).
		copies := g.buildBlockCopies(f, t.Then, t.ThenArgs)
		thenLbl := g.branchLabel(f, t.Then, copies)
		g.emitParallelCopy(copies)
		if !g.isFallThrough(f, t.Then) || len(copies) != 0 {
			g.emitf("    JRS %s", thenLbl)
		}

	case *TermUnreachable:
		g.comment("unreachable")
	}
}

// branchLabel returns the label to jump to for a BrIf edge.
// If the edge has parallel copies, a trampoline block is registered and its
// label is returned instead of the real target label.
func (g *z80cg) branchLabel(f *Func, target string, copies []parallelCopy) string {
	realLbl := blockLabel(f.Name, target)
	if len(copies) == 0 {
		return realLbl
	}
	tramLbl := fmt.Sprintf(".%s_trmp%d", sanitizeIdent(f.Name), g.trampIdx)
	g.trampIdx++
	g.trampolines = append(g.trampolines, trampolineBlock{
		label:  tramLbl,
		copies: copies,
		target: realLbl,
	})
	return tramLbl
}

// buildBlockCopies computes the parallel copies needed to pass args to a
// target block's formal parameters.  Returns only moves where src ≠ dst.
func (g *z80cg) buildBlockCopies(f *Func, targetName string, args []Reg) []parallelCopy {
	if len(args) == 0 {
		return nil
	}
	var target *Block
	for _, b := range f.Blocks {
		if b.Label == targetName {
			target = b
			break
		}
	}
	if target == nil {
		return nil
	}
	var copies []parallelCopy
	for i, arg := range args {
		if i >= len(target.Params) {
			break
		}
		src := g.ar.Loc(arg).Name
		dst := g.ar.Loc(target.Params[i].Dst).Name
		if src != dst {
			copies = append(copies, parallelCopy{srcName: src, dstName: dst, ty: target.Params[i].Ty})
		}
	}
	return copies
}

// emitParallelCopy resolves and emits a set of parallel register moves,
// correctly handling cycles (e.g. HL↔DE → EX DE,HL).
func (g *z80cg) emitParallelCopy(copies []parallelCopy) {
	if len(copies) == 0 {
		return
	}

	type move struct {
		src, dst string
		ty       Ty
		done     bool
	}
	moves := make([]move, len(copies))
	for i, c := range copies {
		moves[i] = move{src: c.srcName, dst: c.dstName, ty: c.ty}
	}

	for {
		// Emit any move whose dst is not a source of another pending move.
		progress := false
		for i := range moves {
			if moves[i].done {
				continue
			}
			dstNeeded := false
			for j := range moves {
				if j != i && !moves[j].done && moves[j].src == moves[i].dst {
					dstNeeded = true
					break
				}
			}
			if !dstNeeded {
				g.emitSingleCopy(moves[i].src, moves[i].dst, moves[i].ty)
				moves[i].done = true
				progress = true
				break
			}
		}
		if progress {
			continue
		}

		// All remaining moves form cycles.  Find first undone.
		first := -1
		undone := 0
		for i := range moves {
			if !moves[i].done {
				undone++
				if first == -1 {
					first = i
				}
			}
		}
		if first == -1 {
			break
		}

		// Special case: HL↔DE two-node cycle → EX DE, HL.
		if undone == 2 {
			a, b := -1, -1
			for i := range moves {
				if !moves[i].done {
					if a == -1 {
						a = i
					} else {
						b = i
					}
				}
			}
			as, ad := moves[a].src, moves[a].dst
			bs, bd := moves[b].src, moves[b].dst
			if (as == "HL" && ad == "DE" && bs == "DE" && bd == "HL") ||
				(as == "DE" && ad == "HL" && bs == "HL" && bd == "DE") {
				g.emit("    EX DE, HL")
				moves[a].done = true
				moves[b].done = true
				continue
			}
		}

		// General cycle: break with a temporary.
		m := &moves[first]
		if m.ty.Width() <= 8 {
			// u8 cycle: use A as scratch.
			//
			// Walk BACKWARD through the cycle so we always read old values.
			// Example 3-cycle D→C, C→E, E→D:
			//   Save A = D  (free the D slot)
			//   LD D, E     (backward: who writes TO D? E→D. Do it now while E is clean.)
			//   LD E, C     (backward: who writes TO E? C→E.)
			//   LD C, A     (put D_old into C, the first.dst)
			firstDst := m.dst
			if m.src != "A" {
				g.emitf("    LD A, %s", m.src)
			}
			m.done = true
			cur := m.src // start at the freed slot (m.src moved to A)
			for {
				found := false
				for i := range moves {
					if !moves[i].done && moves[i].dst == cur {
						g.emitf("    LD %s, %s", moves[i].dst, moves[i].src)
						cur = moves[i].src // the source is the new freed slot
						moves[i].done = true
						found = true
						break
					}
				}
				if !found {
					break
				}
			}
			if firstDst != "A" {
				g.emitf("    LD %s, A", firstDst)
			}
		} else {
			// u16 cycle: use stack.
			g.emitf("    PUSH %s", m.src)
			m.done = true
			cur := m.dst
			for {
				found := false
				for i := range moves {
					if !moves[i].done && moves[i].src == cur {
						g.emitSingleCopy(moves[i].src, moves[i].dst, moves[i].ty)
						cur = moves[i].dst
						moves[i].done = true
						found = true
						break
					}
				}
				if !found {
					break
				}
			}
			g.emitf("    POP %s", cur)
		}
	}
}

// emitSingleCopy emits a non-destructive register copy (src → dst).
// For 16-bit, this emits two LD instructions (not EX DE,HL which is a swap).
func (g *z80cg) emitSingleCopy(src, dst string, ty Ty) {
	if src == dst {
		return
	}
	if ty.Width() <= 8 {
		g.emitf("    LD %s, %s", dst, src)
	} else {
		// 16-bit non-destructive copy: two 8-bit LDs.
		g.emitf("    LD %s, %s", highByte(dst), highByte(src))
		g.emitf("    LD %s, %s", lowByte(dst), lowByte(src))
	}
}

// condCode returns the Z80 condition code for the virtual register holding
// the comparison result.  If genCmp swapped the operands, the condition
// is automatically inverted via CmpCond.Swap().
//
// For ClassFlag returns from CALL instructions, callFlags[cond] holds the
// agreed FlagCond directly — no AND A / CP 0 is needed at the call site.
func (g *z80cg) condCode(f *Func, cond Reg) string {
	// Fast path: call result with ClassFlag return — condition already in F.
	if fc, ok := g.callFlags[cond]; ok {
		return cmpCondCode(fc)
	}

	for _, b := range f.Blocks {
		for _, inst := range b.Insts {
			if inst.Dst == cond && inst.Op == OpCmp {
				c := inst.Cond
				if g.cmpSwapped[cond] {
					c = c.Swap() // operands were swapped → invert condition
				}
				// When genCmp emitted AND A (rhs=0), carry is always 0.
				// Replace NC/C-based conditions with NZ/Z-based ones:
				//   CmpGt(n, 0) → n != 0 → NZ
				//   CmpGe(n, 0) → n >= 0 → always true → handled as NC (fine)
				//   CmpLt(n, 0) → never for unsigned → C (never fires)
				//   CmpLe(n, 0) → n == 0 → Z
				if g.cmpAndZero[cond] {
					switch c {
					case CmpGt, CmpUgt:
						return "NZ"
					case CmpLe, CmpUle:
						return "Z"
					}
				}
				if g.cmpNeedsTwo[cond] {
					switch c {
					case CmpGt, CmpUgt:
						return "CGT" // NC && NZ: JP Z,else; JP NC,then
					case CmpLe, CmpUle:
						return "CLE" // C || Z: JP C,then; JP Z,then
					}
				}
				return cmpCondCode(c)
			}
		}
	}
	return "NZ" // fallback
}

// isFallThrough reports whether targetLabel is the next physical block after
// the current one (g.blockIdx), making a JP redundant.
func (g *z80cg) isFallThrough(f *Func, targetLabel string) bool {
	next := g.blockIdx + 1
	if next >= len(f.Blocks) {
		return false
	}
	return f.Blocks[next].Label == targetLabel
}

// invertCC returns the Z80 condition code that is the logical negation of cc.
func invertCC(cc string) string {
	switch cc {
	case "Z":
		return "NZ"
	case "NZ":
		return "Z"
	case "C":
		return "NC"
	case "NC":
		return "C"
	case "PE":
		return "PO"
	case "PO":
		return "PE"
	case "M":
		return "P"
	case "P":
		return "M"
	}
	return cc
}

// cmpCondCode maps CmpCond → Z80 condition string.
func cmpCondCode(c CmpCond) string {
	switch c {
	case CmpEq:
		return "Z"
	case CmpNe:
		return "NZ"
	case CmpLt, CmpUlt, CmpSubCarry:
		return "C"
	case CmpGe, CmpUge:
		return "NC"
	case CmpLe, CmpUle:
		// LE: JP Z / JP C — requires two jumps; emit Z for now (backend TODO).
		return "Z"
	case CmpGt, CmpUgt:
		return "NC"
	}
	return "NZ"
}

// canonicalReturnLoc returns the physical register name where a return value of
// the given class and type must reside on function exit (calling convention).
func canonicalReturnLoc(cls RegClass, ty Ty) string {
	w := ty.Width()
	switch cls {
	case ClassFlag:
		// Flag-return ABI: result lives in the CPU flag register (F), not in A.
		// Callers test with JP <FlagCond> directly after the CALL instruction.
		// "F" is the sentinel name for LocFlag in Z80PhysLocs.
		return "F"
	case ClassAcc:
		if w <= 8 {
			return "A"
		}
		return "HL" // u16 [acc] → HL
	case ClassPointer, ClassPair:
		return "HL"
	case ClassIndex:
		return "DE"
	case ClassCounter:
		return "B"
	default:
		if w <= 8 {
			return "A"
		}
		return "HL"
	}
}

// ── Label helpers ─────────────────────────────────────────────────────────────

func blockLabel(funcName, blockLabel string) string {
	if blockLabel == "entry" {
		return sanitizeIdent(funcName)
	}
	return fmt.Sprintf(".%s_%s", sanitizeIdent(funcName), sanitizeIdent(blockLabel))
}

func sanitizeIdent(s string) string {
	var b strings.Builder
	for _, c := range s {
		if (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') ||
			(c >= '0' && c <= '9') || c == '_' {
			b.WriteRune(c)
		} else {
			b.WriteByte('_')
		}
	}
	return b.String()
}

// ── 16-bit register half helpers ──────────────────────────────────────────────

// lowByte returns the low-byte name of a 16-bit register.
func lowByte(rr string) string {
	switch rr {
	case "HL":
		return "L"
	case "DE":
		return "E"
	case "BC":
		return "C"
	case "IX":
		return "IXL"
	case "IY":
		return "IYL"
	}
	return rr // already 8-bit
}

// highByte returns the high-byte name of a 16-bit register.
func highByte(rr string) string {
	switch rr {
	case "HL":
		return "H"
	case "DE":
		return "D"
	case "BC":
		return "B"
	case "IX":
		return "IXH"
	case "IY":
		return "IYH"
	}
	return rr
}

// isPairReg reports whether r is a 16-bit register pair name.
func isPairReg(r string) bool {
	switch r {
	case "HL", "DE", "BC", "IX", "IY":
		return true
	}
	return false
}

// genCmp16 emits a 16-bit comparison using SBC HL, rr.
//
// Z80 only provides SBC HL, rr for 16-bit arithmetic that sets flags.
// The sequence is:
//
//	OR A           ; clear carry (preserves A; sets S/Z/H/PV from A)
//	SBC HL, rr     ; HL = lhs − rhs − 0; sets C (borrow) and Z (equal)
//
// SBC is destructive (clobbers HL).  We save/restore HL with PUSH/POP so
// that lhs remains available for subsequent uses (e.g. the "return a" branch
// of min16).
//
// Conditions after SBC HL, rr (unsigned):
//
//	C flag set   → lhs < rhs (CmpUlt / CmpUge after negation)
//	Z flag set   → lhs == rhs
//
// Signed comparisons (CmpLt/CmpGt on i16) require S⊕V which needs two
// conditional jumps — marked as TODO.
func (g *z80cg) genCmp16(inst *Inst) {
	lhs := g.loc(inst.Src[0])
	rhs := g.loc(inst.Src[1])

	// Handle CmpGt/CmpLe by swapping operands:
	//   CmpUgt(a,b): a>b ↔ b<a → swap → SBC HL(=b), rr(=a) → C means b<a ✓
	//   CmpUle(a,b): a≤b ↔ b≥a → swap → SBC HL(=b), rr(=a) → NC means b≥a ✓
	isGtOrLe := inst.Cond == CmpGt || inst.Cond == CmpUgt ||
		inst.Cond == CmpLe || inst.Cond == CmpUle
	if isGtOrLe {
		lhs, rhs = rhs, lhs
		g.cmpSwapped[inst.Dst] = true
	}

	// SBC HL, rr requires lhs in HL.  If lhs is already HL we proceed.
	// If rhs is HL and lhs is DE, EX DE,HL is the cheapest fix.
	// Otherwise move lhs byte-by-byte into HL.
	if lhs != "HL" {
		if lhs == "DE" && rhs == "HL" {
			// Swap via EX DE,HL: after EX, HL=old_DE=lhs, DE=old_HL=rhs.
			g.emit("    EX DE, HL")
			g.invalidate("HL")
			g.invalidate("DE")
			lhs, rhs = "HL", "DE"
		} else if rhs == "HL" {
			// rhs is HL, lhs is BC or IX/IY.  Byte-copy lhs into a temp.
			// Swap via move: save HL in rhs pair, load lhs to HL.
			// NOTE: this clobbers any live value in DE — use only when DE is free.
			g.emitf("    LD D, %s", highByte(rhs)) // save rhs high into D
			g.emitf("    LD E, %s", lowByte(rhs))  // save rhs low  into E
			g.emitf("    LD H, %s", highByte(lhs))
			g.emitf("    LD L, %s", lowByte(lhs))
			g.invalidate("HL")
			g.invalidate("DE")
			lhs, rhs = "HL", "DE"
		} else {
			// Neither operand is HL; move lhs into HL byte-by-byte.
			g.emitf("    LD H, %s", highByte(lhs))
			g.emitf("    LD L, %s", lowByte(lhs))
			g.invalidate("HL")
			lhs = "HL"
		}
	}

	// lhs is now in HL.  SBC HL, rr clobbers HL; save and restore so the
	// original lhs value survives for use in taken/not-taken branches.
	// TODO: elide PUSH/POP when liveness shows HL is dead after this compare.
	g.emit("    PUSH HL") // save lhs
	g.emit("    OR A")    // clear carry; idempotent for A
	g.emitf("    SBC HL, %s", rhs)
	g.emit("    POP HL")  // restore lhs
	g.invalidate("HL")
}

// ── PUSH/POP pair helpers ─────────────────────────────────────────────────────

// toPair returns the 16-bit register pair containing the given register.
func toPair(r string) string {
	switch r {
	case "A", "F", "AF":
		return "AF"
	case "B", "C", "BC":
		return "BC"
	case "D", "E", "DE":
		return "DE"
	case "H", "L", "HL":
		return "HL"
	}
	return r // IX, IY already pairs
}

// ── DJNZ peephole ─────────────────────────────────────────────────────────────

// findConstInFunc finds the Imm value of an OpConst instruction defining r.
func findConstInFunc(f *Func, r Reg) (int64, bool) {
	for _, b := range f.Blocks {
		for _, inst := range b.Insts {
			if inst.Op == OpConst && inst.Dst == r {
				return inst.Imm, true
			}
		}
	}
	return 0, false
}

// djnzPeepholeResult holds the result of DJNZ peephole detection.
type djnzPeepholeResult struct {
	skipLast  bool      // skip the last OpSub instruction (DJNZ handles DEC B)
	bodyLbl   string    // DJNZ target: the loop body label (brif.Then)
	checkBrif *TermBrIf // the check block's brif (for exit-edge copies)
}

// detectDJNZPeephole checks if block b ends with the DJNZ-optimizable pattern:
//
//	last_inst: OpSub(counter→B, 1)
//	term:      TermJmp to check_block
//	check_block: [OpCmp(CmpNe, B, 0)] + TermBrIf(Then=body, Else=exit)
//	all args trivially in-place (no non-trivial copies needed)
func (g *z80cg) detectDJNZPeephole(f *Func, b *Block) djnzPeepholeResult {
	if len(b.Insts) == 0 {
		return djnzPeepholeResult{}
	}
	jmp, ok := b.Term.(*TermJmp)
	if !ok {
		return djnzPeepholeResult{}
	}
	// Last instruction must be OpSub(counter, 1) with counter→B.
	last := b.Insts[len(b.Insts)-1]
	if last.Op != OpSub {
		return djnzPeepholeResult{}
	}
	if g.ar.Loc(last.Src[0]).Name != "B" || g.ar.Loc(last.Dst).Name != "B" {
		return djnzPeepholeResult{}
	}
	// RHS must be constant 1.
	rhs, found := findConstInFunc(f, last.Src[1])
	if !found || rhs != 1 {
		return djnzPeepholeResult{}
	}
	// Target must be the check block: only CmpNe(B, 0) + optional Const(0) + TermBrIf.
	check := f.BlockByLabel(jmp.Target)
	if check == nil || len(check.Insts) == 0 || len(check.Insts) > 2 {
		return djnzPeepholeResult{}
	}
	// Find the OpCmp instruction (last if there are two).
	var cmp *Inst
	for i := len(check.Insts) - 1; i >= 0; i-- {
		if check.Insts[i].Op == OpCmp {
			cmp = check.Insts[i]
			break
		}
	}
	if cmp == nil || cmp.Cond != CmpNe {
		return djnzPeepholeResult{}
	}
	if g.ar.Loc(cmp.Src[0]).Name != "B" {
		return djnzPeepholeResult{}
	}
	zero, found2 := findConstInFunc(f, cmp.Src[1])
	if !found2 || zero != 0 {
		return djnzPeepholeResult{}
	}
	// Verify all instructions in check block are CmpNe + optional Const(0) only.
	for _, inst := range check.Insts {
		if inst.Op != OpCmp && inst.Op != OpConst {
			return djnzPeepholeResult{}
		}
	}
	brif, ok2 := check.Term.(*TermBrIf)
	if !ok2 || brif.Cond != cmp.Dst {
		return djnzPeepholeResult{}
	}
	// Verify all TermJmp args are trivially in-place (excluding counter B→B).
	for i, arg := range jmp.Args {
		if i >= len(check.Params) {
			break
		}
		srcLoc := g.ar.Loc(arg).Name
		dstLoc := g.ar.Loc(check.Params[i].Dst).Name
		if srcLoc == "B" && dstLoc == "B" {
			continue // counter handled by DJNZ
		}
		if srcLoc != dstLoc {
			return djnzPeepholeResult{} // non-trivial copy, fall back
		}
	}
	// Verify exit-edge copies are trivial.
	exitBlock := f.BlockByLabel(brif.Else)
	if exitBlock != nil {
		for i, arg := range brif.ElseArgs {
			if i >= len(exitBlock.Params) {
				break
			}
			if g.ar.Loc(arg).Name != g.ar.Loc(exitBlock.Params[i].Dst).Name {
				return djnzPeepholeResult{} // non-trivial exit copy, fall back
			}
		}
	}
	return djnzPeepholeResult{
		skipLast:  true,
		bodyLbl:   blockLabel(f.Name, brif.Then),
		checkBrif: brif,
	}
}
