// Z80Codegen lowers allocated MIR2 to Z80 assembly text (.a80 format).
//
// Prerequisites:
//   - AllocResult covering every virtual register in the module
//   - Verified MIR2 module (Verify passed)
//
// Output: a string of Z80 assembly ready for MZA.
// Label format: @funcname_blockname (underscore-joined, no special chars).
//
// Supported opcodes (first pass):
//
//	OpConst        → LD r, n  /  LD rr, nn
//	OpMove         → LD r, r  /  EX DE,HL  /  PUSH+POP
//	OpAdd          → ADD A,r  /  ADD HL,rr
//	OpSub          → SUB r    /  SBC HL,rr
//	OpAnd/Or/Xor   → AND/OR/XOR r
//	OpNeg          → NEG
//	OpNot          → CPL
//	OpExt          → LD H,0 / LD L,r  (zero-extend u8→u16 via HL)
//	OpCmp          → CP r  (result stays in F; ClassFlag)
//	OpLoad         → LD A,(HL)  /  LD r,(HL)
//	OpStore        → LD (HL),A  /  LD (HL),r
//	OpCall         → CALL label
//	OpPatchSlot    → LD r, 0   (initial value; literal byte patchable)
//	OpLoadPatched  → LD r, r   (SMC: already patched in stream)
//	OpPatch        → (comment: SMC patch — no emission in pure assembler)
//	TermJmp        → JP label
//	TermBrIf       → JP Z/NZ/C/NC label  (flag-class cond)
//	TermRet        → RET

// ── Public entry point ────────────────────────────────────────────────────────

// Z80CodegenOptions controls optional codegen features.
type Z80CodegenOptions struct {
	// AnnotateTStates adds T-state cost comments to every instruction line
	// and emits per-block and per-function totals.  Useful for hand-optimisation.
	AnnotateTStates bool
}

// Z80Codegen generates Z80 assembly for the entire module.
// An optional Z80CodegenOptions value may be passed as the third argument;
// callers that don't need options can omit it entirely.
func Z80Codegen(m *Module, ar *AllocResult, opts ...Z80CodegenOptions) string {
	var opt Z80CodegenOptions
	if len(opts) > 0 {
		opt = opts[0]
	}
	var sb strings.Builder
	cg := &z80cg{ar: ar, sb: &sb, mod: m, annotateT: opt.AnnotateTStates}

	sb.WriteString("; generated by MIR2 Z80 codegen\n\n")

	// Emit main first so the binary entry point is at address 0 — no JP needed.
	funcs := m.Funcs
	if main := m.FuncByName("main"); main != nil && len(funcs) > 0 && funcs[0].Name != "main" {
		ordered := make([]*Func, 0, len(funcs))
		ordered = append(ordered, main)
		for _, f := range funcs {
			if f.Name != "main" {
				ordered = append(ordered, f)
			}
		}
		funcs = ordered
	}

	for _, f := range funcs {
		cg.genFunc(f)
		sb.WriteByte('\n')
	}

	// Emit global variable data sections.
	if len(m.Globals) > 0 {
		sb.WriteString("; globals\n")
		for _, g := range m.Globals {
			w := ByteWidth(g.Ty)
			if w == 0 {
				// Zero-size struct: emit the label so address-of references resolve,
				// but no data bytes — the struct occupies no memory at runtime.
				sanitized := sanitizeIdent(g.Name)
				sb.WriteString(sanitized + ":\n")
				continue
			}
			// Page-aligned globals (e.g. LUT tables): emit ALIGN directive first.
			if at, ok := g.Ty.(*ArrayTy); ok && at.Align > 0 {
				fmt.Fprintf(&sb, "    ALIGN %d\n", at.Align)
			}
			sanitized := sanitizeIdent(g.Name)
			sb.WriteString(sanitized + ":\n")
			// Emit as DB sequence for all types — always readable,
			// correct for struct fields, and unambiguous byte order.
			sb.WriteString("    DB ")
			for i := 0; i < w; i++ {
				if i > 0 {
					sb.WriteString(", ")
				}
				b := byte(0)
				if i < len(g.Init) {
					b = g.Init[i]
				}
				fmt.Fprintf(&sb, "%d", b)
			}
			sb.WriteByte('\n')
			// For struct globals, emit EQU labels for each field so that direct
			// addressing (LD A,(sym__field)) works without pointer arithmetic.
			// Format: sanitizeIdent(sym)__fieldName  EQU  sym + byteOffset
			if st, ok := g.Ty.(*StructTy); ok {
				off := 0
				for _, f := range st.Fields {
					var equLbl string
					if f.Name != "" {
						equLbl = sanitized + "__" + f.Name
					} else {
						equLbl = fmt.Sprintf("%s__off%d", sanitized, off)
					}
					if off == 0 {
						fmt.Fprintf(&sb, "%s    EQU  %s\n", equLbl, sanitized)
					} else {
						fmt.Fprintf(&sb, "%s    EQU  %s + %d\n", equLbl, sanitized, off)
					}
					off += ByteWidth(f.Ty)
				}
			}
		}
	}

	// Emit string pool — NUL-terminated byte sequences.
	// Symbol names: @mir2.str.N → mir2_str_N (sanitized for assembler).
	if m.Strings.Len() > 0 {
		sb.WriteString("; strings\n")
		for i := 0; i < m.Strings.Len(); i++ {
			sym := sanitizeIdent(m.Strings.Symbol(i))
			s := m.Strings.At(i)
			sb.WriteString(sym + ":\n")
			sb.WriteString("    DB ")
			for j, c := range []byte(s) {
				if j > 0 {
					sb.WriteString(", ")
				}
				fmt.Fprintf(&sb, "%d", c)
			}
			sb.WriteString(", 0\n") // NUL terminator
		}
	}

	return asmPeepholePass(sb.String())
}

// asmPeepholePass applies post-emit string-level peephole optimisations:
//  1. Double EX DE,HL elimination — two consecutive EX DE,HL cancel; remove both.
//  2. Single-JP function → EQU alias — a function whose entire body is one JP
//     becomes a zero-byte/zero-T EQU alias (tail-call guaranteed by contract).
func asmPeepholePass(src string) string {
	lines := strings.Split(src, "\n")
	lines = elimDoubleExDeHl(lines)
	lines = elimSingleJpEqu(lines)
	return strings.Join(lines, "\n")
}

// elimDoubleExDeHl removes consecutive EX DE,HL pairs.
// Blank lines and comment-only lines between the pair are preserved.
func elimDoubleExDeHl(lines []string) []string {
	const exLine = "    EX DE, HL"
	out := make([]string, 0, len(lines))
	for i := 0; i < len(lines); i++ {
		if strings.TrimSpace(lines[i]) != "EX DE, HL" {
			out = append(out, lines[i])
			continue
		}
		// lines[i] is an EX DE,HL. Look for a second one after skipping
		// blank/comment lines (no real instructions between).
		j := i + 1
		for j < len(lines) {
			t := strings.TrimSpace(lines[j])
			if t == "" || strings.HasPrefix(t, ";") {
				j++
				continue
			}
			break
		}
		if j < len(lines) && strings.TrimSpace(lines[j]) == "EX DE, HL" {
			// Skip both EX DE,HL lines (drop them from output).
			i = j // loop increment makes i = j+1
			continue
		}
		out = append(out, lines[i])
	}
	return out
}

// elimSingleJpEqu converts a function that is exactly one JP target into an EQU.
//
// Pattern (consecutive lines, optionally separated by blank/comment lines):
//
//	funcname:
//	    JP  target
//
// → replaced with a single line:
//
//	funcname    EQU target
//
// Safety conditions:
//   - No additional instructions in the block (comments/blanks OK).
//   - No local labels between funcname: and JP (would break relative refs).
//   - Not "main" (entry point must remain a real label).
func elimSingleJpEqu(lines []string) []string {
	out := make([]string, 0, len(lines))
	i := 0
	for i < len(lines) {
		line := lines[i]
		// Match a bare label line: word followed by ':' with no leading whitespace.
		if !strings.HasPrefix(line, " ") && strings.HasSuffix(strings.TrimSpace(line), ":") {
			label := strings.TrimSuffix(strings.TrimSpace(line), ":")
			if label != "main" && label != "" && !strings.Contains(label, ".") {
				// Scan forward past blank/comment lines to find first instruction.
				j := i + 1
				for j < len(lines) {
					t := strings.TrimSpace(lines[j])
					if t == "" || strings.HasPrefix(t, ";") {
						j++
						continue
					}
					break
				}
				if j < len(lines) {
					instr := strings.TrimSpace(lines[j])
					// Must be exactly "JP target" (not DJNZ, not JP cc).
					if strings.HasPrefix(instr, "JP ") && !strings.Contains(instr, ",") {
						target := strings.TrimSpace(strings.TrimPrefix(instr, "JP "))
						// Check that the next non-blank/comment line after JP is
						// a top-level label or end-of-section (not another instruction
						// inside this "function").
						k := j + 1
						for k < len(lines) {
							t := strings.TrimSpace(lines[k])
							if t == "" || strings.HasPrefix(t, ";") {
								k++
								continue
							}
							break
						}
						nextIsTopLevel := k >= len(lines) ||
							(!strings.HasPrefix(lines[k], " ") && strings.HasSuffix(strings.TrimSpace(lines[k]), ":")) ||
							lines[k] == "; globals" || lines[k] == "; strings"
						if nextIsTopLevel {
							// Emit EQU alias, skip all consumed lines.
							out = append(out, fmt.Sprintf("%s    EQU %s", label, target))
							// Preserve blank lines that came before JP (already in out
							// via j-loop... actually they were skipped). Emit one blank
							// to maintain section spacing.
							i = j + 1
							continue
						}
					}
				}
			}
		}
		out = append(out, line)
		i++
	}
	return out
}

// ── Internal codegen state ────────────────────────────────────────────────────

type z80cg struct {
	ar         *AllocResult
	sb         *strings.Builder
	mod        *Module // parent module (for callee contract lookup at call sites)
	fn         *Func   // current function
	blockIdx   int     // index of current block in fn.Blocks (for fall-through)
	cmpSwapped  map[Reg]bool    // dst reg → operands were swapped in genCmp
	cmpAndZero  map[Reg]bool    // dst reg → comparison used AND A (rhs=0), use NZ/Z not NC/C
	cmpNeedsTwo map[Reg]bool    // dst reg → CmpGt/CmpLe with lhs in A, needs two-JP in BrIf
	callFlags   map[Reg]CmpCond // dst reg of OpCall → FlagCond when callee returns ClassFlag
	constVals  map[Reg]int64 // virtual reg → compile-time constant value (for peepholes)
	deadConsts map[Reg]bool  // OpConst dsts whose LD is suppressed by DSE

	// holdsPhys is a bidirectional alias map for local copy-propagation within a
	// basic block.  holdsPhys[r] = s means physical register r currently holds the
	// same value as s (and holdsPhys[s] = r by symmetry).  Used to eliminate
	// redundant LD instructions: if A ≡ D, we skip "LD A, D" before an ALU op.
	// The map is cleared at every block boundary and at any CALL.
	holdsPhys map[string]string

	// physOverride tracks dynamic relocation of virtual registers that happened
	// as a side-effect of call-argument setup (emitCallArgs parallel copies).
	// physOverride[r] = "B" means virtual register r is now in physical "B",
	// overriding the static allocator assignment g.ar.Loc(r).Name.
	// Cleared at every CALL (the call clobbers volatile state).
	physOverride map[Reg]string

	// trampolines: small glue blocks emitted after main function body that
	// perform block-argument parallel copies then jump to the real target.
	// Needed for BrIf edges where the non-fall-through path requires copies.
	trampolines []trampolineBlock
	trampIdx    int

	// Page-aligned LUT optimisation (21T vs 39T).
	// Pre-scanned per block; cleared at each new block.
	//
	// lutLoadPat: Load dst → pattern descriptor for page-aligned table accesses.
	//   When set, emit LD HL,sym + LD L,src8 + LD A,(HL) instead of the
	//   general Ext+PtrAdd+Load sequence.
	// lutSkip: virtual regs whose emit is merged into the Load instruction above.
	//   Affected: Ext(idx16), AddrOf(base), PtrAdd(ptr).
	lutLoadPat map[Reg]lutLoadPat
	lutSkip    map[Reg]bool

	// Global struct field direct-addressing optimisation.
	// Pre-scanned per block; cleared at each new block.
	//
	// globalFieldLoad[loadDst]  → info for emitting LD A,(sym__field) / LD (sym__field),A
	// globalFieldStore[addrReg] → info for emitting LD (sym__field),val
	// globalFieldSkip[r]        → these intermediate regs are no-ops in genInst
	//   Affected: AddrOf(base), Field(fptr), and (for stores) the store's addrReg.
	globalFieldLoad  map[Reg]globalFieldInfo
	globalFieldStore map[Reg]globalFieldInfo
	globalFieldSkip  map[Reg]bool

	// globalU16StoreSym[addrReg] = sym: addrReg holds the address of a u16 global.
	// Enables emitting LD (sym), HL (16T, no A clobber) instead of the
	// byte-by-byte DE-based sequence (LD A,lo; LD (DE),A; INC DE; LD A,hi; LD (DE),A; DEC DE).
	globalU16StoreSym map[Reg]string

	// globalU16LoadSym[addrReg] = sym: addrReg holds the address of a u16 global load.
	// Enables emitting LD HL, (sym) (20T, no A clobber) instead of the
	// byte-by-byte sequence LD A,(HL)/INC HL/LD H,(HL)/LD L,A that uses A as scratch.
	globalU16LoadSym map[Reg]string

	// lastFlagsLhs / lastFlagsRhs track the effective operands of the most recent
	// flags-setting instruction (SUB / CP / AND A) within the current block.
	// Empty strings mean "unknown / not tracked".
	// Used by genCmp to suppress a redundant CP when SUB already set the same flags.
	lastFlagsLhs string // physical location of the lhs (always A at time of emission)
	lastFlagsRhs string // physical location or immediate string of the rhs

	// curBlock is the block currently being code-generated.
	// Set at the start of genBlock; used by materializePendingFlag for forward scans.
	curBlock *Block

	// pendingFlagReg is the ClassFlag virtual register produced by the most
	// recent genCmp that has not yet been consumed (by OR/AND/brif).
	// Before any new CP that would clobber F, materializePendingFlag() checks
	// whether this register is still live and, if so, emits SBC A,A; LD D,A
	// so the value survives in "D" (via physOverride).
	pendingFlagReg Reg

	// pendingAccReg is a ClassAcc virtual register currently in A that may be
	// clobbered by an upcoming "LD A, imm" in a subsequent genCmp.
	// When genCmp is about to emit "LD A, imm", if pendingAccReg is still live
	// downstream, it emits LD D,A and reroutes pendingAccReg to "D".
	pendingAccReg Reg

	// ptrAddPushHL: set by scanPtrAddBase when a ptr_add's base is in HL and
	// the base virtual is live after the instruction (needs to survive across
	// the loop body). The value is the ptr_add result virtual (Dst).
	// OpPtrAdd emits PUSH HL before ADD HL,rr; OpLoad emits POP HL after
	// the load to restore the saved base ptr.
	ptrAddPushHL Reg

	// tailCallInst: set by genBlock when the last instruction of a block is an
	// OpCall whose result feeds directly into TermRet (tail call pattern).
	// genCall emits JP instead of CALL; genTerm skips RET when this is set.
	tailCallInst *Inst

	// smcPatchers: synthesised patcher functions for @smc parameters.
	// Populated during OpPatchSlot codegen when inst.Sym != "".
	// Flushed after each function body is emitted.
	smcPatchers []smcPatcherInfo

	// T-state annotation (enabled via Z80CodegenOptions.AnnotateTStates).
	// annotateT: emit "; NNT" / "; NT/MT" trailing comments on instruction lines.
	// blockT:    accumulated T-states for the current block (reset at block entry).
	// fnWorstT:  worst-case T-state sum across all blocks in the current function.
	annotateT bool
	blockT    int
	fnWorstT  int
}

// smcPatcherInfo records metadata for a synthesised @smc patcher function.
// Sym is "funcName$paramName"; eqLabel is the EQU pointing at the imm16 bytes.
type smcPatcherInfo struct {
	sym     string // e.g. "draw_player$r0"
	eqLabel string // e.g. "draw_player$r0$imm"
}

// lutLoadPat describes a page-aligned LUT access merged at codegen time.
type lutLoadPat struct {
	sym     string // page-aligned global symbol
	src8Reg Reg    // virtual reg holding the 8-bit index (after lo-subtract if any)
}

// globalFieldInfo describes a global struct field access that can be lowered
// to direct Z80 addressing: LD A,(sym__field) or LD (sym__field),A.
//
// The EQU label is: {sanitizeIdent(sym)}__{fieldName}  (or just sanitizeIdent(sym) for offset 0).
// Emission: LD A,(sym__field)  for loads; LD A,val + LD (sym__field),A  for stores.
type globalFieldInfo struct {
	sym       string // global symbol name (raw, before sanitize)
	offset    int64  // byte offset within the global
	fieldName string // field name for the EQU label (may be empty → use offset)
	// HL-chain: when true, emit LD HL,sym chain instead of LD (sym__field),A.
	hlChain bool // part of a consecutive-field HL-chain group
	hlHead  bool // first in group → emit LD HL,sym before
	hlLast  bool // last in group  → no INC HL after
}

// trampolineBlock is emitted after all regular blocks of a function.
// It resolves block-argument copies for one outgoing BrIf edge.
// If isRet is true, the block ends with RET instead of JRS target.
type trampolineBlock struct {
	label  string        // local label for this trampoline
	copies []parallelCopy
	target string        // real destination label (already formatted)
	isRet  bool          // true → emit RET instead of JRS target
}

// parallelCopy is a single register-to-register move in a parallel copy sequence.
type parallelCopy struct {
	srcName string
	dstName string
	ty      Ty
}

func (g *z80cg) emit(s string) {
	if g.annotateT && strings.HasPrefix(s, "    ") && !strings.HasPrefix(s, "    ;") {
		ts, tsAlt := z80TStates(s)
		if ts > 0 {
			g.blockT += ts
			if tsAlt > 0 {
				s = fmt.Sprintf("%-40s; %dT/%dT", s, ts, tsAlt)
			} else {
				s = fmt.Sprintf("%-40s; %dT", s, ts)
			}
		}
	}
	g.sb.WriteString(s)
	g.sb.WriteByte('\n')
}
func (g *z80cg) emitf(f string, args ...any) { g.emit(fmt.Sprintf(f, args...)) }
func (g *z80cg) comment(s string)            { g.emitf("    ; %s", s) }

// isIXY reports whether reg is an index register (IX or IY).
// Z80 indexed loads/stores require explicit displacement: (IX+d), never bare (IX).
func isIXY(reg string) bool { return reg == "IX" || reg == "IY" }

// ptrIndirect returns the memory-operand string for a pointer register.
// For IX/IY the Z80 requires an explicit displacement byte — even zero:
//
//	HL → "(HL)"
//	IX → "(IX+0)"   DE → "(DE)"
//
// An optional byte offset d shifts the displacement for 16-bit multi-byte accesses.
func ptrIndirect(ptr string, d int) string {
	if isIXY(ptr) {
		if d == 0 {
			return fmt.Sprintf("(%s+0)", ptr)
		}
		return fmt.Sprintf("(%s+%d)", ptr, d)
	}
	return fmt.Sprintf("(%s)", ptr)
}

// isSimpleReg reports whether s names a plain physical register (no parens,
// no digits) — safe to use as an alias key in holdsPhys.
func isSimpleReg(s string) bool {
	if len(s) == 0 {
		return false
	}
	for _, c := range s {
		if !((c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z')) {
			return false
		}
	}
	return true
}

// ── Register topology ─────────────────────────────────────────────────────────
//
// Writing to a 16-bit pair register (e.g. HL) implicitly changes its bytes
// (H, L), and vice versa: writing to H invalidates HL.  These tables encode
// that topology so invalidate() can clear all affected aliases at once.

// regBytes maps a 16-bit register to its 8-bit byte components.
var regBytes = map[string][]string{
	"BC": {"B", "C"},
	"DE": {"D", "E"},
	"HL": {"H", "L"},
	"IX": {"IXH", "IXL"},
	"IY": {"IYH", "IYL"},
}

// regParent maps an 8-bit component to its 16-bit parent register.
var regParent = map[string]string{
	"B": "BC", "C": "BC",
	"D": "DE", "E": "DE",
	"H": "HL", "L": "HL",
	"IXH": "IX", "IXL": "IX",
	"IYH": "IY", "IYL": "IY",
}

// killOne removes a single register and its bidirectional partner from holdsPhys.
func (g *z80cg) killOne(r string) {
	if partner, ok := g.holdsPhys[r]; ok {
		delete(g.holdsPhys, partner)
		delete(g.holdsPhys, r)
	}
}

// invalidate removes all tracking for r: kills r itself, its byte components
// (if r is a 16-bit pair), and its parent pair (if r is an 8-bit component).
func (g *z80cg) invalidate(r string) {
	g.killOne(r)
	if bytes, ok := regBytes[r]; ok {
		for _, b := range bytes {
			g.killOne(b)
		}
	}
	if parent, ok := regParent[r]; ok {
		g.killOne(parent)
	}
}

// setCopy records that dst was loaded from src (they now hold the same value).
// Invalidates dst's old aliases and clears src's previous bidirectional link
// before establishing the new one, preventing stale reverse entries.
func (g *z80cg) setCopy(dst, src string) {
	g.invalidate(dst)
	g.killOne(src) // break src's old reverse-link (could be left by a prior setCopy)
	if isSimpleReg(dst) && isSimpleReg(src) {
		g.holdsPhys[dst] = src
		g.holdsPhys[src] = dst
	}
}

// holdsValue reports whether physical register a currently holds the same
// value as b (either they are the same register, or a copy alias exists).
func (g *z80cg) holdsValue(a, b string) bool {
	return a == b || g.holdsPhys[a] == b
}

// emitLDA emits "LD A, src" and records the copy alias A ≡ src.
// When src is a LocMem address ($Fxxx), emits "LD A, ($Fxxx)" — the only
// valid Z80 form for loading an 8-bit value from an absolute 16-bit address.
func (g *z80cg) emitLDA(src string) {
	if strings.HasPrefix(src, "$") {
		g.emitf("    LD A, (%s)", src)
	} else {
		g.emitf("    LD A, %s", src)
	}
	g.setCopy("A", src)
}

// loc returns the physical location name for virtual register r.
// For LocMem registers the allocator stores the actual byte address in Offset;
// return it as a hex literal so the assembler resolves it correctly.
// e.g. Offset=0xF001 → "$F001", which assembles as LD D, ($F001) / LD ($F001), A etc.
func (g *z80cg) loc(r Reg) string {
	if r == NoReg {
		return "?"
	}
	if phys, ok := g.physOverride[r]; ok {
		return phys
	}
	pl := g.ar.Loc(r)
	if pl.Kind == LocMem {
		return fmt.Sprintf("$%04X", pl.Offset)
	}
	return pl.Name
}

// ── Function ──────────────────────────────────────────────────────────────────

// computeDeadConsts returns the set of OpConst dsts whose LD can be suppressed
// because every use of the constant is already handled by a codegen peephole:
//
//   - OpCmp with Src[1] being the const → CP imm8 fires (no register needed).
//   - OpAdd/OpSub with Src[1]==const, value==1, and lhs/dst at the same physical
//     location → INC/DEC fires (no register needed).
//
// Constants with zero uses are also suppressed.
func computeDeadConsts(f *Func, ar *AllocResult) map[Reg]bool {
	// Collect all OpConst dsts and their immediate values.
	constVal := make(map[Reg]int64)
	for _, b := range f.Blocks {
		for _, inst := range b.Insts {
			if inst.Op == OpConst {
				constVal[inst.Dst] = inst.Imm
			}
		}
	}
	if len(constVal) == 0 {
		return nil
	}

	physName := func(r Reg) string {
		if loc, ok := ar.Locs[r]; ok {
			return loc.Name
		}
		return ""
	}

	totalUses  := make(map[Reg]int)
	foldedUses := make(map[Reg]int)

	for _, b := range f.Blocks {
		for _, inst := range b.Insts {
			// Call/CallIndirect args live in inst.Args, not inst.Src — count them
			// as non-peephole uses so their LD is not suppressed.
			for _, src := range inst.Args {
				if _, isConst := constVal[src]; isConst {
					totalUses[src]++
					// call args are never peephole-foldable
				}
			}
			for _, src := range inst.Src {
				cv, isConst := constVal[src]
				if !isConst {
					continue
				}
				totalUses[src]++
				switch inst.Op {
				case OpCmp:
					// CP imm8: fires when rhs (Src[1]) has a known constant.
					if src == inst.Src[1] {
						foldedUses[src]++
					}
				case OpAdd, OpSub:
					// INC/DEC: fires when rhs==1 and the op is in-place (lhs phys == dst phys).
					if src == inst.Src[1] && cv == 1 &&
						physName(inst.Src[0]) == physName(inst.Dst) {
						foldedUses[src]++
					}
				case OpAnd, OpOr, OpXor:
					// AND/OR/XOR immediate peephole: always emits "AND n" etc., no register needed.
					if src == inst.Src[1] {
						foldedUses[src]++
					}
				case OpStore:
					// LD (HL),n / LD (IX+d),n — 8-bit stores can take an immediate
					// operand directly; no register needed for the value.
					if src == inst.Src[1] && inst.Ty.Width() <= 8 {
						foldedUses[src]++
					}
				case OpMul:
					// genMul folds constant Src[1] into shift sequences.
					if src == inst.Src[1] {
						foldedUses[src]++
					}
					case OpShl, OpShr, OpSar:
					// genShift always shifts by 1 and completely ignores Src[1].
					// Any constant passed as the shift count is effectively dead.
					if src == inst.Src[1] {
						foldedUses[src]++
					}
				}
			}
		}
		// Block args in terminators (TermJmp.Args, TermBrIf.*Args, TermRet.Vals)
		// are general uses — they cannot be peephole-folded.
		if b.Term != nil {
			for _, src := range b.Term.termUses() {
				if _, isConst := constVal[src]; isConst {
					totalUses[src]++
					// no foldedUses increment — terminators are never peephole-dead
				}
			}
		}
	}

	dead := make(map[Reg]bool)
	for r := range constVal {
		total := totalUses[r]
		if total == 0 || total == foldedUses[r] {
			dead[r] = true
		}
	}
	return dead
}

func (g *z80cg) genFunc(f *Func) {
	g.fn = f
	g.cmpSwapped = make(map[Reg]bool)
	g.cmpAndZero = make(map[Reg]bool)
	g.cmpNeedsTwo = make(map[Reg]bool)
	g.callFlags = make(map[Reg]CmpCond)
	g.constVals = make(map[Reg]int64)
	g.deadConsts = computeDeadConsts(f, g.ar)
	g.holdsPhys = make(map[string]string)
	g.physOverride = make(map[Reg]string)
	g.trampolines = g.trampolines[:0]
	g.trampIdx = 0
	g.smcPatchers = g.smcPatchers[:0]
	g.lutLoadPat = make(map[Reg]lutLoadPat)
	g.lutSkip = make(map[Reg]bool)
	g.globalFieldLoad = make(map[Reg]globalFieldInfo)
	g.globalFieldStore = make(map[Reg]globalFieldInfo)
	g.globalFieldSkip = make(map[Reg]bool)
	g.globalU16StoreSym = make(map[Reg]string)
	g.globalU16LoadSym = make(map[Reg]string)
	g.fnWorstT = 0

	label := sanitizeIdent(f.Name)
	g.emitf("; %s", funcAnnotation(f, g.ar))
	g.emitf("%s:", label)

	for i, b := range f.Blocks {
		g.blockIdx = i
		g.genBlock(f, b)
	}

	// Emit trampoline blocks: small copy+JR stubs for BrIf edges with block args.
	// MZA auto-promotes JR→JP if the target is beyond ±127 bytes.
	for _, tramp := range g.trampolines {
		g.emitf("%s:", tramp.label)
		g.emitParallelCopy(tramp.copies)
		if tramp.isRet {
			g.emit("    RET")
		} else {
			g.emitf("    JRS %s", tramp.target)
		}
	}

	// Emit function-level T-state summary (worst-case block = deepest hot path).
	if g.annotateT && g.fnWorstT > 0 {
		g.emitf("; — %s worst-case block: %dT", label, g.fnWorstT)
	}

	// Emit synthesised @smc patcher functions for any named PatchSlots.
	// Each patcher: draw_player_set_r0(v: u16 in HL) → patches imm16 bytes in draw_player.
	for _, p := range g.smcPatchers {
		// Derive patcher name: "funcName$paramName" → "funcName_set_paramName"
		parts := strings.SplitN(p.sym, "$", 2)
		patcherName := p.sym // fallback if no $
		if len(parts) == 2 {
			patcherName = parts[0] + "_set_" + parts[1]
		}
		g.emitf("\n; synthesised @smc patcher — fun %s(v: u16 = HL)", patcherName)
		g.emitf("; patches imm16 at %s", p.eqLabel)
		g.emitf("%s:", patcherName)
		g.emitf("    LD A, L")
		g.emitf("    LD (%s), A", p.eqLabel)
		g.emitf("    LD A, H")
		g.emitf("    LD (%s+1), A", p.eqLabel)
		g.emitf("    RET")
	}
}

// ── Page-aligned LUT pre-scan ──────────────────────────────────────────────────

// scanLUTPatterns detects the pattern emitted by LUTGen for page-aligned tables:
//
//	idx16 = Ext(src8, u8→u16, ClassIndex)
//	base  = AddrOf("sym")                      ← sym has Align==256
//	ptr   = PtrAdd(base, idx16)
//	dst   = Load(ptr, u8, ClassAcc)
//
// When found:
//   - g.lutLoadPat[dst] = {sym, src8Reg}
//   - g.lutSkip[idx16, base, ptr] = true
//
// The pattern is cleared (g.lutLoadPat, g.lutSkip rebuilt) at each new block.
// This is safe because LUTGen only ever creates single-use intermediate regs.
func (g *z80cg) scanLUTPatterns(b *Block) {
	// Reset per-block maps (keep same map objects; just clear them).
	clear(g.lutLoadPat)
	clear(g.lutSkip)

	// Build: reg → defining instruction (within this block only).
	defInst := make(map[Reg]*Inst, len(b.Insts))
	for _, inst := range b.Insts {
		if inst.Dst != NoReg {
			defInst[inst.Dst] = inst
		}
	}

	for _, inst := range b.Insts {
		// Looking for: dst = Load(ptr, u8)
		if inst.Op != OpLoad || inst.Ty.Width() != 8 || inst.Dst == NoReg {
			continue
		}
		ptrReg := inst.Src[0]

		// ptr = PtrAdd(base, idx16)
		ptrInst, ok := defInst[ptrReg]
		if !ok || ptrInst.Op != OpPtrAdd {
			continue
		}
		baseReg := ptrInst.Src[0]
		idx16Reg := ptrInst.Src[1]

		// base = AddrOf(sym) where sym is page-aligned
		baseInst, ok := defInst[baseReg]
		if !ok || baseInst.Op != OpAddrOf {
			continue
		}
		sym := baseInst.Sym
		if !g.isGlobalPageAligned(sym) {
			continue
		}

		// idx16 = Ext(src8, u8→u16)
		extInst, ok := defInst[idx16Reg]
		if !ok || extInst.Op != OpExt {
			continue
		}
		if extInst.SrcTy == nil || extInst.SrcTy.Width() != 8 || extInst.Ty.Width() != 16 {
			continue
		}
		src8Reg := extInst.Src[0]

		// Pattern matched: record and mark intermediates for skipping.
		g.lutLoadPat[inst.Dst] = lutLoadPat{sym: sym, src8Reg: src8Reg}
		g.lutSkip[idx16Reg] = true
		g.lutSkip[baseReg] = true
		g.lutSkip[ptrReg] = true
	}
}

// isGlobalPageAligned reports whether the named global in the current module
// has Align == 256 (i.e. is a page-aligned LUT candidate).
func (g *z80cg) isGlobalPageAligned(sym string) bool {
	for _, gl := range g.mod.Globals {
		if gl.Name == sym {
			if at, ok := gl.Ty.(*ArrayTy); ok {
				return at.Align == 256
			}
		}
	}
	return false
}

// globalFieldLabel returns the EQU label for a global struct field access.
// Format: sanitizeIdent(sym)__fieldName  (or just sanitizeIdent(sym) for offset 0 / no name).
func globalFieldLabel(sym string, offset int64, fieldName string) string {
	base := sanitizeIdent(sym)
	if fieldName != "" {
		return base + "__" + fieldName
	}
	if offset == 0 {
		return base
	}
	return fmt.Sprintf("%s__off%d", base, offset)
}

// globalStructField looks up a global in the module by symbol name and returns its
// StructTy if it has one, plus the field name for a given byte offset.
// Returns ("", -1, false) when not found or not a struct global.
func (g *z80cg) globalStructField(sym string, offset int64) (fieldName string, found bool) {
	for _, gl := range g.mod.Globals {
		if gl.Name != sym {
			continue
		}
		st, ok := gl.Ty.(*StructTy)
		if !ok {
			return "", false
		}
		// Find field by byte offset.
		off := int64(0)
		for _, f := range st.Fields {
			if off == offset {
				return f.Name, true
			}
			off += int64(ByteWidth(f.Ty))
		}
		// Offset is valid but doesn't align with a named field boundary — still use it.
		return "", false
	}
	return "", false
}

// scanGlobalFieldPatterns detects patterns where a global struct field is loaded
// or stored via AddrOf + optional Field + Load/Store.  When found, the load/store
// is rewritten to use Z80 direct addressing (LD A,(sym__field) or LD (sym__field),A).
//
// Patterns detected (u8 only — all addressable via single LD A,(nn)):
//
//	Load pattern (with field):
//	  base  = AddrOf(sym)            [OpAddrOf]
//	  fptr  = Field(base, imm)       [OpField]
//	  dst   = Load(fptr, u8)         [OpLoad]
//
//	Load pattern (field 0, no OpField):
//	  base  = AddrOf(sym)            [OpAddrOf]
//	  dst   = Load(base, u8)         [OpLoad]
//
//	Store pattern (with field):
//	  base  = AddrOf(sym)
//	  fptr  = Field(base, imm)
//	          Store(fptr, val, u8)   [OpStore, Dst==NoReg]
//
//	Store pattern (field 0):
//	  base  = AddrOf(sym)
//	          Store(base, val, u8)
//
// Only fires when the AddrOf refers to a global in m.Globals (not a func symbol).
// Only u8 loads and stores are handled (single-byte LD A,(nn) / LD (nn),A).
func (g *z80cg) scanGlobalFieldPatterns(b *Block) {
	// Reset per-block maps.
	clear(g.globalFieldLoad)
	clear(g.globalFieldStore)
	clear(g.globalFieldSkip)
	clear(g.globalU16StoreSym)
	clear(g.globalU16LoadSym)

	// Build: reg → defining instruction within this block.
	defInst := make(map[Reg]*Inst, len(b.Insts))
	for _, inst := range b.Insts {
		if inst.Dst != NoReg {
			defInst[inst.Dst] = inst
		}
	}

	// Helper: check if sym names a module-level global (not a string or function symbol).
	isGlobal := func(sym string) bool {
		for _, gl := range g.mod.Globals {
			if gl.Name == sym {
				return true
			}
		}
		return false
	}

	// Count uses of each virtual reg in this block (instructions + block terminators).
	// Used to guard against skipping intermediates that are shared with other users.
	useCount := make(map[Reg]int)
	for _, inst := range b.Insts {
		for _, s := range inst.Src {
			if s != NoReg {
				useCount[s]++
			}
		}
		for _, s := range inst.Args {
			if s != NoReg {
				useCount[s]++
			}
		}
	}
	if b.Term != nil {
		for _, s := range b.Term.termUses() {
			if s != NoReg {
				useCount[s]++
			}
		}
	}

	// Scan Load instructions.
	// Only mark intermediates as skip when:
	//   1. The load's allocated destination IS A (LD A,(nn) is the only direct read on Z80).
	//   2. Each intermediate register (AddrOf/Field results) is used exactly once —
	//      by this Load (and the Field uses the AddrOf, counted once).
	//      If an intermediate is shared (e.g., base ptr reused for multiple fields),
	//      we must not skip it or the other consumer will see a dead register.
	for _, inst := range b.Insts {
		if inst.Op == OpLoad && inst.Ty.Width() == 8 && inst.Dst != NoReg {
			// Only apply when the allocated destination is the A register.
			if g.ar.Loc(inst.Dst).Name != "A" {
				continue
			}
			ptrReg := inst.Src[0]
			ptrInst, hasDef := defInst[ptrReg]
			if !hasDef {
				continue
			}

			switch ptrInst.Op {
			case OpAddrOf:
				// Pattern: Load(AddrOf(sym), u8)  — offset 0
				if !isGlobal(ptrInst.Sym) {
					continue
				}
				// Only skip AddrOf if its result is used only by this Load.
				if useCount[ptrReg] != 1 {
					continue
				}
				fieldName, _ := g.globalStructField(ptrInst.Sym, 0)
				g.globalFieldLoad[inst.Dst] = globalFieldInfo{
					sym:       ptrInst.Sym,
					offset:    0,
					fieldName: fieldName,
				}
				g.globalFieldSkip[ptrReg] = true

			case OpField:
				// Pattern: Load(Field(AddrOf(sym), imm), u8)
				// Guard: Field result used only by this Load, AddrOf result used only by Field.
				if useCount[ptrReg] != 1 {
					continue
				}
				baseReg := ptrInst.Src[0]
				baseDef, ok := defInst[baseReg]
				if !ok || baseDef.Op != OpAddrOf {
					continue
				}
				if !isGlobal(baseDef.Sym) {
					continue
				}
				if useCount[baseReg] != 1 {
					continue
				}
				offset := ptrInst.Imm
				fieldName, _ := g.globalStructField(baseDef.Sym, offset)
				g.globalFieldLoad[inst.Dst] = globalFieldInfo{
					sym:       baseDef.Sym,
					offset:    offset,
					fieldName: fieldName,
				}
				g.globalFieldSkip[ptrReg] = true    // Field result
				g.globalFieldSkip[baseReg] = true   // AddrOf result
			}
		}
	}

	// Scan Store instructions (Dst==NoReg, Src[0]=addr, Src[1]=val).
	for _, inst := range b.Insts {
		if inst.Op != OpStore || inst.Ty.Width() != 8 {
			continue
		}
		addrReg := inst.Src[0]
		addrInst, hasDef := defInst[addrReg]
		if !hasDef {
			continue
		}

		switch addrInst.Op {
		case OpAddrOf:
			if !isGlobal(addrInst.Sym) {
				continue
			}
			// Only skip if the AddrOf result is used solely by this Store.
			if useCount[addrReg] != 1 {
				continue
			}
			fieldName, _ := g.globalStructField(addrInst.Sym, 0)
			g.globalFieldStore[addrReg] = globalFieldInfo{
				sym:       addrInst.Sym,
				offset:    0,
				fieldName: fieldName,
			}
			g.globalFieldSkip[addrReg] = true

		case OpField:
			if useCount[addrReg] != 1 {
				continue
			}
			baseReg2 := addrInst.Src[0]
			baseDef, ok := defInst[baseReg2]
			if !ok || baseDef.Op != OpAddrOf {
				continue
			}
			if !isGlobal(baseDef.Sym) {
				continue
			}
			if useCount[baseReg2] != 1 {
				continue
			}
			offset := addrInst.Imm
			fieldName, _ := g.globalStructField(baseDef.Sym, offset)
			g.globalFieldStore[addrReg] = globalFieldInfo{
				sym:       baseDef.Sym,
				offset:    offset,
				fieldName: fieldName,
			}
			g.globalFieldSkip[addrReg] = true     // Field result
			g.globalFieldSkip[baseReg2] = true    // AddrOf result
		}
	}

	// ── HL-chain detection ──────────────────────────────────────────────────────
	// When 2+ stores to the same global struct cover consecutive byte offsets and
	// all value registers are safe (not H or L, which alias with the HL pointer),
	// replace independent LD (sym__field),A sequences with:
	//   LD HL,sym  ;  LD (HL),r  ;  INC HL  ;  LD (HL),r  ;  ...
	// Saves 8T and 4 bytes for a 3-field struct (61T→53T, 12B→8B).
	type hlEntry struct {
		addrReg Reg
		valReg  Reg
		offset  int64
	}
	symStores := make(map[string][]hlEntry)
	for addrReg, info := range g.globalFieldStore {
		for _, inst := range b.Insts {
			if inst.Op == OpStore && inst.Src[0] == addrReg {
				symStores[info.sym] = append(symStores[info.sym], hlEntry{
					addrReg: addrReg,
					valReg:  inst.Src[1],
					offset:  info.offset,
				})
				break
			}
		}
	}
	for _, entries := range symStores {
		if len(entries) < 2 {
			continue
		}
		sort.Slice(entries, func(i, j int) bool { return entries[i].offset < entries[j].offset })
		// Check consecutive offsets.
		consecutive := true
		for i := 1; i < len(entries); i++ {
			if entries[i].offset != entries[i-1].offset+1 {
				consecutive = false
				break
			}
		}
		if !consecutive {
			continue
		}
		// Check all value regs safe (not H/L which aliases with HL pointer).
		safe := true
		for _, e := range entries {
			if e.valReg != NoReg {
				loc := g.ar.Loc(e.valReg).Name
				if loc == "H" || loc == "L" {
					safe = false
					break
				}
			}
		}
		if !safe {
			continue
		}
		// Mark as HL-chain.
		for i, e := range entries {
			entry := g.globalFieldStore[e.addrReg]
			entry.hlChain = true
			entry.hlHead = (i == 0)
			entry.hlLast = (i == len(entries)-1)
			g.globalFieldStore[e.addrReg] = entry
		}
	}

	// ── u16 direct-address store detection ──────────────────────────────────────
	// Pattern: OpStore(w=16, addrReg=AddrOf(sym), valReg)
	// Enables LD (sym), HL (16T, no A clobber) when valReg is in HL.
	for _, inst := range b.Insts {
		if inst.Op != OpStore || inst.Ty.Width() != 16 {
			continue
		}
		addrReg := inst.Src[0]
		def, ok := defInst[addrReg]
		if !ok || def.Op != OpAddrOf || !isGlobal(def.Sym) {
			continue
		}
		g.globalU16StoreSym[addrReg] = def.Sym
	}

	// ── u16 direct-address load detection ────────────────────────────────────
	// Pattern: OpLoad(w=16, addrReg=AddrOf(sym)) → dst (u16, must be HL)
	// Enables LD HL, (sym) (20T, no A clobber) instead of INC/DEC trick via A.
	// Only fires when addrReg is used solely by this load (useCount==1) so we
	// can safely skip the AddrOf instruction (suppress LD HL,sym).
	for _, inst := range b.Insts {
		if inst.Op != OpLoad || inst.Ty.Width() != 16 || inst.Dst == NoReg {
			continue
		}
		if g.ar.Loc(inst.Dst).Name != "HL" {
			continue // only LD HL,(nn) exists for direct u16 load
		}
		addrReg := inst.Src[0]
		def, ok := defInst[addrReg]
		if !ok || def.Op != OpAddrOf || !isGlobal(def.Sym) {
			continue
		}
		if useCount[addrReg] != 1 {
			continue // addr reg used by other instructions too
		}
		g.globalU16LoadSym[addrReg] = def.Sym
		g.globalFieldSkip[addrReg] = true // suppress LD HL, sym from OpAddrOf
	}
}

// scanPtrAddBase detects OpPtrAdd instructions where the base pointer is in HL
// AND the base virtual is live after the ptr_add (e.g. needed on a loop
// back-edge).  In that case ADD HL,rr would clobber HL (the base), so we
// arrange for PUSH HL before the ADD and POP HL after the subsequent load.
//
// Sets g.ptrAddPushHL = ptr_add.Dst  when the pattern fires; cleared by the
// OpLoad codegen after it emits the POP HL.
func (g *z80cg) scanPtrAddBase(b *Block) {
	g.ptrAddPushHL = NoReg

	for idx, inst := range b.Insts {
		if inst.Op != OpPtrAdd {
			continue
		}
		baseReg := inst.Src[0]
		if g.ar.Loc(baseReg).Name != "HL" {
			continue // base not in HL — no clobber risk
		}

		// Check if baseReg is live after this ptr_add.
		// A base is live-after if it appears in any later instruction's sources
		// OR in the block terminator's argument list.
		liveAfter := false
		for _, later := range b.Insts[idx+1:] {
			for _, s := range later.Src {
				if s == baseReg {
					liveAfter = true
					break
				}
			}
			for _, a := range later.Args {
				if a == baseReg {
					liveAfter = true
					break
				}
			}
			if liveAfter {
				break
			}
		}
		if !liveAfter {
			if t := b.Term; t != nil {
				for _, r := range t.termUses() {
					if r == baseReg {
						liveAfter = true
						break
					}
				}
			}
		}

		if liveAfter {
			g.ptrAddPushHL = inst.Dst
			return // one pattern per block is enough
		}
	}
}

// ── Block ─────────────────────────────────────────────────────────────────────

func (g *z80cg) genBlock(f *Func, b *Block) {
	if b.Label != "entry" {
		g.emitf(".%s_%s:", sanitizeIdent(f.Name), sanitizeIdent(b.Label))
	}
	clear(g.holdsPhys)       // all register aliases unknown at block entry
	g.lastFlagsLhs = ""      // flags state unknown at block entry
	g.lastFlagsRhs = ""
	g.blockT = 0             // reset per-block T-state accumulator
	g.curBlock = b
	g.pendingFlagReg = NoReg
	g.pendingAccReg = NoReg
	// If a block param is allocated to A, any compare instruction in this block
	// would clobber it with "LD A, lhs". Mark it as pending so materializePendingAcc
	// can save it to a scratch register before the clobber occurs.
	for _, bp := range b.Params {
		if bp.Dst != NoReg && g.ar.Loc(bp.Dst).Name == "A" {
			g.pendingAccReg = bp.Dst
			break
		}
	}

	// Pre-scan: identify page-aligned LUT access patterns so we can merge
	// Ext + AddrOf + PtrAdd + Load into: LD HL,sym; LD L,src8; LD A,(HL).
	g.scanLUTPatterns(b)

	// Pre-scan: identify global struct field accesses so we can emit
	// LD A,(sym__field) / LD (sym__field),A instead of LD HL,sym + INC HL… + LD A,(HL).
	g.scanGlobalFieldPatterns(b)

	// Pre-scan: detect ptr_add+load patterns where the base (ptr) is in HL
	// and must survive across the instruction (e.g. in a loop).  Arranges
	// for PUSH HL / ADD HL,rr / LD dst,(HL) / POP HL to preserve the base.
	g.scanPtrAddBase(b)

	// Detect DJNZ peephole: DEC B + JP loop_head → DJNZ loop_body.
	peep := g.detectDJNZPeephole(f, b)

	// Detect tail call: last instruction is OpCall whose result feeds directly
	// into TermRet. genCall will emit JP instead of CALL; genTerm skips RET.
	g.tailCallInst = nil
	if len(b.Insts) > 0 && peep.bodyLbl == "" {
		last := b.Insts[len(b.Insts)-1]
		if last.Op == OpCall && !isIntrinsic(last.Sym) {
			if ret, ok := b.Term.(*TermRet); ok {
				isTail := len(ret.Vals) == 0 ||
					(len(ret.Vals) == 1 && ret.Vals[0] == last.Dst)
				if isTail {
					g.tailCallInst = last
				}
			}
		}
	}

	limit := len(b.Insts)
	if peep.skipLast {
		limit-- // skip final DEC B; DJNZ handles it
	}
	for _, inst := range b.Insts[:limit] {
		g.genInst(inst)
	}

	if peep.bodyLbl != "" {
		g.emitf("    DJNZ %s", peep.bodyLbl)
		// Exit path after DJNZ falls through (B=0).
		// Use the check block's Else edge copies.
		exitCopies := g.buildBlockCopies(f, peep.checkBrif.Else, peep.checkBrif.ElseArgs)
		g.emitParallelCopy(exitCopies)
		if !g.isFallThrough(f, peep.checkBrif.Else) || len(exitCopies) != 0 {
			g.emitf("    JRS %s", blockLabel(f.Name, peep.checkBrif.Else))
		}
	} else {
		g.genTerm(f, b.Term)
	}

	// Emit per-block T-state total and accumulate into function worst-case.
	if g.annotateT && g.blockT > 0 {
		g.emitf("    ; — block %q: %dT", b.Label, g.blockT)
		if g.blockT > g.fnWorstT {
			g.fnWorstT = g.blockT
		}
	}
}

// ── Instructions ──────────────────────────────────────────────────────────────

func (g *z80cg) genInst(inst *Inst) {
	// Instructions merged into a page-aligned LUT load are skipped here;
	// their code is emitted by the Load case below.
	if g.lutSkip[inst.Dst] {
		return
	}

	// Instructions merged into a global-field direct-addressing sequence are
	// skipped here; their code is emitted by the Load/Store case below.
	// (Stores have Dst==NoReg; check the addr-reg via the instruction's Src[0].)
	if inst.Op != OpStore && g.globalFieldSkip[inst.Dst] {
		return
	}

	// Flag-clobbering ops clear lastFlagsLhs/Rhs explicitly in their cases.
	// Flag-preserving ops (LD, PUSH, POP, …) leave the tracker intact so that
	// the Sub+CmpLt flag-fusion peephole can fire across an intervening LD.

	dst := g.loc(inst.Dst)

	switch inst.Op {
	case OpConst:
		g.constVals[inst.Dst] = inst.Imm
		if dst == "F" {
			// Bool constant into flag register: SCF (true) or AND A (false, clears C+sets Z).
			g.lastFlagsLhs = ""
			g.lastFlagsRhs = ""
			if inst.Imm != 0 {
				g.emit("    SCF")
			} else {
				g.emit("    AND A") // A=A (no change), clears C, sets Z based on A
			}
			return
		}
		if !g.deadConsts[inst.Dst] {
			w := inst.Ty.Width()
			if w >= 24 {
				// 24/32-bit constant via shadow pair.
				//   LD rr, lo16   (10T)
				//   EXX           (4T)
				//   LD rr, hi     (10T) — hi8 for u24, hi16 for u32
				//   EXX           (4T)  = 28T total
				// For u24: hi is at most 0x00FF, so shadow H' is always 0.
				lo := uint32(inst.Imm) & 0xFFFF
				hi := uint32(inst.Imm) >> 16
				g.emitf("    LD %s, %d", dst, lo)
				g.emit("    EXX")
				g.emitf("    LD %s, %d", dst, hi)
				g.emit("    EXX")
			} else {
				g.emitf("    LD %s, %d", dst, inst.Imm)
			}
		}

	case OpMove:
		src := g.loc(inst.Src[0])
		if dst == src {
			return // no-op
		}
		g.emitMov(dst, src, inst.Ty.Width())

	case OpAdd:
		g.lastFlagsLhs = ""
		g.lastFlagsRhs = ""
		g.genBinOp("ADD", inst)

	case OpSub:
		g.lastFlagsLhs = "" // clear stale tracking before this sub
		g.lastFlagsRhs = ""
		g.genBinOp("SUB", inst)
		// Record that flags were set by SUB(lhs, rhs) for the Sub+CmpLt fusion.
		// Only track 8-bit subs; 16-bit uses SBC which sets different flags.
		if inst.Ty.Width() <= 8 {
			rhsP := g.loc(inst.Src[1])
			if cv, ok := g.constVals[inst.Src[1]]; ok {
				rhsP = fmt.Sprintf("%d", cv)
			}
			if rhsP != "A" { // skip NEG-trick case (rhs was in A)
				g.lastFlagsLhs = g.loc(inst.Src[0]) // logical lhs
				g.lastFlagsRhs = rhsP
			}
		}

	case OpMul:
		g.lastFlagsLhs = ""
		g.lastFlagsRhs = ""
		g.genMul(inst)

	case OpAnd:
		g.lastFlagsLhs = ""
		g.lastFlagsRhs = ""
		g.genBinOp("AND", inst)

	case OpOr:
		g.lastFlagsLhs = ""
		g.lastFlagsRhs = ""
		g.genBinOp("OR", inst)

	case OpXor:
		g.lastFlagsLhs = ""
		g.lastFlagsRhs = ""
		g.genBinOp("XOR", inst)

	case OpNeg:
		g.lastFlagsLhs = ""
		g.lastFlagsRhs = ""
		if inst.Ty.Width() == 16 {
			// 16-bit NEG HL using the classic demo-scene SBC A,A trick:
			//   XOR A      ; A=0, CF=0
			//   SUB L      ; A = 0-L, CF=1 if L≠0 (borrow)
			//   LD L, A    ; save negated low byte
			//   SBC A, A   ; A = 0-CF → 0x00 or 0xFF (propagate borrow)
			//   SUB H      ; A = -CF - H  (correct high byte with borrow)
			//   LD H, A    ; save negated high byte
			// 6 bytes, 24T — saves 2 bytes and 7T vs NEG-based sequence.
			g.emit("    XOR A")
			g.emit("    SUB L")
			g.emit("    LD L, A")
			g.emit("    SBC A, A")
			g.emit("    SUB H")
			g.emit("    LD H, A")
			g.invalidate("A")
			g.invalidate("HL")
		} else {
			// Z80 NEG always operates on A; ensure source is in A first.
			srcLoc := g.loc(inst.Src[0])
			if srcLoc != "A" && !g.holdsValue("A", srcLoc) {
				g.emitf("    LD A, %s", srcLoc)
			}
			g.emit("    NEG")
			g.invalidate("A")
			// Record that inst.Dst is now in A so TermRet can skip the redundant move.
			if g.loc(inst.Dst) != "A" {
				g.physOverride[inst.Dst] = "A"
			}
		}

	case OpNot:
		g.lastFlagsLhs = ""
		g.lastFlagsRhs = ""
		g.emit("    CPL")
		g.invalidate("A")

	case OpShl:
		g.lastFlagsLhs = ""
		g.lastFlagsRhs = ""
		g.genShift("SLA", inst)

	case OpShr:
		g.lastFlagsLhs = ""
		g.lastFlagsRhs = ""
		g.genShift("SRL", inst)

	case OpSar:
		g.lastFlagsLhs = ""
		g.lastFlagsRhs = ""
		g.genShift("SRA", inst)

	case OpExt:
		// Zero-extend srcTy → Ty.  Primary case: u8 → u16 into HL.
		// genExt may emit XOR (flag-clobbering) — clear to be safe.
		g.lastFlagsLhs = ""
		g.lastFlagsRhs = ""
		g.genExt(inst)

	case OpSext:
		g.lastFlagsLhs = ""
		g.lastFlagsRhs = ""
		g.genSext(inst)

	case OpTrunc:
		src := g.loc(inst.Src[0])
		// Truncate 16-bit → 8-bit: take low byte.
		// If dst is L and src is HL, or dst is E and src is DE — no-op.
		if dst != src {
			g.emitf("    LD %s, %s", dst, lowByte(src))
		}

	case OpCmp:
		g.genCmp(inst)

	case OpLoad:
		// Page-aligned LUT fast path:
		//   LD H, sym^H  ;  7T, 2 bytes — only need the page (high byte)
		//   LD L, idx8   ;  4T           — L is overwritten anyway
		//   LD A, (HL)   ;  7T  → 18T total vs 21T (LD HL) vs 39T general
		// MZA supports the ^H suffix: sym^H extracts (addr >> 8) & 0xFF.
		// LD HL, sym would also load L=low(sym), which is immediately
		// discarded by the following LD L — wasted 3T and 1 byte.
		if pat, ok := g.lutLoadPat[inst.Dst]; ok {
			src8 := g.loc(pat.src8Reg)
			g.emitf("    LD H, %s^H", sanitizeIdent(pat.sym))
			g.invalidate("H")
			g.emitf("    LD L, %s", src8)
			g.invalidate("L")
			if dst != "A" {
				g.emitf("    LD A, (HL)")
				g.invalidate("A")
				g.emitMov(dst, "A", 8)
			} else {
				g.emitf("    LD A, (HL)")
				g.invalidate("A")
			}
			break
		}
		// Global struct field direct-addressing fast path:
		//   LD A, (sym__field)   ; 13T, 3 bytes — direct memory addressing
		// Replaces: LD HL,sym + INC HL×N + LD r,(HL) + (LD A,r)  = 33–43T, 4–8 bytes.
		// Only u8 loads where dst == A are eligible without clobbering risk.
		// When dst != A the intermediates (AddrOf/Field) are NOT skipped in this path,
		// so the original HL-indirect code is emitted instead.
		if info, ok := g.globalFieldLoad[inst.Dst]; ok && dst == "A" {
			lbl := globalFieldLabel(info.sym, info.offset, info.fieldName)
			g.emitf("    LD A, (%s)", lbl)
			g.invalidate("A")
			break
		}
		// u16 direct-address load: LD HL, (sym) — 20T, no A clobber.
		// Fires when the address comes from OpAddrOf(global) and dst is HL.
		// Avoids the INC/DEC trick (LD A,(HL)/INC HL/LD H,(HL)/LD L,A) that
		// uses A as scratch and corrupts loop counters stored in A.
		if inst.Ty.Width() == 16 {
			if sym, ok := g.globalU16LoadSym[inst.Src[0]]; ok && dst == "HL" {
				g.emitf("    LD HL, (%s)    ; u16 direct load (20T, no A clobber)", sanitizeIdent(sym))
				g.invalidate("HL")
				break
			}
		}
		ptr := g.loc(inst.Src[0])
		w := inst.Ty.Width()
		// If the POINTER value itself is spilled to a memory slot ($Fxxx), reload it
		// into HL first. Z80 supports LD HL,(nn) for this (3 bytes, 16T).
		// After this, ptr=="HL" and the rest of the OpLoad path works unchanged.
		if strings.HasPrefix(ptr, "$") {
			g.emitf("    LD HL, (%s)   ; reload spilled ptr", ptr)
			g.invalidate("HL")
			ptr = "HL"
		}
		if w == 24 {
			// 24-bit load (3 bytes little-endian) into DWord shadow pair.
			// Shadow H' (high byte of hi16) is always zero for u24 semantics.
			if isIXY(ptr) {
				g.emitf("    LD %s, %s     ; byte0 lo_lo", lowByte(dst), ptrIndirect(ptr, 0))
				g.emitf("    LD %s, %s     ; byte1 lo_hi", highByte(dst), ptrIndirect(ptr, 1))
				g.emit("    EXX")
				g.emitf("    LD %s, %s     ; byte2 hi_lo (shadow)", lowByte(dst), ptrIndirect(ptr, 2))
				g.emitf("    LD %s, 0        ; hi_hi always 0 for u24", highByte(dst))
				g.emit("    EXX")
			} else {
				g.emitf("    LD %s, (%s)     ; byte0 lo_lo", lowByte(dst), ptr)
				g.emitf("    INC %s", ptr)
				g.emitf("    LD %s, (%s)     ; byte1 lo_hi", highByte(dst), ptr)
				g.emitf("    INC %s", ptr)
				g.emit("    EXX")
				g.emitf("    LD %s, (%s)     ; byte2 hi8 (shadow lo)", lowByte(dst), ptr)
				g.emitf("    LD %s, 0        ; hi_hi always 0 for u24", highByte(dst))
				g.emit("    EXX")
				g.emitf("    DEC %s", ptr)
				g.emitf("    DEC %s", ptr)
			}
		} else if w == 32 {
			// 32-bit load via ptr (must not be same pair as dst DWord).
			if isIXY(ptr) {
				g.emitf("    LD %s, %s     ; byte0 lo_lo", lowByte(dst), ptrIndirect(ptr, 0))
				g.emitf("    LD %s, %s     ; byte1 lo_hi", highByte(dst), ptrIndirect(ptr, 1))
				g.emit("    EXX")
				g.emitf("    LD %s, %s     ; byte2 hi_lo (shadow)", lowByte(dst), ptrIndirect(ptr, 2))
				g.emitf("    LD %s, %s     ; byte3 hi_hi (shadow)", highByte(dst), ptrIndirect(ptr, 3))
				g.emit("    EXX")
			} else {
				g.emitf("    LD %s, (%s)     ; byte0 lo_lo", lowByte(dst), ptr)
				g.emitf("    INC %s", ptr)
				g.emitf("    LD %s, (%s)     ; byte1 lo_hi", highByte(dst), ptr)
				g.emitf("    INC %s", ptr)
				g.emit("    EXX")
				g.emitf("    LD %s, (%s)     ; byte2 hi_lo (shadow)", lowByte(dst), ptr)
				g.emitf("    INC %s", ptr)
				g.emitf("    LD %s, (%s)     ; byte3 hi_hi (shadow)", highByte(dst), ptr)
				g.emit("    EXX")
				g.emitf("    DEC %s", ptr)
				g.emitf("    DEC %s", ptr)
				g.emitf("    DEC %s", ptr)
			}
		} else if w <= 8 {
			// Z80 restriction: only LD A,(BC) and LD A,(DE) exist for BC/DE indirect.
			// Any other destination register must load through A first.
			if (ptr == "BC" || ptr == "DE") && dst != "A" {
				g.emitf("    LD A, %s", ptrIndirect(ptr, 0))
				g.invalidate("A")
				g.emitMov(dst, "A", 8)
			} else {
				g.emitf("    LD %s, %s", dst, ptrIndirect(ptr, 0))
			}
		} else if isIXY(ptr) {
			// 16-bit load via IX/IY: use displacement addressing — avoids INC/DEC IX.
			// LD lo, (IX+0) ; LD hi, (IX+1)  — 2×19T = 38T
			g.emitf("    LD %s, %s     ; lo", lowByte(dst), ptrIndirect(ptr, 0))
			g.emitf("    LD %s, %s     ; hi", highByte(dst), ptrIndirect(ptr, 1))
		} else {
			// 16-bit load via HL/DE/BC: INC/DEC trick — little-endian
			if dst == ptr {
				// Self-pointer: LD L,(HL) corrupts the address in HL before INC HL.
				// Use A as scratch: LD A,(HL) / INC HL / LD H,(HL) / LD L,A
				g.emitf("    LD A, (%s)     ; lo", ptr)
				g.emitf("    INC %s", ptr)
				g.emitf("    LD %s, (%s)     ; hi", highByte(dst), ptr)
				g.emitf("    LD %s, A       ; lo", lowByte(dst))
				g.invalidate("A")
			} else {
				g.emitf("    LD %s, (%s)     ; lo", lowByte(dst), ptr)
				g.emitf("    INC %s", ptr)
				g.emitf("    LD %s, (%s)     ; hi", highByte(dst), ptr)
				g.emitf("    DEC %s", ptr)
			}
		}

		// POP HL to restore the base ptr that was saved by OpPtrAdd (scanPtrAddBase).
		// The ptr_add emitted PUSH HL before ADD HL,rr; we restore it here, after the
		// load that consumed the ptr_add result.  This puts the original pointer back
		// in HL so the back-edge parallel copy can read it correctly.
		if g.ptrAddPushHL == inst.Src[0] {
			g.emit("    POP HL         ; restore base ptr (saved by ptr_add)")
			g.ptrAddPushHL = NoReg
			g.invalidate("HL")
		}

	case OpStore:
		addrReg := inst.Src[0]
		if info, ok := g.globalFieldStore[addrReg]; ok && inst.Ty.Width() == 8 {
			if info.hlChain {
				// HL-chain: consecutive field stores share one LD HL,sym base load.
				//   head:  LD HL, sym   ; 10T
				//   each:  LD (HL), r   ; 7T  (r already in correct reg)
				//          INC HL       ; 6T  (omitted for last)
				if info.hlHead {
					g.emitf("    LD HL, %s", sanitizeIdent(info.sym))
				}
				if cv, ok := g.constVals[inst.Src[1]]; ok {
					g.emitf("    LD (HL), %d", cv)
				} else {
					val := g.loc(inst.Src[1])
					g.emitf("    LD (HL), %s", val)
				}
				if !info.hlLast {
					g.emitf("    INC HL")
				}
			} else {
				// Global struct field direct-addressing fast path.
				lbl := globalFieldLabel(info.sym, info.offset, info.fieldName)
				if cv, ok := g.constVals[inst.Src[1]]; ok {
					// Constant store: LD HL, sym; LD (HL), imm — 10T+10T = 20T, no A clobber.
					// Avoids LD A, imm (4T) + LD (sym), A (13T) which would destroy A (= first param).
					g.emitf("    LD HL, %s", lbl)
					g.emitf("    LD (HL), %d", cv)
					g.invalidate("HL")
				} else {
					//   LD A, val           ; 4T (omitted when val is already A)
					//   LD (sym__field), A  ; 13T
					val := g.loc(inst.Src[1])
					if val != "A" {
						g.emitLDA(val)
					}
					g.emitf("    LD (%s), A", lbl)
				}
			}
			break
		}
		// u16 direct-address store: LD (sym), HL — 16T, no A clobber.
		// Fires when the address register traces back to OpAddrOf(global) and the
		// value is allocated to HL.  Avoids the byte-by-byte DE path that clobbers A.
		if inst.Ty.Width() == 16 {
			if sym, ok := g.globalU16StoreSym[inst.Src[0]]; ok {
				if g.loc(inst.Src[1]) == "HL" {
					g.emitf("    LD (%s), HL    ; u16 direct store (16T, no A clobber)", sanitizeIdent(sym))
					break
				}
			}
		}
		ptr := g.loc(inst.Src[0])
		val := g.loc(inst.Src[1])
		w := inst.Ty.Width()
		// If ptr is spilled to a memory slot ($Fxxx), reload it into HL first.
		if strings.HasPrefix(ptr, "$") {
			g.emitf("    LD HL, (%s)   ; reload spilled ptr", ptr)
			g.invalidate("HL")
			ptr = "HL"
		}
		if w == 24 {
			// 24-bit store: write 3 bytes little-endian.
			if isIXY(ptr) {
				g.emitf("    LD %s, %s     ; byte0 lo_lo", ptrIndirect(ptr, 0), lowByte(val))
				g.emitf("    LD %s, %s     ; byte1 lo_hi", ptrIndirect(ptr, 1), highByte(val))
				g.emit("    EXX")
				g.emitf("    LD %s, %s     ; byte2 hi8 (shadow lo)", ptrIndirect(ptr, 2), lowByte(val))
				g.emit("    EXX")
			} else {
				g.emitf("    LD (%s), %s     ; byte0 lo_lo", ptr, lowByte(val))
				g.emitf("    INC %s", ptr)
				g.emitf("    LD (%s), %s     ; byte1 lo_hi", ptr, highByte(val))
				g.emitf("    INC %s", ptr)
				g.emit("    EXX")
				g.emitf("    LD (%s), %s     ; byte2 hi8 (shadow lo)", ptr, lowByte(val))
				g.emit("    EXX")
				g.emitf("    DEC %s", ptr)
				g.emitf("    DEC %s", ptr)
			}
		} else if w == 32 {
			// 32-bit store: write 4 bytes little-endian.
			if isIXY(ptr) {
				// Via IX/IY displacement: 4 × LD (IX+d),r = 4×19T = 76T.
				g.emitf("    LD %s, %s     ; byte0 lo_lo", ptrIndirect(ptr, 0), lowByte(val))
				g.emitf("    LD %s, %s     ; byte1 lo_hi", ptrIndirect(ptr, 1), highByte(val))
				g.emit("    EXX")
				g.emitf("    LD %s, %s     ; byte2 hi_lo (shadow)", ptrIndirect(ptr, 2), lowByte(val))
				g.emitf("    LD %s, %s     ; byte3 hi_hi (shadow)", ptrIndirect(ptr, 3), highByte(val))
				g.emit("    EXX")
			} else {
				// Via ptr INC trick (HL/DE/BC): ptr is advanced then restored.
				g.emitf("    LD (%s), %s     ; byte0 lo_lo", ptr, lowByte(val))
				g.emitf("    INC %s", ptr)
				g.emitf("    LD (%s), %s     ; byte1 lo_hi", ptr, highByte(val))
				g.emitf("    INC %s", ptr)
				g.emit("    EXX")
				g.emitf("    LD (%s), %s     ; byte2 hi_lo (shadow)", ptr, lowByte(val))
				g.emitf("    INC %s", ptr)
				g.emitf("    LD (%s), %s     ; byte3 hi_hi (shadow)", ptr, highByte(val))
				g.emit("    EXX")
				g.emitf("    DEC %s", ptr)
				g.emitf("    DEC %s", ptr)
				g.emitf("    DEC %s", ptr)
			}
		} else if w <= 8 {
			if cv, ok := g.constVals[inst.Src[1]]; ok {
				// LD (HL),n = 10T/2B  or  LD (IX+d),n = 19T/4B
				// Cheaper than: LD r,n (7T) + LD (HL),r (7T) = 14T/3B
				g.emitf("    LD %s, %d", ptrIndirect(ptr, 0), cv)
			} else {
				g.emitf("    LD %s, %s", ptrIndirect(ptr, 0), val)
			}
		} else if isIXY(ptr) {
			// 16-bit store via IX/IY: use displacement addressing — avoids INC/DEC IX.
			// LD (IX+0), lo ; LD (IX+1), hi  — 2×19T = 38T
			g.emitf("    LD %s, %s     ; lo", ptrIndirect(ptr, 0), lowByte(val))
			if !isPairReg(val) {
				g.emitf("    LD %s, 0     ; hi (zero-extend u8→u16)", ptrIndirect(ptr, 1))
			} else {
				g.emitf("    LD %s, %s     ; hi", ptrIndirect(ptr, 1), highByte(val))
			}
		} else if ptr == "HL" {
			// LD (HL), r is valid for any r — use INC/DEC trick.
			g.emitf("    LD (%s), %s     ; lo", ptr, lowByte(val))
			g.emitf("    INC %s", ptr)
			if !isPairReg(val) {
				g.emitf("    LD (%s), 0     ; hi (zero-extend u8→u16)", ptr)
			} else {
				g.emitf("    LD (%s), %s     ; hi", ptr, highByte(val))
			}
			g.emitf("    DEC %s", ptr)
		} else {
			// DE/BC: only LD (DE),A / LD (BC),A are valid — route both bytes through A.
			lo := lowByte(val)
			if lo != "A" {
				g.emitf("    LD A, %s", lo)
				g.invalidate("A")
			}
			g.emitf("    LD (%s), A     ; lo", ptr)
			g.emitf("    INC %s", ptr)
			if !isPairReg(val) {
				g.emitf("    XOR A          ; hi = 0 (zero-extend u8→u16)")
				g.invalidate("A")
			} else {
				hi := highByte(val)
				if hi != "A" {
					g.emitf("    LD A, %s", hi)
					g.invalidate("A")
				}
			}
			g.emitf("    LD (%s), A     ; hi", ptr)
			g.emitf("    DEC %s", ptr)
		}

	case OpCall, OpCallIndirect:
		g.lastFlagsLhs = ""
		g.lastFlagsRhs = ""
		g.genCall(inst)

	case OpAddrOf:
		g.emitf("    LD %s, %s", dst, sanitizeIdent(inst.Sym))

	case OpPtrAdd:
		// Runtime pointer advance: dst = base_ptr + offset_u16.
		// Z80 ONLY has ADD HL, rr — there is no ADD DE,rr or ADD BC,rr.
		// Strategy: get base into HL, offset into DE (or BC), emit ADD HL,rr,
		// then move result from HL to dst if dst != HL.
		//
		// When the base is in HL and is live after this instruction (loop body
		// pattern: ptr survives to the next iteration), scanPtrAddBase sets
		// g.ptrAddPushHL = inst.Dst.  We emit PUSH HL before the ADD to save
		// the base; the subsequent OpLoad emits POP HL to restore it.
		g.lastFlagsLhs = ""
		g.lastFlagsRhs = ""
		base := g.loc(inst.Src[0])
		off := g.loc(inst.Src[1])

		// PUSH HL to preserve the base ptr before the ADD clobbers it.
		if g.ptrAddPushHL == inst.Dst {
			g.emit("    PUSH HL") // base is in HL; save it for POP HL after load
		}

		// Determine the offset pair: must be a 16-bit pair ≠ HL.
		// Choose DE; fall back to BC if DE is the base (moving base to HL would
		// clobber DE, so the offset must already be safe there) or same as dst.
		offPair := "DE"
		if base == "DE" || off == "HL" {
			offPair = "BC"
		}

		// Place offset into offPair BEFORE moving the base (avoids clobbering
		// the offset when base and off share a register like DE).
		if off != offPair {
			if len(off) == 1 { // 8-bit: zero-extend into pair
				g.emitf("    LD %s, 0", offPair)
				g.emitf("    LD %s, %s", lowByte(offPair), off)
			} else {
				g.emitMov(offPair, off, 16)
			}
		}

		// Get base into HL.
		if base != "HL" {
			g.emitMov("HL", base, 16)
		}

		// ADD HL, offPair — the only valid 16-bit add on Z80.
		g.emitf("    ADD HL, %s", offPair)

		// When the base was PUSHed to save it, keep the result in HL and
		// override the dst's physical location so the subsequent load uses
		// LD r,(HL) directly — avoiding the LD D,H;LD E,L byte-copy that
		// would force the load through A (LD A,(DE)) and clobber the accumulator.
		if g.ptrAddPushHL == inst.Dst {
			if dst != "HL" {
				g.physOverride[inst.Dst] = "HL"
			}
		} else {
			// Move result from HL to dst if needed.
			if dst != "HL" {
				g.emitMov(dst, "HL", 16)
				g.invalidate("HL")
			}
		}
		g.invalidate(dst)

	case OpField, OpPtrBump:
		// Advance pointer by compile-time byte offset.
		// OpField: struct field access; OpPtrBump: iterator advance.
		// SoA256 special strides: -1 → INC L (element advance), 256 → INC H (field switch).
		// INC and ADD clobber flags.
		g.lastFlagsLhs = ""
		g.lastFlagsRhs = ""
		src := g.loc(inst.Src[0])
		offset := inst.Imm
		if dst != src {
			g.emitMov(dst, src, 16) // copy base ptr
		}
		switch {
		case offset == 0:
			// nothing — dst already at target
		case offset == -1:
			// SoA256: INC L — advance element index (H=column, L=index)
			g.emitf("    INC %s", lowByte(dst))
		case offset == 256:
			// SoA256: INC H — switch to next field column (H=column, L=index)
			g.emitf("    INC %s", highByte(dst))
		case offset <= 3:
			for range offset {
				g.emitf("    INC %s", dst)
			}
		default:
			// LD BC, offset; ADD HL, BC  (or equivalent pair for dst)
			tmp := "BC"
			if dst == "BC" {
				tmp = "DE"
			}
			g.emitf("    LD %s, %d", tmp, offset)
			g.emitf("    ADD %s, %s", dst, tmp)
		}
		g.invalidate(dst)

	case OpAlloca:
		// Reserve bytes on stack; dst = current SP.
		// Z80 has no direct "LD rp, SP" (only the reverse LD SP,rp is valid).
		// Use: LD HL,0 / ADD HL,SP (→ HL=SP), then copy to dst if needed.
		n := inst.Imm
		for range n {
			g.emit("    DEC SP")
		}
		switch dst {
		case "HL":
			g.emit("    LD HL, 0")
			g.emit("    ADD HL, SP")
		case "DE":
			g.emit("    LD HL, 0")
			g.emit("    ADD HL, SP")
			g.emit("    EX DE, HL")
		case "BC":
			g.emit("    LD HL, 0")
			g.emit("    ADD HL, SP")
			g.emit("    LD B, H")
			g.emit("    LD C, L")
		default:
			// Fallback for any other pair name — assume HL is safe here.
			g.emit("    LD HL, 0")
			g.emit("    ADD HL, SP")
			if dst != "HL" {
				g.emitf("    ; WARN: alloca dst=%s not handled, using HL", dst)
			}
		}

	case OpPatchSlot:
		// Mutable immediate: emit initial value; the byte(s) after LD are patchable.
		w := inst.Ty.Width()
		if w <= 8 {
			g.emitf("    LD %s, %d          ; [patch_slot init=%d]", dst, inst.Imm, inst.Imm)
		} else {
			// 16-bit @smc slot (LD HL, imm16): emit EQU pointing at the imm16 bytes.
			g.emitf("    LD %s, %d          ; [patch_slot init=%d]", dst, inst.Imm, inst.Imm)
		}
		// Named slot (@smc parameter): record EQU label and register patcher.
		if inst.Sym != "" {
			eqLabel := inst.Sym + "$imm"
			g.sb.WriteString(eqLabel + "  EQU $-" + fmt.Sprintf("%d", w/8) + "\n")
			g.smcPatchers = append(g.smcPatchers, smcPatcherInfo{sym: inst.Sym, eqLabel: eqLabel})
		}

	case OpLoadPatched:
		// After patching, the slot register already holds the new value.
		// Emit a move; the codegen may elide this if dst == slot.
		slot := g.loc(inst.Src[0])
		if dst != slot {
			g.emitMov(dst, slot, inst.Ty.Width())
		}

	case OpPatch:
		// SMC patch: at runtime the code rewrites the immediate in OpPatchSlot.
		// In the pure-assembler path we emit a self-modifying write sequence.
		// slot = inst.Src[0], newVal = inst.Src[1]
		slotReg := g.loc(inst.Src[0])
		newVal := g.loc(inst.Src[1])
		g.comment(fmt.Sprintf("patch %s ← %s  (SMC: rewrite immediate in stream)", slotReg, newVal))
		// The patch_slot instruction is always LD r, n (2 bytes).
		// At runtime: caller computes address of the immediate byte and writes newVal.
		// We emit a placeholder comment; actual SMC requires knowing the patch address.
		// The Z80 backend will resolve this in a second pass.
		g.emitf("    ; TODO: LD (patch_addr_%s), %s", slotReg, newVal)

	case OpPush:
		src := g.loc(inst.Src[0])
		// PUSH requires a 16-bit pair; pad single registers to their pair.
		pair := toPair(src)
		g.emitf("    PUSH %s", pair)
		g.invalidate(src)

	case OpPop:
		pair := toPair(dst)
		g.emitf("    POP %s", pair)
		g.invalidate(pair)

	case OpAsm:
		// Inline asm may emit any instruction — conservatively clobber flags.
		g.lastFlagsLhs = ""
		g.lastFlagsRhs = ""
		if inst.Asm != nil {
			g.emitf("    %s", inst.Asm.Template)
		}

	default:
		g.comment(fmt.Sprintf("TODO: %s", inst.Op))
	}
}

// ── Binary operations ─────────────────────────────────────────────────────────

func (g *z80cg) genBinOp(mnem string, inst *Inst) {
	dst := g.loc(inst.Dst)
	lhs := g.loc(inst.Src[0])
	rhs := g.loc(inst.Src[1])
	w := inst.Ty.Width()

	if w >= 24 {
		g.genBinOp32(mnem, dst, lhs, rhs)
		return
	}

	if w <= 8 {
		// Special case: boolean OR with a ClassFlag operand — Z80 cannot LD A, F
		// or OR F.  Materialize the flag condition as 0/1 via a conditional skip:
		//   (ensure A holds the non-flag operand)
		//   JR Ncc, skip    ; if condition false, skip setting bit 0
		//   OR 1            ; A |= 1 (condition true)
		// skip:
		// Also treat a source as a flag if it's the pending carry-flag result
		// (g.loc() may return "A" because PBQP assigned it there, but the
		// actual value is still live in the carry flag via pendingFlagReg).
		isPendingFlag0 := len(inst.Src) > 0 && inst.Src[0] == g.pendingFlagReg
		isPendingFlag1 := len(inst.Src) > 1 && inst.Src[1] == g.pendingFlagReg
		if mnem == "OR" && (lhs == "F" || rhs == "F" || isPendingFlag0 || isPendingFlag1) {
			var flagSrc Reg
			var otherLoc string
			if lhs == "F" || isPendingFlag0 {
				flagSrc = inst.Src[0]
				otherLoc = rhs
			} else {
				flagSrc = inst.Src[1]
				otherLoc = lhs
			}
			// Consume the pending flag tracking for flagSrc.
			if flagSrc == g.pendingFlagReg {
				g.pendingFlagReg = NoReg
			}
			if otherLoc != "A" && !g.holdsValue("A", otherLoc) {
				g.emitLDA(otherLoc)
			}
			g.invalidate("A")
			cc := g.condCode(g.fn, flagSrc)
			skipLbl := fmt.Sprintf(".%s_orf_%d_sk", sanitizeIdent(g.fn.Name), int(inst.Dst))
			g.emitf("    JR %s, %s", invertCC(cc), skipLbl)
			g.emit("    OR 1")
			g.emitf("%s:", skipLbl)
			if dst != "A" {
				g.emitf("    LD %s, A", dst)
				g.setCopy(dst, "A")
			}
			// Result is in A (or dst). Track it as a pending acc value in case
			// a subsequent genCmp overwrites A with "LD A, imm".
			if dst == "A" {
				g.pendingAccReg = inst.Dst
			}
			return
		}

		// If there is a pending ClassAcc value in A that is still live after this
		// instruction, save it to a scratch register before we overwrite A.
		// This fires when two successive 8-bit ALU ops both need A: the first
		// result (r33=acc) must survive while the second (r35=i+1) runs.
		// Skip when the peephole below will use INC/DEC (does not touch A).
		willUseINCDEC := (mnem == "ADD" || mnem == "SUB") && lhs == dst
		if !willUseINCDEC {
			g.materializePendingAcc(inst)
		}

		// Peephole: ADD/SUB dst, N where dst == lhs and N ≤ 3 → INC/DEC dst × N.
		// N=1: 1B/4T vs 4B/15T; N=2: 2B/8T vs 4B/15T; N=3: 3B/12T vs 4B/15T.
		// N=4 would be 16T vs 15T — worse in T-states, skip and fall through to ALU.
		if mnem == "ADD" && lhs == dst {
			if cv, ok := g.constVals[inst.Src[1]]; ok && cv >= 1 && cv <= 3 {
				for range cv {
					g.emitf("    INC %s", dst)
				}
				g.invalidate(dst)
				return
			}
		}
		if mnem == "SUB" && lhs == dst {
			if cv, ok := g.constVals[inst.Src[1]]; ok && cv >= 1 && cv <= 3 {
				for range cv {
					g.emitf("    DEC %s", dst)
				}
				g.invalidate(dst)
				return
			}
		}
		// 8-bit: accumulator must hold lhs.  Emit LD A,lhs if needed.
		//
		// Special case: rhs is already A and lhs is elsewhere.
		// Loading lhs into A would destroy the rhs value.
		//   ADD: commutative → just ADD A, lhs.
		//   SUB: A = lhs - A → NEG first (A = -A), then ADD A, lhs.
		if rhs == "A" && lhs != "A" {
			g.invalidate("A") // A about to hold a new result
			switch mnem {
			case "ADD":
				g.emitf("    ADD A, %s", lhs)
			case "SUB":
				g.emit("    NEG")
				g.emitf("    ADD A, %s", lhs)
			default:
				g.comment(fmt.Sprintf("TODO: 8-bit %s %s, A → %s with A as rhs", mnem, lhs, dst))
				g.emitf("    LD A, %s", lhs)
				g.emit8ALU(mnem, rhs)
			}
			if dst != "A" {
				g.emitf("    LD %s, A", dst)
				g.setCopy(dst, "A")
			} else {
				g.pendingAccReg = inst.Dst
			}
			return
		}
		// Coalescing: if A already holds lhs or (commutative) rhs, skip LD A, reg.
		isCommutative := mnem == "ADD" || mnem == "AND" || mnem == "OR" || mnem == "XOR"
		if g.holdsValue("A", lhs) {
			// A == lhs already — skip LD A, lhs.
			g.invalidate("A")
			g.emit8ALU(mnem, rhs)
			if dst != "A" {
				g.emitf("    LD %s, A", dst)
				g.setCopy(dst, "A")
			} else {
				g.pendingAccReg = inst.Dst
			}
			return
		}
		if isCommutative && g.holdsValue("A", rhs) {
			// A == rhs, commutative swap: emit OP A, lhs instead.
			g.invalidate("A")
			g.emit8ALU(mnem, lhs)
			if dst != "A" {
				g.emitf("    LD %s, A", dst)
				g.setCopy(dst, "A")
			} else {
				g.pendingAccReg = inst.Dst
			}
			return
		}

		// Immediate peephole: AND/OR/XOR/ADD/SUB n — no register needed for rhs.
		if cv, ok := g.constVals[inst.Src[1]]; ok {
			if lhs != "A" {
				g.emitLDA(lhs)
			}
			switch mnem {
			case "AND", "OR", "XOR", "SUB":
				g.emitf("    %s %d", mnem, cv)
			case "ADD":
				g.emitf("    ADD A, %d", cv)
			default:
				g.emit8ALU(mnem, rhs)
			}
			g.invalidate("A") // ALU result is a new value — break old lhs alias
			if dst != "A" {
				g.emitf("    LD %s, A", dst)
				g.setCopy(dst, "A")
			} else {
				g.pendingAccReg = inst.Dst
			}
			return
		}
		if lhs != "A" {
			g.emitLDA(lhs)
		}
		g.emit8ALU(mnem, rhs)
		g.invalidate("A") // ALU result is a new value — break old lhs alias
		if dst != "A" {
			g.emitf("    LD %s, A", dst)
			g.setCopy(dst, "A")
		} else {
			g.pendingAccReg = inst.Dst
		}
	} else {
		// 16-bit peephole: INC/DEC rr when adding/subtracting 1 in-place.
		if lhs == dst {
			if cv, ok := g.constVals[inst.Src[1]]; ok {
				if mnem == "ADD" && cv == 1 {
					g.emitf("    INC %s", dst)
					g.invalidate(dst) // pair + its bytes all change
					return
				}
				if mnem == "SUB" && cv == 1 {
					g.emitf("    DEC %s", dst)
					g.invalidate(dst)
					return
				}
			}
		}
		// 16-bit ADD: ADD HL,rr  (Z80 only has ADD HL,rr natively)
		// SUB/AND/OR/XOR on 16-bit require workarounds; emit comment for now.
		switch mnem {
		case "ADD":
			// Z80 only has ADD HL, rr.  If dst is not HL we must route
			// through HL.  The common case is dst=DE, which can be handled
			// cheaply with EX DE,HL:
			//   EX DE, HL          ; HL ← lhs (was in DE), DE ← old HL
			//   ADD HL, <rhs'>     ; rhs' adjusted for any EX swap
			//   EX DE, HL          ; DE ← result, HL ← restored old value
			if dst != "HL" {
				// After EX DE,HL: the register formerly in DE is now in HL,
				// and what was in HL is now in DE.
				adjustedRhs := rhs
				if lhs == "DE" && dst == "DE" {
					g.emit("    EX DE, HL")
					if rhs == "HL" {
						adjustedRhs = "DE" // what was HL is now in DE after EX
					}
					g.emitf("    ADD HL, %s", adjustedRhs)
					g.emit("    EX DE, HL")
					g.invalidate("HL")
					g.invalidate("DE")
					break
				}
				// General fallback: move lhs to HL, add rhs, move result to dst.
				// Track rhs renaming if lhs is moved from HL/DE.
				if rhs == "HL" && lhs == "DE" {
					adjustedRhs = "DE" // lhs/dst swap via EX
				}
				g.emitMov("HL", lhs, w)
				g.emitf("    ADD HL, %s", adjustedRhs)
				g.emitMov(dst, "HL", w)
				g.invalidate(dst)
				break
			}
			// Standard path: dst == HL.
			if lhs != dst {
				g.emitMov(dst, lhs, w)
			}
			g.emitf("    ADD %s, %s", dst, rhs)
			g.invalidate(dst)
		case "SUB":
			// Z80 only has SBC HL, rr for 16-bit subtraction.
			// When dst != "HL" we must route through HL; the only legal instruction is
			// SBC HL, rr, so the general strategy is:
			//   EX DE,HL  (put lhs in HL, save rhs in DE — only when both are DE/HL)
			//   OR A
			//   SBC HL, rhs'
			//   EX DE,HL  (restore HL=rhs, put result in DE=dst)
			if dst != "HL" && lhs == dst && rhs == "HL" && dst == "DE" {
				// dst=DE, lhs=DE (0 or anything), rhs=HL.
				// EX DE,HL swaps: HL=lhs, DE=rhs.  SBC HL,DE = lhs-rhs.
				// Second EX DE,HL: DE=result, HL=rhs restored.
				g.emit("    EX DE, HL")
				g.emit("    OR A")
				g.emit("    SBC HL, DE")
				g.emit("    EX DE, HL")
				g.invalidate("HL")
				g.invalidate("DE")
				return
			}
			if lhs != dst {
				// When lhs and dst are the HL/DE pair AND the rhs is the other member,
				// use EX DE,HL (a true swap, 4T) to move lhs→dst while simultaneously
				// placing the old dst contents into lhs's old location.
				// This keeps rhs accessible in the swapped location.
				// Note: emitMov(HL,DE) does byte-by-byte (LD H,D; LD L,E) — it preserves
				// DE but does NOT produce the swap that the rhs update below relies on.
				if (dst == "HL" && lhs == "DE") || (dst == "DE" && lhs == "HL") {
					g.emit("    EX DE, HL")
					// After EX DE,HL: whatever was in HL is now in DE, and vice versa.
					switch rhs {
					case "HL":
						rhs = "DE"
					case "DE":
						rhs = "HL"
					}
				} else {
					g.emitMov(dst, lhs, w)
				}
			}
			g.emit("    OR A") // clear carry (1b/4T; SCF+CCF would be 2b/8T)
			g.emitf("    SBC %s, %s", dst, rhs)
			g.invalidate(dst)
		case "OR", "AND", "XOR":
			// Z80 has no 16-bit OR/AND/XOR directly; operate byte-by-byte.
			// Strategy: load each byte pair through A.
			// If lhs != dst, move lhs into dst first.
			if lhs != dst {
				g.emitMov(dst, lhs, w)
			}
			hi := highByte(dst)
			lo := lowByte(dst)
			hi_rhs := highByte(rhs)
			lo_rhs := lowByte(rhs)
			// High byte: A = dst_hi OP rhs_hi → dst_hi
			g.emitf("    LD A, %s", hi)
			g.emitf("    %s %s", mnem, hi_rhs)
			g.emitf("    LD %s, A", hi)
			// Low byte: A = dst_lo OP rhs_lo → dst_lo
			g.emitf("    LD A, %s", lo)
			g.emitf("    %s %s", mnem, lo_rhs)
			g.emitf("    LD %s, A", lo)
			g.invalidate("A")
			g.invalidate(dst)
		default:
			g.comment(fmt.Sprintf("TODO: 16-bit %s %s, %s → %s", mnem, lhs, rhs, dst))
		}
	}
}

// genBinOp32 emits 32-bit ADD or SUB using the Z80 EXX / shadow-pair technique.
//
// The 32-bit value is split across main and shadow register banks:
//
//	LocDWord{"HL"}: main HL = lo16, shadow H'L' = hi16 (via EXX)
//
// For ADD (dst=HL, rhs=DE):
//
//	ADD HL, DE    ; lo ← lo(lhs) + lo(rhs), carry set if overflow  (11T)
//	EXX           ; switch to shadow bank: HL←H'L', DE←D'E'        (4T)
//	ADC HL, DE    ; hi ← hi(lhs) + hi(rhs) + carry                 (15T)
//	EXX           ; switch back to main bank                         (4T)
//
// For SUB (dst=HL, rhs=DE):
//
//	AND A         ; clear carry                                      (4T)
//	SBC HL, DE   ; lo ← lo(lhs) - lo(rhs), borrow in carry         (15T)
//	EXX           ; switch to shadow bank                            (4T)
//	SBC HL, DE   ; hi ← hi(lhs) - hi(rhs) - borrow                 (15T)
//	EXX           ; switch back                                       (4T)
//
// EXX simultaneously swaps BC↔BC', DE↔DE', HL↔HL', so after EXX:
//   - "HL" refers to the old H'L' (hi of lhs/dst)
//   - "DE" refers to the old D'E' (hi of rhs)
//
// This works because both dst and rhs are LocDWord with the same name in both
// banks.  The rhs DWord is restored to its original state after the final EXX.
//
// Limitation: Z80 only provides ADD/ADC/SBC with HL as destination.
// When dst≠HL, we temporarily use HL via emitMov32 (TODO: optimise).
func (g *z80cg) genBinOp32(mnem, dst, lhs, rhs string) {
	// ADD is commutative: if rhs == dst and lhs != dst, swap so we don't clobber rhs.
	if mnem == "ADD" && rhs == dst && lhs != dst {
		lhs, rhs = rhs, lhs
	}

	// SUB when lhs != dst and rhs == dst: moving lhs into dst would clobber rhs.
	// Special case lhs=DE, dst=HL: use EX DE,HL to swap lo/hi words in place,
	// then SBC computes original_lhs - original_rhs in HL.
	if mnem == "SUB" && lhs != dst && rhs == dst {
		if lhs == "DE" && dst == "HL" {
			// EX DE,HL swaps main words; EXX + EX DE,HL + EXX swaps shadow words.
			// After: HL = old DE = lhs_lo, DE = old HL = rhs_lo  (and same in shadow).
			g.emit("    EX DE, HL")
			g.emit("    EXX")
			g.emit("    EX DE, HL")
			g.emit("    EXX")
			g.emit("    AND A")
			g.emit("    SBC HL, DE") // lhs_lo - rhs_lo
			g.emit("    EXX")
			g.emit("    SBC HL, DE") // lhs_hi - rhs_hi - borrow
			g.emit("    EXX")
			return
		}
		// General fallback: save rhs on stack, move lhs to dst, reload rhs to DE.
		// Only HL is supported as dst for now.
		g.comment(fmt.Sprintf("TODO: 32-bit SUB rhs==dst non-EX case: %s - %s → %s", lhs, rhs, dst))
		return
	}

	// Ensure lhs is in dst before the operation.
	if lhs != dst {
		g.emitMov32(dst, lhs)
	}

	switch mnem {
	case "ADD":
		if dst == "HL" {
			// Native 32-bit add: ADD HL,rr / EXX / ADC HL,rr / EXX
			g.emitf("    ADD HL, %s", rhs)
			g.emit("    EXX")
			g.emitf("    ADC HL, %s", rhs)
			g.emit("    EXX")
		} else {
			// Non-HL dst: save HL, use it as scratch, then move result.
			g.comment(fmt.Sprintf("32-bit ADD via HL scratch: %s += %s", dst, rhs))
			g.emit("    PUSH HL")     // save main HL
			g.emit("    EXX")
			g.emit("    PUSH HL")     // save shadow HL
			g.emit("    EXX")
			// Transfer dst to HL.
			g.emitMov32("HL", dst)
			// Now add rhs (rhs was LocDWord; after emitMov32 we haven't clobbered it
			// because emitMov32 uses PUSH/POP+EXX which preserves all non-HL regs).
			g.emitf("    ADD HL, %s", rhs)
			g.emit("    EXX")
			g.emitf("    ADC HL, %s", rhs)
			g.emit("    EXX")
			// Move result from HL to dst, then restore HL.
			g.emitMov32(dst, "HL")
			g.emit("    EXX")
			g.emit("    POP HL")      // restore shadow HL
			g.emit("    EXX")
			g.emit("    POP HL")      // restore main HL
		}
	case "SUB":
		if dst == "HL" {
			g.emit("    AND A")       // clear carry
			g.emitf("    SBC HL, %s", rhs)
			g.emit("    EXX")
			g.emitf("    SBC HL, %s", rhs)
			g.emit("    EXX")
		} else {
			g.comment(fmt.Sprintf("32-bit SUB via HL scratch: %s -= %s", dst, rhs))
			g.emit("    PUSH HL")
			g.emit("    EXX")
			g.emit("    PUSH HL")
			g.emit("    EXX")
			g.emitMov32("HL", dst)
			g.emit("    AND A")
			g.emitf("    SBC HL, %s", rhs)
			g.emit("    EXX")
			g.emitf("    SBC HL, %s", rhs)
			g.emit("    EXX")
			g.emitMov32(dst, "HL")
			g.emit("    EXX")
			g.emit("    POP HL")
			g.emit("    EXX")
			g.emit("    POP HL")
		}
	default:
		g.comment(fmt.Sprintf("TODO: 32-bit %s %s, %s → %s", mnem, lhs, rhs, dst))
	}
}

// emit8ALU emits an 8-bit ALU instruction with A as the implicit destination.
// MZA requires "ADD A, src" (two operands) but "SUB/AND/OR/XOR src" (one operand).
func (g *z80cg) emit8ALU(mnem, src string) {
	switch mnem {
	case "ADD", "ADC":
		g.emitf("    %s A, %s", mnem, src)
	default:
		g.emitf("    %s %s", mnem, src)
	}
}

// ── Shifts ────────────────────────────────────────────────────────────────────

func (g *z80cg) genShift(mnem string, inst *Inst) {
	w := inst.Ty.Width()
	if w >= 24 {
		g.genShift32(mnem, inst)
		return
	}
	dst := g.loc(inst.Dst)
	src := g.loc(inst.Src[0])
	if dst != src {
		g.emitf("    LD %s, %s", dst, src)
		g.setCopy(dst, src)
	}
	// Shift count in Src[1] — Z80 shifts are always by 1 per instruction.
	// For constant counts, emit N copies.  Variable shifts → TODO.
	count := int64(1)
	if cv, ok := g.constVals[inst.Src[1]]; ok && cv > 0 {
		count = cv
	}
	if w == 16 {
		// Z80 has no SLA/SRL/SRA on register pairs.
		// SHL u16: use ADD dst,dst (doubles the value = shift left by 1). 11T each.
		//   Special case: SHL by 8 on a zero-extended u8 → LD H,L / LD L,0. 11T total.
		// SHR u16: SRL H / RR L (logical right shift with carry). 8T+8T=16T each.
		// SAR u16: SRA H / RR L (arithmetic right shift). 8T+8T=16T each.
		hi := highByte(dst)
		lo := lowByte(dst)
		if mnem == "SLA" && count == 8 {
			// Byte-swap optimisation: u8 zero-extended to u16, shift left 8 bits.
			// After ext u8→u16, the u8 value is in the low byte (L/E/C).
			// Result = {value, 0}: move low byte to high, zero low byte.
			g.emitf("    LD %s, %s", hi, lo)
			g.emitf("    LD %s, 0", lo)
		} else {
			for i := int64(0); i < count; i++ {
				switch mnem {
				case "SLA":
					g.emitf("    ADD %s, %s", dst, dst) // valid: ADD HL,HL etc.
				case "SRL":
					g.emitf("    SRL %s", hi)
					g.emitf("    RR  %s", lo)
				case "SRA":
					g.emitf("    SRA %s", hi)
					g.emitf("    RR  %s", lo)
				}
			}
		}
		g.invalidate(dst)
		return
	}
	for i := int64(0); i < count; i++ {
		g.emitf("    %s %s", mnem, dst)
	}
	g.invalidate(dst) // shift modifies dst
}

// genShift32 emits 24/32-bit shifts via the EXX shadow-pair technique.
//
// SHL by 1 (logical left):
//
//	ADD HL, HL    ; lo16 <<= 1, carry = old bit15  (11T)
//	EXX           ; switch to shadow                (4T)
//	ADC HL, HL    ; hi16 <<= 1, carry in from lo   (15T)
//	EXX           ; switch back                      (4T)  = 34T per bit
//
// SHR by 1 (logical right):
//
//	EXX           ; switch to shadow
//	SRL H         ; hi16: H >>= 1 (zero-extend), carry = old bit0  (8T)
//	RR  L         ; hi16: L = carry<<7 | L>>1                      (8T)
//	EXX           ; back to main
//	RR  H         ; lo16: H = carry<<7 | H>>1                      (8T)
//	RR  L         ; lo16: L = carry<<7 | L>>1                      (8T)  = 40T per bit
//
// SAR by 1 (arithmetic right, sign-extend):
//
//	EXX / SRA H / RR L / EXX / RR H / RR L  (same as SHR but SRA preserves sign)
func (g *z80cg) genShift32(mnem string, inst *Inst) {
	dst := g.loc(inst.Dst)
	src := g.loc(inst.Src[0])
	if dst != src {
		g.emitMov32(dst, src)
	}

	count := int64(1)
	if cv, ok := g.constVals[inst.Src[1]]; ok && cv > 0 {
		count = cv
	}

	hi := highByte(dst) // e.g. "H" for dst="HL"
	lo := lowByte(dst)  // e.g. "L"

	switch mnem {
	case "SHL":
		// Left shift: ADD HL,HL / EXX / ADC HL,HL / EXX  (× count)
		for i := int64(0); i < count; i++ {
			g.emitf("    ADD %s, %s", dst, dst)
			g.emit("    EXX")
			g.emitf("    ADC %s, %s", dst, dst)
			g.emit("    EXX")
		}
	case "SHR":
		// Logical right shift: EXX / SRL H / RR L / EXX / RR H / RR L  (× count)
		for i := int64(0); i < count; i++ {
			g.emit("    EXX")
			g.emitf("    SRL %s", hi)
			g.emitf("    RR  %s", lo)
			g.emit("    EXX")
			g.emitf("    RR  %s", hi)
			g.emitf("    RR  %s", lo)
		}
	case "SAR":
		// Arithmetic right shift: sign bit preserved via SRA on high byte.
		for i := int64(0); i < count; i++ {
			g.emit("    EXX")
			g.emitf("    SRA %s", hi)
			g.emitf("    RR  %s", lo)
			g.emit("    EXX")
			g.emitf("    RR  %s", hi)
			g.emitf("    RR  %s", lo)
		}
	default:
		g.comment(fmt.Sprintf("TODO: 32-bit shift %s", mnem))
	}
	g.invalidate(dst)
}

// ── Multiply ──────────────────────────────────────────────────────────────────

// genMul emits 8-bit unsigned multiply via shift-and-add.
// Power-of-2 constants use N×(ADD A,A); small constants use LD tmp,A + adds.
// Variable or large constants fall back to a software-loop comment (TODO).
func (g *z80cg) genMul(inst *Inst) {
	dst := g.loc(inst.Dst)
	lhs := g.loc(inst.Src[0])

	if inst.Ty.Width() >= 24 {
		g.genMul32(inst)
		return
	}
	if inst.Ty.Width() > 8 {
		g.genMul16(inst)
		return
	}

	cv, isConst := g.constVals[inst.Src[1]]

	if isConst {
		switch cv {
		case 0:
			g.emit("    XOR A")
			g.invalidate("A")
			if dst != "A" {
				g.emitf("    LD %s, A", dst)
				g.setCopy(dst, "A")
			}
			return
		case 1:
			if dst != lhs {
				g.emitMov(dst, lhs, 8)
			}
			return
		}
		// Power-of-2: log2(cv) × (ADD A,A).
		if cv > 0 && cv&(cv-1) == 0 {
			shifts := 0
			for n := cv; n > 1; n >>= 1 {
				shifts++
			}
			if !g.holdsValue("A", lhs) {
				g.emitLDA(lhs)
			}
			for i := 0; i < shifts; i++ {
				g.emit("    ADD A, A")
			}
			g.invalidate("A")
			if dst != "A" {
				g.emitf("    LD %s, A", dst)
				g.setCopy(dst, "A")
			}
			return
		}
		// x*3 = x + x*2: LD tmp,A; ADD A,A; ADD A,tmp
		// x*5 = x + x*4: LD tmp,A; ADD A,A; ADD A,A; ADD A,tmp
		// x*6 = x*2 + x*4: LD tmp,A; ADD A,A (tmp=x*2 in tmp); ADD A,A (A=x*4); ADD A,tmp
		// x*9 = x + x*8:   LD tmp,A; 3×ADD A,A; ADD A,tmp
		if cv == 3 || cv == 5 || cv == 6 || cv == 9 {
			if !g.holdsValue("A", lhs) {
				g.emitLDA(lhs)
			}
			// Pick a temp register that isn't A or dst.
			tmp := "C"
			if dst == "C" {
				tmp = "D"
			}
			switch cv {
			case 3: // x + x*2
				g.emitf("    LD %s, A", tmp) // tmp = x
				g.emit("    ADD A, A")        // A  = x*2
				g.emitf("    ADD A, %s", tmp) // A  = x*3
			case 5: // x + x*4
				g.emitf("    LD %s, A", tmp)
				g.emit("    ADD A, A")
				g.emit("    ADD A, A")         // A  = x*4
				g.emitf("    ADD A, %s", tmp) // A  = x*5
			case 6: // x*2 + x*4
				g.emit("    ADD A, A")         // A  = x*2
				g.emitf("    LD %s, A", tmp)  // tmp= x*2
				g.emit("    ADD A, A")         // A  = x*4
				g.emitf("    ADD A, %s", tmp) // A  = x*6
			case 9: // x + x*8
				g.emitf("    LD %s, A", tmp)
				g.emit("    ADD A, A")
				g.emit("    ADD A, A")
				g.emit("    ADD A, A")         // A  = x*8
				g.emitf("    ADD A, %s", tmp) // A  = x*9
			}
			g.invalidate("A")
			if dst != "A" {
				g.emitf("    LD %s, A", dst)
				g.setCopy(dst, "A")
			}
			return
		}
	}

	// Variable or unsupported constant: emit software-loop comment.
	rhs := g.loc(inst.Src[1])
	g.comment(fmt.Sprintf("TODO: general mul %s * %s → %s", lhs, rhs, dst))
}

// genMul16 emits 16-bit multiply.
//
// Constants:
//
//	0:       LD H,0 / LD L,0
//	1:       no-op
//	2^n:     n × ADD HL,HL  (7T per shift)
//	3,5,6,9: PUSH HL / POP BC + shift+add sequence
//
// Variable (software shift-and-add, Russian-peasant LSB-first, 16 iterations):
//
//	BC = multiplicand (lhs)
//	DE = multiplier   (rhs)
//	HL = result = 0
//	A  = 16 (iteration counter — DEC A / JR NZ preserves SRL carry)
//	loop:
//	  SRL D / RR E   → DE >>= 1, old bit0 → carry
//	  JR NC, no_add  → skip if bit was 0
//	  ADD HL, BC     → result += multiplicand (carry from ADD is ignored by next SRL)
//	no_add:
//	  SLA C / RL B   → BC <<= 1 (next power-of-2 multiplicand)
//	  DEC A / JR NZ loop
//
// SRL D is independent of incoming carry, so ADD HL,BC's carry does not corrupt
// the extraction.  Total: ~320T worst case.
func (g *z80cg) genMul16(inst *Inst) {
	dst := g.loc(inst.Dst)
	lhs := g.loc(inst.Src[0])

	cv, isConst := g.constVals[inst.Src[1]]

	// Ensure lhs is in HL (u16 multiply needs HL for ADD HL,rr).
	if lhs != "HL" {
		g.emitf("    LD H, %s", highByte(lhs))
		g.emitf("    LD L, %s", lowByte(lhs))
		g.invalidate("HL")
	}
	_ = dst // result ends up in HL

	if isConst {
		switch cv {
		case 0:
			g.emit("    LD H, 0")
			g.emit("    LD L, 0")
			g.invalidate("HL")
			return
		case 1:
			return
		}
		// Fix A: byte-boundary shift — LD H,L / LD L,0 is cheaper than ADD HL,HL chains.
		// * 256: LD H,L / LD L,0  (8T, 2B)  vs 8×ADD HL,HL (56T, 16B)
		// * 512: LD H,L / LD L,0 / ADD HL,HL (19T) vs 9×ADD HL,HL (63T)
		if cv >= 256 && cv&(cv-1) == 0 {
			g.emit("    LD H, L")
			g.emit("    LD L, 0")
			for n := cv >> 8; n > 1; n >>= 1 {
				g.emit("    ADD HL, HL")
			}
			g.invalidate("HL")
			return
		}
		if cv > 0 && cv&(cv-1) == 0 { // power-of-2: log2(cv) × ADD HL,HL
			for n := cv; n > 1; n >>= 1 {
				g.emit("    ADD HL, HL")
			}
			g.invalidate("HL")
			return
		}
		// Small multiples via PUSH/POP BC save + shift sequences.
		if cv == 3 || cv == 5 || cv == 6 || cv == 9 {
			g.emit("    PUSH HL") // save x → BC
			g.emit("    POP BC")  // BC = x (17T)
			switch cv {
			case 3: // x*2 + x
				g.emit("    ADD HL, HL") // HL = x*2
				g.emit("    ADD HL, BC") // HL = x*3
			case 5: // x*4 + x
				g.emit("    ADD HL, HL")
				g.emit("    ADD HL, HL") // HL = x*4
				g.emit("    ADD HL, BC") // HL = x*5
			case 6: // x*4 + x*2
				g.emit("    ADD HL, HL")  // HL = x*2
				g.emit("    PUSH HL")
				g.emit("    POP BC")       // BC = x*2
				g.emit("    ADD HL, HL")  // HL = x*4
				g.emit("    ADD HL, BC")  // HL = x*6
			case 9: // x*8 + x
				g.emit("    ADD HL, HL")
				g.emit("    ADD HL, HL")
				g.emit("    ADD HL, HL") // HL = x*8
				g.emit("    ADD HL, BC") // HL = x*9
			}
			g.invalidate("HL")
			return
		}
	}

	// Variable or unsupported constant: software shift-and-add loop.
	// Register layout:
	//   BC = multiplicand (lhs, copied from HL)
	//   DE = multiplier   (rhs)
	//   HL = result = 0
	//   A  = iteration counter (16)
	rhs := g.loc(inst.Src[1])
	loopLbl := fmt.Sprintf(".%s_m16_%d_lp", sanitizeIdent(g.fn.Name), int(inst.Dst))
	skipLbl := fmt.Sprintf(".%s_m16_%d_sk", sanitizeIdent(g.fn.Name), int(inst.Dst))
	g.comment(fmt.Sprintf("mul16 %s * %s → HL  (~320T, 16-iter shift-and-add)", lhs, rhs))
	// Save AF and DE: the multiply uses A as a loop counter and clobbers DE by
	// shifting it 16 times.  Any live variable in A, D, or E would be corrupted.
	g.emit("    PUSH AF")             // preserve A (= possible live variable) and F
	g.emit("    PUSH DE")             // preserve D and E across multiply
	// Load multiplier into DE BEFORE overwriting BC with the multiplicand.
	// (rhs may be in C/B/BC which gets clobbered by LD B,H; LD C,L below.)
	if rhs != "DE" {
		if isPairReg(rhs) {
			g.emitf("    LD D, %s", highByte(rhs))
			g.emitf("    LD E, %s", lowByte(rhs))
		} else {
			// 8-bit rhs: zero-extend into DE.
			// Load E first so that rhs="D" reads the old D before it is zeroed.
			g.emitf("    LD E, %s", rhs)
			g.emit("    LD D, 0")
		}
		g.invalidate("DE")
	}
	g.emit("    PUSH BC")              // save BC across multiply
	g.emit("    LD B, H")
	g.emit("    LD C, L")             // BC = multiplicand (lhs)
	g.emit("    LD H, 0")
	g.emit("    LD L, 0")             // HL = result = 0
	g.emit("    LD A, 16")            // A = bit counter
	g.emitf("%s:", loopLbl)
	g.emit("    SRL D")               // DE >>= 1 (logical right shift, bit0 → carry)
	g.emit("    RR E")
	g.emitf("    JRS NC, %s", skipLbl)
	g.emit("    ADD HL, BC")          // result += multiplicand (current bit weight)
	g.emitf("%s:", skipLbl)
	g.emit("    SLA C")               // BC <<= 1 (multiplicand doubles)
	g.emit("    RL B")
	g.emit("    DEC A")               // counter-- (does not affect carry)
	g.emitf("    JRS NZ, %s", loopLbl)
	g.emit("    POP BC")              // restore BC
	g.emit("    POP DE")              // restore old DE (live variables in D/E preserved)
	g.emit("    POP AF")              // restore old A (live variables in A preserved)
	g.invalidate("HL")
	g.invalidate("DE")
	g.invalidate("BC")
}

// genMul32 emits 24/32-bit multiply by a constant via SHL-and-add.
//
// Power-of-2 constants: log2(cv) × SHL32 (ADD HL,HL / EXX / ADC HL,HL / EXX per bit).
// Small constants (3,5,6,9): LD+saves using emitMov32 for the partial product.
// General constants: decompose into Σ 2^k terms (binary method).
// Variable multiplier: TODO (software loop).
func (g *z80cg) genMul32(inst *Inst) {
	dst := g.loc(inst.Dst)
	lhs := g.loc(inst.Src[0])

	// Emit one 32-bit left-shift-by-1 on the register pair p.
	shl1 := func(p string) {
		g.emitf("    ADD %s, %s", p, p)
		g.emit("    EXX")
		g.emitf("    ADC %s, %s", p, p)
		g.emit("    EXX")
	}

	cv, isConst := g.constVals[inst.Src[1]]

	if !isConst {
		rhs := g.loc(inst.Src[1])
		g.comment(fmt.Sprintf("TODO: 32-bit variable mul %s * %s → %s", lhs, rhs, dst))
		return
	}

	// Ensure lhs is in dst before operating.
	if dst != lhs {
		g.emitMov32(dst, lhs)
	}

	switch cv {
	case 0:
		// dst = 0: load zero constant.
		g.emitf("    LD %s, 0", dst)
		g.emit("    EXX")
		g.emitf("    LD %s, 0", dst)
		g.emit("    EXX")
		g.invalidate(dst)
		return
	case 1:
		// dst = lhs — already done by move above.
		return
	}

	// Power-of-2: log2(cv) left shifts.
	if cv > 0 && cv&(cv-1) == 0 {
		shifts := 0
		for n := cv; n > 1; n >>= 1 {
			shifts++
		}
		for i := 0; i < shifts; i++ {
			shl1(dst)
		}
		g.invalidate(dst)
		return
	}

	// Binary decomposition: dst = Σ (dst_orig << k) for each set bit k in cv.
	// Uses a saved copy of the original value to accumulate.
	// Only valid when dst is HL (has ADD/ADC). For others, fall through to TODO.
	if dst == "HL" && cv > 0 {
		// Save original in DE (push to stack if DE is occupied).
		g.emit("    PUSH DE")      // save main DE
		g.emit("    EXX")
		g.emit("    PUSH DE")      // save shadow DE
		g.emit("    EXX")
		// Copy lhs (already in HL/H'L') to DE/D'E'.
		g.emitMov32("DE", "HL")
		// Accumulate: acc = 0, then for each set bit k add (orig << k).
		// Clear HL for accumulation.
		g.emitf("    LD HL, 0")
		g.emit("    EXX")
		g.emitf("    LD HL, 0")
		g.emit("    EXX")
		shift := 0
		for bit := int64(0); bit < 32; bit++ {
			if cv&(1<<bit) != 0 {
				// Shift DE/D'E' to the current bit position (relative to prev shift).
				for i := shift; i < int(bit); i++ {
					// SHL DE by 1: ADD HL,DE / ... — no, we shift DE itself.
					// Use: EXX / SLA E / RL D / EXX / SLA E / RL D
					// Wait, that shifts D'E'. Let's use ADD DE,DE — Z80 has no ADD DE,DE.
					// Instead: shift DE using SLA/RL pattern.
					g.emit("    EXX")
					g.emit("    SLA E")
					g.emit("    RL  D")
					g.emit("    EXX")
					g.emit("    SLA E")
					g.emit("    RL  D")
				}
				shift = int(bit)
				// acc (HL/H'L') += DE/D'E'.
				g.emitf("    ADD HL, DE")
				g.emit("    EXX")
				g.emitf("    ADC HL, DE")
				g.emit("    EXX")
			}
		}
		// Restore DE.
		g.emit("    EXX")
		g.emit("    POP DE")
		g.emit("    EXX")
		g.emit("    POP DE")
		g.invalidate(dst)
		return
	}

	// Fallback for non-HL dst or complex constants.
	g.comment(fmt.Sprintf("TODO: 32-bit mul by %d in %s", cv, dst))
}

// ── Type conversions ──────────────────────────────────────────────────────────

func (g *z80cg) genExt(inst *Inst) {
	dst := g.loc(inst.Dst)
	src := g.loc(inst.Src[0])
	srcW := inst.SrcTy.Width()
	dstW := inst.Ty.Width()

	if srcW == 8 && dstW == 16 {
		// Zero-extend u8 → u16.
		// dst should be a 16-bit reg (HL/DE/BC/IX/IY).
		// Most natural: put source in low byte, zero high byte.
		lo := lowByte(dst)
		hi := highByte(dst)
		if src != lo {
			g.emitf("    LD %s, %s", lo, src)
		}
		g.emitf("    LD %s, 0", hi)
		return
	}
	// Fallback.
	g.comment(fmt.Sprintf("TODO: ext %s→%s %s→%s", inst.SrcTy, inst.Ty, src, dst))
}

func (g *z80cg) genSext(inst *Inst) {
	dst := g.loc(inst.Dst)
	src := g.loc(inst.Src[0])
	srcW := inst.SrcTy.Width()
	dstW := inst.Ty.Width()

	if srcW == 8 && dstW == 16 {
		// Sign-extend u8 → u16 via A.
		lo := lowByte(dst)
		hi := highByte(dst)
		if src != "A" {
			g.emitf("    LD A, %s", src)
		}
		if lo != "A" {
			g.emitf("    LD %s, A", lo)
		}
		// Propagate sign bit into high byte: RLCA; SBC A,A gives 0x00 or 0xFF.
		g.emit("    RLCA")
		g.emit("    SBC A, A")
		if hi != "A" {
			g.emitf("    LD %s, A", hi)
		}
		return
	}
	g.comment(fmt.Sprintf("TODO: sext %s→%s %s→%s", inst.SrcTy, inst.Ty, src, dst))
}

// ── Compare ───────────────────────────────────────────────────────────────────

// flagStillNeeded reports whether pendingFlagReg is used as a source
// in any instruction AFTER upcomingInst in the current block.
func (g *z80cg) flagStillNeeded(upcomingInst *Inst) bool {
	if g.curBlock == nil {
		return false
	}
	seen := false
	for _, inst := range g.curBlock.Insts {
		if inst == upcomingInst {
			seen = true
			continue
		}
		if !seen {
			continue
		}
		for _, s := range inst.Src {
			if s == g.pendingFlagReg {
				return true
			}
		}
	}
	return false
}

// accStillNeeded reports whether pendingAccReg is used as a source
// in any instruction AFTER upcomingInst in the current block, or by
// the block's terminal (e.g. passed as a block arg to a successor).
func (g *z80cg) accStillNeeded(upcomingInst *Inst) bool {
	if g.curBlock == nil {
		return false
	}
	seen := false
	for _, inst := range g.curBlock.Insts {
		if inst == upcomingInst {
			seen = true
			continue
		}
		if !seen {
			continue
		}
		for _, s := range inst.Src {
			if s == g.pendingAccReg {
				return true
			}
		}
	}
	// Also check the block terminal — block params are passed via term args
	// (e.g. TermBrIf passes acc through to the loop body block).
	if g.curBlock.Term != nil {
		for _, r := range g.curBlock.Term.termUses() {
			if r == g.pendingAccReg {
				return true
			}
		}
	}
	return false
}

// pickScratch8 returns an 8-bit scratch register that is not currently
// occupied by any live virtual register at or after upcomingInst.
// Prefers E, H, L (unlikely to hold params) before D, B, C.
// Always excludes "A" and "F".
func (g *z80cg) pickScratch8(upcomingInst *Inst) string {
	// Collect physical locations of all live values from upcomingInst onwards.
	livePhys := map[string]bool{"A": true, "F": true}
	if g.curBlock != nil {
		seen := false
		for _, inst := range g.curBlock.Insts {
			if inst == upcomingInst {
				seen = true
			}
			if !seen {
				continue
			}
			for _, src := range inst.Src {
				if loc := g.loc(src); loc != "" {
					livePhys[loc] = true
				}
			}
		}
	}
	// Also protect any physOverride destinations already in use.
	for _, loc := range g.physOverride {
		livePhys[loc] = true
	}
	for _, r := range []string{"E", "H", "L", "D", "B", "C"} {
		if !livePhys[r] {
			return r
		}
	}
	return "D" // last-resort fallback
}

// materializePendingFlag checks whether the most recent ClassFlag result
// (pendingFlagReg) is still needed after upcomingInst. If so, it emits:
//
//	SBC A, A      ; A = 0xFF if condition-true, 0x00 if condition-false
//	LD  <scratch>, A
//
// where <scratch> is a register that is not currently holding any live value,
// and reroutes pendingFlagReg via physOverride so subsequent genBinOp reads
// it from there rather than from the (now-clobbered) carry flag.
func (g *z80cg) materializePendingFlag(upcomingInst *Inst) {
	if g.pendingFlagReg == NoReg {
		return
	}
	if !g.flagStillNeeded(upcomingInst) {
		g.pendingFlagReg = NoReg
		return
	}
	scratch := g.pickScratch8(upcomingInst)
	// Materialize carry → 0xFF (true) or 0x00 (false) via SBC A, A.
	g.emit("    SBC A, A")
	g.invalidate("A")
	g.emitf("    LD %s, A", scratch)
	g.physOverride[g.pendingFlagReg] = scratch
	g.pendingFlagReg = NoReg
}

// materializePendingAcc checks whether pendingAccReg (a ClassAcc value
// currently in A) is still needed after upcomingInst. If so, it saves A
// to a scratch register that is not currently holding any live value,
// and reroutes pendingAccReg via physOverride so the upcoming "LD A, imm"
// in genCmp does not clobber the live value.
func (g *z80cg) materializePendingAcc(upcomingInst *Inst) {
	if g.pendingAccReg == NoReg {
		return
	}
	if !g.accStillNeeded(upcomingInst) {
		g.pendingAccReg = NoReg
		return
	}
	scratch := g.pickScratch8(upcomingInst)
	g.emitf("    LD %s, A", scratch)
	g.physOverride[g.pendingAccReg] = scratch
	g.pendingAccReg = NoReg
}

func (g *z80cg) genCmp(inst *Inst) {
	// CmpSubCarry / CmpSubCarryNot: carry flag already set by the immediately
	// preceding SUB.  No instruction needed — carry encodes a < b (C) or a >= b (NC).
	if inst.Cond == CmpSubCarry || inst.Cond == CmpSubCarryNot {
		return
	}

	// Before emitting any flag-clobbering comparison instruction:
	// 1. Materialize any live ClassFlag register whose carry would be overwritten.
	// 2. Save any live ClassAcc register whose A value would be overwritten by
	//    the "LD A, imm" used to set up the CP operand.
	// Both are saved to "D" (scratch) via physOverride; the OR-from-flag handler
	// in genBinOp will then read them from "D" instead of from "F"/"A".
	g.materializePendingFlag(inst)
	g.materializePendingAcc(inst)

	lhs := g.loc(inst.Src[0])
	rhs := g.loc(inst.Src[1])

	// 32-bit DWord comparison: must dispatch before isPairReg (DWord locs also
	// have pair names like "HL", so they'd otherwise fall into genCmp16).
	if g.isDWord(inst.Src[0]) || g.isDWord(inst.Src[1]) {
		g.genCmp32(inst)
		return
	}

	// 16-bit comparison: one or both operands are register pairs (HL/DE/BC/…).
	// Z80 only supports SBC HL, rr for 16-bit flag-setting subtraction.
	if isPairReg(lhs) || isPairReg(rhs) {
		g.genCmp16(inst)
		return
	}

	// CmpGt / CmpUgt and CmpLe / CmpUle are not directly expressible as a
	// single Z80 flag after a normal CP (which would need NC+NZ or C+Z).
	// Fix: force-swap the operands.
	//   CmpGt(a,b): a>b ↔ b<a → put b in A, CP a → C flag single-condition ✓
	//   CmpLe(a,b): a≤b ↔ b≥a → put b in A, CP a → NC flag single-condition ✓
	// Exception: rhs==0 is handled by the AND A path below (cmpAndZero mechanism
	// already returns NZ for Gt and Z for Le in condCode, so no swap needed).
	isGtOrLe := inst.Cond == CmpGt || inst.Cond == CmpUgt ||
		inst.Cond == CmpLe || inst.Cond == CmpUle
	if isGtOrLe {
		rhsIsZero := false
		if cv, ok := g.constVals[inst.Src[1]]; ok && cv == 0 {
			rhsIsZero = true
		}
		if !rhsIsZero {
			if lhs != "A" {
				// Force-swap: put rhs in A, emit CP lhs → single condition.
				//   CmpGt(a,b) → b<a → C flag ✓
				//   CmpLe(a,b) → b≥a → NC flag ✓
				if cv, ok := g.constVals[inst.Src[1]]; ok {
					g.emitf("    LD A, %d", cv)
					g.invalidate("A")
				} else if !g.holdsValue("A", rhs) {
					g.emitLDA(rhs)
				}
				g.emitf("    CP %s", lhs)
				g.cmpSwapped[inst.Dst] = true
				g.pendingFlagReg = inst.Dst
				return
			}
			// lhs IS "A": force-swap would clobber the live value in A.
			// Emit normally (A=lhs already, CP rhs); TermBrIf will use two JPs.
			g.cmpNeedsTwo[inst.Dst] = true
			// Fall through to normal CP code (which will find A=lhs and emit CP rhs).
		}
		// rhsIsZero: fall through to AND A path (cmpAndZero handles NZ/Z).
	}

	// Z80 CP instruction: computes A − operand and sets flags.
	// We need A = lhs, then CP rhs.
	//
	// Peephole: if rhs is a known constant, use CP imm8 directly.
	// This avoids an extra register load (e.g. LD C,0 / LD A,B / CP C
	// → LD A,B / CP 0), and the constant no longer needs to be
	// materialised into a register (eliminating a dead store).
	if cv, ok := g.constVals[inst.Src[1]]; ok {
		if !g.holdsValue("A", lhs) {
			g.emitLDA(lhs)
		}
		g.lastFlagsLhs = ""
		g.lastFlagsRhs = ""
		if cv == 0 {
			g.emit("    AND A") // AND A ≡ CP 0 for all flags; 1B/4T vs 2B/7T
			g.cmpAndZero[inst.Dst] = true
		} else {
			g.emitf("    CP %d", cv)
		}
		// CP/AND A does not modify A; aliases remain valid.
		g.pendingFlagReg = inst.Dst
		return
	}

	// Two-address conflict: if rhs is already in A and lhs is elsewhere,
	// loading lhs into A would destroy rhs.
	// Fix: swap operands (emit CP lhs with A=rhs) and mark as swapped.
	// condCode() will invert the CmpCond to compensate.
	if rhs == "A" && lhs != "A" {
		// A already holds rhs. CP lhs computes A−lhs = rhs−lhs.
		// This is the swapped comparison; condCode will invert it.
		// For CmpLt/CmpGe (and unsigned variants), the equality case (A==lhs)
		// is not captured by a single carry flag after the reversal, so we need
		// two jumps (CGT/CLE) in TermBrIf.
		g.lastFlagsLhs = ""
		g.lastFlagsRhs = ""
		g.emitf("    CP %s", lhs)
		g.cmpSwapped[inst.Dst] = true
		swappedCond := inst.Cond.Swap()
		if swappedCond == CmpGt || swappedCond == CmpUgt ||
			swappedCond == CmpLe || swappedCond == CmpUle {
			g.cmpNeedsTwo[inst.Dst] = true
		}
		// CP does not modify A; aliases remain valid.
		g.pendingFlagReg = inst.Dst
		return
	}

	// Sub+Cmp flag fusion: if the immediately preceding instruction was
	// SUB with the same operands, the carry flag is already set correctly.
	//   CmpLt/CmpUlt  → C  (borrow from SUB)
	//   CmpGe/CmpUge  → NC (no borrow from SUB)
	// CRITICAL: check BEFORE loading lhs into A, because if r = Sub(a,b)
	// lives in A and lhs is somewhere else (e.g. B), emitLDA would overwrite
	// r.  The IAR abs_diff pattern depends on this: r must survive to the
	// return path after the comparison.
	subCmpFused := (inst.Cond == CmpLt || inst.Cond == CmpUlt ||
		inst.Cond == CmpGe || inst.Cond == CmpUge) &&
		g.lastFlagsLhs == lhs && g.lastFlagsRhs == rhs
	if subCmpFused {
		// Flags valid from preceding SUB — skip both LD A and CP.
		return
	}

	// Special case: rhs is currently in A but lhs is not.
	// We cannot emit "LD A, lhs; CP A" (overwrites rhs before compare).
	// Instead keep A=rhs and emit "CP lhs" — the comparison is reversed.
	// Record the swap so condCode inverts the condition.  The swapped condition
	// may require two jumps (CmpGt/CmpLe) to handle the equality case.
	if rhs == "A" && !g.holdsValue("A", lhs) {
		g.emitf("    CP %s", lhs)
		g.cmpSwapped[inst.Dst] = true
		swappedCond := inst.Cond.Swap()
		if swappedCond == CmpGt || swappedCond == CmpUgt ||
			swappedCond == CmpLe || swappedCond == CmpUle {
			g.cmpNeedsTwo[inst.Dst] = true
		}
		g.pendingFlagReg = inst.Dst
		return
	}

	// Coalescing: A already holds lhs — skip LD A, lhs.
	if !g.holdsValue("A", lhs) {
		g.emitLDA(lhs)
	}
	g.lastFlagsLhs = ""
	g.lastFlagsRhs = ""
	g.emitf("    CP %s", rhs)
	// CP does not modify A; aliases remain valid.
	g.pendingFlagReg = inst.Dst
}

// ── Calls ─────────────────────────────────────────────────────────────────────

func (g *z80cg) genCall(inst *Inst) {
	clear(g.holdsPhys) // calls clobber all volatile registers
	if inst.Op == OpCallIndirect {
		ptr := g.loc(inst.Src[0])
		g.emitf("    CALL (%s)          ; indirect", ptr)
		return
	}

	// ── Built-in intrinsics (inlined, no CALL emitted) ────────────────────────
	switch inst.Sym {
	case "@mir.io.print.str":
		// Emit inline NUL-terminated string output loop via OUT ($23), A.
		// The string pointer must be in HL (ClassPointer).
		// HL is advanced in-place; A and F are clobbered.
		idx := g.trampIdx
		g.trampIdx++
		g.emitf(".print_str_%d:", idx)
		g.emit("    LD A, (HL)")
		g.emit("    AND A")
		g.emitf("    JR Z, .print_str_done_%d", idx)
		g.emit("    OUT (0x23), A")
		g.emit("    INC HL")
		g.emitf("    JR .print_str_%d", idx)
		g.emitf(".print_str_done_%d:", idx)
		// A, F, HL clobbered — invalidate holdsPhys entries for these.
		g.invalidate("A")
		g.invalidate("HL")
		return

	case "@mir.io.print.u8":
		// Emit single OUT ($23), A.  The value must already be in A.
		g.emit("    OUT (0x23), A")
		g.invalidate("A")
		return

	case "@mir.io.print.nl":
		// Emit newline (\n = 0x0A) via OUT ($23), A.
		g.emit("    LD A, 0x0A")
		g.emit("    OUT (0x23), A")
		g.invalidate("A")
		return

	case "@mir.io.print.dec":
		// Print u8 value in A as decimal ASCII digits via OUT ($23).
		// Inline: divide by 100, 10 (using repeated subtraction — small and fast
		// enough for 0-255).  Clobbers A, B, C, D, H, L.
		idx := g.trampIdx
		g.trampIdx++
		// Hundreds digit
		g.emitf("    LD C, A")                       // C = n
		g.emitf("    LD B, 0")                        // B = hundreds count
		g.emitf(".pdec_h%d:", idx)
		g.emitf("    LD A, C")
		g.emitf("    CP 100")
		g.emitf("    JR C, .pdec_ht%d", idx)
		g.emitf("    SUB 100")
		g.emitf("    LD C, A")
		g.emitf("    INC B")
		g.emitf("    JR .pdec_h%d", idx)
		g.emitf(".pdec_ht%d:", idx)
		// Only print hundreds if non-zero
		g.emitf("    LD A, B")
		g.emitf("    OR A")
		g.emitf("    JR Z, .pdec_t%d", idx)
		g.emitf("    ADD A, 48")                      // '0'
		g.emitf("    OUT (0x23), A")
		// Tens digit
		g.emitf(".pdec_t%d:", idx)
		g.emitf("    LD D, 0")                        // D = tens count
		g.emitf(".pdec_tl%d:", idx)
		g.emitf("    LD A, C")
		g.emitf("    CP 10")
		g.emitf("    JR C, .pdec_tt%d", idx)
		g.emitf("    SUB 10")
		g.emitf("    LD C, A")
		g.emitf("    INC D")
		g.emitf("    JR .pdec_tl%d", idx)
		g.emitf(".pdec_tt%d:", idx)
		// Only print tens if hundreds or tens non-zero
		g.emitf("    LD A, B")
		g.emitf("    OR D")
		g.emitf("    JR Z, .pdec_u%d", idx)
		g.emitf("    LD A, D")
		g.emitf("    ADD A, 48")
		g.emitf("    OUT (0x23), A")
		// Units digit (always print)
		g.emitf(".pdec_u%d:", idx)
		g.emitf("    LD A, C")
		g.emitf("    ADD A, 48")
		g.emitf("    OUT (0x23), A")
		g.invalidate("A")
		g.invalidate("B")
		g.invalidate("C")
		g.invalidate("D")
		return

	case "@mir.io.console.log":
		// console_log(n: u8) — OUT ($23), A  (mze/mzx stdout port)
		g.emit("    OUT (0x23), A")
		g.invalidate("A")
		return

	case "@mir.io.console.err":
		// console_err(n: u8) — OUT ($25), A  (mze/mzx stderr port)
		g.emit("    OUT (0x25), A")
		g.invalidate("A")
		return
	}

	sym := sanitizeIdent(inst.Sym)

	// Emit argument setup (parallel copy) when we have explicit Args and the
	// callee's contract is known.  This covers cases where the current physical
	// locations of the argument registers differ from the callee's expected
	// parameter locations (e.g. phi in C must move to A for the second CALL).
	var callee *Func
	if g.mod != nil {
		callee = g.mod.FuncByName(inst.Sym)
	}
	if len(inst.Args) > 0 && callee != nil && len(callee.Contract.Params) > 0 {
		g.emitCallArgs(inst.Args, callee.Contract.Params)
	}

	// Tail call optimisation: if this is the tail call instruction detected by
	// genBlock, emit JP instead of CALL so the callee's RET returns to our caller.
	if inst == g.tailCallInst {
		if callee != nil && callee.Attrs.ExternAddr != 0 {
			g.emitf("    JP 0x%04X", callee.Attrs.ExternAddr)
		} else {
			g.emitf("    JP %s", sym)
		}
		return // genTerm will skip RET
	}

	// Check if callee has a fixed address (ExternAddr)
	if callee != nil && callee.Attrs.ExternAddr != 0 {
		addr := callee.Attrs.ExternAddr
		// RST addresses on Z80: 0x00, 0x08, 0x10, 0x18, 0x20, 0x28, 0x30, 0x38
		if addr <= 0x38 && addr%8 == 0 {
			g.emitf("    RST 0x%02X", addr)
		} else {
			g.emitf("    CALL 0x%04X", addr)
		}
	} else {
		g.emitf("    CALL %s", sym)
	}

	// The CALL clobbers A and F (volatile registers on Z80).  Remove physOverride
	// entries for any virtual register that was relocated into A or F by
	// emitCallArgs — those locations are no longer valid after the call.
	// Non-volatile relocations (B/C/D/E/H/L) remain valid.
	for r, phys := range g.physOverride {
		if phys == "A" || phys == "F" {
			delete(g.physOverride, r)
		}
	}

	// Flag-return ABI: if the callee returns ClassFlag, the result is in the CPU
	// flag register (not A).  Record which condition means "true" so that a
	// subsequent TermBrIf on inst.Dst can emit JP <cond> directly without
	// AND A / CP 0.
	if inst.Dst != NoReg && callee != nil {
		if len(callee.Contract.Returns) > 0 {
			ret := callee.Contract.Returns[0]
			if ret.Class == ClassFlag {
				g.callFlags[inst.Dst] = ret.FlagCond
			}
		}
	}

	// Multi-return: bind ExtraRets[i] to the physical register that holds
	// return position i+1.  We do this via physOverride so that subsequent
	// uses of these virtual regs see the correct physical location without
	// emitting any extra move instructions.
	for i, r := range inst.ExtraRets {
		if r == NoReg {
			continue
		}
		// Determine the physical register for return position i+1.
		var retClass RegClass
		var retTy Ty = TyU16
		if i < len(inst.ExtraRetClasses) {
			retClass = inst.ExtraRetClasses[i]
		} else {
			retClass = ClassIndex // default: DE for pos 1
		}
		if i < len(inst.ExtraRetTys) {
			retTy = inst.ExtraRetTys[i]
		} else if callee != nil && i+1 < len(callee.Contract.Returns) {
			retTy = callee.Contract.Returns[i+1].Ty
		}
		phys := canonicalReturnLoc(retClass, retTy)
		g.physOverride[r] = phys
	}
}

// emitCallArgs emits the parallel-copy argument setup for a CALL instruction.
// It maps the current physical locations of the call arguments to the physical
// locations expected by the callee's parameter contract and uses emitParallelCopy
// to resolve any cycles (e.g. A→B, C→A).
//
// As a side effect it updates physOverride so that loc(r) returns the new
// physical location for any virtual register that was moved by the copy.
// physOverride is cleared after the CALL by genCall.
func (g *z80cg) emitCallArgs(args []Reg, params []Param) {
	var copies []parallelCopy
	for i, arg := range args {
		if i >= len(params) {
			break
		}
		srcPhys := g.loc(arg)
		dstPhys := canonicalReturnLoc(params[i].Class, params[i].Ty)
		if srcPhys != dstPhys {
			copies = append(copies, parallelCopy{srcName: srcPhys, dstName: dstPhys, ty: params[i].Ty})
		}
	}
	if len(copies) == 0 {
		return
	}
	g.emitParallelCopy(copies)

	// Update physOverride for each argument that was relocated.
	// After any parallel copy sequence, each source arg ends up at its declared
	// destination physical location — regardless of chain/cycle resolution order.
	for i, arg := range args {
		if i >= len(params) {
			break
		}
		srcPhys := g.ar.Loc(arg).Name
		if p, ok := g.physOverride[arg]; ok {
			srcPhys = p
		}
		dstPhys := canonicalReturnLoc(params[i].Class, params[i].Ty)
		if srcPhys != dstPhys {
			g.physOverride[arg] = dstPhys
		}
	}
}

// ── 32-bit DWord helpers ──────────────────────────────────────────────────────

// isDWord reports whether virtual register r is allocated to a LocDWord.
func (g *z80cg) isDWord(r Reg) bool {
	return r != NoReg && g.ar.Loc(r).Kind == LocDWord
}

// emitMov32 moves a 32-bit DWord value from src pair to dst pair using PUSH/EXX.
//
// Strategy (47T, 5 instructions):
//
//	PUSH src      ; push main src_lo  (11T)
//	EXX           ; switch to shadow  (4T)
//	PUSH src      ; push shadow src_hi (11T)
//	POP dst       ; pop into shadow dst_hi (10T)
//	EXX           ; switch back (4T)
//	POP dst       ; pop into main dst_lo (10T)
//
// The push of src_lo happens before EXX, so it's the main-bank value.
// After EXX, src refers to the shadow-bank value (src_hi).
func (g *z80cg) emitMov32(dst, src string) {
	if dst == src {
		return
	}
	g.emitf("    PUSH %s", src)     // save main src_lo
	g.emit("    EXX")               // switch to shadow
	g.emitf("    PUSH %s", src)     // save shadow src_hi
	g.emitf("    POP %s", dst)      // restore shadow dst_hi
	g.emit("    EXX")               // switch back to main
	g.emitf("    POP %s", dst)      // restore main dst_lo
}

// ── Move helper ───────────────────────────────────────────────────────────────

func (g *z80cg) emitMov(dst, src string, widthBits int) {
	if dst == src {
		return
	}

	// ── Flag-register special cases ───────────────────────────────────────────

	if dst == "F" {
		// Materialise a register value into the flag register.
		// Convention: Z=1 (zero) means false, NZ means true — i.e. AND A / OR A.
		// Callers using CmpNe (NZ) as the flag condition get this for free.
		if src == "A" {
			g.emit("    AND A") // sets Z/NZ and clears C based on A's value
		} else {
			// Load into A first, then set flags.
			g.emitf("    LD A, %s", src)
			g.emit("    AND A")
		}
		g.invalidate("A")
		return
	}

	if src == "F" {
		// Materialise a flag result into a register.
		// Uses the SBC A,A trick for C-flag convention: A = 0xFF (carry set = true)
		// or 0x00 (carry clear = false).  Works for CmpLt/CmpUlt/CmpGe/CmpUge.
		//
		// For Z-flag convention (CmpEq/CmpNe), the sequence is:
		//   JR NZ, $+3 / SCF / then SBC A,A — converts Z to C, then materialise.
		// We use the simpler carry path by default; HIR lowers bool-returning
		// functions to carry-based comparisons where possible.
		if dst == "A" {
			g.emit("    SBC A, A") // A=0xFF if C=1 (true), A=0x00 if C=0 (false)
		} else {
			g.emit("    SBC A, A")
			g.emitf("    LD %s, A", dst)
		}
		g.invalidate("A")
		return
	}

	// ── Normal register moves ─────────────────────────────────────────────────

	if widthBits <= 8 {
		// LocMem spill slot: "LD r, $Fxxx" and "LD $Fxxx, r" are not valid Z80.
		// Only "LD A, (nn)" and "LD (nn), A" work for absolute 8-bit memory I/O.
		// Route all other combinations through A.
		switch {
		case strings.HasPrefix(src, "$") && dst == "A":
			g.emitf("    LD A, (%s)", src)
		case strings.HasPrefix(src, "$"):
			g.emitf("    LD A, (%s)", src)
			g.emitf("    LD %s, A", dst)
			g.invalidate("A")
		case strings.HasPrefix(dst, "$") && src == "A":
			g.emitf("    LD (%s), A", dst)
		case strings.HasPrefix(dst, "$"):
			g.emitLDA(src)
			g.emitf("    LD (%s), A", dst)
		default:
			g.emitf("    LD %s, %s", dst, src)
			if isSimpleReg(dst) && isSimpleReg(src) {
				g.setCopy(dst, src)
			}
		}
		return
	}

	// 32-bit DWord move via PUSH/EXX sequence.
	if widthBits == 32 {
		g.emitMov32(dst, src)
		return
	}

	// 16-bit register move.
	switch {
	case dst == "HL" && src == "DE":
		// Copy DE→HL: must NOT use EX DE,HL (swap destroys DE).
		g.emitf("    LD %s, %s", highByte(dst), highByte(src)) // LD H, D
		g.emitf("    LD %s, %s", lowByte(dst), lowByte(src))   // LD L, E
	case dst == "DE" && src == "HL":
		// Copy HL→DE: must NOT use EX DE,HL (swap destroys HL).
		g.emitf("    LD %s, %s", highByte(dst), highByte(src)) // LD D, H
		g.emitf("    LD %s, %s", lowByte(dst), lowByte(src))   // LD E, L
	case (dst == "IX" || dst == "IY") && (src == "DE" || src == "BC"):
		// DE/BC → IX/IY: undocumented byte-copy (DD/FD prefix), 2×8T = 16T.
		// Safe because D, E, B, C are NOT substituted by the DD/FD prefix.
		// e.g. DE→IX: LD IXH, D (DD 62) / LD IXL, E (DD 6B)
		//      BC→IX: LD IXH, B (DD 60) / LD IXL, C (DD 69)
		g.emitf("    LD %s, %s", highByte(dst), highByte(src))
		g.emitf("    LD %s, %s", lowByte(dst), lowByte(src))
	case (dst == "IX" || dst == "IY") && src == "HL":
		// HL→IX: byte-copy is INVALID — DD prefix substitutes H→IXH, L→IXL,
		// so LD IXH,H encodes as LD IXH,IXH (NOP). Must use PUSH/POP.
		g.emitf("    PUSH HL")
		g.emitf("    POP %s", dst)
	case (src == "IX" || src == "IY") && (dst == "DE" || dst == "BC"):
		// IX/IY → DE/BC: safe byte-copy, D/E/B/C not substituted by DD prefix.
		// e.g. IX→DE: LD D, IXH (DD 57? no — DD 7A? no) actually DD prefix on LD D,H:
		// opcode 0x54 = LD D,H → DD 54 = LD D,IXH ✓ (D is destination, IXH is source)
		g.emitf("    LD %s, %s", highByte(dst), highByte(src))
		g.emitf("    LD %s, %s", lowByte(dst), lowByte(src))
	case (src == "IX" || src == "IY") && dst == "HL":
		// IX→HL: byte-copy INVALID (H,L substituted). Must use PUSH/POP.
		g.emitf("    PUSH %s", src)
		g.emit("    POP HL")
	default:
		// If src is an 8-bit register being widened to a 16-bit pair,
		// PUSH/POP is wrong: PUSH A doesn't exist (only PUSH AF, which
		// would corrupt the low byte with the flags register).
		// Use zero-extension instead: LD lo, src ; LD hi, 0.
		if isSimpleReg(src) && !isPairReg(src) && isPairReg(dst) {
			lo := lowByte(dst)
			hi := highByte(dst)
			if lo != src {
				g.emitf("    LD %s, %s", lo, src)
			}
			g.emitf("    LD %s, 0", hi)
			break
		}
		// LocMem spill slot → register pair: use LD rr, (nn).
		// Z80 supports: LD HL,(nn) [native], LD DE/BC/SP,(nn) [ED-prefix].
		// Cannot use PUSH/POP since PUSH nn is not a valid Z80 instruction.
		if strings.HasPrefix(src, "$") {
			g.emitf("    LD %s, (%s)", dst, src)
			break
		}
		// register pair → LocMem spill slot: use LD (nn), rr.
		if strings.HasPrefix(dst, "$") {
			g.emitf("    LD (%s), %s", dst, src)
			break
		}
		// General 16-bit move via PUSH/POP.
		// PUSH/POP only works with 16-bit register pairs; 8-bit regs must
		// not reach here (they would silently emit e.g. PUSH AF instead of
		// PUSH A, corrupting the low byte with the flags register).
		g.emitf("    PUSH %s", src)
		g.emitf("    POP %s", dst)
	}
	// Track the copy alias so downstream redundant moves can be suppressed.
	g.setCopy(dst, src)
}

// ── Terminators ───────────────────────────────────────────────────────────────

func (g *z80cg) genTerm(f *Func, t Term) {
	// If any block param was saved to a scratch register (via materializePendingAcc),
	// restore it to its canonical physical location before any terminal jump or ret.
	// This ensures live-through values (used in successor blocks without explicit
	// block params) are in their allocator-assigned locations when those blocks run.
	// physOverride[r] was valid within this block; canonical location = ar.Loc(r).
	for _, bp := range g.curBlock.Params {
		if scratch, ok := g.physOverride[bp.Dst]; ok {
			canon := g.ar.Loc(bp.Dst).Name
			if canon != "" && canon != scratch {
				g.emitf("    LD %s, %s    ; restore block param from scratch", canon, scratch)
			}
			delete(g.physOverride, bp.Dst)
		}
	}

	switch t := t.(type) {
	case *TermRet:
		// Tail call: JP was already emitted by genCall; skip all moves and RET.
		if g.tailCallInst != nil {
			g.tailCallInst = nil
			return
		}
		// Move return values to their calling-convention physical registers using
		// parallel copy resolution.  Sequential moves are incorrect when two return
		// values share the same physical register after constant folding/PBQP
		// (e.g. both [acc]=A), causing write-after-write clobber.
		g.emitParallelCopy(g.buildReturnCopies(t.Vals))
		// main() is the program entry point: use XOR A / DI / HALT instead of
		// RET so mze/mzx can detect program termination cleanly.  XOR A zeroes
		// A for a clean exit code 0.
		if f.Name == "main" && len(t.Vals) == 0 {
			g.emit("    XOR A")
			g.emit("    DI")
			g.emit("    HALT")
		} else {
			g.emit("    RET")
		}

	case *TermJmp:
		// Resolve block-argument parallel copies before the jump.
		copies := g.buildBlockCopies(f, t.Target, t.Args)
		g.emitParallelCopy(copies)
		// Fall-through elimination: if the target is the very next physical block,
		// the JR is redundant — execution falls through naturally.
		if !g.isFallThrough(f, t.Target) {
			g.emitf("    JRS %s", blockLabel(f.Name, t.Target))
		}

	case *TermBrIf:
		cc := g.condCode(f, t.Cond)

		// Build block-arg copies for each edge.
		thenCopies := g.buildBlockCopies(f, t.Then, t.ThenArgs)
		elseCopies := g.buildBlockCopies(f, t.Else, t.ElseArgs)

		// If a branch has non-trivial copies, it cannot be a fall-through:
		// redirect it through a trampoline that performs the copies then JR.
		thenLbl := g.branchLabel(f, t.Then, thenCopies)
		elseLbl := g.branchLabel(f, t.Else, elseCopies)

		// Fall-through is only possible when there are no copies for that edge.
		thenFT := g.isFallThrough(f, t.Then) && len(thenCopies) == 0
		elseFT := g.isFallThrough(f, t.Else) && len(elseCopies) == 0

		// Two-condition sentinels: CmpGt/CmpLe with lhs in A (no operand swap).
		// CGT = NC && NZ (a > b); CLE = C || Z (a ≤ b).
		// Note: CLE/CGT need two jumps — first uses JR, second uses JR too.
		// MZA auto-promotes any JR to JP when out of range.
		if cc == "CLE" {
			// a ≤ b: branch to then if C (a<b) or Z (a==b).
			g.emitf("    JRS C, %s", thenLbl)
			g.emitf("    JRS Z, %s", thenLbl)
			if !elseFT {
				g.emitf("    JRS %s", elseLbl)
			}
		} else if cc == "CGT" {
			// a > b: branch to else if Z (a==b) or C (a<b), else fall/JR to then.
			g.emitf("    JRS Z, %s", elseLbl)
			g.emitf("    JRS C, %s", elseLbl)
			if !thenFT {
				g.emitf("    JRS %s", thenLbl)
			}
		} else if elseFT {
			g.emitf("    JRS %s, %s", cc, thenLbl)
			// else falls through naturally
		} else if thenFT {
			g.emitf("    JRS %s, %s", invertCC(cc), elseLbl)
			// then falls through naturally
		} else {
			g.emitf("    JRS %s, %s", cc, thenLbl)
			g.emitf("    JRS %s", elseLbl)
		}

	case *TermBrIf2:
		// Three-way unsigned comparison: one CP, three outcomes (==, <, >).
		// Emit: CP rhs (with A=lhs), then JR Z eq, JR C lt, fall-through/JR gt.
		lhs := g.loc(t.Lhs)
		rhs := g.loc(t.Rhs)

		// Emit the CP (same logic as genCmp).
		if cv, ok := g.constVals[t.Rhs]; ok {
			if !g.holdsValue("A", lhs) {
				g.emitLDA(lhs)
			}
			g.emitf("    CP %d", cv)
		} else if rhs == "A" && lhs != "A" {
			// A already holds rhs; swap: CP lhs computes rhs-lhs.
			// Eq is still Z (rhs-lhs==0 ↔ rhs==lhs), but C now means rhs<lhs.
			// So we swap Lt↔Gt below.
			g.emitf("    CP %s", lhs)
			// Build copies for eq, swapped lt/gt.
			eqCopies := g.buildBlockCopies(f, t.Eq, t.EqArgs)
			ltCopies := g.buildBlockCopies(f, t.Gt, t.GtArgs) // swapped: C→gt
			gtCopies := g.buildBlockCopies(f, t.Lt, t.LtArgs) // swapped: NC,NZ→lt
			eqLbl := g.branchLabel(f, t.Eq, eqCopies)
			ltLbl := g.branchLabel(f, t.Gt, ltCopies)
			gtLbl := g.branchLabel(f, t.Lt, gtCopies)
			g.emitf("    JRS Z, %s", eqLbl)
			g.emitf("    JRS C, %s", ltLbl)
			if !g.isFallThrough(f, t.Lt) || len(gtCopies) != 0 {
				g.emitf("    JRS %s", gtLbl)
			}
			return
		} else {
			if !g.holdsValue("A", lhs) {
				g.emitLDA(lhs)
			}
			g.emitf("    CP %s", rhs)
		}

		// Build copies for each of the three edges.
		eqCopies := g.buildBlockCopies(f, t.Eq, t.EqArgs)
		ltCopies := g.buildBlockCopies(f, t.Lt, t.LtArgs)
		gtCopies := g.buildBlockCopies(f, t.Gt, t.GtArgs)
		eqLbl := g.branchLabel(f, t.Eq, eqCopies)
		ltLbl := g.branchLabel(f, t.Lt, ltCopies)
		gtLbl := g.branchLabel(f, t.Gt, gtCopies)

		g.emitf("    JRS Z, %s", eqLbl)
		g.emitf("    JRS C, %s", ltLbl)
		if !g.isFallThrough(f, t.Gt) || len(gtCopies) != 0 {
			g.emitf("    JRS %s", gtLbl)
		}

	case *TermDJNZ:
		// Emit body-edge copies for non-counter args.
		// The counter (B) is handled implicitly by DJNZ.
		// body.Params[0] = counter (gets decremented B); BodyArgs = params[1:].
		bodyBlock := f.BlockByLabel(t.Body)
		var bodyCopies []parallelCopy
		if bodyBlock != nil {
			for i, arg := range t.BodyArgs {
				if i+1 >= len(bodyBlock.Params) {
					break
				}
				param := bodyBlock.Params[i+1] // skip counter param[0]
				src := g.loc(arg)
				dst := g.ar.Loc(param.Dst).Name
				if src != dst {
					bodyCopies = append(bodyCopies, parallelCopy{srcName: src, dstName: dst, ty: param.Ty})
				}
			}
		}
		g.emitParallelCopy(bodyCopies)
		g.emitf("    DJNZ %s", blockLabel(f.Name, t.Body))
		// Exit path.
		exitCopies := g.buildBlockCopies(f, t.Exit, t.ExitArgs)
		g.emitParallelCopy(exitCopies)
		if !g.isFallThrough(f, t.Exit) || len(exitCopies) != 0 {
			g.emitf("    JP %s", blockLabel(f.Name, t.Exit))
		}

	case *TermCondRet:
		// Strategy: jump to Then FIRST (before moving return values),
		// because moving return values may emit instructions that clobber
		// the flag register the condition depends on (e.g. OR A before SBC).
		//
		//   JRS cc, @then      ; when Cond!=0 → jump, skipping the return path
		//   [move return vals] ; only executed when Cond==0
		//   RET
		//
		// Compound conditions CGT/CLE need two jumps — no single Z80 condition
		// encodes (NC && NZ) or (C || Z). Handle them separately.
		cc := g.condCode(f, t.Cond)
		copies := g.buildBlockCopies(f, t.Then, t.ThenArgs)
		thenLbl := g.branchLabel(f, t.Then, copies)
		retCopies := g.buildReturnCopies(t.Vals)
		thenFT := g.isFallThrough(f, t.Then) && len(copies) == 0

		switch cc {
		case "CLE":
			// a ≤ b: take Then if C (a<b) or Z (a==b).
			// Jump to Then with two conditional JRs; fall through to RET.
			g.emitf("    JRS C, %s", thenLbl)
			g.emitf("    JRS Z, %s", thenLbl)
			g.emitParallelCopy(retCopies)
			g.emit("    RET")
		case "CGT":
			// a > b: take Then if NC && NZ.
			// Invert: skip Then (jump to ret path) if C or Z.
			retLbl := fmt.Sprintf(".%s_cret%d", sanitizeIdent(f.Name), g.trampIdx)
			g.trampIdx++
			g.emitf("    JRS Z, %s", retLbl)
			g.emitf("    JRS C, %s", retLbl)
			if !thenFT {
				g.emitf("    JRS %s", thenLbl)
			}
			// Register ret path as trampoline so it's emitted AFTER the fallthrough
			// then-block (otherwise the inline label would block the fallthrough path).
			g.trampolines = append(g.trampolines, trampolineBlock{
				label:  retLbl,
				copies: retCopies,
				isRet:  true,
			})
		default:
			if thenFT && len(retCopies) == 0 {
				// Then-block is the fallthrough AND return path is empty:
				// use RET invertCC (1 byte, optimal). Only safe when retCopies is
				// empty — otherwise retCopies would corrupt registers that @then
				// reads, since they execute before the branch is resolved.
				g.emitf("    RET %s", invertCC(cc))
			} else if thenFT {
				// Then-block is the fallthrough but retCopies are non-trivial.
				// Jump to @then when condition is true (skipping the return path),
				// then fall through to @then naturally.
				g.emitf("    JRS %s, %s", cc, thenLbl)
				g.emitParallelCopy(retCopies)
				g.emit("    RET")
			} else {
				// General case: emit conditional jump to Then first, then return path.
				g.emitf("    JRS %s, %s", cc, thenLbl)
				g.emitParallelCopy(copies)
				g.emitParallelCopy(retCopies)
				g.emit("    RET")
			}
		}

	case *TermUnreachable:
		g.comment("unreachable")
	}
}

// branchLabel returns the label to jump to for a BrIf edge.
// If the edge has parallel copies, a trampoline block is registered and its
// label is returned instead of the real target label.
func (g *z80cg) branchLabel(f *Func, target string, copies []parallelCopy) string {
	realLbl := blockLabel(f.Name, target)
	if len(copies) == 0 {
		return realLbl
	}
	tramLbl := fmt.Sprintf(".%s_trmp%d", sanitizeIdent(f.Name), g.trampIdx)
	g.trampIdx++
	g.trampolines = append(g.trampolines, trampolineBlock{
		label:  tramLbl,
		copies: copies,
		target: realLbl,
	})
	return tramLbl
}

// buildReturnCopies computes the parallel copies needed to move return values
// into their calling-convention physical registers.
// Using parallel copy resolution (instead of sequential emitMov) is essential
// when two return values are allocated to the same physical register after
// constant folding/PBQP — sequential moves would clobber one value.
func (g *z80cg) buildReturnCopies(vals []Reg) []parallelCopy {
	var copies []parallelCopy
	for i, rv := range vals {
		if i >= len(g.fn.Contract.Returns) {
			break
		}
		if rv == NoReg {
			continue // void call result; return register already correct
		}
		ret := g.fn.Contract.Returns[i]
		retLoc := canonicalReturnLoc(ret.Class, ret.Ty)
		src := g.loc(rv)
		if src != retLoc && !g.holdsValue(retLoc, src) {
			copies = append(copies, parallelCopy{srcName: src, dstName: retLoc, ty: ret.Ty})
		}
	}
	return copies
}

// buildBlockCopies computes the parallel copies needed to pass args to a
// target block's formal parameters.  Returns only moves where src ≠ dst.
func (g *z80cg) buildBlockCopies(f *Func, targetName string, args []Reg) []parallelCopy {
	if len(args) == 0 {
		return nil
	}
	var target *Block
	for _, b := range f.Blocks {
		if b.Label == targetName {
			target = b
			break
		}
	}
	if target == nil {
		return nil
	}
	var copies []parallelCopy
	for i, arg := range args {
		if i >= len(target.Params) {
			break
		}
		// Use g.loc (which respects physOverride) so that values saved to scratch
		// registers by materializePendingAcc/materializePendingFlag are correctly
		// moved to their canonical destination in the target block.
		src := g.loc(arg)
		dst := g.ar.Loc(target.Params[i].Dst).Name
		if src != dst {
			copies = append(copies, parallelCopy{srcName: src, dstName: dst, ty: target.Params[i].Ty})
		}
	}
	return copies
}

// emitParallelCopy resolves and emits a set of parallel register moves,
// correctly handling cycles (e.g. HL↔DE → EX DE,HL).
func (g *z80cg) emitParallelCopy(copies []parallelCopy) {
	if len(copies) == 0 {
		return
	}
	type move struct {
		src, dst string
		ty       Ty
		done     bool
	}
	moves := make([]move, len(copies))
	for i, c := range copies {
		moves[i] = move{src: c.srcName, dst: c.dstName, ty: c.ty}
	}

	for {
		// Emit any move whose dst is not a source of another pending move.
		progress := false
		for i := range moves {
			if moves[i].done {
				continue
			}
			dstNeeded := false
			for j := range moves {
				if j != i && !moves[j].done && moves[j].src == moves[i].dst {
					dstNeeded = true
					break
				}
			}
			if !dstNeeded {
				g.emitSingleCopy(moves[i].src, moves[i].dst, moves[i].ty)
				moves[i].done = true
				progress = true
				break
			}
		}
		if progress {
			continue
		}

		// All remaining moves form cycles.  Find first undone.
		first := -1
		undone := 0
		for i := range moves {
			if !moves[i].done {
				undone++
				if first == -1 {
					first = i
				}
			}
		}
		if first == -1 {
			break
		}

		// Special case: HL↔DE two-node cycle → EX DE, HL.
		if undone == 2 {
			a, b := -1, -1
			for i := range moves {
				if !moves[i].done {
					if a == -1 {
						a = i
					} else {
						b = i
					}
				}
			}
			as, ad := moves[a].src, moves[a].dst
			bs, bd := moves[b].src, moves[b].dst
			if (as == "HL" && ad == "DE" && bs == "DE" && bd == "HL") ||
				(as == "DE" && ad == "HL" && bs == "HL" && bd == "DE") {
				g.emit("    EX DE, HL")
				moves[a].done = true
				moves[b].done = true
				continue
			}
		}

		// General cycle: break with a temporary.
		m := &moves[first]
		if m.ty.Width() <= 8 {
			// u8 cycle: break by saving the first node's source to a scratch register.
			//
			// Walk BACKWARD through the cycle so we always read old values.
			// Example 3-cycle D→C, C→E, E→D (scratch=A):
			//   LD A, D     (save D into scratch)
			//   LD D, E     (backward: who writes TO D? E→D. E still original.)
			//   LD E, C     (backward: who writes TO E? C→E. C still original.)
			//   LD C, A     (put D_old into C via scratch)
			//
			// When A is part of the cycle, using A as scratch would overwrite it
			// during the walk before the final restore.  Pick the first 8-bit
			// register not involved in any pending move instead.
			cycleRegs := map[string]bool{}
			for i := range moves {
				if !moves[i].done {
					cycleRegs[moves[i].src] = true
					cycleRegs[moves[i].dst] = true
				}
			}
			scratch := "A"
			if cycleRegs["A"] {
				for _, r := range []string{"C", "E", "H", "L", "D", "B"} {
					if !cycleRegs[r] {
						scratch = r
						break
					}
				}
			}

			firstDst := m.dst
			if m.src != scratch {
				g.emitf("    LD %s, %s", scratch, m.src)
			}
			m.done = true
			cur := m.src // start at the freed slot (m.src saved to scratch)
			for {
				found := false
				for i := range moves {
					if !moves[i].done && moves[i].dst == cur {
						g.emitf("    LD %s, %s", moves[i].dst, moves[i].src)
						cur = moves[i].src // the source is the new freed slot
						moves[i].done = true
						found = true
						break
					}
				}
				if !found {
					break
				}
			}
			if firstDst != scratch {
				g.emitf("    LD %s, %s", firstDst, scratch)
			}
		} else {
			// u16 cycle: use stack.
			// If m.src is a LocMem spill slot ($Fxxx), PUSH is invalid.
			// Save the LocMem value into the destination first (it will be
			// overwritten by the cycle walk anyway), then push that pair.
			if strings.HasPrefix(m.src, "$") {
				g.emitf("    LD %s, (%s)", m.dst, m.src) // load LocMem into dest pair
				g.emitf("    PUSH %s", m.dst)             // save that value on stack
			} else {
				g.emitf("    PUSH %s", m.src)
			}
			m.done = true
			cur := m.dst
			for {
				found := false
				for i := range moves {
					if !moves[i].done && moves[i].src == cur {
						g.emitSingleCopy(moves[i].src, moves[i].dst, moves[i].ty)
						cur = moves[i].dst
						moves[i].done = true
						found = true
						break
					}
				}
				if !found {
					break
				}
			}
			if strings.HasPrefix(cur, "$") {
				// POP into LocMem: pop to HL then store.
				g.emit("    POP HL")
				g.emitf("    LD (%s), HL", cur)
			} else {
				g.emitf("    POP %s", cur)
			}
		}
	}
}

// emitSingleCopy emits a non-destructive register copy (src → dst).
// For 16-bit, this emits two LD instructions (not EX DE,HL which is a swap).
func (g *z80cg) emitSingleCopy(src, dst string, ty Ty) {
	if src == dst {
		return
	}
	if ty.Width() <= 8 {
		switch {
		case strings.HasPrefix(src, "$") && dst == "A":
			g.emitf("    LD A, (%s)", src)
		case strings.HasPrefix(src, "$"):
			g.emitf("    LD A, (%s)", src)
			g.emitf("    LD %s, A", dst)
			g.invalidate("A")
		case strings.HasPrefix(dst, "$") && src == "A":
			g.emitf("    LD (%s), A", dst)
		case strings.HasPrefix(dst, "$"):
			g.emitLDA(src)
			g.emitf("    LD (%s), A", dst)
		default:
			g.emitf("    LD %s, %s", dst, src)
		}
	} else if strings.HasPrefix(src, "$") {
		// LocMem spill slot → register pair: LD rr, (nn).
		g.emitf("    LD %s, (%s)", dst, src)
	} else if strings.HasPrefix(dst, "$") {
		// register pair → LocMem spill slot: LD (nn), rr.
		g.emitf("    LD (%s), %s", dst, src)
	} else {
		// 16-bit non-destructive copy: two 8-bit LDs.
		g.emitf("    LD %s, %s", highByte(dst), highByte(src))
		g.emitf("    LD %s, %s", lowByte(dst), lowByte(src))
	}
}

// condCode returns the Z80 condition code for the virtual register holding
// the comparison result.  If genCmp swapped the operands, the condition
// is automatically inverted via CmpCond.Swap().
//
// For ClassFlag returns from CALL instructions, callFlags[cond] holds the
// agreed FlagCond directly — no AND A / CP 0 is needed at the call site.
func (g *z80cg) condCode(f *Func, cond Reg) string {
	// Fast path: call result with ClassFlag return — condition already in F.
	if fc, ok := g.callFlags[cond]; ok {
		return cmpCondCode(fc)
	}

	for _, b := range f.Blocks {
		for _, inst := range b.Insts {
			if inst.Dst == cond && inst.Op == OpCmp {
				c := inst.Cond
				if g.cmpSwapped[cond] {
					c = c.Swap() // operands were swapped → invert condition
				}
				// When genCmp emitted AND A (rhs=0), carry is always 0.
				// Replace NC/C-based conditions with NZ/Z-based ones:
				//   CmpGt(n, 0) → n != 0 → NZ
				//   CmpGe(n, 0) → n >= 0 → always true → handled as NC (fine)
				//   CmpLt(n, 0) → never for unsigned → C (never fires)
				//   CmpLe(n, 0) → n == 0 → Z
				if g.cmpAndZero[cond] {
					switch c {
					case CmpGt, CmpUgt:
						return "NZ"
					case CmpLe, CmpUle:
						return "Z"
					}
				}
				if g.cmpNeedsTwo[cond] {
					switch c {
					case CmpGt, CmpUgt:
						return "CGT" // NC && NZ: JP Z,else; JP NC,then
					case CmpLe, CmpUle:
						return "CLE" // C || Z: JP C,then; JP Z,then
					}
				}
				return cmpCondCode(c)
			}
		}
	}
	return "NZ" // fallback
}

// isFallThrough reports whether targetLabel is the next physical block after
// the current one (g.blockIdx), making a JP redundant.
func (g *z80cg) isFallThrough(f *Func, targetLabel string) bool {
	next := g.blockIdx + 1
	if next >= len(f.Blocks) {
		return false
	}
	return f.Blocks[next].Label == targetLabel
}

// invertCC returns the Z80 condition code that is the logical negation of cc.
func invertCC(cc string) string {
	switch cc {
	case "Z":
		return "NZ"
	case "NZ":
		return "Z"
	case "C":
		return "NC"
	case "NC":
		return "C"
	case "PE":
		return "PO"
	case "PO":
		return "PE"
	case "M":
		return "P"
	case "P":
		return "M"
	}
	return cc
}

// cmpCondCode maps CmpCond → Z80 condition string.
func cmpCondCode(c CmpCond) string {
	switch c {
	case CmpEq:
		return "Z"
	case CmpNe:
		return "NZ"
	case CmpLt, CmpUlt, CmpSubCarry:
		return "C"
	case CmpGe, CmpUge, CmpSubCarryNot:
		return "NC"
	case CmpLe, CmpUle:
		// LE: JP Z / JP C — requires two jumps; emit Z for now (backend TODO).
		return "Z"
	case CmpGt, CmpUgt:
		return "NC"
	}
	return "NZ"
}

// canonicalReturnLoc returns the physical register name where a return value of
// the given class and type must reside on function exit (calling convention).
func canonicalReturnLoc(cls RegClass, ty Ty) string {
	w := ty.Width()
	switch cls {
	case ClassFlag:
		// Flag-return ABI: result lives in the CPU flag register (F), not in A.
		// Callers test with JP <FlagCond> directly after the CALL instruction.
		// "F" is the sentinel name for LocFlag in Z80PhysLocs.
		return "F"
	case ClassAcc:
		if w <= 8 {
			return "A"
		}
		return "HL" // u16 [acc] → HL
	case ClassPointer, ClassPair:
		return "HL"
	case ClassIndex:
		return "DE"
	case ClassCounter:
		return "B"
	default:
		if w <= 8 {
			return "A"
		}
		return "HL"
	}
}

