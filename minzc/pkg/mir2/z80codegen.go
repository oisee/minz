// ── DJNZ peephole ─────────────────────────────────────────────────────────────

// findConstInFunc finds the Imm value of an OpConst instruction defining r.
func findConstInFunc(f *Func, r Reg) (int64, bool) {
	for _, b := range f.Blocks {
		for _, inst := range b.Insts {
			if inst.Op == OpConst && inst.Dst == r {
				return inst.Imm, true
			}
		}
	}
	return 0, false
}

// djnzPeepholeResult holds the result of DJNZ peephole detection.
type djnzPeepholeResult struct {
	skipLast  bool      // skip the last OpSub instruction (DJNZ handles DEC B)
	bodyLbl   string    // DJNZ target: the loop body label (brif.Then)
	checkBrif *TermBrIf // the check block's brif (for exit-edge copies)
}

// detectDJNZPeephole checks if block b ends with the DJNZ-optimizable pattern:
//
//	last_inst: OpSub(counter→B, 1)
//	term:      TermJmp to check_block
//	check_block: [OpCmp(CmpNe, B, 0)] + TermBrIf(Then=body, Else=exit)
//	all args trivially in-place (no non-trivial copies needed)
func (g *z80cg) detectDJNZPeephole(f *Func, b *Block) djnzPeepholeResult {
	if len(b.Insts) == 0 {
		return djnzPeepholeResult{}
	}
	jmp, ok := b.Term.(*TermJmp)
	if !ok {
		return djnzPeepholeResult{}
	}
	// Last instruction must be OpSub(counter, 1) with counter→B.
	last := b.Insts[len(b.Insts)-1]
	if last.Op != OpSub {
		return djnzPeepholeResult{}
	}
	if g.ar.Loc(last.Src[0]).Name != "B" || g.ar.Loc(last.Dst).Name != "B" {
		return djnzPeepholeResult{}
	}
	// RHS must be constant 1.
	rhs, found := findConstInFunc(f, last.Src[1])
	if !found || rhs != 1 {
		return djnzPeepholeResult{}
	}
	// Target must be the check block: only CmpNe(B, 0) + optional Const(0) + TermBrIf.
	check := f.BlockByLabel(jmp.Target)
	if check == nil || len(check.Insts) == 0 || len(check.Insts) > 2 {
		return djnzPeepholeResult{}
	}
	// Find the OpCmp instruction (last if there are two).
	var cmp *Inst
	for i := len(check.Insts) - 1; i >= 0; i-- {
		if check.Insts[i].Op == OpCmp {
			cmp = check.Insts[i]
			break
		}
	}
	if cmp == nil || cmp.Cond != CmpNe {
		return djnzPeepholeResult{}
	}
	if g.ar.Loc(cmp.Src[0]).Name != "B" {
		return djnzPeepholeResult{}
	}
	zero, found2 := findConstInFunc(f, cmp.Src[1])
	if !found2 || zero != 0 {
		return djnzPeepholeResult{}
	}
	// Verify all instructions in check block are CmpNe + optional Const(0) only.
	for _, inst := range check.Insts {
		if inst.Op != OpCmp && inst.Op != OpConst {
			return djnzPeepholeResult{}
		}
	}
	brif, ok2 := check.Term.(*TermBrIf)
	if !ok2 || brif.Cond != cmp.Dst {
		return djnzPeepholeResult{}
	}
	// Verify all TermJmp args are trivially in-place (excluding counter B→B).
	for i, arg := range jmp.Args {
		if i >= len(check.Params) {
			break
		}
		srcLoc := g.ar.Loc(arg).Name
		dstLoc := g.ar.Loc(check.Params[i].Dst).Name
		if srcLoc == "B" && dstLoc == "B" {
			continue // counter handled by DJNZ
		}
		if srcLoc != dstLoc {
			return djnzPeepholeResult{} // non-trivial copy, fall back
		}
	}
	// Verify exit-edge copies are trivial.
	exitBlock := f.BlockByLabel(brif.Else)
	if exitBlock != nil {
		for i, arg := range brif.ElseArgs {
			if i >= len(exitBlock.Params) {
				break
			}
			if g.ar.Loc(arg).Name != g.ar.Loc(exitBlock.Params[i].Dst).Name {
				return djnzPeepholeResult{} // non-trivial exit copy, fall back
			}
		}
	}
	return djnzPeepholeResult{
		skipLast:  true,
		bodyLbl:   blockLabel(f.Name, brif.Then),
		checkBrif: brif,
	}
}

// ── Function annotation comment ───────────────────────────────────────────────

// funcAnnotation builds a one-line ABI summary for a function:
//
//	fn name(param0: type = REG, ...) -> ret = REG [recursive] [clobbers: REG, ...]
//
// This is emitted as a "; ..." comment immediately before the function label.
func funcAnnotation(f *Func, ar *AllocResult) string {
	var sb strings.Builder

	sb.WriteString("fun ")
	sb.WriteString(f.Name)
	sb.WriteByte('(')
	for i, p := range f.Contract.Params {
		if i > 0 {
			sb.WriteString(", ")
		}
		loc := ar.Loc(p.Reg)
		sb.WriteString(p.Name)
		sb.WriteString(": ")
		if p.Ty != nil {
			sb.WriteString(p.Ty.String())
		} else {
			sb.WriteString("?")
		}
		if loc.Name != "" {
			sb.WriteString(" = ")
			sb.WriteString(loc.Name)
		}
	}
	sb.WriteByte(')')

	// Return values (class → canonical register name).
	if len(f.Contract.Returns) == 1 {
		r := f.Contract.Returns[0]
		sb.WriteString(" -> ")
		if r.Ty != nil {
			sb.WriteString(r.Ty.String())
		} else {
			sb.WriteString("?")
		}
		if reg := classToRegName(r.Class, r.Ty); reg != "" {
			sb.WriteString(" = ")
			sb.WriteString(reg)
		}
	} else if len(f.Contract.Returns) > 1 {
		// For multi-return, the contract optimizer may change Return[i].Class
		// after lowering (e.g. both u16 slots become ClassPointer).  Use the
		// actual allocated physical locations from the first TermRet instead,
		// which reflect what the allocator and codegen actually produce.
		retLocs := multiReturnLocs(f, ar)
		sb.WriteString(" -> (")
		for i, r := range f.Contract.Returns {
			if i > 0 {
				sb.WriteString(", ")
			}
			if r.Ty != nil {
				sb.WriteString(r.Ty.String())
			} else {
				sb.WriteString("?")
			}
			reg := ""
			if i < len(retLocs) && retLocs[i] != "" {
				reg = retLocs[i]
			} else {
				reg = classToRegName(r.Class, r.Ty)
			}
			if reg != "" {
				sb.WriteString(" = ")
				sb.WriteString(reg)
			}
		}
		sb.WriteByte(')')
	}

	// Recursive check: any OpCall instruction that calls f itself?
	if isRecursive(f) {
		sb.WriteString(" [recursive]")
	}

	// Clobber set: all Dst phys locs that aren't param or return locs.
	clobbers := computeClobbers(f, ar)
	if len(clobbers) > 0 {
		sb.WriteString(" ; clobbers: ")
		for i, name := range clobbers {
			if i > 0 {
				sb.WriteString(", ")
			}
			sb.WriteString(name)
		}
	}

	return sb.String()
}

// multiReturnLocs returns the physical register name for each return position
// by scanning the function's TermRet instructions and looking up the allocator
// result.  This is more accurate than classToRegName(Contract.Returns[i].Class)
// because the contract optimizer may reassign classes after lowering.
// Returns a slice with one entry per return position; entries may be "" if unknown.
func multiReturnLocs(f *Func, ar *AllocResult) []string {
	n := len(f.Contract.Returns)
	if n == 0 {
		return nil
	}
	for _, b := range f.Blocks {
		if ret, ok := b.Term.(*TermRet); ok && len(ret.Vals) == n {
			locs := make([]string, n)
			for i, v := range ret.Vals {
				locs[i] = ar.Loc(v).Name
			}
			return locs
		}
	}
	return nil
}

// classToRegName maps a RegClass to the canonical Z80 register name for that class.
// ty is used to disambiguate (e.g. ClassAcc is always A, ClassPointer is HL for 16-bit).
func classToRegName(cls RegClass, ty Ty) string {
	switch cls {
	case ClassAcc:
		return "A"
	case ClassPointer:
		return "HL"
	case ClassIndex:
		return "DE"
	case ClassCounter:
		return "B"
	case ClassGeneral:
		return "C"
	}
	return ""
}

// isRecursive reports whether f contains a direct recursive call to itself.
func isRecursive(f *Func) bool {
	for _, b := range f.Blocks {
		for _, inst := range b.Insts {
			if inst.Op == OpCall && inst.Sym == f.Name {
				return true
			}
		}
	}
	return false
}

// computeClobbers returns the sorted list of physical register names written by f
// that are not in f's parameter or return register set.
func computeClobbers(f *Func, ar *AllocResult) []string {
	// Collect param and return phys names (these are "owned" by the ABI).
	owned := make(map[string]bool)
	for _, p := range f.Contract.Params {
		if loc := ar.Loc(p.Reg); loc.Name != "" {
			owned[loc.Name] = true
		}
	}
	for _, r := range f.Contract.Returns {
		if reg := classToRegName(r.Class, r.Ty); reg != "" {
			owned[reg] = true
		}
	}

	// Collect Dst phys locs from all instructions.
	seen := make(map[string]bool)
	for _, b := range f.Blocks {
		for _, p := range b.Params {
			if loc := ar.Loc(p.Dst); loc.Name != "" && !owned[loc.Name] {
				seen[loc.Name] = true
			}
		}
		for _, inst := range b.Insts {
			if inst.Dst != NoReg {
				if loc := ar.Loc(inst.Dst); loc.Name != "" && !owned[loc.Name] {
					seen[loc.Name] = true
				}
			}
			// ExtraRets on OpCall are callee-provided return values, not
			// registers independently clobbered by the caller.  Counting them
			// as clobbers of the *caller* is wrong (e.g. "larger" calling
			// "minmax" would wrongly show "clobbers: BC" for DE/BC extra returns).
			if inst.Op != OpCall {
				for _, er := range inst.ExtraRets {
					if er != NoReg {
						if loc := ar.Loc(er); loc.Name != "" && !owned[loc.Name] {
							seen[loc.Name] = true
						}
					}
				}
			}
		}
	}

	if len(seen) == 0 {
		return nil
	}
	// Sort for determinism.
	out := make([]string, 0, len(seen))
	for name := range seen {
		out = append(out, name)
	}
	sortStrings(out)
	return out
}

func sortStrings(ss []string) {
	// Simple insertion sort for small lists.
	for i := 1; i < len(ss); i++ {
		for j := i; j > 0 && ss[j] < ss[j-1]; j-- {
			ss[j], ss[j-1] = ss[j-1], ss[j]
		}
	}
}
