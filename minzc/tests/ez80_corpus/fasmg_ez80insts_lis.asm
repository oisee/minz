	; IX-indexed loads with .LIS suffix
	LD.LIS BC,(IX+$00) ; 49DD07 $00
	LD.LIS (IX+$00),BC ; 49DD0F $00
	LD.LIS DE,(IX+$00) ; 49DD17 $00
	ADD.LIS IX,DE ; 49DD19
	LD.LIS (IX+$00),DE ; 49DD1F $00
	LD.LIS IX,$0000 ; 49DD21 $0000
