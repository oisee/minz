#!/usr/bin/env python3
"""Unroll the two pull state machines, avoiding recursive static-spill frames."""
from pathlib import Path
HERE=Path(__file__).resolve().parent
TEMPLATE='''
fun @NAME@_load_earlier() {
    mix_have_earlier[@U@] = @NEXT@
    if mix_have_earlier[@U@] != 0 { mix_copy(@EARLIER@,@SOURCE@) }
}
fun @NAME@_next()->u8 {
    if fault != 0 { return 0 }
    if mix_initialized[@U@] == 0 {
        @NAME@_load_earlier()
        mix_have_incoming[@U@] = lane_next(mix_sources[@U@])
        mix_initialized[@U@] = 1
    }
    while fault == 0 {
        let incoming:u16 = u16(mix_sources[@U@])*16
        var before:u32 = 65540
        if mix_have_incoming[@U@] != 0 { before = u32(mix_word(incoming+2)) }
        var have:u8 = 0
        var chosen:u16 = 0
        var row:u32 = 0
        var slot:u16 = @START@
        while slot < @END@ {
            if mix_live[slot] != 0 && u32(mix_rows[slot]) < before {
                if have == 0 || u32(mix_rows[slot]) < row {
                    chosen = slot
                    row = u32(mix_rows[slot])
                    have = 1
                }
            }
            slot = slot + 1
        }
        if mix_have_earlier[@U@] != 0 {
            let earlier_row:u32 = u32(mix_word(@EARLIER@+2))
            if earlier_row < before && (have == 0 || earlier_row < row) {
                mix_copy(@OUT@,@EARLIER@)
                @NAME@_load_earlier()
                if fault != 0 { return 0 }
                return 1
            }
        }
        if have != 0 {
            mix_copy(@OUT@,112+chosen*16)
            mix_live[chosen] = 0
            mix_pending[@U@] = mix_pending[@U@] - 1
            return 1
        }
        if mix_have_incoming[@U@] == 0 { return 0 }
        // Prefill only R..R+3; larger earlier cells stay in the owned head.
        while mix_have_earlier[@U@] != 0 && fault == 0 {
            let earlier_row:u32 = u32(mix_word(@EARLIER@+2))
            if earlier_row > before + 3 { break }
            mix_place(@U@,earlier_row,@EARLIER@)
            @NAME@_load_earlier()
        }
        if fault != 0 { return 0 }
        mix_accept(@U@,before,incoming)
        if fault != 0 { return 0 }
        mix_have_incoming[@U@] = lane_next(mix_sources[@U@])
    }
    return 0
}
'''
def generated():
    result='// Generated by generate_folds.py. Two separate functions: no recursive spill frames.\n'
    for u,name,nxt,source in [(0,'fold_a','lane_next(mix_first)','u16(mix_first)*16'),(1,'fold_b','fold_a_next()','80')]:
        s=TEMPLATE
        values=dict(NAME=name,U=u,NEXT=nxt,SOURCE=source,EARLIER=48+u*16,OUT=80+u*16,START=u*4,END=u*4+4)
        for k,v in values.items():s=s.replace('@'+k+'@',str(v))
        assert '@' not in s
        result+=s
    return result
if __name__=='__main__':(HERE/'folds.nanz').write_text(generated())
