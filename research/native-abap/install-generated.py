#!/usr/bin/env python3
"""Install exactly the pinned abapiti Go output; never rewrite its implementation."""
import hashlib, json, pathlib, sys
root=pathlib.Path(__file__).resolve().parents[2]
dest=root/"minzc/pkg/abap/internal/abapparse"
source=pathlib.Path(sys.argv[1])
expected=json.loads((dest/"generated-inputs.json").read_text())
files={}
for name,digest in expected.items():
    raw=(source/name).read_bytes()
    if hashlib.sha256(raw).hexdigest()!=digest:
        raise SystemExit("generation mismatch: "+name)
    text=raw.decode().replace("//go:build !profile_sites\n\n", "").replace("package main", "package abapparse", 1)
    files[name]="// Code generated by pinned abapiti; see PROVENANCE.md. DO NOT EDIT.\n"+text
for name,text in files.items():
    (dest/name).write_text(text)
print("Installed", len(files), "verified generated files")
