#!/usr/bin/env python3
"""Derive a memory-routing staging core, retaining host I/O for validation."""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[2]
source = root / 'examples/zmachine/zork-west-demo/zvm.nanz'
target = root / 'examples/zmachine/spectrum128/zvm_core.nanz'
lines = []
wide_read = False
for line in source.read_text().splitlines():
    if line.lstrip().startswith('//'):
        lines.append(line)
        continue
    if line.startswith('fun '):
        wide_read = line.startswith(('fun code_byte_at(', 'fun code_word_at(', 'fun verify_story('))
    line = re.sub(r'story\[([^\]]+)\]\s*=(?!=)\s*(.*?)(?=\s*\}|$)',
                  lambda m: 'memory_write(' + m[1] + ', ' + m[2].rstrip() + ')', line)
    line = re.sub(r'story\[([^\]]+)\]', lambda m: ('memory_read(u32(' + m[1] + '))' if wide_read else 'memory_read16(' + m[1] + ')'), line)
    lines.append(line)
text = '\n'.join(lines) + '\n'
accessors = '''// Only these accessors index story storage; native backend replaces them.
fun memory_read(address: u32) -> u8 { return story[address] }
fun memory_read16(address: u16) -> u8 { return story[address] }
fun memory_write(address: u16, value: u8) { story[address] = value }

'''
text = text.replace('file_read_bounded(&story_path, &story, capacity)', 'memory_load(capacity)')
text = text.replace('file_write_pair(&save_path, &snapshot, 9018, &story, word_at(14))', 'memory_save(word_at(14))')
text = text.replace('file_read_pair_checked(&save_path, &snapshot, 9018, &story, dynamic_size)', 'memory_restore(dynamic_size)')
accessors += """// Lifecycle also stays behind the interface: native memory has no flat &story.
fun memory_load(capacity: u32) -> u32 {
    return file_read_bounded(&story_path, &story, capacity)
}
fun memory_save(dynamic_size: u16) -> u8 {
    return file_write_pair(&save_path, &snapshot, 9018, &story, dynamic_size)
}
fun memory_restore(dynamic_size: u16) -> u8 {
    return file_read_pair_checked(&save_path, &snapshot, 9018, &story, dynamic_size)
}

"""
text = text.replace('fun byte_at(addr: u16)', accessors + 'fun byte_at(addr: u16)', 1)
header = '''// Generated by scripts/zmachine/prepare_memory_core.py from the host core.
// Memory-routing staging version; host I/O and large allocation remain.
// NOT a native Spectrum binary. Original regression fixture is unchanged.
'''
assert text.count('story[') == 3, 'Unrouted story access remains'
assert text.count('&story,') == 3, 'Unrouted lifecycle access remains'
target.write_text(header + text)
print(target.relative_to(root))
